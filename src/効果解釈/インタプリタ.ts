// 効果インタプリタ（TCG非依存）
//
// 責務は4つだけ：
//   1. 処理列を上から順に実行する
//   2. プレイヤー入力が要る選択で中断し、入力後に同じ場所から再開する
//   3. 中間スコープ（「その中の」「残りは」）を保持する
//   4. 変数（条件で変わる数値）を解決する
//
// 「フィルタが何を意味するか」「アクションが何をするか」は知らない。
// それは ゲーム接続 が与える。

import { カード } from '../データ/カード/カード.js';
import {
  カードフィルタ,
  効果定義,
  処理ステップ,
  数値式,
  発動条件,
  選択指定,
} from './効果定義.js';
import { ゲーム接続, 実行文脈, 対象を解決, 選択肢 } from './ゲーム接続.js';
import { 決定者, 対象参照 } from './効果定義.js';

// === 実行結果 ===

export interface 中断状態 {
  処理列: 処理ステップ[];
  位置: number;
  コスト長: number;
  文脈: 実行文脈;
  候補: カード[];
  最小: number;
  最大: number;
  任意: boolean;
  // この判断を誰がするか。効果の持ち主から見た呼び方。
  決定者: 決定者;
  // カードを選ぶのではない判断のとき、選択肢と問いが入る。
  // このとき 候補 は空で、答えは選択肢の識別子で返す。
  選択肢?: 選択肢[];
  問い?: string;
  // 選択肢の答えを 文脈.決定 に書き込むための鍵。
  // 答えを受け取ったら同じステップをもう一度実行する。
  決定鍵?: string;
  // 「好きな順で」の並べ替えを聞いているとき、結果を書き戻す先。
  // 入っていれば、選ばれた順がそのまま並び順になる。
  並べ替え先?: 対象参照;
}

export type 実行結果 =
  | { 状態: '完了'; 発動した: boolean; ログ: string[] }
  | {
      状態: '選択待ち';
      候補: カード[];
      最小: number;
      最大: number;
      任意: boolean;
      決定者: 決定者;
      選択肢?: 選択肢[];
      問い?: string;
      並べ替え先?: 対象参照;
      中断状態: 中断状態;
    }
  | { 状態: '失敗'; 理由: string; ログ: string[] };

// === 数値式の解決 ===

// '$名前' なら変数を引く。数値ならそのまま。
export function 数値を解決(式: 数値式 | undefined, 文脈: 実行文脈): number | undefined {
  if (式 === undefined) {
    return undefined;
  }
  if (typeof 式 === 'number') {
    return 式;
  }
  if (式.startsWith('$')) {
    return 文脈.変数.get(式.slice(1));
  }
  const 数値 = Number(式);
  return Number.isNaN(数値) ? undefined : 数値;
}

// フィルタ内の数値式を、実際の数値に置き換えたコピーを返す
function フィルタを解決<T extends カードフィルタ>(フィルタ: T, 文脈: 実行文脈): T {
  const 解決済み = { ...フィルタ } as any;
  for (const キー of ['BP以下', 'BP以上', 'コスト以下', 'コスト以上'] as const) {
    if (フィルタ[キー] !== undefined) {
      解決済み[キー] = 数値を解決(フィルタ[キー], 文脈);
    }
  }
  return 解決済み;
}

// === インタプリタ本体 ===

export class 効果インタプリタ {
  private 接続: ゲーム接続;

  constructor(接続: ゲーム接続) {
    this.接続 = 接続;
  }

  // 効果を実行する。選択が要るところで中断して返ることがある。
  実行(効果: 効果定義, 自身: カード, プレイヤー識別子: string): 実行結果 {
    const 文脈: 実行文脈 = {
      自身,
      プレイヤー識別子,
      スコープ: [],
      選択済み: [],
      残り: [],
      変数: new Map(),
      直前成功: false,
      決定: new Map(),
      ログ: [],
    };

    if (効果.条件 && !this.条件を評価(効果.条件, 文脈)) {
      文脈.ログ.push('発動条件を満たしていません');
      return { 状態: '完了', 発動した: false, ログ: 文脈.ログ };
    }

    // コストと本体をひと続きの処理列にする。
    // 境界を覚えておき、コスト側で失敗したら効果全体を取りやめる。
    const コスト = 効果.コスト ?? [];
    const 処理列 = [...コスト, ...効果.処理];

    return this.処理列を進める(処理列, 0, コスト.length, 文脈);
  }

  // 答えを受け取って、中断したところから続きを実行する。
  // 答えはカードの識別子か、選択肢の識別子（カードを選ぶ判断でないとき）。
  再開(中断: 中断状態, 答え: string[]): 実行結果 {
    const 文脈 = 中断.文脈;

    // カードを選ぶのではない判断（「置くコアは相手が選ぶ」など）。
    // 答えを文脈に控えて、同じステップをもう一度実行する。
    // アクション側は答えがあることを見て、今度は実際に処理を行う。
    if (中断.選択肢 && 中断.決定鍵) {
      const 選ばれた識別子 = 答え[0];
      if (!中断.選択肢.some(選択肢 => 選択肢.識別子 === 選ばれた識別子)) {
        return { 状態: '失敗', 理由: '選択肢にない答えが返されました', ログ: 文脈.ログ };
      }
      文脈.決定.set(中断.決定鍵, 選ばれた識別子);
      return this.処理列を進める(中断.処理列, 中断.位置, 中断.コスト長, 文脈);
    }

    // 答えの並び順を保って解決する。「好きな順で」の並べ替えでは
    // この順番そのものが答えなので、候補の並びに戻してはいけない。
    const 選ばれた = 答え
      .map(識別子 => 中断.候補.find(c => c.識別子 === 識別子))
      .filter((c): c is カード => c !== undefined);
    if (選ばれた.length !== 答え.length) {
      return { 状態: '失敗', 理由: '候補にないカードが選ばれました', ログ: 文脈.ログ };
    }
    if (選ばれた.length < 中断.最小 || 選ばれた.length > 中断.最大) {
      return {
        状態: '失敗',
        理由: `選択数が範囲外です（${中断.最小}〜${中断.最大}体のところ${選ばれた.length}体）`,
        ログ: 文脈.ログ,
      };
    }

    // 並べ替えは「選ぶ」のではなく「並べる」ので、選択済み／残り は動かさず、
    // 並べ替えた結果を元の参照先へ書き戻すだけにする。
    if (中断.並べ替え先) {
      this.並べ替え結果を書き戻す(中断.並べ替え先, 選ばれた, 文脈);
      return this.処理列を進める(中断.処理列, 中断.位置 + 1, 中断.コスト長, 文脈);
    }

    this.選択を確定(選ばれた, 文脈);

    return this.処理列を進める(中断.処理列, 中断.位置 + 1, 中断.コスト長, 文脈);
  }

  // === 内部 ===

  // 判断の答えを控える鍵。処理列の位置ごとに別の判断として扱う。
  private 決定鍵を作る(位置: number): string {
    return `決定@${位置}`;
  }

  // 条件を評価する。「そうしたなら」＝直前の処理が行われたか、はインタプリタ自身が持つ
  // 情報なのでここで答える。それ以外はゲーム接続に委ねる。
  private 条件を評価(条件: 発動条件, 文脈: 実行文脈): boolean {
    if ('直前成功' in 条件) {
      return 文脈.直前成功 === 条件.直前成功;
    }
    return this.接続.条件を評価(条件, 文脈);
  }

  private 並べ替え結果を書き戻す(
    参照: 対象参照,
    並び: カード[],
    文脈: 実行文脈
  ): void {
    if (参照 === '残り') {
      文脈.残り = 並び;
    } else if (参照 === '選択') {
      文脈.選択済み = 並び;
    } else if (参照 === 'スコープ') {
      文脈.スコープ = 並び;
    }
    文脈.ログ.push(
      `${並び.map(c => this.接続.カード名を取得(c)).join('、')} の順に並べました`
    );
  }

  private 選択を確定(選ばれた: カード[], 文脈: 実行文脈): void {
    文脈.選択済み = 選ばれた;
    const 選ばれた識別子 = new Set(選ばれた.map(c => c.識別子));
    文脈.残り = 文脈.スコープ.filter(c => !選ばれた識別子.has(c.識別子));
    if (選ばれた.length > 0) {
      const 名前 = 選ばれた.map(c => this.接続.カード名を取得(c)).join('、');
      文脈.ログ.push(`${名前} を選択しました`);
    }
  }

  private 処理列を進める(
    処理列: 処理ステップ[],
    開始位置: number,
    コスト長: number,
    文脈: 実行文脈
  ): 実行結果 {
    // もし ブロックは実行時に平坦化して差し込むため、作業用コピーを持つ
    const 作業列 = [...処理列];

    for (let 位置 = 開始位置; 位置 < 作業列.length; 位置++) {
      const ステップ = 作業列[位置];
      const コスト段階 = 位置 < コスト長;

      // --- 制御ステップ（インタプリタが解釈する） ---

      if ('もし' in ステップ) {
        const 成立 = this.条件を評価(ステップ.もし, 文脈);
        const 差し込む = 成立 ? ステップ.ならば : ステップ.そうでなければ ?? [];
        作業列.splice(位置 + 1, 0, ...差し込む);
        continue;
      }

      if ('変数' in ステップ) {
        const 定義 = ステップ.変数;
        let 値 = 定義.既定;
        if (定義.もし && this.条件を評価(定義.もし, 文脈) && 定義.ならば !== undefined) {
          値 = 定義.ならば;
        }
        文脈.変数.set(定義.名, 値);
        continue;
      }

      if ('選択' in ステップ) {
        const 結果 = this.選択を処理(ステップ.選択, 作業列, 位置, コスト長, 文脈);
        if (結果) {
          return 結果; // 中断
        }
        continue;
      }

      if ('並べ替え' in ステップ) {
        const 結果 = this.並べ替えを処理(ステップ.並べ替え, 作業列, 位置, コスト長, 文脈);
        if (結果) {
          return 結果; // 中断（順番を聞いている）
        }
        continue;
      }

      if ('オープン' in ステップ) {
        const 開いた = this.接続.カードを収集(
          { 場: ステップ.オープン.場, ゾーン: ステップ.オープン.ゾーン },
          文脈
        );
        const 数 = ステップ.オープン.数;
        文脈.スコープ = 開いた.slice(0, 数);
        文脈.選択済み = [];
        文脈.残り = [...文脈.スコープ];
        const 名前 = 文脈.スコープ.map(c => this.接続.カード名を取得(c)).join('、');
        文脈.ログ.push(`${文脈.スコープ.length}枚をオープンしました${名前 ? `（${名前}）` : ''}`);
        continue;
      }

      // --- アクション（ゲーム接続に委ねる） ---

      const 対象 = this.アクションの対象を求める(ステップ, 文脈);
      const 解決済みステップ = this.ステップの数値を解決(ステップ, 文脈);
      // 判断が要るアクションは、答えを文脈から読む。まだ無ければ問い返してくる。
      文脈.決定鍵 = this.決定鍵を作る(位置);
      const 結果 = this.接続.アクションを実行(解決済みステップ, 対象, 文脈);

      // 「これは自分では決められない」と返ってきたら、答えを聞いてから同じ位置をやり直す
      if (結果.決定依頼) {
        return {
          状態: '選択待ち',
          候補: [],
          最小: 1,
          最大: 1,
          任意: false,
          決定者: 結果.決定依頼.決定者,
          選択肢: 結果.決定依頼.選択肢,
          問い: 結果.決定依頼.問い,
          中断状態: {
            処理列: 作業列,
            位置,
            コスト長,
            文脈,
            候補: [],
            最小: 1,
            最大: 1,
            任意: false,
            決定者: 結果.決定依頼.決定者,
            選択肢: 結果.決定依頼.選択肢,
            問い: 結果.決定依頼.問い,
            決定鍵: this.決定鍵を作る(位置),
          },
        };
      }

      文脈.直前成功 = 結果.成功;

      if (結果.メッセージ) {
        文脈.ログ.push(結果.メッセージ);
      }

      if (!結果.成功 && コスト段階) {
        文脈.ログ.push('コストを支払えないため、効果は発動しませんでした');
        return { 状態: '完了', 発動した: false, ログ: 文脈.ログ };
      }
    }

    return { 状態: '完了', 発動した: true, ログ: 文脈.ログ };
  }

  // 選択ステップを処理する。中断が必要なら実行結果を返し、不要なら undefined を返す。
  // 「好きな順で」の順番を聞く。
  //
  // 並べ替えは選ぶ／選ばないの判断ではなく、全部を順番に並べる操作なので、
  // 最小＝最大＝枚数にして「全部を順に選ばせる」形で聞く。
  // 答えの並び順がそのまま結果の順番になる。
  private 並べ替えを処理(
    指定: { 対象: 対象参照; 問い?: string },
    作業列: 処理ステップ[],
    位置: number,
    コスト長: number,
    文脈: 実行文脈
  ): 実行結果 | undefined {
    const 候補 = 対象を解決(指定.対象, 文脈);
    if (候補.length <= 1) {
      return undefined; // 0枚か1枚なら並べ替える余地がない
    }

    return {
      状態: '選択待ち',
      候補,
      最小: 候補.length,
      最大: 候補.length,
      任意: false,
      決定者: '自分',
      問い: 指定.問い ?? '置く順番に選んでください（先に選んだものから置きます）',
      並べ替え先: 指定.対象,
      中断状態: {
        処理列: 作業列,
        位置,
        コスト長,
        文脈,
        候補,
        最小: 候補.length,
        最大: 候補.length,
        任意: false,
        決定者: '自分',
        問い: 指定.問い ?? '置く順番に選んでください（先に選んだものから置きます）',
        並べ替え先: 指定.対象,
      },
    };
  }

  private 選択を処理(
    指定: 選択指定,
    作業列: 処理ステップ[],
    位置: number,
    コスト長: number,
    文脈: 実行文脈
  ): 実行結果 | undefined {
    const 解決済み指定 = フィルタを解決(指定, 文脈);
    const 候補 = this.接続.カードを収集(解決済み指定, 文脈);

    if (候補.length === 0) {
      文脈.ログ.push('選択できる対象がいません');
      this.選択を確定([], 文脈);
      return undefined;
    }

    const { 最小, 最大 } = this.個数を求める(解決済み指定, 候補.length, 文脈);

    if (最大 === 0) {
      this.選択を確定([], 文脈);
      return undefined;
    }

    // 選ぶ余地がない（候補数＝必要数）なら、確認を挟まず自動で確定する
    const 選ぶ余地なし = 最小 === 最大 && 候補.length === 最大;
    if (選ぶ余地なし) {
      this.選択を確定(候補, 文脈);
      return undefined;
    }

    return {
      状態: '選択待ち',
      候補,
      最小,
      最大,
      任意: 指定.任意 === true,
      // 対象を「指定する」のは効果を使っている側（カード側に指定が無い限り）
      決定者: '自分',
      中断状態: {
        処理列: 作業列,
        位置,
        コスト長,
        文脈,
        候補,
        最小,
        最大,
        任意: 指定.任意 === true,
        決定者: '自分',
      },
    };
  }

  private 個数を求める(
    指定: 選択指定,
    候補数: number,
    文脈: 実行文脈
  ): { 最小: number; 最大: number } {
    if (指定.数 === 'すべて') {
      return { 最小: 候補数, 最大: 候補数 };
    }

    const 指定数 = 数値を解決(指定.数, 文脈) ?? 0;
    const 最大 = Math.min(指定数, 候補数);

    // 「N個まで」も「指定できる」も、0体を選べる
    if (指定.まで || 指定.任意) {
      return { 最小: 0, 最大 };
    }
    return { 最小: 最大, 最大 };
  }

  private アクションの対象を求める(ステップ: 処理ステップ, 文脈: 実行文脈): カード[] {
    for (const キー of [
      '破壊',
      '破棄',
      '手札に加える',
      '手札に戻す',
      'デッキ下に戻す',
      '疲労',
      '回復',
    ] as const) {
      if (キー in ステップ) {
        return 対象を解決((ステップ as any)[キー], 文脈);
      }
    }
    if ('BP変更' in ステップ) {
      return 対象を解決(ステップ.BP変更.対象, 文脈);
    }
    if ('制約' in ステップ) {
      // 対象が書かれていない制約はプレイヤーにかかるもの（「自分のライフは減らない」）
      return ステップ.制約.対象 ? 対象を解決(ステップ.制約.対象, 文脈) : [];
    }
    return [];
  }

  // ステップ内の数値式（'$変数'）を実数に置き換えたコピーを返す
  private ステップの数値を解決(ステップ: 処理ステップ, 文脈: 実行文脈): 処理ステップ {
    if ('BP変更' in ステップ) {
      return {
        BP変更: {
          ...ステップ.BP変更,
          値: 数値を解決(ステップ.BP変更.値, 文脈) ?? 0,
        },
      };
    }
    if ('ドロー' in ステップ) {
      return { ドロー: 数値を解決(ステップ.ドロー, 文脈) ?? 0 };
    }
    if ('コア移動' in ステップ) {
      return {
        コア移動: {
          ...ステップ.コア移動,
          数: 数値を解決(ステップ.コア移動.数, 文脈) ?? 0,
        },
      };
    }
    return ステップ;
  }
}

// 発動条件が使われているかの簡易判定（デバッグ・検証用）
export function 条件を持つ(効果: 効果定義): 効果定義['条件'] extends undefined ? false : boolean {
  return (効果.条件 !== undefined) as any;
}

export type { 発動条件, カードフィルタ };
