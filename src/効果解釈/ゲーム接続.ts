// インタプリタと各TCGをつなぐ境界（ポート）
//
// インタプリタが知っているのは「処理列の順序・中断再開・中間スコープ・変数」だけ。
// 「フィルタが何を意味するか」「アクションが何をするか」は各TCGがここを実装して与える。
// 別のTCGを載せるときは、このインターフェースの実装だけを差し替える。

import { カード } from '../データ/カード/カード.js';
import { カードフィルタ, 決定者, 発動条件, 処理ステップ, 対象参照 } from './効果定義.js';

// 効果を実行している最中の状態
export interface 実行文脈 {
  // 効果の発生元カード
  自身: カード;
  // 効果を使っているプレイヤー
  プレイヤー識別子: string;
  // オープンなどで一時的に載せたカード群（「その中の」の参照先）
  スコープ: カード[];
  // 直前の選択で選ばれたカード
  選択済み: カード[];
  // スコープのうち選ばれなかったカード（「残りは〜」の参照先）
  残り: カード[];
  // 効果内で定義した数値変数
  変数: Map<string, number>;
  // 直前のアクションが実際に行われたか（「そうしたなら」の判断に使う）
  直前成功: boolean;
  // 受け取った選択肢の答え。鍵はインタプリタが処理列の位置から作る。
  // アクションは「答えがまだ無ければ問い返し、あれば実行する」形で書く。
  決定: Map<string, string>;
  // 今実行しているステップの決定鍵。インタプリタが実行の直前に入れる。
  決定鍵?: string;
  // 実行の記録
  ログ: string[];
}

// カード以外の選択肢（「ソウルコアを含める」「通常コアだけ」など）
export interface 選択肢 {
  識別子: string;
  表示: string;
}

// アクションが「これは自分では決められない」と申し出るときの内容。
// カードを選ぶのではない判断、または効果の持ち主でない側が決める判断に使う。
export interface 決定依頼 {
  問い: string;
  選択肢: 選択肢[];
  決定者: 決定者;
}

export interface アクション結果 {
  成功: boolean;
  メッセージ?: string;
  // これが入っていたら、まだ実行していない。
  // インタプリタが判断を仰いでから、同じステップをもう一度実行する。
  決定依頼?: 決定依頼;
}

export interface ゲーム接続 {
  // フィルタに合致するカードを集める
  カードを収集(フィルタ: カードフィルタ, 文脈: 実行文脈): カード[];

  // 発動条件を評価する
  条件を評価(条件: 発動条件, 文脈: 実行文脈): boolean;

  // アクションを実行する。対象は解決済みのカード配列。
  // インタプリタが解釈する制御ステップ（選択・もし・変数）はここには来ない。
  アクションを実行(ステップ: 処理ステップ, 対象: カード[], 文脈: 実行文脈): アクション結果;

  // 表示用のカード名
  カード名を取得(カード: カード): string;
}

// 対象参照を実際のカード配列に解決する（TCG非依存なのでここで持つ）
export function 対象を解決(参照: 対象参照, 文脈: 実行文脈): カード[] {
  switch (参照) {
    case '選択':
      return 文脈.選択済み;
    case '残り':
      return 文脈.残り;
    case '自身':
      return [文脈.自身];
    case 'スコープ':
      return 文脈.スコープ;
    default:
      return [];
  }
}
