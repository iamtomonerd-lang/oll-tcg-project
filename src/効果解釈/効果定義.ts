// カード効果のデータ形式定義（TCG非依存）
//
// カードは「クラス」ではなく「データ」として書く。
// このファイルはその文法だけを定義し、各語彙の意味は各TCGの「ゲーム接続」が与える。

// === 参照 ===

// 処理の対象をどこから取るか
// '選択'   : 直前の選択ステップで選ばれたカード
// '残り'   : 中間スコープのうち選ばれなかったカード
// '自身'   : 効果の発生元カード
// 'スコープ': 中間スコープ全体
export type 対象参照 = '選択' | '残り' | '自身' | 'スコープ';

// 数値は定数または変数参照（'$BP上限' のように書く）
export type 数値式 = number | string;

// === フィルタ ===

// カードを絞り込む条件。指定した項目すべてを満たすカードが対象（AND）。
// 各項目の意味は「ゲーム接続」が解釈する。
export interface カードフィルタ {
  場?: '自分' | '相手';
  ゾーン?: string;
  元?: 'スコープ';
  種別?: string | string[];
  BP以下?: 数値式;
  BP以上?: 数値式;
  コスト以下?: 数値式;
  コスト以上?: 数値式;
  系統?: string;
  属性?: string;
  状態?: string;
  アタック中?: boolean;
  カード名以外?: string;
  キーワード?: string;
  キーワードなし?: string;
  真界放?: boolean;
}

// === コアの置き場所 ===

// コアの移動元・移動先。ゾーン指定か、効果内で参照するカード指定のいずれか。
export type コア位置 =
  | { ゾーン: string; 場?: '自分' | '相手' }
  | { 対象: 対象参照 };

// === 条件 ===

export interface 存在条件 {
  存在: カードフィルタ;
}

export interface 不在条件 {
  不在: カードフィルタ;
}

export interface 数量条件 {
  数量: カードフィルタ & { 以下?: number; 以上?: number };
}

export interface 状態条件 {
  状態: string;
  値?: boolean;
}

// 効果の発生元カード自身がフィルタに合致するか
// （《真界放》のように「このカードが今その状態か」を問う条件に使う）
export interface 自身条件 {
  自身: カードフィルタ;
}

export type 発動条件 = 存在条件 | 不在条件 | 数量条件 | 状態条件 | 自身条件;

// === 選択 ===

export interface 選択指定 extends カードフィルタ {
  // 選ぶ枚数。'すべて' は候補全部。
  数: 数値式 | 'すべて';
  // 「N個まで」= 0〜N。指定時は 数 が上限になる。
  まで?: boolean;
  // 「指定できる」= 選ばずに飛ばせる
  任意?: boolean;
}

// === 処理ステップ ===

export type 処理ステップ =
  // 対象選択（プレイヤー入力で中断しうる）
  | { 選択: 選択指定 }
  // カードを一時的に開いて中間スコープに載せる
  | { オープン: { 場?: '自分' | '相手'; ゾーン: string; 数: number } }
  // 破壊・除去
  | { 破壊: 対象参照 }
  | { 破棄: 対象参照 }
  // ゾーン移動
  | { 手札に加える: 対象参照 }
  | { 手札に戻す: 対象参照 }
  | { デッキ下に戻す: 対象参照 }
  // 数値・状態
  | { ドロー: 数値式 }
  | { BP変更: { 対象: 対象参照; 値: 数値式; 期間?: 期間 } }
  | { 疲労: 対象参照 }
  | { 回復: 対象参照 }
  // コア
  // 除外:'ソウルコア' … 通常コアだけを動かす（「{ソウルコア}以外のコア」）
  // 種類:'ソウルコア' … ソウルコアだけを動かす（「{ソウルコア}を置く」）
  // まで:true         … 「N個まで」。動かせるだけ動かす（0個でもよい）
  | {
      コア移動: {
        元: コア位置;
        先: コア位置;
        数: 数値式;
        除外?: 'ソウルコア';
        種類?: 'ソウルコア';
        まで?: boolean;
      };
    }
  // 制御
  | { もし: 発動条件; ならば: 処理ステップ[]; そうでなければ?: 処理ステップ[] }
  | { 変数: { 名: string; 既定: number; もし?: 発動条件; ならば?: number } };

export type 期間 = 'このバトル中' | 'このターン中' | '永続';

// === 効果定義 ===

export type 効果種別 = '誘発' | '起動' | '常在' | '使用';

export interface 効果定義 {
  // 発動できるLv（スピリット／ネクサス用）。未指定なら不問。
  Lv?: number[];
  種別?: 効果種別;
  // 誘発トリガー（'召喚時' など）
  トリガー?: string;
  // 起動・使用のタイミング（'フラッシュ' 'メイン' など）
  タイミング?: string;
  // 効果が働くための持続状態（'アタック中' など）
  状態?: string;
  // 発動条件
  条件?: 発動条件;
  // 〔ターン1回〕などの回数制限
  制限?: string;
  // 起動効果のコスト（▶ の左側）。失敗したら処理は行わない。
  コスト?: 処理ステップ[];
  // 効果本体
  処理: 処理ステップ[];
}
