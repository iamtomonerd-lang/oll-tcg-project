test('任意選択：0体を選んで飛ばせる', () => {
  const { 試合: 試合インスタンス, インタプリタ } = 環境を作る();

  const 効果: 効果定義 = {
    処理: [
      { 選択: { 場: '相手', 種別: 'スピリット', 数: 1, 任意: true } },
      { 破壊: '選択' },
    ],
  };

  場に出す(試合インスタンス, 'p2', ゲン_ボーを作成('相手1'), 3000);

  const 自身 = 場に出す(試合インスタンス, 'p1', グンガタを作成('自身'), 5000);
  const 中断 = インタプリタ.実行(効果, 自身, 'p1');

  assert.equal(中断.状態, '選択待ち', '任意なので候補1体でも確認を挟む');
  if (中断.状態 !== '選択待ち') return;
  assert.equal(中断.最小, 0, '0体を選べる');
  assert.equal(中断.任意, true);

  const 結果 = インタプリタ.再開(中断.中断状態, []);
  assert.equal(結果.状態, '完了');

  assert.equal(破壊待ちか(試合インスタンス, 'p2', '相手1'), false, '選ばなければ破壊されない');
});

// === 選択の検証 ===

test('再開時に不正な選択は拒否される', async t => {
  function 中断を作る() {
    const { 試合: 試合インスタンス, インタプリタ } = 環境を作る();
    場に出す(試合インスタンス, 'p2', ゲン_ボーを作成('相手1'), 3000);
    場に出す(試合インスタンス, 'p2', ゲン_ボーを作成('相手2'), 2000);
    const 自身 = 場に出す(試合インスタンス, 'p1', グンガタを作成('自身'), 5000);

    const 効果: 効果定義 = {
      処理: [{ 選択: { 場: '相手', 種別: 'スピリット', 数: 1 } }, { 破壊: '選択' }],
    };
    const 中断 = インタプリタ.実行(効果, 自身, 'p1');
    return { インタプリタ, 中断 };
  }

  await t.test('候補にないカードは選べない', () => {
    const { インタプリタ, 中断 } = 中断を作る();
    assert.equal(中断.状態, '選択待ち');
    if (中断.状態 !== '選択待ち') return;

    const 結果 = インタプリタ.再開(中断.中断状態, ['存在しないカード']);
    assert.equal(結果.状態, '失敗');
  });

  await t.test('必要数を超えて選べない', () => {
    const { インタプリタ, 中断 } = 中断を作る();
    assert.equal(中断.状態, '選択待ち');
    if (中断.状態 !== '選択待ち') return;

    const 結果 = インタプリタ.再開(中断.中断状態, ['相手1', '相手2']);
    assert.equal(結果.状態, '失敗');
  });
});
