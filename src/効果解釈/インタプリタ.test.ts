// === 試験環境 ===

function 試合を準備する(): 試合 {
  const 試合インスタンス = new 試合();
  試合インスタンス.プレイヤーを準備する('p1', 'プレイヤー1');
  試合インスタンス.プレイヤーを準備する('p2', 'プレイヤー2');
  試合インスタンス.ボイドを準備する();
  試合インスタンス.デッキを設定する(
    'p1',
    Array.from({ length: 10 }, (_, i) => グンガタを作成(`p1-deck-${i + 1}`))
  );
  試合インスタンス.デッキを設定する(
    'p2',
    Array.from({ length: 10 }, (_, i) => グンガタを作成(`p2-deck-${i + 1}`))
  );
  試合インスタンス.準備を行う('p1');
  試合インスタンス.準備を行う('p2');
  試合インスタンス.先攻を決める('p1');
  return 試合インスタンス;
}

function 場に出す(試合インスタンス: 試合, プレイヤー識別子: string, カード: カード, BP?: number): カード {
  const フィールド = 試合インスタンス.ゾーン管理.フィールドを取得(試合インスタンス.ゲーム, プレイヤー識別子)!;
  フィールド.カードを追加(カード);
  // 場のカードには必ずコアが乗っている。乗せずに置くと、ルール処理の消滅判定に
  // 引っかかって即トラッシュ行きになる（実戦では起こらない状態）。
  // Lv1を保てる最小限だけ乗せる。Lvを変えたいテストは、このあとで自分で乗せ直す。
  試合インスタンス.コア管理
    .カードを保持者に(カード)
    .コア数を設定(new 消滅判定().最小必要コア数を取得(カード));
  if (BP !== undefined) {
    試合インスタンス.BP管理.BPを設定(カード, BP);
  }
  return カード;
}

function 環境を作る() {
  const 試合インスタンス = 試合を準備する();
  const 接続 = new バトスピ接続(試合インスタンス);
  const インタプリタ = new 効果インタプリタ(接続);
  return { 試合: 試合インスタンス, インタプリタ };
}

// 破壊は2段階（待機状態 →「破壊された時」効果の余地 → トラッシュ）なので、
// 効果の実行直後は場に残ったまま待機状態になっているのが正しい。
function 破壊待ちか(試合インスタンス: 試合, プレイヤー識別子: string, カード識別子: string): boolean {
  const フィールド = 試合インスタンス.ゾーン管理.フィールドを取得(試合インスタンス.ゲーム, プレイヤー識別子)!;
  const カード = フィールド.カードを取得(カード識別子);
  if (!カード) {
    return false;
  }
  return (
    試合インスタンス.待機状態管理.待機状態か(カード) &&
    試合インスタンス.待機状態管理.待機理由を取得(カード) === '破壊'
  );
}

// ゲーム進行側が行う第2段階。待機状態のカードを実際にトラッシュへ移す。
function 待機状態を解決する(試合インスタンス: 試合, プレイヤー識別子: string): void {
  const フィールド = 試合インスタンス.ゾーン管理.フィールドを取得(試合インスタンス.ゲーム, プレイヤー識別子)!;
  for (const カード of [...フィールド.カード一覧を取得()]) {
    if (試合インスタンス.待機状態管理.待機状態か(カード)) {
      試合インスタンス.破壊管理.トラッシュへ置く(試合インスタンス.ゲーム, プレイヤー識別子, カード);
    }
  }
}

