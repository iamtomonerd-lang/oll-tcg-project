// === 中間スコープ（カード4の「その中の」「残りは」）===

test('中間スコープ：オープンしたカード群から選び、残りを処理できる', () => {
  const { 試合: 試合インスタンス, インタプリタ } = 環境を作る();

  // ［Lv2］『アタック時』自分のデッキの上から2枚をオープンする。
  //        その中の1枚を手札に加える。残りは破棄する。
  const カード4効果: 効果定義 = {
    Lv: [2],
    トリガー: 'アタック時',
    処理: [
      { オープン: { 場: '自分', ゾーン: 'デッキ上', 数: 2 } },
      { 選択: { 元: 'スコープ', 数: 1 } },
      { 手札に加える: '選択' },
      { 破棄: '残り' },
    ],
  };

  const 自身 = 場に出す(試合インスタンス, 'p1', グンガタを作成('自身'), 5000);

  const 手札枚数の前 = 試合インスタンス.ゾーン管理.手札を取得(試合インスタンス.ゲーム, 'p1')!.カード枚数を取得();
  const トラッシュ枚数の前 = 試合インスタンス.ゾーン管理
    .トラッシュを取得(試合インスタンス.ゲーム, 'p1')!
    .カード枚数を取得();

  const 中断 = インタプリタ.実行(カード4効果, 自身, 'p1');
  assert.equal(中断.状態, '選択待ち', '2枚から1枚選ぶので中断する');
  if (中断.状態 !== '選択待ち') return;
  assert.equal(中断.候補.length, 2, 'オープンした2枚が候補になる');

  const 選んだ = 中断.候補[0];
  const 残るはず = 中断.候補[1];

  const 結果 = インタプリタ.再開(中断.中断状態, [選んだ.識別子]);
  assert.equal(結果.状態, '完了');

  const 手札 = 試合インスタンス.ゾーン管理.手札を取得(試合インスタンス.ゲーム, 'p1')!;
  const トラッシュ = 試合インスタンス.ゾーン管理.トラッシュを取得(試合インスタンス.ゲーム, 'p1')!;

  assert.ok(手札.カードを取得(選んだ.識別子), '選んだ1枚は手札に入る');
  assert.ok(トラッシュ.カードを取得(残るはず.識別子), '残り1枚はトラッシュに行く');
  assert.equal(手札.カード枚数を取得(), 手札枚数の前 + 1);
  assert.equal(トラッシュ.カード枚数を取得(), トラッシュ枚数の前 + 1);
});

