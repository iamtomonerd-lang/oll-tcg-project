// === カード3をデータで動かす ===

test('カード3（ロワミーク）をデータ定義で実行する', async t => {
  await t.test('疲労状態の自分の赤スピリットがいなければ発動しない', () => {
    const { 試合: 試合インスタンス, インタプリタ } = 環境を作る();

    // 自分の場に赤スピリットはいるが、回復状態なので条件を満たさない
    場に出す(試合インスタンス, 'p1', グンガタを作成('自分1'), 5000);
    場に出す(試合インスタンス, 'p2', ゲン_ボーを作成('相手1'), 3000);

    const 自身 = 場に出す(試合インスタンス, 'p1', グンガタを作成('ロワミーク'), 3000);
    const 結果 = インタプリタ.実行(ロワミーク効果, 自身, 'p1');

    assert.equal(結果.状態, '完了');
    assert.equal(結果.状態 === '完了' && 結果.発動した, false);
  });

  await t.test('条件を満たすと、対象の選択待ちで中断する', () => {
    const { 試合: 試合インスタンス, インタプリタ } = 環境を作る();

    const 味方 = 場に出す(試合インスタンス, 'p1', グンガタを作成('自分1'), 5000);
    試合インスタンス.カードの表示形式管理.疲労する(味方);

    // 相手の場にBP3000以下が2体 → 選ぶ余地があるので中断するはず
    場に出す(試合インスタンス, 'p2', ゲン_ボーを作成('相手1'), 3000);
    場に出す(試合インスタンス, 'p2', ゲン_ボーを作成('相手2'), 2000);

    const 自身 = 場に出す(試合インスタンス, 'p1', グンガタを作成('ロワミーク'), 3000);
    const 結果 = インタプリタ.実行(ロワミーク効果, 自身, 'p1');

    assert.equal(結果.状態, '選択待ち');
    if (結果.状態 !== '選択待ち') return;
    assert.equal(結果.候補.length, 2);
    assert.equal(結果.最小, 1);
    assert.equal(結果.最大, 1);
  });

  await t.test('選択を返すと、そのカードが破壊される', () => {
    const { 試合: 試合インスタンス, インタプリタ } = 環境を作る();

    const 味方 = 場に出す(試合インスタンス, 'p1', グンガタを作成('自分1'), 5000);
    試合インスタンス.カードの表示形式管理.疲労する(味方);

    場に出す(試合インスタンス, 'p2', ゲン_ボーを作成('相手1'), 3000);
    場に出す(試合インスタンス, 'p2', ゲン_ボーを作成('相手2'), 2000);

    const 自身 = 場に出す(試合インスタンス, 'p1', グンガタを作成('ロワミーク'), 3000);
    const 中断 = インタプリタ.実行(ロワミーク効果, 自身, 'p1');
    assert.equal(中断.状態, '選択待ち');
    if (中断.状態 !== '選択待ち') return;

    const 結果 = インタプリタ.再開(中断.中断状態, ['相手1']);

    assert.equal(結果.状態, '完了');
    assert.equal(結果.状態 === '完了' && 結果.発動した, true);

    // 第1段階：選んだカードだけが破壊待ちになる
    assert.equal(破壊待ちか(試合インスタンス, 'p2', '相手1'), true, '選んだカードが破壊待ちになる');
    assert.equal(破壊待ちか(試合インスタンス, 'p2', '相手2'), false, '選ばなかったカードは無事');

    // 第2段階：進行側が解決するとトラッシュへ移る
    待機状態を解決する(試合インスタンス, 'p2');
    const 相手フィールド = 試合インスタンス.ゾーン管理.フィールドを取得(試合インスタンス.ゲーム, 'p2')!;
    const 相手トラッシュ = 試合インスタンス.ゾーン管理.トラッシュを取得(試合インスタンス.ゲーム, 'p2')!;
    assert.equal(相手フィールド.カードを取得('相手1'), undefined, '解決後は場から消える');
    assert.ok(相手トラッシュ.カードを取得('相手1'), 'トラッシュへ置かれる');
    assert.ok(相手フィールド.カードを取得('相手2'), '選ばなかったカードは場に残る');
  });

  await t.test('BP3000を超える相手は候補にならない', () => {
    const { 試合: 試合インスタンス, インタプリタ } = 環境を作る();

    const 味方 = 場に出す(試合インスタンス, 'p1', グンガタを作成('自分1'), 5000);
    試合インスタンス.カードの表示形式管理.疲労する(味方);

    場に出す(試合インスタンス, 'p2', グンガタを作成('相手大'), 8000);

    const 自身 = 場に出す(試合インスタンス, 'p1', グンガタを作成('ロワミーク'), 3000);
    const 結果 = インタプリタ.実行(ロワミーク効果, 自身, 'p1');

    // 候補ゼロなので中断せずに完了し、何も破壊されない
    assert.equal(結果.状態, '完了');
    const 相手フィールド = 試合インスタンス.ゾーン管理.フィールドを取得(試合インスタンス.ゲーム, 'p2')!;
    assert.ok(相手フィールド.カードを取得('相手大'), '対象外のカードは破壊されない');
  });

  await t.test('候補が1体しかなければ、確認を挟まず自動で確定する', () => {
    const { 試合: 試合インスタンス, インタプリタ } = 環境を作る();

    const 味方 = 場に出す(試合インスタンス, 'p1', グンガタを作成('自分1'), 5000);
    試合インスタンス.カードの表示形式管理.疲労する(味方);

    場に出す(試合インスタンス, 'p2', ゲン_ボーを作成('相手1'), 3000);

    const 自身 = 場に出す(試合インスタンス, 'p1', グンガタを作成('ロワミーク'), 3000);
    const 結果 = インタプリタ.実行(ロワミーク効果, 自身, 'p1');

    assert.equal(結果.状態, '完了', '選ぶ余地がないので中断しない');
    assert.equal(破壊待ちか(試合インスタンス, 'p2', '相手1'), true, '自動確定して破壊まで進む');
  });
});

