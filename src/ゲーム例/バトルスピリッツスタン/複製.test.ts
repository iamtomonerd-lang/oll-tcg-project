// 複製が壊れていると、先読みは**嘘の盤面を読む**。しかも静かに間違えるので、
// 「読んだ結果が変」ではなく「なんとなく弱い」としか見えない。
// ここで固定するのは次の3つ。
//
//   1. 複製した直後は本物と寸分たがわない
//   2. 複製に手を打っても本物は1ミリも動かない（漏れがない）
//   3. 本物と複製に同じ手を打てば、同じ盤面になる（写し忘れがない）

const 風牙のカード = カード帳.filter(x => !/^紫/.test(x.カード名));

function デッキを作る(接頭辞: string): カード[] {
  const デッキ: カード[] = [];
  for (let i = 0; i < 40; i++) {
    デッキ.push(風牙のカード[i % 風牙のカード.length].作る(`${接頭辞}-${i}`));
  }
  return デッキ;
}

// 試合をいくらか進めて、盤面に中身がある状態を作る。
// 開始直後の空っぽな盤面で複製を試すと、写し忘れがあっても通ってしまう。
function 進めた試合(種: number, 手数: number) {
  const 試合インスタンス = 試合を用意する(デッキを作る, 種);
  const AIマップ = new Map<string, 対戦相手>([
    ['p1', new 思考AI('p1', 'p2')],
    ['p2', new 練習用AI('p2', 'p1')],
  ]);
  // 対戦を進行する は決着まで走ってしまうので、途中で止まるよう手数で切る
  対戦を進行する(試合インスタンス, AIマップ, 手数);
  return { 試合インスタンス, AIマップ };
}

test('複製した直後は、本物と寸分たがわない', () => {
  for (const 種 of [1, 2, 3, 7, 11]) {
    const { 試合インスタンス } = 進めた試合(種, 12);
    const 複製 = 試合インスタンス.複製する(種);
    assert.equal(
      盤面の指紋(複製),
      盤面の指紋(試合インスタンス),
      `種${種}: 複製した直後から盤面が違う`
    );
  }
});

test('複製に手を打っても、本物は動かない', () => {
  const { 試合インスタンス } = 進めた試合(11, 12);
  const 複製前 = 盤面の指紋(試合インスタンス);

  const 複製 = 試合インスタンス.複製する(11);

  // 複製の上で、盤面が確実に変わることをする。
  // コアを動かし、カードを場から抜き、ライフを削る。
  const 複製のリザーブ = 複製.ゾーン管理.リザーブを取得(複製.ゲーム, 'p1')!;
  const 複製のトラッシュ = 複製.ゾーン管理.トラッシュを取得(複製.ゲーム, 'p1')!;
  複製.コアを移動する(複製のリザーブ, 複製のトラッシュ, 1);
  複製.降参する('p2');
  const 複製の場 = 複製.ゾーン管理.フィールドを取得(複製.ゲーム, 'p1')!;
  for (const c of [...複製の場.カード一覧を取得()]) {
    複製の場.カードを削除(c.識別子);
  }

  assert.notEqual(盤面の指紋(複製), 複製前, '前提：複製をいじったのに盤面が変わっていない');
  assert.equal(盤面の指紋(試合インスタンス), 複製前, '複製をいじったら本物まで変わった');
});

test('本物と複製に同じ手を打てば、同じ盤面になる', () => {
  // 写し忘れがあると、ここで初めて食い違う。
  // 見えない状態（〔ターン1回〕を使ったか・このターンにライフが減ったか・
  // 誘発の待ち行列）は、続きを打って初めて盤面に出てくるため。
  for (const 種 of [1, 3, 11]) {
    const { 試合インスタンス } = 進めた試合(種, 14);
    const 複製 = 試合インスタンス.複製する(種);

    const 続きを打つ = (対象: typeof 試合インスタンス) => {
      const AIマップ = new Map<string, 対戦相手>([
        ['p1', new 思考AI('p1', 'p2')],
        ['p2', new 練習用AI('p2', 'p1')],
      ]);
      対戦を進行する(対象, AIマップ, 30);
    };
    続きを打つ(試合インスタンス);
    続きを打つ(複製);

    assert.equal(
      盤面の指紋(複製),
      盤面の指紋(試合インスタンス),
      `種${種}: 同じ手を打ったのに盤面が食い違う（どこかの状態を写し忘れている）`
    );
  }
});

// === 見えない状態を1つずつ ===
//
// 上の3本だけでは足りなかった。写しの呼び出しを1行ずつ消して確かめたところ、
// **6つの管理すべてを消してもテストが通った**。
// 途中まで進めただけの盤面では、どの管理も中身が空だったため。
//
// 空のものを写しても写さなくても同じなのは当たり前で、
// あれは「複製できている」ではなく「何も入っていない」を見ていた。
// ここでは中身を入れてから複製し、複製側に届いているかを1つずつ見る。
test('見えない状態も複製に写る', async t => {
  const 空デッキを作る = (接頭辞: string): カード[] => {
    const デッキ: カード[] = [];
    for (let i = 0; i < 40; i++) デッキ.push(グンガタを作成(`${接頭辞}-${i}`));
    return デッキ;
  };

  await t.test('ターン履歴（このターンにライフが減ったか）', () => {
    const 試合インスタンス = 試合を用意する(空デッキを作る, 1);
    試合インスタンス.ターン履歴管理.記録する('ライフが減った', 'p1');
    assert.equal(試合インスタンス.ターン履歴管理.記録数を取得() > 0, true, '前提：記録が空');

    const 複製 = 試合インスタンス.複製する(1);
    assert.equal(
      複製.ターン履歴管理.起きたか('ライフが減った', 'p1'),
      true,
      'ターン履歴が写っていない（『このターンにライフが減っていたなら』が複製で嘘になる）'
    );
  });

  await t.test('〔ターン1回〕をもう使ったか', () => {
    const 試合インスタンス = 試合を用意する(空デッキを作る, 1);
    試合インスタンス.制限効果管理.ターン1回を記録する('カードA', '効果0', 1);
    assert.equal(
      試合インスタンス.制限効果管理.ターン1回は発揮可能か('カードA', '効果0', 1),
      false,
      '前提：記録できていない'
    );

    const 複製 = 試合インスタンス.複製する(1);
    assert.equal(
      複製.制限効果管理.ターン1回は発揮可能か('カードA', '効果0', 1),
      false,
      '〔ターン1回〕の記録が写っていない（複製の中で同じ効果を何度も撃ててしまう）'
    );
  });

  await t.test('期限付きのBP補正', () => {
    const 試合インスタンス = 試合を用意する(空デッキを作る, 1);
    const 場 = 試合インスタンス.ゾーン管理.フィールドを取得(試合インスタンス.ゲーム, 'p1')!;
    const 味方 = グンガタを作成('p1-味方');
    場.カードを追加(味方);
    試合インスタンス.BP管理.BPを設定(味方, 5000);
    試合インスタンス.一時効果管理.BP変更を記録する(味方, 3000, 'このターン中');
    assert.equal(試合インスタンス.一時効果管理.記録数を取得() > 0, true, '前提：記録が空');

    const 複製 = 試合インスタンス.複製する(1);
    assert.equal(複製.一時効果管理.記録数を取得(), 1, 'BP補正の記録が写っていない');

    // 記録が写っていても、指している先が本物のカードのままだと
    // 期限が切れたときに複製のカードが元に戻らない。そこまで見る。
    const 複製の味方 = 複製.ゾーン管理
      .フィールドを取得(複製.ゲーム, 'p1')!
      .カードを取得('p1-味方')!;
    const 戻す前 = 複製.BP管理.現在のBPを取得(複製の味方);
    複製.一時効果管理.期限切れを解除する('このターン中');
    const 戻した後 = 複製.BP管理.現在のBPを取得(複製の味方);
    assert.notEqual(戻した後, 戻す前, 'BP補正の記録が複製のカードを指していない');
  });

  await t.test('誘発の待ち行列', () => {
    const 試合インスタンス = 試合を用意する(空デッキを作る, 1);
    const 場 = 試合インスタンス.ゾーン管理.フィールドを取得(試合インスタンス.ゲーム, 'p1')!;
    const 味方 = グンガタを作成('p1-味方');
    場.カードを追加(味方);
    試合インスタンス.誘発型効果管理.誘発する('p1-味方#0', 味方, 'p1', '試し');
    assert.equal(試合インスタンス.誘発型効果管理.空か(), false, '前提：待ち行列が空');

    const 複製 = 試合インスタンス.複製する(1);
    assert.equal(複製.誘発型効果管理.空か(), false, '誘発の待ち行列が写っていない');

    // 発揮源が複製のカードを指していること（本物を指していたら別の盤面を見て解決する）
    const 複製の発揮源 = 複製.誘発型効果管理.キューを取得()[0].発揮源;
    const 複製の味方 = 複製.ゾーン管理
      .フィールドを取得(複製.ゲーム, 'p1')!
      .カードを取得('p1-味方')!;
    assert.equal(複製の発揮源, 複製の味方, '誘発の発揮源が本物のカードを指したままになっている');
  });

  await t.test('期限付きの制約（「〜されない」）', () => {
    const 試合インスタンス = 試合を用意する(空デッキを作る, 1);
    const 場 = 試合インスタンス.ゾーン管理.フィールドを取得(試合インスタンス.ゲーム, 'p1')!;
    const 味方 = グンガタを作成('p1-味方');
    場.カードを追加(味方);
    試合インスタンス.常在効果管理.制約を登録する({
      名: 'ブロックされない',
      対象: 味方,
      所有者識別子: 'p1',
      相手: undefined,
      期限: 'このターン中',
    } as any);
    assert.equal(試合インスタンス.常在効果管理.登録数を取得(), 1, '前提：登録できていない');

    const 複製 = 試合インスタンス.複製する(1);
    assert.equal(複製.常在効果管理.登録数を取得(), 1, '期限付きの制約が写っていない');

    // 対象が複製のカードを指していること。
    // 本物を指したままだと、複製の中で「別のカードにかかった制約」になる。
    const 複製の味方 = 複製.ゾーン管理
      .フィールドを取得(複製.ゲーム, 'p1')!
      .カードを取得('p1-味方')!;
    assert.equal(
      複製.常在効果管理.制約が働いているか('ブロックされない', { 対象: 複製の味方 } as any),
      true,
      '制約が複製のカードを指していない'
    );
  });

  await t.test('置換した事象', () => {
    const 試合インスタンス = 試合を用意する(空デッキを作る, 1);
    試合インスタンス.置換型効果管理.置換を適用する('事象A', {} as any);
    assert.equal(試合インスタンス.置換型効果管理.適用可能か('事象A'), false, '前提：記録できていない');

    const 複製 = 試合インスタンス.複製する(1);
    assert.equal(
      複製.置換型効果管理.適用可能か('事象A'),
      false,
      '置換済みの記録が写っていない（複製で同じ置換が二重にかかる）'
    );
  });
});

test('効果の答え待ちの最中は複製を断る', () => {
  // 途中で複製すると「誰に何を聞いていたか」を取り違える。
  // 黙って壊れた複製を返すより、断るほうがよい。
  const 試合インスタンス = 試合を用意する(接頭辞 => {
    const デッキ: カード[] = [];
    for (let i = 0; i < 40; i++) デッキ.push(グンガタを作成(`${接頭辞}-${i}`));
    return デッキ;
  }, 1);

  // 本物の経路で選択待ちを作る。
  // ロワミークの『召喚時』は、疲労した自分の赤スピリットがいると相手を選ばせる。
  // 候補が2体ないと自動で決まってしまい、選択待ちにならない。
  const 味方 = グンガタを作成('p1-味方');
  試合インスタンス.ゾーン管理.フィールドを取得(試合インスタンス.ゲーム, 'p1')!.カードを追加(味方);
  試合インスタンス.BP管理.BPを設定(味方, 5000);
  試合インスタンス.カードの表示形式管理.疲労する(味方);
  for (const 識別子 of ['p2-標的A', 'p2-標的B']) {
    const 標的 = グンガタを作成(識別子);
    試合インスタンス.ゾーン管理.フィールドを取得(試合インスタンス.ゲーム, 'p2')!.カードを追加(標的);
    試合インスタンス.BP管理.BPを設定(標的, 3000);
  }
  const ロワミーク = ロワミークを作成('p1-ロワミーク');
  試合インスタンス.ゾーン管理.フィールドを取得(試合インスタンス.ゲーム, 'p1')!.カードを追加(ロワミーク);
  試合インスタンス.効果実行器.事象を通知する('召喚時', ロワミーク);
  試合インスタンス.効果実行器.キューを進める();

  assert.equal(試合インスタンス.効果実行器.選択待ちか(), true, '前提：選択待ちになっていない');
  assert.throws(() => 試合インスタンス.複製する(1), /答え待ち/);
});
