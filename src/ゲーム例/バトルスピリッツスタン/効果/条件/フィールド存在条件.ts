import { カード } from '../../../../データ/カード/カード.js';
import { プレイヤー } from '../../../../データ/プレイヤー/プレイヤー.js';
import { 効果条件 } from '../条件.js';
import { ゾーン管理 } from '../../管理/ゾーン管理.js';
import { ゲームエンジン } from '../../../../ゲームエンジン.js';

// 単一カードの判定関数型
export type カード判定 = (カード: カード) => boolean;

// フィールド存在条件
// 指定された複数の判定条件をすべて満たすカードがフィールドに存在するかを判定する
// 「疲労状態の自分の赤のスピリットがいるなら」のような複合条件に対応
export class フィールド存在条件 extends 効果条件 {
  private 判定条件一覧: カード判定[];
  private ゾーン管理: ゾーン管理;

  constructor(名前: string, ...判定条件一覧: カード判定[]) {
    super(`field-exists-${名前}`, `${名前}がフィールドに存在`);
    this.判定条件一覧 = 判定条件一覧;
    this.ゾーン管理 = new ゾーン管理();
  }

  判定(カード?: カード, プレイヤー?: プレイヤー): boolean {
    if (!プレイヤー) return false;

    // プレイヤーの試合インスタンスを取得する方法がないため、
    // ここではプレイヤーから直接ゲーム情報を取得することは不可
    // 呼び出し側で適切なコンテキストを提供する必要があります

    // 暫定実装：プレイヤーのゲーム情報がアクセスできるまで false を返す
    // 実際の実装では、効果実行文脈からゲーム情報を取得します
    return false;
  }

  // ゲーム情報を直接受け取るバージョン
  フィールドに存在するか(ゲーム: ゲームエンジン, プレイヤー識別子: string): boolean {
    const フィールド = this.ゾーン管理.フィールドを取得(ゲーム, プレイヤー識別子);
    if (!フィールド) {
      return false;
    }

    // フィールド内のカードを走査し、すべての判定条件を満たすカードが存在するかチェック
    for (const カード of フィールド.カード一覧を取得()) {
      if (this.すべての条件を満たすか(カード)) {
        return true;
      }
    }

    return false;
  }

  private すべての条件を満たすか(カード: カード): boolean {
    return this.判定条件一覧.every(判定 => 判定(カード));
  }
}
