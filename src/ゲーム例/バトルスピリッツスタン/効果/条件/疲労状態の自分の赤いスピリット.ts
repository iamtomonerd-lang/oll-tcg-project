import { 効果条件 } from '../条件.js';
import { フィールド存在条件 } from './フィールド存在条件.js';
import { 表示形式判定 } from '../../判定/表示形式判定.js';
import { 属性ルール } from '../../カードの情報/属性.js';
import { カード種別ルール } from '../../カードの情報/カード種別.js';
import { ゲームエンジン } from '../../../../ゲームエンジン.js';
import { プレイヤー } from '../../../../データ/プレイヤー/プレイヤー.js';

// 「疲労状態の自分の赤のスピリットがいるなら」という複合条件
// 自分のフィールドから疲労状態で赤いスピリットを検索
export class 疲労状態の自分の赤いスピリット条件 extends 効果条件 {
  private フィールド検索: フィールド存在条件;
  private 表示形式判定: 表示形式判定;
  private 属性ルール: 属性ルール;
  private カード種別ルール: カード種別ルール;

  constructor() {
    super('tired-red-spirit-self', '疲労状態の自分の赤いスピリットが存在');

    this.表示形式判定 = new 表示形式判定();
    this.属性ルール = new 属性ルール();
    this.カード種別ルール = new カード種別ルール();

    // Layer 1：カード判定
    const 疲労状態か = (カード: any) => this.表示形式判定.疲労か(カード);
    const 赤いスピリットか = (カード: any) =>
      this.カード種別ルール.スピリットか(カード) &&
      this.属性ルール.属性を持つ(カード, '赤');

    // Layer 2：フィールド検索
    this.フィールド検索 = new フィールド存在条件(
      'tired-red-spirit-self',
      疲労状態か,
      赤いスピリットか
    );
  }

  判定(カード?: any, プレイヤー?: プレイヤー): boolean {
    // 基本インターフェースは実装しない - フィールド検索版を使用
    return false;
  }

  // 自分のフィールドで条件を満たすカードが存在するか判定
  存在するか(ゲーム: ゲームエンジン, プレイヤー識別子: string): boolean {
    return this.フィールド検索.フィールドに存在するか(ゲーム, プレイヤー識別子);
  }
}
