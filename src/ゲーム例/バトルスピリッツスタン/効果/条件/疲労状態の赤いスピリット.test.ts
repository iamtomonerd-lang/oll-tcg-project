import { test } from 'node:test';
import assert from 'node:assert';
import { 疲労状態の赤いスピリット条件 } from './疲労状態の赤いスピリット.js';
import { ゲームエンジン } from '../../../../ゲームエンジン.js';
import { プレイヤー } from '../../../../データ/プレイヤー/プレイヤー.js';
import { グンガタを作成 } from '../../カードデータ/グンガタ.js';
import { ムーシャッコを作成 } from '../../カードデータ/ムーシャッコ.js';
import { ゾーン管理 as ゾーン管理クラス } from '../../管理/ゾーン管理.js';

function 試合環境を準備() {
  const ゲーム = new ゲームエンジン();
  const ゾーン管理 = new ゾーン管理クラス();
  const p1 = new プレイヤー('player-1', 'プレイヤー1');
  ゲーム.プレイヤーを追加(p1);
  ゾーン管理.プレイヤーの領域を生成(ゲーム, 'player-1', 5);
  return { ゲーム, ゾーン管理 };
}

test('疲労状態の赤いスピリット条件', async (t) => {
  await t.test('疲労状態の赤いスピリットが存在しない場合はfalse', () => {
    const { ゲーム, ゾーン管理 } = 試合環境を準備();
    const 条件 = new 疲労状態の赤いスピリット条件();

    assert.equal(条件.存在するか(ゲーム, 'player-1'), false);
  });

  await t.test('赤いスピリットが存在するが回復状態の場合はfalse', () => {
    const { ゲーム, ゾーン管理 } = 試合環境を準備();
    const カード = グンガタを作成('test-1');
    const 条件 = new 疲労状態の赤いスピリット条件();

    const フィールド = ゾーン管理.フィールドを取得(ゲーム, 'player-1');
    if (フィールド) {
      フィールド.カードを追加(カード);
      // カードは初期状態で回復状態
    }

    assert.equal(条件.存在するか(ゲーム, 'player-1'), false);
  });

  await t.test('疲労状態の赤いスピリットが存在する場合はtrue', () => {
    const { ゲーム, ゾーン管理 } = 試合環境を準備();
    const カード = グンガタを作成('test-1');
    const 条件 = new 疲労状態の赤いスピリット条件();

    const フィールド = ゾーン管理.フィールドを取得(ゲーム, 'player-1');
    if (フィールド) {
      フィールド.カードを追加(カード);
      // カードを疲労状態に設定
      カード.状態を設定('表示形式', '疲労');
    }

    assert.equal(条件.存在するか(ゲーム, 'player-1'), true);
  });

  await t.test('複数のスピリットがあり、1つだけが疲労状態の赤の場合はtrue', () => {
    const { ゲーム, ゾーン管理 } = 試合環境を準備();
    const カード1 = グンガタを作成('test-1');
    const カード2 = ムーシャッコを作成('test-2');
    const 条件 = new 疲労状態の赤いスピリット条件();

    const フィールド = ゾーン管理.フィールドを取得(ゲーム, 'player-1');
    if (フィールド) {
      フィールド.カードを追加(カード1); // グンガタ：赤のスピリット
      カード1.状態を設定('表示形式', '回復'); // 回復状態

      フィールド.カードを追加(カード2); // ムーシャッコ：赤のスピリット
      カード2.状態を設定('表示形式', '疲労'); // 疲労状態
    }

    assert.equal(条件.存在するか(ゲーム, 'player-1'), true);
  });

  await t.test('複数の赤いスピリットがあり、1つが疲労状態の場合はtrue', () => {
    const { ゲーム, ゾーン管理 } = 試合環境を準備();
    const カード1 = グンガタを作成('test-1');
    const カード2 = グンガタを作成('test-2');
    const 条件 = new 疲労状態の赤いスピリット条件();

    const フィールド = ゾーン管理.フィールドを取得(ゲーム, 'player-1');
    if (フィールド) {
      フィールド.カードを追加(カード1);
      カード1.状態を設定('表示形式', '回復');

      フィールド.カードを追加(カード2);
      カード2.状態を設定('表示形式', '疲労');
    }

    assert.equal(条件.存在するか(ゲーム, 'player-1'), true);
  });

  await t.test('重疲労状態の赤いスピリットの場合はfalse', () => {
    const { ゲーム, ゾーン管理 } = 試合環境を準備();
    const カード = グンガタを作成('test-1');
    const 条件 = new 疲労状態の赤いスピリット条件();

    const フィールド = ゾーン管理.フィールドを取得(ゲーム, 'player-1');
    if (フィールド) {
      フィールド.カードを追加(カード);
      カード.状態を設定('表示形式', '重疲労');
    }

    assert.equal(条件.存在するか(ゲーム, 'player-1'), false);
  });
});
