import { 効果, 効果実行文脈, 効果結果 } from '../../../../効果処理/効果.js';
import { デッキ管理 } from '../../管理/デッキ管理.js';
import { ゲームエンジン } from '../../../../ゲームエンジン.js';

// ドロー効果
// 指定された枚数だけカードをドローする
export class ドロー効果 extends 効果 {
  private デッキ管理: デッキ管理;

  constructor(private ドロー枚数: number) {
    super('draw', `${ドロー枚数}枚ドロー`);
    this.デッキ管理 = new デッキ管理();
  }

  async 実行(文脈: 効果実行文脈): Promise<効果結果> {
    const ゲーム = 文脈.ゲーム as ゲームエンジン;
    const 所有者 = 文脈.追加データ?.所有者識別子 as string;

    if (!ゲーム || !所有者) {
      return { 成功: false, メッセージ: 'ゲーム参照または所有者が指定されていません' };
    }

    const 実際にドローした枚数 = this.デッキ管理.ドローする(ゲーム, 所有者, this.ドロー枚数);

    if (実際にドローした枚数 === 0) {
      return { 成功: false, メッセージ: 'デッキが空のためドローできません' };
    }

    return {
      成功: true,
      メッセージ: `${実際にドローした枚数}枚ドローしました`,
      データ: { ドロー枚数: 実際にドローした枚数 },
    };
  }
}
