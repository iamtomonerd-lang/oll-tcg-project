import { 効果実行文脈, 効果結果 } from '../../../../効果処理/効果.js';
import { カード } from '../../../../データ/カード/カード.js';
import { ゲームエンジン } from '../../../../ゲームエンジン.js';
import { 対象選択効果 } from './対象選択効果.js';
import { BP管理 } from '../../管理/BP管理.js';
import { カード種別ルール } from '../../カードの情報/カード種別.js';

// 「BP3000以下の相手のスピリット1体を指定する」効果の実装例
// Layer 1（カード判定）を組み合わせて対象を選択
export class BP制限相手スピリット指定効果 extends 対象選択効果 {
  private BP管理: BP管理;
  private カード種別ルール: カード種別ルール;

  constructor(private BP上限: number) {
    // BP管理とカード種別ルールのインスタンスを先に作成
    const bp管理 = new BP管理();
    const カード種別 = new カード種別ルール();

    // Layer 1：各判定条件
    const BP条件 = (カード: カード) => bp管理.現在のBPを取得(カード) <= BP上限;
    const スピリット条件 = (カード: カード) => カード種別.スピリットか(カード);

    super(
      `target-bp-limit-${BP上限}`,
      `BP${BP上限}以下の相手のスピリット1体を指定`,
      [BP条件, スピリット条件],
      1 // 選択個数：1体
    );

    this.BP管理 = bp管理;
    this.カード種別ルール = カード種別;
  }

  protected async 対象を選択して実行(
    ゲーム: ゲームエンジン,
    候補: カード[],
    文脈: 効果実行文脈
  ): Promise<効果結果> {
    // 候補から選択されたカード（文脈の対象）を取得
    const 選択されたカード = 文脈.対象 as カード;

    if (!選択されたカード) {
      return { 成功: false, メッセージ: '対象カードが選択されていません' };
    }

    // 選択されたカードが候補に含まれているか確認
    if (!候補.some((c) => c.識別子 === 選択されたカード.識別子)) {
      return { 成功: false, メッセージ: '無効な対象が選択されました' };
    }

    const BP = this.BP管理.現在のBPを取得(選択されたカード);

    return {
      成功: true,
      メッセージ: `${選択されたカード.名称.表示名}（BP${BP}）を対象に指定しました`,
      データ: { 対象カード: 選択されたカード.識別子, BP },
    };
  }
}
