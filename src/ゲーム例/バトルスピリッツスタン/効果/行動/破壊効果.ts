import { 効果, 効果実行文脈, 効果結果 } from '../../../../効果処理/効果.js';
import { カード } from '../../../../データ/カード/カード.js';
import { 破壊管理 } from '../../管理/破壊管理.js';
import { ゲームエンジン } from '../../../../ゲームエンジン.js';

// 破壊効果
// 指定されたカードを破壊する
export class 破壊効果 extends 効果 {
  private 破壊管理: 破壊管理;

  constructor() {
    super('destroy', 'それを破壊する');
    this.破壊管理 = new 破壊管理();
  }

  async 実行(文脈: 効果実行文脈): Promise<効果結果> {
    const 対象カード = 文脈.対象 as カード;

    if (!対象カード) {
      return { 成功: false, メッセージ: '対象カードが指定されていません' };
    }

    // 破壊管理で対象カードを破壊（自分の効果による破壊として記録）
    const 破壊成功 = this.破壊管理.破壊する(対象カード, {
      由来: '自分の効果',
      効果識別子: this.識別子,
    });

    if (!破壊成功) {
      return { 成功: false, メッセージ: `${対象カード.名称.表示名}の破壊に失敗しました` };
    }

    return {
      成功: true,
      メッセージ: `${対象カード.名称.表示名}を破壊しました`,
      データ: { 破壊されたカード: 対象カード.識別子 },
    };
  }
}
