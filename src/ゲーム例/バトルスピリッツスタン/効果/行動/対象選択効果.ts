import { 効果, 効果実行文脈, 効果結果 } from '../../../../効果処理/効果.js';
import { カード } from '../../../../データ/カード/カード.js';
import { ゲームエンジン } from '../../../../ゲームエンジン.js';
import { ゾーン管理 } from '../../管理/ゾーン管理.js';

// カード判定関数型 - 単一カードが条件を満たすか判定
export type カード判定 = (カード: カード) => boolean;

// 対象選択効果（基盤クラス）
// 複数の判定条件をすべて満たすカードから、指定された個数分を選択する
// Layer 1（カード判定）：個別カードが条件を満たすか
// Layer 2（フィルタリング）：フィールドから条件を満たすカードを抽出＆個数制限
export abstract class 対象選択効果 extends 効果 {
  protected ゾーン管理: ゾーン管理;

  constructor(
    識別子: string,
    名前: string,
    protected 判定条件一覧: カード判定[],
    protected 選択個数: number
  ) {
    super(識別子, 名前);
    this.ゾーン管理 = new ゾーン管理();
  }

  // 対象となるカード候補を取得
  protected 対象候補を取得(ゲーム: ゲームエンジン, プレイヤー識別子: string): カード[] {
    const フィールド = this.ゾーン管理.フィールドを取得(ゲーム, プレイヤー識別子);
    if (!フィールド) {
      return [];
    }

    const 候補 = [];
    for (const カード of フィールド.カード一覧を取得()) {
      if (this.すべての条件を満たすか(カード)) {
        候補.push(カード);
      }
    }

    return 候補;
  }

  // すべての判定条件を満たすか
  private すべての条件を満たすか(カード: カード): boolean {
    return this.判定条件一覧.every((判定) => 判定(カード));
  }

  // 選択個数が有効か
  protected 選択可能か(候補: カード[]): boolean {
    return 候補.length >= this.選択個数;
  }

  // 実行：対象候補を取得して、実装クラスに判定を委譲
  async 実行(文脈: 効果実行文脈): Promise<効果結果> {
    const ゲーム = 文脈.ゲーム as ゲームエンジン;
    const 対象プレイヤー識別子 = 文脈.追加データ?.対象プレイヤー識別子 as string;

    if (!ゲーム || !対象プレイヤー識別子) {
      return { 成功: false, メッセージ: 'ゲーム参照または対象プレイヤーが指定されていません' };
    }

    const 候補 = this.対象候補を取得(ゲーム, 対象プレイヤー識別子);

    if (!this.選択可能か(候補)) {
      return {
        成功: false,
        メッセージ: `条件を満たすカードが${this.選択個数}体以上見つかりません（見つかった数：${候補.length}）`,
      };
    }

    // 実装クラスで対象を選択する処理を実行
    return this.対象を選択して実行(ゲーム, 候補, 文脈);
  }

  // 実装クラスで実装：対象を選択して実行
  protected abstract 対象を選択して実行(
    ゲーム: ゲームエンジン,
    候補: カード[],
    文脈: 効果実行文脈
  ): Promise<効果結果>;
}
