// 試合で使う乱数
//
// シャッフルに Math.random を直に呼ぶと、種を決めても試合を再現できない。
// 「同じ種なら同じ試合になる」ようにしておくと、
//   ・テストが毎回同じ結果になる（たまたま落ちる／たまたま通るが無くなる）
//   ・落ちたときに種だけ控えれば、その試合をそのまま作り直せる
// という2つが得られる。
//
// 種を渡さなければ Math.random のままなので、実際の対戦の引きは毎回変わる。

export type 乱数 = () => number;

// 線形合同法。暗号用途ではないが、シャッフルの再現には十分。
export function 種から乱数を作る(種: number): 乱数 {
  let 状態 = 種 >>> 0;
  return () => {
    状態 = (状態 * 1664525 + 1013904223) >>> 0;
    return 状態 / 0x100000000;
  };
}

export const 既定の乱数: 乱数 = () => Math.random();
