import { ゲームエンジン } from '../../../ゲームエンジン.js';
import { プレイヤー } from '../../../データ/プレイヤー/プレイヤー.js';

export interface 勝利結果 {
  勝利: boolean;
  勝者: プレイヤー | null;
  敗者: プレイヤー | null;
  理由: string;
}

export class バトルスピリッツ勝利判定 {
  勝利判定(ゲーム: ゲームエンジン, デッキゾーン識別子マップ: Map<string, string>): 勝利結果 {
    const プレイヤー一覧 = ゲーム.全プレイヤーを取得();

    if (プレイヤー一覧.length < 2) {
      return { 勝利: false, 勝者: null, 敗者: null, 理由: 'プレイヤーが2人以上必要です' };
    }

    for (const プレイヤー of プレイヤー一覧) {
      const 現在フェーズ = ゲーム.現在のフェーズを取得();
      const ライフ = プレイヤー.ライフを取得();

      // 条件1: 相手のライフが0になった
      if (ライフ <= 0) {
        const 相手 = プレイヤー一覧.find(p => p.識別子 !== プレイヤー.識別子);
        return {
          勝利: true,
          勝者: 相手 || null,
          敗者: プレイヤー,
          理由: `${プレイヤー.名前} のライフが0になりました`,
        };
      }

      // 条件2: スタートステップに相手のデッキが0枚
      if (現在フェーズ && 現在フェーズ.名前 === 'スタートステップ') {
        const デッキゾーン識別子 = デッキゾーン識別子マップ.get(プレイヤー.識別子);
        if (デッキゾーン識別子) {
          const デッキゾーン = ゲーム.ゾーンを取得(デッキゾーン識別子);
          if (デッキゾーン && デッキゾーン.カード枚数を取得() === 0) {
            const 相手 = プレイヤー一覧.find(p => p.識別子 !== プレイヤー.識別子);
            return {
              勝利: true,
              勝者: 相手 || null,
              敗者: プレイヤー,
              理由: `${プレイヤー.名前} のデッキが0枚になりました`,
            };
          }
        }
      }
    }

    return { 勝利: false, 勝者: null, 敗者: null, 理由: 'ゲーム続行中' };
  }
}
