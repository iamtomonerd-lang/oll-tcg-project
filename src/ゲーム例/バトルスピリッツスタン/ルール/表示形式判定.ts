import { カード } from '../../../データ/カード/カード.js';

// カードの表示形式（公式ルールの名称）
// フィールドのカードは常にいずれか1つを持つ（排他）
// UI/UXの向きなどの表示データは持たず、状態の識別のみに用いる
export type カードの表示形式 = '回復' | '疲労' | '重疲労';

// 表示形式判定（ルール層）
// カードの現在の表示形式を読み取り、状態を返すだけ（遷移はしない）
export class 表示形式判定 {
  // 現在の表示形式を取得（未設定時は回復を既定とする ※初期状態の正式定義は詳細待ち）
  現在の表示形式を取得(カード: カード): カードの表示形式 {
    const 値 = カード.状態を取得('表示形式');
    if (値 === '疲労' || 値 === '重疲労') {
      return 値;
    }
    return '回復';
  }

  回復か(カード: カード): boolean {
    return this.現在の表示形式を取得(カード) === '回復';
  }

  疲労か(カード: カード): boolean {
    return this.現在の表示形式を取得(カード) === '疲労';
  }

  重疲労か(カード: カード): boolean {
    return this.現在の表示形式を取得(カード) === '重疲労';
  }
}
