import { test } from 'node:test';
import assert from 'node:assert';
import { 試合 } from './試合.js';
import { グンガタを作成 } from './カードデータ/グンガタ.js';
import { ロワミークを作成 } from './カードデータ/ロワミーク.js';
import { 種から乱数を作る } from './乱数.js';

// デッキのシャッフルが Math.random 直呼びだったころ、種を決めても試合は再現できなかった。
// 自動対戦テストは種を固定していたのに引きだけが毎回変わるため、
// 「たまたま落ちる／たまたま通る」が起きていた。ここはその再発を止めるための固定。

test('種から乱数を作る：同じ種なら同じ並びを返す', () => {
  const a = 種から乱数を作る(1234);
  const b = 種から乱数を作る(1234);
  const c = 種から乱数を作る(9999);

  const 取り出す = (乱数: () => number) => Array.from({ length: 8 }, () => 乱数());

  assert.deepEqual(取り出す(a), 取り出す(b), '同じ種なら同じ');
  assert.notDeepEqual(取り出す(種から乱数を作る(1234)), 取り出す(c), '種が違えば違う');
});

test('種から乱数を作る：0以上1未満に収まる', () => {
  const 乱数 = 種から乱数を作る(7);
  for (let i = 0; i < 200; i++) {
    const 値 = 乱数();
    assert.ok(値 >= 0 && 値 < 1, `範囲外の値が出た: ${値}`);
  }
});

// 見分けのつくデッキ（グン＝ガタとロワミークの混成）を積んで、
// シャッフル後の並びを識別子で見る。
function デッキの並びを取る(種?: number): string[] {
  const 試合インスタンス = new 試合(種);
  試合インスタンス.プレイヤーを準備する('p1', 'プレイヤー1');
  試合インスタンス.プレイヤーを準備する('p2', 'プレイヤー2');
  試合インスタンス.ボイドを準備する();

  const デッキ = Array.from({ length: 30 }, (_, i) =>
    i % 3 === 0 ? ロワミークを作成(`r${i}`) : グンガタを作成(`g${i}`)
  );
  試合インスタンス.デッキを設定する('p1', デッキ);
  試合インスタンス.デッキを設定する(
    'p2',
    Array.from({ length: 30 }, (_, i) => グンガタを作成(`p2-${i}`))
  );
  試合インスタンス.準備を行う('p1');
  試合インスタンス.準備を行う('p2');

  // 準備で手札に流れたぶんも含めて、引いた順が分かるように手札＋デッキで見る
  const 手札 = 試合インスタンス.ゾーン管理
    .手札を取得(試合インスタンス.ゲーム, 'p1')!
    .カード一覧を取得()
    .map(c => c.識別子);
  const 残り = 試合インスタンス.ゾーン管理
    .デッキエリアを取得(試合インスタンス.ゲーム, 'p1')!
    .カード一覧を取得()
    .map(c => c.識別子);
  return [...手札, ...残り];
}

test('試合：同じ種なら同じ試合になる', async t => {
  await t.test('同じ種を渡せばデッキの並びが一致する', () => {
    assert.deepEqual(デッキの並びを取る(2024), デッキの並びを取る(2024));
  });

  await t.test('違う種なら並びが変わる', () => {
    assert.notDeepEqual(デッキの並びを取る(2024), デッキの並びを取る(2025));
  });

  // 種を渡さないときは Math.random のまま。実際の対戦は毎回違う引きになる。
  await t.test('種を渡さなければ毎回変わる', () => {
    const 並び一覧 = Array.from({ length: 5 }, () => デッキの並びを取る().join(','));
    assert.ok(
      new Set(並び一覧).size > 1,
      '種なしで5回引いて全部同じ並びになるのは、シャッフルが効いていない'
    );
  });
});
