function 試合を準備する(): 試合 {
  const 試合インスタンス = new 試合();
  試合インスタンス.プレイヤーを準備する('p1', 'プレイヤー1');
  試合インスタンス.プレイヤーを準備する('p2', 'プレイヤー2');
  試合インスタンス.ボイドを準備する();
  試合インスタンス.デッキを設定する(
    'p1',
    Array.from({ length: 10 }, (_, i) => グンガタを作成(`p1-deck-${i + 1}`))
  );
  試合インスタンス.デッキを設定する(
    'p2',
    Array.from({ length: 10 }, (_, i) => グンガタを作成(`p2-deck-${i + 1}`))
  );
  試合インスタンス.準備を行う('p1');
  試合インスタンス.準備を行う('p2');
  試合インスタンス.先攻を決める('p1');
  試合インスタンス.試合を開始する();
  return 試合インスタンス;
}

function 場に出す(試合インスタンス: 試合, 識別子: string, カード: any, BP?: number) {
  試合インスタンス.ゾーン管理.フィールドを取得(試合インスタンス.ゲーム, 識別子)!.カードを追加(カード);
  // 場のカードには必ずコアが乗っている。乗せずに置くと、ルール処理の消滅判定に
  // 引っかかって即トラッシュ行きになる（実戦では起こらない状態）。
  // Lv1を保てる最小限だけ乗せる。Lvを変えたいテストは、このあとで自分で乗せ直す。
  試合インスタンス.コア管理
    .カードを保持者に(カード)
    .コア数を設定(new 消滅判定().最小必要コア数を取得(カード));
  if (BP !== undefined) 試合インスタンス.BP管理.BPを設定(カード, BP);
  return カード;
}

// マジックはどのゾーンにも属さないまま解決する（11-3-1-6）。
// 1枚で［メイン］と［フラッシュ］の2つの撃ち方を持つので、どちらで撃つかを渡す。
function 使う(試合インスタンス: 試合, タイミング: 'メイン' | 'フラッシュ') {
  const 呪文 = ブレイククローを作成('ブレイククロー');
  return 試合インスタンス.効果実行器.使用効果を発動する(呪文, 'p1', タイミング);
}

const リザーブのコア数 = (試合インスタンス: 試合): number =>
  試合インスタンス.コア管理
    .ゾーンを保持者に(試合インスタンス.ゾーン管理.リザーブを取得(試合インスタンス.ゲーム, 'p1')!)
    .コア数を取得();

function トラッシュにコアを積む(試合インスタンス: 試合, 通常コア: number, ソウルコア = false) {
  const トラッシュ = 試合インスタンス.ゾーン管理.トラッシュを取得(試合インスタンス.ゲーム, 'p1')!;
  const 保持者 = 試合インスタンス.コア管理.ゾーンを保持者に(トラッシュ);
  保持者.コア数を設定(通常コア + (ソウルコア ? 1 : 0));
  保持者.ソウルコアを設定(ソウルコア);
}

// 破壊は「待機状態にする → トラッシュへ置く」の2段階。
// 最後まで、つまり場から消えてトラッシュにあることを見る。
const 破壊されたか = (試合インスタンス: 試合, 識別子: string): boolean => {
  const 場 = 試合インスタンス.ゾーン管理.フィールドを取得(試合インスタンス.ゲーム, 'p2')!;
  const トラッシュ = 試合インスタンス.ゾーン管理.トラッシュを取得(試合インスタンス.ゲーム, 'p2')!;
  return !場.カードを取得(識別子) && !!トラッシュ.カードを取得(識別子);
};

test('ブレイククロー［メイン］：真界放していない相手のネクサスを破壊する', async t => {
  // 「真界放していない」の部分。最奥：風牙岩はLv2で真界放状態になる。
  await t.test('真界放しているネクサスは対象にならない', () => {
    const 試合インスタンス = 試合を準備する();
    const 真界放中 = 場に出す(試合インスタンス, 'p2', 最奥_風牙岩を作成('真界放中'));
    試合インスタンス.Lv管理.Lvを上げる(真界放中, 2);
    // 浮遊岩域は真界放を持たないので、Lvに関わらず対象になる
    場に出す(試合インスタンス, 'p2', 浮遊岩域を作成('真界放でない'));

    使う(試合インスタンス, 'メイン');

    assert.equal(破壊されたか(試合インスタンス, '真界放でない'), true, '真界放していない方が壊れる');
    assert.equal(破壊されたか(試合インスタンス, '真界放中'), false, '真界放中は守られる');
  });

  await t.test('Lv1の真界放持ちは、まだ真界放状態でないので対象になる', () => {
    const 試合インスタンス = 試合を準備する();
    const 岩 = 場に出す(試合インスタンス, 'p2', 最奥_風牙岩を作成('Lv1の岩'));
    試合インスタンス.Lv管理.Lvを上げる(岩, 1);

    使う(試合インスタンス, 'メイン');

    assert.equal(破壊されたか(試合インスタンス, 'Lv1の岩'), true);
  });

  await t.test('疲労した赤の味方がいれば、その後トラッシュのコアがリザーブに戻る', () => {
    const 試合インスタンス = 試合を準備する();
    場に出す(試合インスタンス, 'p2', 浮遊岩域を作成('相手ネクサス'));
    const 味方 = 場に出す(試合インスタンス, 'p1', グンガタを作成('赤の味方'), 5000);
    試合インスタンス.カードの表示形式管理.疲労する(味方);
    トラッシュにコアを積む(試合インスタンス, 2);
    const 元のリザーブ = リザーブのコア数(試合インスタンス);

    使う(試合インスタンス, 'メイン');

    assert.equal(破壊されたか(試合インスタンス, '相手ネクサス'), true);
    assert.equal(リザーブのコア数(試合インスタンス), 元のリザーブ + 1, 'コア1個が戻る');
  });

  await t.test('味方が回復状態なら、破壊だけしてコアは戻らない', () => {
    const 試合インスタンス = 試合を準備する();
    場に出す(試合インスタンス, 'p2', 浮遊岩域を作成('相手ネクサス'));
    場に出す(試合インスタンス, 'p1', グンガタを作成('赤の味方'), 5000);
    トラッシュにコアを積む(試合インスタンス, 2);
    const 元のリザーブ = リザーブのコア数(試合インスタンス);

    使う(試合インスタンス, 'メイン');

    assert.equal(破壊されたか(試合インスタンス, '相手ネクサス'), true, '破壊は条件なしで起きる');
    assert.equal(リザーブのコア数(試合インスタンス), 元のリザーブ, 'コアは戻らない');
  });

  // 「{ソウルコア}以外の」の部分
  await t.test('トラッシュにソウルコアしかなければ、コアは戻らない', () => {
    const 試合インスタンス = 試合を準備する();
    場に出す(試合インスタンス, 'p2', 浮遊岩域を作成('相手ネクサス'));
    const 味方 = 場に出す(試合インスタンス, 'p1', グンガタを作成('赤の味方'), 5000);
    試合インスタンス.カードの表示形式管理.疲労する(味方);
    トラッシュにコアを積む(試合インスタンス, 0, true);
    const 元のリザーブ = リザーブのコア数(試合インスタンス);

    使う(試合インスタンス, 'メイン');

    assert.equal(リザーブのコア数(試合インスタンス), 元のリザーブ, 'ソウルコアは戻らない');
  });
});

test('ブレイククロー［フラッシュ］：自分のスピリットをBP+3000', async t => {
  await t.test('選んだ味方がこのターン中BP+3000される', () => {
    const 試合インスタンス = 試合を準備する();
    const 味方 = 場に出す(試合インスタンス, 'p1', グンガタを作成('味方'), 5000);

    使う(試合インスタンス, 'フラッシュ');

    assert.equal(試合インスタンス.BP管理.現在のBPを取得(味方), 8000);
  });

  // 「このターン中」なので、ターンが変われば戻る
  await t.test('ターンが変われば元のBPに戻る', () => {
    const 試合インスタンス = 試合を準備する();
    const 味方 = 場に出す(試合インスタンス, 'p1', グンガタを作成('味方'), 5000);

    使う(試合インスタンス, 'フラッシュ');
    assert.equal(試合インスタンス.BP管理.現在のBPを取得(味方), 8000);

    for (let i = 0; i < 30 && 試合インスタンス.ゲーム.現在のプレイヤーを取得()?.識別子 === 'p1'; i++) {
      試合インスタンス.ステップを終了する();
    }

    assert.equal(試合インスタンス.BP管理.現在のBPを取得(味方), 5000);
  });
});

// 1枚で2つの撃ち方を持つマジックは、選んだほうだけが起きる。
// ここが効いていないと、メインで撃っただけで味方のBPまで上がってしまう。
test('ブレイククロー：撃った撃ち方だけが起きる', async t => {
  await t.test('メインで撃つと、フラッシュ側のBP+3000は起きない', () => {
    const 試合インスタンス = 試合を準備する();
    場に出す(試合インスタンス, 'p2', 浮遊岩域を作成('相手ネクサス'));
    const 味方 = 場に出す(試合インスタンス, 'p1', グンガタを作成('味方'), 5000);

    使う(試合インスタンス, 'メイン');

    assert.equal(破壊されたか(試合インスタンス, '相手ネクサス'), true, 'メイン側は起きる');
    assert.equal(試合インスタンス.BP管理.現在のBPを取得(味方), 5000, 'フラッシュ側は起きない');
  });

  await t.test('フラッシュで撃つと、メイン側の破壊は起きない', () => {
    const 試合インスタンス = 試合を準備する();
    場に出す(試合インスタンス, 'p2', 浮遊岩域を作成('相手ネクサス'));
    const 味方 = 場に出す(試合インスタンス, 'p1', グンガタを作成('味方'), 5000);

    使う(試合インスタンス, 'フラッシュ');

    assert.equal(試合インスタンス.BP管理.現在のBPを取得(味方), 8000, 'フラッシュ側は起きる');
    assert.equal(破壊されたか(試合インスタンス, '相手ネクサス'), false, 'メイン側は起きない');
  });
});
