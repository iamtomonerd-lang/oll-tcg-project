function 試合を準備する(): 試合 {
  const 試合インスタンス = new 試合();
  試合インスタンス.プレイヤーを準備する('p1', 'プレイヤー1');
  試合インスタンス.プレイヤーを準備する('p2', 'プレイヤー2');
  試合インスタンス.ボイドを準備する();
  試合インスタンス.デッキを設定する(
    'p1',
    Array.from({ length: 10 }, (_, i) => グンガタを作成(`p1-deck-${i + 1}`))
  );
  試合インスタンス.デッキを設定する(
    'p2',
    Array.from({ length: 10 }, (_, i) => グンガタを作成(`p2-deck-${i + 1}`))
  );
  試合インスタンス.準備を行う('p1');
  試合インスタンス.準備を行う('p2');
  試合インスタンス.先攻を決める('p1');
  試合インスタンス.試合を開始する();
  return 試合インスタンス;
}

// 準備（シャッフル＋初期ドロー）のあとに、デッキの中身を指定の並びに入れ替える
function デッキを積み直す(試合インスタンス: 試合, カード一覧: any[]): void {
  const デッキ = 試合インスタンス.ゾーン管理.デッキエリアを取得(試合インスタンス.ゲーム, 'p1')!;
  for (const カード of デッキ.カード一覧を取得()) {
    デッキ.カードを削除(カード.識別子);
  }
  for (const カード of カード一覧) {
    デッキ.カードを追加(カード);
  }
}

function 場に出す(試合インスタンス: 試合, 識別子: string, カード: any, BP?: number) {
  試合インスタンス.ゾーン管理.フィールドを取得(試合インスタンス.ゲーム, 識別子)!.カードを追加(カード);
  if (BP !== undefined) 試合インスタンス.BP管理.BPを設定(カード, BP);
  return カード;
}

function 使う(試合インスタンス: 試合, タイミング: 'メイン' | 'フラッシュ') {
  const 呪文 = オフェリングドローを作成('オフェリングドロー');
  return 試合インスタンス.効果実行器.使用効果を発動する(呪文, 'p1', タイミング);
}

const 手札の識別子 = (試合インスタンス: 試合): string[] =>
  試合インスタンス.ゾーン管理
    .手札を取得(試合インスタンス.ゲーム, 'p1')!
    .カード一覧を取得()
    .map(c => c.識別子);

const デッキの識別子 = (試合インスタンス: 試合): string[] =>
  試合インスタンス.ゾーン管理
    .デッキエリアを取得(試合インスタンス.ゲーム, 'p1')!
    .カード一覧を取得()
    .map(c => c.識別子);

test('オフェリングドロー［メイン］：デッキの上3枚から風牙2枚を手札に', async t => {
  await t.test('風牙がちょうど2枚なら、選択を挟まず手札に加わる', () => {
    const 試合インスタンス = 試合を準備する();
    デッキを積み直す(試合インスタンス, [
      グンガタを作成('風牙1'),
      グンガタを作成('風牙2'),
      紫01を作成('風牙でない'),
    ]);
    const 手札の元 = 手札の識別子(試合インスタンス);

    // 手札に加える候補がちょうど2枚なので自動確定。残りも1枚なので順番も聞かれない。
    const 進行 = 使う(試合インスタンス, 'メイン');
    assert.equal(進行.状態, 'アイドル');

    assert.deepEqual(
      手札の識別子(試合インスタンス).filter(id => !手札の元.includes(id)).sort(),
      ['風牙1', '風牙2']
    );
    assert.ok(デッキの識別子(試合インスタンス).includes('風牙でない'), '残りはデッキに戻る');
  });

  // 「「オフェリングドロー」以外の」の部分。
  // ここが効いていないと、めくった中の自分自身を回収し続けられてしまう。
  await t.test('めくった中のオフェリングドローは対象にならない', () => {
    const 試合インスタンス = 試合を準備する();
    デッキを積み直す(試合インスタンス, [
      オフェリングドローを作成('デッキのオフェリング'),
      グンガタを作成('風牙1'),
      グンガタを作成('風牙2'),
    ]);
    const 手札の元 = 手札の識別子(試合インスタンス);

    使う(試合インスタンス, 'メイン');

    const 増えた = 手札の識別子(試合インスタンス).filter(id => !手札の元.includes(id));
    assert.deepEqual(増えた.sort(), ['風牙1', '風牙2']);
    assert.ok(
      !増えた.includes('デッキのオフェリング'),
      'オフェリングドロー自身は手札に加わらない'
    );
    assert.ok(
      デッキの識別子(試合インスタンス).includes('デッキのオフェリング'),
      '対象外はデッキの下に戻る'
    );
  });

  await t.test('風牙が3枚あれば、どの2枚を取るか選択待ちになる', () => {
    const 試合インスタンス = 試合を準備する();
    デッキを積み直す(試合インスタンス, [
      グンガタを作成('風牙1'),
      グンガタを作成('風牙2'),
      グンガタを作成('風牙3'),
    ]);
    const 手札の元 = 手札の識別子(試合インスタンス);

    const 進行 = 使う(試合インスタンス, 'メイン');
    assert.equal(進行.状態, '選択待ち');
    if (進行.状態 !== '選択待ち') return;
    assert.equal(進行.候補.length, 3);
    assert.equal(進行.最大, 2, '取れるのは2枚まで');

    試合インスタンス.効果実行器.選択に答える(['風牙1', '風牙3']);

    assert.deepEqual(
      手札の識別子(試合インスタンス).filter(id => !手札の元.includes(id)).sort(),
      ['風牙1', '風牙3']
    );
    assert.ok(デッキの識別子(試合インスタンス).includes('風牙2'), '選ばなかった分はデッキへ');
  });

  await t.test('風牙が1枚しかなければ、その1枚だけ手札に加わる', () => {
    const 試合インスタンス = 試合を準備する();
    デッキを積み直す(試合インスタンス, [
      グンガタを作成('風牙1'),
      紫01を作成('風牙でない1'),
      紫01を作成('風牙でない2'),
    ]);
    const 手札の元 = 手札の識別子(試合インスタンス);

    使う(試合インスタンス, 'メイン');
    // 残り2枚の順番を聞かれるので答える
    試合インスタンス.効果実行器.選択に答える(['風牙でない1', '風牙でない2']);

    assert.deepEqual(
      手札の識別子(試合インスタンス).filter(id => !手札の元.includes(id)),
      ['風牙1']
    );
  });

  await t.test('風牙が1枚も無ければ、3枚とも戻る（順番だけ聞かれる）', () => {
    const 試合インスタンス = 試合を準備する();
    デッキを積み直す(試合インスタンス, [
      紫01を作成('他1'),
      紫01を作成('他2'),
      紫01を作成('他3'),
    ]);
    const 手札の元 = 手札の識別子(試合インスタンス);

    // 手札に加える候補はいないが、戻す3枚の順番は決める余地がある
    const 進行 = 使う(試合インスタンス, 'メイン');
    assert.equal(進行.状態, '選択待ち');
    if (進行.状態 !== '選択待ち') return;
    試合インスタンス.効果実行器.選択に答える(['他1', '他2', '他3']);

    assert.deepEqual(手札の識別子(試合インスタンス).filter(id => !手札の元.includes(id)), []);
    const デッキ = デッキの識別子(試合インスタンス);
    assert.ok(['他1', '他2', '他3'].every(id => デッキ.includes(id)), '3枚ともデッキに残る');
  });
});

// 「残りは好きな順でデッキの下に戻す」の順番。
// 先に選んだものがデッキの上側（＝先に引く側）に来る。
test('オフェリングドロー：戻す順番はプレイヤーが決める', async t => {
  // 手札に加えるのは2枚なので、残り1枚のときは並べ替える余地がない
  await t.test('戻すのが1枚だけなら、順番は聞かれない', () => {
    const 試合インスタンス = 試合を準備する();
    デッキを積み直す(試合インスタンス, [
      グンガタを作成('風牙1'),
      グンガタを作成('風牙2'),
      紫01を作成('残り1枚'),
    ]);

    const 進行 = 使う(試合インスタンス, 'メイン');
    assert.equal(進行.状態, 'アイドル', '選ぶ余地がないので素通りする');
    assert.ok(デッキの識別子(試合インスタンス).includes('残り1枚'));
  });

  await t.test('戻すのが2枚以上なら順番を聞かれ、選んだ順に積まれる', () => {
    const 試合インスタンス = 試合を準備する();
    デッキを積み直す(試合インスタンス, [
      グンガタを作成('風牙1'),
      紫01を作成('残りA'),
      紫01を作成('残りB'),
    ]);

    // 手札に加える候補は風牙1枚だけなので自動確定し、残り2枚の順番を聞かれる
    const 進行 = 使う(試合インスタンス, 'メイン');
    assert.equal(進行.状態, '選択待ち');
    if (進行.状態 !== '選択待ち') return;
    assert.deepEqual(
      進行.候補.map(c => c.識別子).sort(),
      ['残りA', '残りB'],
      '戻す2枚の順番を聞かれる'
    );
    assert.equal(進行.最小, 2, '全部を順に選ぶ');
    assert.equal(進行.最大, 2);

    試合インスタンス.効果実行器.選択に答える(['残りB', '残りA']);

    // デッキの先頭が「上」。元から入っていた分の後ろに、選んだ順で積まれる。
    const デッキ = デッキの識別子(試合インスタンス);
    assert.ok(
      デッキ.indexOf('残りB') < デッキ.indexOf('残りA'),
      '先に選んだ 残りB のほうが上に来る'
    );
  });

  await t.test('逆の順に選べば、積まれる順も逆になる', () => {
    const 試合インスタンス = 試合を準備する();
    デッキを積み直す(試合インスタンス, [
      グンガタを作成('風牙1'),
      紫01を作成('残りA'),
      紫01を作成('残りB'),
    ]);

    使う(試合インスタンス, 'メイン');
    試合インスタンス.効果実行器.選択に答える(['残りA', '残りB']);

    const デッキ = デッキの識別子(試合インスタンス);
    assert.ok(
      デッキ.indexOf('残りA') < デッキ.indexOf('残りB'),
      '先に選んだ 残りA のほうが上に来る'
    );
  });
});

test('オフェリングドロー［フラッシュ］：自分のスピリットをBP+2000', async t => {
  await t.test('選んだ味方がこのターン中BP+2000される', () => {
    const 試合インスタンス = 試合を準備する();
    const 味方 = 場に出す(試合インスタンス, 'p1', グンガタを作成('味方'), 5000);

    使う(試合インスタンス, 'フラッシュ');

    assert.equal(試合インスタンス.BP管理.現在のBPを取得(味方), 7000);
  });

  // 撃ち分けが効いていないと、フラッシュで撃っただけでデッキがめくれてしまう
  await t.test('フラッシュで撃つと、メイン側のめくりは起きない', () => {
    const 試合インスタンス = 試合を準備する();
    デッキを積み直す(試合インスタンス, [グンガタを作成('風牙1'), グンガタを作成('風牙2')]);
    場に出す(試合インスタンス, 'p1', グンガタを作成('味方'), 5000);
    const 手札の元 = 手札の識別子(試合インスタンス);

    使う(試合インスタンス, 'フラッシュ');

    assert.deepEqual(
      手札の識別子(試合インスタンス).filter(id => !手札の元.includes(id)),
      [],
      '手札は増えない'
    );
  });

  await t.test('メインで撃つと、フラッシュ側のBP+2000は起きない', () => {
    const 試合インスタンス = 試合を準備する();
    デッキを積み直す(試合インスタンス, [グンガタを作成('風牙1'), グンガタを作成('風牙2')]);
    const 味方 = 場に出す(試合インスタンス, 'p1', グンガタを作成('味方'), 5000);

    使う(試合インスタンス, 'メイン');

    assert.equal(試合インスタンス.BP管理.現在のBPを取得(味方), 5000);
  });
});
