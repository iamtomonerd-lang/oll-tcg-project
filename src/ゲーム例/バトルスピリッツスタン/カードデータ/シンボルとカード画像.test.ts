import { test } from 'node:test';
import assert from 'node:assert';
import { カード帳 } from './カード帳.js';
import { シンボルルール } from '../カードの情報/シンボル.js';

// カード画像を1枚ずつ拡大して読み取った、シンボルの答え合わせ表。
//
// シンボルが通常かEXかは画像でしか判断できない（宝玉に金の装飾が付いていればEX）。
// 数値やテキストと違って、間違えても目に見える形では現れないので、
// 実際に3枚ずれていたのに誰も気づかないまま残っていた。
//   ・ムーシャッコ … 通常なのにEXにしていた（食べてはいけないものが継召の燃料になる）
//   ・ブレイククロー／フレイムハリケーン … EXなのにシンボルを持たせていなかった
//     （マジックは場に出ないが、トラッシュで《継召》の燃料になる。燃料が2種類ぶん不足していた）
//
// ここに表を置いて、カードデータ側とずれたら落ちるようにする。
// カードを足したときは、画像を見てこの表にも1行足すこと。
const 画像から読み取ったシンボル: Record<string, { 数: number; EX: boolean }> = {
  '26RSD01-001': { 数: 1, EX: false }, // ムーシャッコ
  '26RSD01-002': { 数: 1, EX: true }, // ゲン＝ボー
  '26RSD01-003': { 数: 1, EX: true }, // ロワミーク
  '26RSD01-004': { 数: 1, EX: false }, // ハーリア
  '26RSD01-005': { 数: 1, EX: true }, // グン＝ガタ
  '26RSD01-006': { 数: 1, EX: false }, // キュペル
  '26RSD01-007': { 数: 1, EX: true }, // グライファー
  '26RSD01-008': { 数: 1, EX: false }, // セルタリウス（《継召》持ちは食べる側）
  '26RSD01-009': { 数: 1, EX: false }, // 飛傑レウファルス
  '26RSD01-010': { 数: 1, EX: false }, // 最奥：風牙岩
  '26RSD01-011': { 数: 1, EX: false }, // 浮遊岩域
  '26RSD01-012': { 数: 1, EX: true }, // ブレイククロー（マジックだが宝玉あり）
  '26RSD01-013': { 数: 0, EX: false }, // オフェリングドロー（《継召》持ち。宝玉なし）
  '26RSD01-014': { 数: 1, EX: true }, // フレイムハリケーン（マジックだが宝玉あり）
  '26RSD01-X01': { 数: 1, EX: false }, // 飛赫レンシス（《継召》持ち）
  '26RSD01-X02': { 数: 1, EX: false }, // 飛剛アクライ（《継召》持ち）
};

test('カードデータのシンボルが、カード画像の読み取りと一致する', async t => {
  const シンボル = new シンボルルール();
  const 収録カード = カード帳.filter(項 => 項.カードナンバー.startsWith('26RSD01'));

  await t.test('画像を読んだ16枚がすべてカード帳にある', () => {
    assert.deepEqual(
      収録カード.map(項 => 項.カードナンバー).sort(),
      Object.keys(画像から読み取ったシンボル).sort()
    );
  });

  for (const 項 of 収録カード) {
    const 期待 = 画像から読み取ったシンボル[項.カードナンバー];
    await t.test(`${項.カードナンバー} ${項.カード名}`, () => {
      const カード = 項.作る('シンボル確認');
      assert.equal(シンボル.シンボル数を取得(カード), 期待.数, 'シンボルの数');
      assert.equal(シンボル.EXシンボルを持つ(カード), 期待.EX, 'EXかどうか');
    });
  }
});
