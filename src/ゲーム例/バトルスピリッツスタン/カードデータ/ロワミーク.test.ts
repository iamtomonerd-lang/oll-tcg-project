// === 召喚から効果発動までを通しで確認する ===

function 試合を準備する(): 試合 {
  const 試合インスタンス = new 試合();
  試合インスタンス.プレイヤーを準備する('p1', 'プレイヤー1');
  試合インスタンス.プレイヤーを準備する('p2', 'プレイヤー2');
  試合インスタンス.ボイドを準備する();
  試合インスタンス.デッキを設定する(
    'p1',
    Array.from({ length: 10 }, (_, i) => ロワミークを作成(`p1-deck-${i + 1}`))
  );
  試合インスタンス.デッキを設定する(
    'p2',
    Array.from({ length: 10 }, (_, i) => グンガタを作成(`p2-deck-${i + 1}`))
  );
  試合インスタンス.準備を行う('p1');
  試合インスタンス.準備を行う('p2');
  試合インスタンス.先攻を決める('p1');
  return 試合インスタンス;
}

function 場に出す(試合インスタンス: 試合, プレイヤー識別子: string, カード: any, BP?: number) {
  試合インスタンス.ゾーン管理
    .フィールドを取得(試合インスタンス.ゲーム, プレイヤー識別子)!
    .カードを追加(カード);
  // 場のカードには必ずコアが乗っている。乗せずに置くと、ルール処理の消滅判定に
  // 引っかかって即トラッシュ行きになる（実戦では起こらない状態）。
  // Lv1を保てる最小限だけ乗せる。Lvを変えたいテストは、このあとで自分で乗せ直す。
    試合インスタンス.コア管理
      .カードを保持者に(カード)
      .コア数を設定(new 消滅判定().最小必要コア数を取得(カード));
  if (BP !== undefined) {
    試合インスタンス.BP管理.BPを設定(カード, BP);
  }
  return カード;
}


// 召喚コストは自分の場のシンボルで軽減され、支払いはちょうどの額でなければ通らない。
// サーバーと同じ手順で必要額を求めてから召喚する。
function 召喚する(試合インスタンス: 試合, プレイヤー識別子: string, 対象: any): boolean {
  const 手札 = 試合インスタンス.ゾーン管理.手札を取得(試合インスタンス.ゲーム, プレイヤー識別子)!;
  const フィールド = 試合インスタンス.ゾーン管理.フィールドを取得(試合インスタンス.ゲーム, プレイヤー識別子)!;
  const リザーブ = 試合インスタンス.ゾーン管理.リザーブを取得(試合インスタンス.ゲーム, プレイヤー識別子)!;

  手札.カードを追加(対象);
  const リザーブ保持者 = 試合インスタンス.コア管理.ゾーンを保持者に(リザーブ);
  リザーブ保持者.コア数を設定(リザーブ保持者.コア数を取得() + 10);

  const フィールドのシンボル = フィールド
    .カード一覧を取得()
    .flatMap(c => new シンボルルール().シンボルを取得(c).map(x => x.色));
  const 基本コスト = new コストルール().コストを取得(対象);
  const 召喚コスト = new 軽減シンボルルール().軽減後のコストを計算(対象, 基本コスト, フィールドのシンボル);
  const 最低必要数 = new 消滅判定().最小必要コア数を取得(対象);

  return 試合インスタンス.召喚する(
    プレイヤー識別子,
    対象,
    [{ 保持者: リザーブ保持者, 数: 召喚コスト }],
    [{ 保持者: リザーブ保持者, 数: 最低必要数 }]
  );
}

// 破壊は「待機状態にする → トラッシュへ置く」の2段階。
// 最後まで、つまり場から消えてトラッシュにあることを見る。
const 破壊されたか = (試合インスタンス: 試合, 識別子: string): boolean => {
  const 場 = 試合インスタンス.ゾーン管理.フィールドを取得(試合インスタンス.ゲーム, 'p2')!;
  const トラッシュ = 試合インスタンス.ゾーン管理.トラッシュを取得(試合インスタンス.ゲーム, 'p2')!;
  return !場.カードを取得(識別子) && !!トラッシュ.カードを取得(識別子);
};

test('ロワミーク：召喚すると効果が誘発する', async t => {
  await t.test('条件を満たすと選択待ちになり、選んだ相手を破壊する', () => {
    const 試合インスタンス = 試合を準備する();

    const 味方 = 場に出す(試合インスタンス, 'p1', グンガタを作成('味方1'), 5000);
    試合インスタンス.カードの表示形式管理.疲労する(味方);

    場に出す(試合インスタンス, 'p2', グンガタを作成('相手1'), 3000);
    場に出す(試合インスタンス, 'p2', グンガタを作成('相手2'), 2000);

    // 召喚と同じ経路（フィールドに置いてから事象を通知）で誘発させる
    const 自身 = 場に出す(試合インスタンス, 'p1', ロワミークを作成('自身'), 3000);
    const 積んだ = 試合インスタンス.効果実行器.事象を通知する('召喚時', 自身);
    assert.equal(積んだ, 1, '召喚時効果が1件キューに積まれる');

    const 進行 = 試合インスタンス.効果実行器.キューを進める();
    assert.equal(進行.状態, '選択待ち');
    if (進行.状態 !== '選択待ち') return;
    assert.equal(進行.候補.length, 2);

    const 完了 = 試合インスタンス.効果実行器.選択に答える(['相手1']);
    assert.equal(完了.状態, 'アイドル');

    assert.equal(破壊されたか(試合インスタンス, '相手1'), true, '選んだ相手がトラッシュへ行く');
  });

  await t.test('試合.召喚する を通しても効果が誘発する', () => {
    const 試合インスタンス = 試合を準備する();
    試合インスタンス.試合を開始する();

    const 味方 = 場に出す(試合インスタンス, 'p1', グンガタを作成('味方1'), 5000);
    試合インスタンス.カードの表示形式管理.疲労する(味方);
    場に出す(試合インスタンス, 'p2', グンガタを作成('相手1'), 3000);

    const ロワミーク = ロワミークを作成('召喚するロワミーク');
    const 成功 = 召喚する(試合インスタンス, 'p1', ロワミーク);
    assert.equal(成功, true, '召喚が成立する');

    // 召喚するの中で誘発・解決まで進み、対象が1体しかないので自動確定している
    assert.equal(
      試合インスタンス.効果実行器.選択待ちか(),
      false,
      '候補が1体なので選択を挟まず解決する'
    );

    assert.equal(
      破壊されたか(試合インスタンス, '相手1'),
      true,
      '召喚しただけで相手がトラッシュへ行く'
    );
  });

  await t.test('召喚時に候補が複数あれば、選択待ちで止まる', () => {
    const 試合インスタンス = 試合を準備する();
    試合インスタンス.試合を開始する();

    const 味方 = 場に出す(試合インスタンス, 'p1', グンガタを作成('味方1'), 5000);
    試合インスタンス.カードの表示形式管理.疲労する(味方);
    場に出す(試合インスタンス, 'p2', グンガタを作成('相手1'), 3000);
    場に出す(試合インスタンス, 'p2', グンガタを作成('相手2'), 2000);

    const ロワミーク = ロワミークを作成('召喚するロワミーク');
    const 成功 = 召喚する(試合インスタンス, 'p1', ロワミーク);
    assert.equal(成功, true, '召喚が成立する');

    assert.equal(試合インスタンス.効果実行器.選択待ちか(), true, '選択待ちで止まる');
    const 情報 = 試合インスタンス.効果実行器.選択待ち情報を取得()!;
    assert.equal(情報.候補.length, 2);
    assert.equal(情報.発揮源.識別子, '召喚するロワミーク');

    試合インスタンス.効果実行器.選択に答える(['相手2']);

    assert.equal(破壊されたか(試合インスタンス, '相手2'), true);
  });

  await t.test('条件を満たさなければ何も起きない', () => {
    const 試合インスタンス = 試合を準備する();

    // 味方は回復状態のまま＝条件不成立
    場に出す(試合インスタンス, 'p1', グンガタを作成('味方1'), 5000);
    場に出す(試合インスタンス, 'p2', グンガタを作成('相手1'), 3000);

    const 自身 = 場に出す(試合インスタンス, 'p1', ロワミークを作成('自身'), 3000);
    試合インスタンス.効果実行器.事象を通知する('召喚時', 自身);
    const 進行 = 試合インスタンス.効果実行器.キューを進める();

    assert.equal(進行.状態, 'アイドル');
    assert.equal(破壊されたか(試合インスタンス, '相手1'), false);
  });
});
