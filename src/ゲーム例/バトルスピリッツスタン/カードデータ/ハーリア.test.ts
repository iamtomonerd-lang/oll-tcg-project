// === アタックから効果解決までを通しで確認する ===

// デッキの上2枚を指定した並びに差し替えてから、アタック時効果を誘発させる。
function 試合を準備する(デッキの上から: 'すべて風牙' | '風牙1枚' | '風牙なし'): {
  試合インスタンス: 試合;
  自身: ReturnType<typeof ハーリアを作成>;
} {
  const 試合インスタンス = new 試合();
  試合インスタンス.プレイヤーを準備する('p1', 'プレイヤー1');
  試合インスタンス.プレイヤーを準備する('p2', 'プレイヤー2');
  試合インスタンス.ボイドを準備する();

  // 風牙を持たないカードとして紫のスピリットを使う（系統：血醒など）
  const 風牙以外を作成 = 紫血醒カード一覧[0].作成;

  試合インスタンス.デッキを設定する(
    'p1',
    Array.from({ length: 10 }, (_, i) => グンガタを作成(`p1-deck-${i + 1}`))
  );
  試合インスタンス.デッキを設定する(
    'p2',
    Array.from({ length: 10 }, (_, i) => グンガタを作成(`p2-deck-${i + 1}`))
  );
  // 準備はデッキをシャッフルして初期ドローまで行うので、先に済ませてから
  // デッキの中身を入れ替える。そうしないと積んだ2枚が手札に流れてしまう。
  試合インスタンス.準備を行う('p1');
  試合インスタンス.準備を行う('p2');
  試合インスタンス.先攻を決める('p1');

  const 上2枚 =
    デッキの上から === 'すべて風牙'
      ? [グンガタを作成('上1-風牙'), グンガタを作成('上2-風牙')]
      : デッキの上から === '風牙1枚'
        ? [グンガタを作成('上1-風牙'), 風牙以外を作成('上2-他')]
        : [風牙以外を作成('上1-他'), 風牙以外を作成('上2-他2')];

  const デッキ = 試合インスタンス.ゾーン管理.デッキエリアを取得(試合インスタンス.ゲーム, 'p1')!;
  for (const カード of デッキ.カード一覧を取得()) {
    デッキ.カードを削除(カード.識別子);
  }
  for (const カード of 上2枚) {
    デッキ.カードを追加(カード);
  }

  const 自身 = ハーリアを作成('アタックするハーリア');
  試合インスタンス.ゾーン管理.フィールドを取得(試合インスタンス.ゲーム, 'p1')!.カードを追加(自身);
  // 効果は［Lv2］なので Lv2 まで上げておく
  試合インスタンス.Lv管理.Lvを上げる(自身, 2);
  試合インスタンス.BP管理.Lvに対応したBPに更新(自身, 2);

  return { 試合インスタンス, 自身 };
}

function 手札の識別子(試合インスタンス: 試合): string[] {
  return 試合インスタンス.ゾーン管理
    .手札を取得(試合インスタンス.ゲーム, 'p1')!
    .カード一覧を取得()
    .map(c => c.識別子);
}

function トラッシュの識別子(試合インスタンス: 試合): string[] {
  return 試合インスタンス.ゾーン管理
    .トラッシュを取得(試合インスタンス.ゲーム, 'p1')!
    .カード一覧を取得()
    .map(c => c.識別子);
}

test('ハーリア：アタック時にデッキの上2枚をめくる', async t => {
  await t.test('風牙が1枚だけなら、選択を挟まず手札に加わり残りは破棄される', () => {
    const { 試合インスタンス, 自身 } = 試合を準備する('風牙1枚');
    const 手札の元 = 手札の識別子(試合インスタンス);

    const 積んだ = 試合インスタンス.効果実行器.事象を通知する('アタック時', 自身);
    assert.equal(積んだ, 1, 'アタック時効果が1件キューに積まれる');

    const 進行 = 試合インスタンス.効果実行器.キューを進める();
    assert.equal(進行.状態, 'アイドル', '候補が1枚なので選択を挟まず解決する');

    const 増えた手札 = 手札の識別子(試合インスタンス).filter(id => !手札の元.includes(id));
    assert.deepEqual(増えた手札, ['上1-風牙'], '風牙を持つカードが手札に加わる');
    assert.ok(トラッシュの識別子(試合インスタンス).includes('上2-他'), '残りは破棄される');
  });

  await t.test('風牙が2枚なら、どちらを手札に加えるか選択待ちになる', () => {
    const { 試合インスタンス, 自身 } = 試合を準備する('すべて風牙');
    const 手札の元 = 手札の識別子(試合インスタンス);

    試合インスタンス.効果実行器.事象を通知する('アタック時', 自身);
    const 進行 = 試合インスタンス.効果実行器.キューを進める();

    assert.equal(進行.状態, '選択待ち');
    if (進行.状態 !== '選択待ち') return;
    assert.deepEqual(
      進行.候補.map(c => c.識別子).sort(),
      ['上1-風牙', '上2-風牙'],
      'めくった2枚が候補になる'
    );

    試合インスタンス.効果実行器.選択に答える(['上2-風牙']);

    const 増えた手札 = 手札の識別子(試合インスタンス).filter(id => !手札の元.includes(id));
    assert.deepEqual(増えた手札, ['上2-風牙'], '選んだほうが手札に加わる');
    assert.ok(トラッシュの識別子(試合インスタンス).includes('上1-風牙'), '選ばなかったほうは破棄される');
  });

  await t.test('風牙が無ければ、何も手札に加わらず2枚とも破棄される', () => {
    const { 試合インスタンス, 自身 } = 試合を準備する('風牙なし');
    const 手札の元 = 手札の識別子(試合インスタンス);

    試合インスタンス.効果実行器.事象を通知する('アタック時', 自身);
    const 進行 = 試合インスタンス.効果実行器.キューを進める();
    assert.equal(進行.状態, 'アイドル', '候補がいないので止まらず進む');

    const 増えた手札 = 手札の識別子(試合インスタンス).filter(id => !手札の元.includes(id));
    assert.deepEqual(増えた手札, [], '手札は増えない');

    const トラッシュ = トラッシュの識別子(試合インスタンス);
    assert.ok(トラッシュ.includes('上1-他') && トラッシュ.includes('上2-他2'), '2枚とも破棄される');
  });
});
