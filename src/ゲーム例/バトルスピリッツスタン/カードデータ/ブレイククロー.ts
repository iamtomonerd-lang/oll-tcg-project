import { カード名称データ } from './カード名称データ.js';
import {
  使用メイン,
  使用フラッシュ,
  疲労している味方がいる,
  相手のネクサスを選ぶ,
  自分のスピリットを選ぶ,
  それを破壊する,
  それのBPを変える,
  トラッシュのコアを置く,
  もし,
  このターン中,
} from '../効果部品/index.js';

// ブレイククロー（26RSD01-012）
// マジック／赤／C／コスト3／系統：風牙
// 軽減シンボル：赤赤
//
// ［メイン］真界放していない相手のネクサス1つを指定する。それを破壊する。
//          その後、疲労状態の自分の赤のスピリットがいるなら、
//          自分のトラッシュの{ソウルコア}以外のコア1個をリザーブに置く。
// ［フラッシュ］自分のスピリット1体を指定する。このターン中、それをBP+3000する。
//
// マジックは1枚で2つの撃ち方を持つ。どちらで使うかは撃つときに選ぶので、
// 効果を2つ並べて、それぞれにタイミングを書く。
//
// 「真界放していない」は 真界放: false。ここが効いていないと、
// 真界放しているネクサスまで巻き込んで破壊してしまう。
export const ブレイククロー名称: Omit<カード名称データ, '識別子'> = {
  表示名: 'ブレイククロー',
  説明: '「紫の切っ先を我らの赤き空に向け続けるなら、相応の対応をさせてもらうぞ」',
  カード名: 'ブレイククロー',
  カードナンバー: '26RSD01-012',
  カード種別: 'マジック',
  レアリティ: 'C',
  コスト: 3,
  系統: ['風牙'],
  ブロックアイコン: 'A',
  属性: ['赤'],
  軽減シンボル: ['赤', '赤'],
  カードテキスト:
    '［メイン］真界放していない相手のネクサス1つを指定する。それを破壊する。その後、疲労状態の自分の赤のスピリットがいるなら、自分のトラッシュの{ソウルコア}以外のコア1個をリザーブに置く。' +
    '［フラッシュ］自分のスピリット1体を指定する。このターン中、それをBP+3000する。',
  効果: [
    {
      ...使用メイン,
      処理: [
        相手のネクサスを選ぶ({ 真界放: false }),
        それを破壊する,
        もし(疲労している味方がいる({ 属性: '赤' }), [
          トラッシュのコアを置く({ 個数: 1, ソウルコアは除く: true, 置き先: 'リザーブ' }),
        ]),
      ],
    },
    {
      ...使用フラッシュ,
      処理: [自分のスピリットを選ぶ(), それのBPを変える(3000, このターン中)],
    },
  ],
};

export function ブレイククローを作成(識別子: string): カード {
  return new カード(識別子, { 識別子, ...ブレイククロー名称 });
}
