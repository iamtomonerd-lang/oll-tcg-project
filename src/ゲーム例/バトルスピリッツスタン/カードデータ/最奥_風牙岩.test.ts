function 試合を準備する(): 試合 {
  const 試合インスタンス = new 試合();
  試合インスタンス.プレイヤーを準備する('p1', 'プレイヤー1');
  試合インスタンス.プレイヤーを準備する('p2', 'プレイヤー2');
  試合インスタンス.ボイドを準備する();
  試合インスタンス.デッキを設定する(
    'p1',
    Array.from({ length: 10 }, (_, i) => グンガタを作成(`p1-deck-${i + 1}`))
  );
  試合インスタンス.デッキを設定する(
    'p2',
    Array.from({ length: 10 }, (_, i) => グンガタを作成(`p2-deck-${i + 1}`))
  );
  試合インスタンス.準備を行う('p1');
  試合インスタンス.準備を行う('p2');
  試合インスタンス.先攻を決める('p1');
  試合インスタンス.試合を開始する();
  return 試合インスタンス;
}

function 場に出す(試合インスタンス: 試合, 識別子: string, カード: any, BP?: number) {
  試合インスタンス.ゾーン管理.フィールドを取得(試合インスタンス.ゲーム, 識別子)!.カードを追加(カード);
  if (BP !== undefined) 試合インスタンス.BP管理.BPを設定(カード, BP);
  return カード;
}

// 指定したプレイヤーのアタックステップまで進める。
// 先攻の第1ターンはアタックステップがスキップされるので、
// p1 のアタックステップに入るには一巡させる必要がある。
function アタックステップへ進める(試合インスタンス: 試合, ターンプレイヤー = 'p1'): void {
  for (let 安全カウンタ = 0; 安全カウンタ < 60; 安全カウンタ++) {
    if (
      試合インスタンス.現在のステップ() === 'アタックステップ' &&
      試合インスタンス.ゲーム.現在のプレイヤーを取得()?.識別子 === ターンプレイヤー
    ) {
      return;
    }
    試合インスタンス.ステップを終了する();
  }
  throw new Error(`${ターンプレイヤー} のアタックステップに到達できませんでした`);
}

function 岩を置く(試合インスタンス: 試合, Lv: number) {
  const 岩 = 場に出す(試合インスタンス, 'p1', 最奥_風牙岩を作成('岩'));
  試合インスタンス.Lv管理.Lvを上げる(岩, Lv);
  return 岩;
}

test('最奥：風牙岩の【起動：フラッシュ】', async t => {
  await t.test('自分のアタックステップなら撃てて、アタック中の風牙をBP+2000する', () => {
    const 試合インスタンス = 試合を準備する();
    岩を置く(試合インスタンス, 1);
    const 味方 = 場に出す(試合インスタンス, 'p1', グンガタを作成('アタック中の風牙'), 5000);
    味方.状態を設定('アタック中', true);
    アタックステップへ進める(試合インスタンス);

    const 候補 = 試合インスタンス.効果実行器.発動できる起動効果を集める('p1', 'フラッシュ');
    assert.equal(候補.length, 1);

    試合インスタンス.効果実行器.起動効果を発動する('p1', 候補[0].効果識別子);

    assert.equal(試合インスタンス.BP管理.現在のBPを取得(味方), 7000, 'BP+2000される');
    assert.equal(
      試合インスタンス.カードの表示形式管理.現在の表示形式を取得(
        試合インスタンス.ゾーン管理.フィールドを取得(試合インスタンス.ゲーム, 'p1')!.カードを取得('岩')!
      ),
      '疲労',
      '代償としてネクサスが疲労する'
    );
  });

  // 『自分のアタックステップ』の制限。ここが効かないとメインステップでも撃ててしまう。
  await t.test('メインステップでは撃てない', () => {
    const 試合インスタンス = 試合を準備する();
    岩を置く(試合インスタンス, 1);
    const 味方 = 場に出す(試合インスタンス, 'p1', グンガタを作成('アタック中の風牙'), 5000);
    味方.状態を設定('アタック中', true);

    試合インスタンス.ステップを終了する(); // スタートステップ → メインステップ
    assert.equal(試合インスタンス.現在のステップ(), 'メインステップ');
    assert.equal(試合インスタンス.効果実行器.発動できる起動効果を集める('p1').length, 0);
  });

  // 「自分の」アタックステップなので、相手のターンのアタックステップでは撃てない
  await t.test('相手のターンのアタックステップでは撃てない', () => {
    const 試合インスタンス = 試合を準備する();
    岩を置く(試合インスタンス, 1);
    const 味方 = 場に出す(試合インスタンス, 'p1', グンガタを作成('アタック中の風牙'), 5000);
    味方.状態を設定('アタック中', true);

    アタックステップへ進める(試合インスタンス, 'p1');
    assert.equal(試合インスタンス.効果実行器.発動できる起動効果を集める('p1').length, 1);

    アタックステップへ進める(試合インスタンス, 'p2');
    assert.equal(
      試合インスタンス.効果実行器.発動できる起動効果を集める('p1').length,
      0,
      'p1の岩は、p2のターンでは撃てない'
    );
  });

  await t.test('アタックしていない風牙しかいなければ、選ぶ相手がいない', () => {
    const 試合インスタンス = 試合を準備する();
    岩を置く(試合インスタンス, 1);
    // アタック中フラグを立てない
    const 味方 = 場に出す(試合インスタンス, 'p1', グンガタを作成('待機中の風牙'), 5000);
    アタックステップへ進める(試合インスタンス);

    const 候補 = 試合インスタンス.効果実行器.発動できる起動効果を集める('p1', 'フラッシュ');
    試合インスタンス.効果実行器.起動効果を発動する('p1', 候補[0].効果識別子);

    assert.equal(試合インスタンス.BP管理.現在のBPを取得(味方), 5000, 'BPは変わらない');
  });
});

test('最奥：風牙岩の《真界放》効果', async t => {
  // 『自分が相手のスピリットを破壊した時』に誘発する。
  // 真界放状態はLv2かどうかだけで決まる（12-2-1-1-3、網羅は 効果語彙/真界放.test.ts）。
  function トラッシュにコアを積む(試合インスタンス: 試合, 通常コア: number, ソウルコア = false) {
    const トラッシュ = 試合インスタンス.ゾーン管理.トラッシュを取得(試合インスタンス.ゲーム, 'p1')!;
    const 保持者 = 試合インスタンス.コア管理.ゾーンを保持者に(トラッシュ);
    保持者.コア数を設定(通常コア + (ソウルコア ? 1 : 0));
    保持者.ソウルコアを設定(ソウルコア);
  }

  const コア数 = (試合インスタンス: 試合, カード: any): number =>
    試合インスタンス.コア管理.カードを保持者に(カード).コア数を取得();

  await t.test('Lv2なら誘発し、選んだ味方にトラッシュのコアが1個乗る', () => {
    const 試合インスタンス = 試合を準備する();
    岩を置く(試合インスタンス, 2);
    トラッシュにコアを積む(試合インスタンス, 2);
    const 味方 = 場に出す(試合インスタンス, 'p1', グンガタを作成('味方'), 5000);

    const 積んだ = 試合インスタンス.効果実行器.事象を通知する(
      '自分が相手のスピリットを破壊した時',
      undefined,
      'p1'
    );
    assert.equal(積んだ, 1);

    const 進行 = 試合インスタンス.効果実行器.キューを進める();
    assert.equal(進行.状態, '選択待ち', '「指定できる」なので選ばせる');
    if (進行.状態 !== '選択待ち') return;

    試合インスタンス.効果実行器.選択に答える(['味方']);
    assert.equal(コア数(試合インスタンス, 味方), 1);
  });

  await t.test('ソウルコアは除くので、ソウルコアしかなければ何も乗らない', () => {
    const 試合インスタンス = 試合を準備する();
    岩を置く(試合インスタンス, 2);
    トラッシュにコアを積む(試合インスタンス, 0, true);
    const 味方 = 場に出す(試合インスタンス, 'p1', グンガタを作成('味方'), 5000);

    試合インスタンス.効果実行器.事象を通知する('自分が相手のスピリットを破壊した時', undefined, 'p1');
    試合インスタンス.効果実行器.キューを進める();
    試合インスタンス.効果実行器.選択に答える(['味方']);

    assert.equal(コア数(試合インスタンス, 味方), 0, 'ソウルコアは対象外');
  });

  await t.test('「指定できる」なので、指定しなければコアは動かない', () => {
    const 試合インスタンス = 試合を準備する();
    岩を置く(試合インスタンス, 2);
    トラッシュにコアを積む(試合インスタンス, 2);
    const 味方 = 場に出す(試合インスタンス, 'p1', グンガタを作成('味方'), 5000);

    試合インスタンス.効果実行器.事象を通知する('自分が相手のスピリットを破壊した時', undefined, 'p1');
    試合インスタンス.効果実行器.キューを進める();
    試合インスタンス.効果実行器.選択に答える([]);

    assert.equal(コア数(試合インスタンス, 味方), 0);
  });

  await t.test('Lv1では真界放状態でないので誘発しない', () => {
    const 試合インスタンス = 試合を準備する();
    岩を置く(試合インスタンス, 1);
    トラッシュにコアを積む(試合インスタンス, 2);
    場に出す(試合インスタンス, 'p1', グンガタを作成('味方'), 5000);

    試合インスタンス.効果実行器.事象を通知する('自分が相手のスピリットを破壊した時', undefined, 'p1');
    const 進行 = 試合インスタンス.効果実行器.キューを進める();

    assert.equal(進行.状態, 'アイドル');
  });

  await t.test('〔ターン1回〕なので、同じターンに2回目は誘発しない', () => {
    const 試合インスタンス = 試合を準備する();
    岩を置く(試合インスタンス, 2);
    トラッシュにコアを積む(試合インスタンス, 3);
    場に出す(試合インスタンス, 'p1', グンガタを作成('味方'), 5000);

    試合インスタンス.効果実行器.事象を通知する('自分が相手のスピリットを破壊した時', undefined, 'p1');
    試合インスタンス.効果実行器.キューを進める();
    試合インスタンス.効果実行器.選択に答える(['味方']);

    const 二度目 = 試合インスタンス.効果実行器.事象を通知する(
      '自分が相手のスピリットを破壊した時',
      undefined,
      'p1'
    );
    assert.equal(二度目, 0);
  });

  // 「自分が」なので、相手が破壊したときには誘発しない
  await t.test('相手側の事象では誘発しない', () => {
    const 試合インスタンス = 試合を準備する();
    岩を置く(試合インスタンス, 2);
    トラッシュにコアを積む(試合インスタンス, 2);
    場に出す(試合インスタンス, 'p1', 紫01を作成('味方'), 5000);

    const 積んだ = 試合インスタンス.効果実行器.事象を通知する(
      '自分が相手のスピリットを破壊した時',
      undefined,
      'p2'
    );
    assert.equal(積んだ, 0);
  });
});
