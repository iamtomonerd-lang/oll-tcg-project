import { カード名称データ } from './カード名称データ.js';
import {
  使用フラッシュ,
  このターンに自分のライフが減っていた,
  数値を決める,
  相手のスピリットを選ぶ,
  それを破壊する,
} from '../効果部品/index.js';

// フレイムハリケーン（26RSD01-014）
// マジック／赤／C／コスト6／系統：風牙
// 軽減シンボル：赤赤赤
//
// 《ソウルマジック：赤》自分の赤シンボルがあれば{ソウルコア}だけで使用できる。
// ［フラッシュ］BP7000以下の相手のスピリット1体を指定する。それを破壊する。
//              このターンに自分のライフが減っていたなら、かわりに指定するBPを10000以下にする。
//
// 《ソウルマジック》は効果ではなくコストの払い方を変える性質なので キーワード に置く。
// 支払いの判定は既にある ソウルマジック判定／ソウルマジック管理 が担う。
//
// 「かわりに指定するBPを10000以下にする」は、絞り込みの数値そのものが条件で変わる書き方。
// 先に BP上限 を決めておき、選ぶ側はその数値（'$BP上限'）を見る。
export const フレイムハリケーン名称: Omit<カード名称データ, '識別子'> = {
  表示名: 'フレイムハリケーン',
  説明:
    'レンシスが生み出す炎の嵐は、かつての世界を飲み込んだ破壊の嵐を思い出させた。——異邦者の千里録より',
  カード名: 'フレイムハリケーン',
  カードナンバー: '26RSD01-014',
  カード種別: 'マジック',
  レアリティ: 'C',
  コスト: 6,
  系統: ['風牙'],
  ブロックアイコン: 'A',
  属性: ['赤'],
  軽減シンボル: ['赤', '赤', '赤'],
  キーワード: ['ソウルマジック'],
  カードテキスト:
    '《ソウルマジック：赤》自分の赤シンボルがあれば{ソウルコア}だけで使用できる。' +
    '［フラッシュ］BP7000以下の相手のスピリット1体を指定する。それを破壊する。このターンに自分のライフが減っていたなら、かわりに指定するBPを10000以下にする。',
  効果: [
    {
      ...使用フラッシュ,
      処理: [
        数値を決める({
          名: 'BP上限',
          既定: 7000,
          もし: このターンに自分のライフが減っていた,
          ならば: 10000,
        }),
        相手のスピリットを選ぶ({ BP以下: '$BP上限' }),
        それを破壊する,
      ],
    },
  ],
};

export function フレイムハリケーンを作成(識別子: string): カード {
  return new カード(識別子, { 識別子, ...フレイムハリケーン名称 });
}
