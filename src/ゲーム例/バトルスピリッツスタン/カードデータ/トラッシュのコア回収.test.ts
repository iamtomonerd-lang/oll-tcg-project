// 「トラッシュのコアが回収できない」という報告の切り分け。
//
// ライフは減ってもリザーブへ行くので、トラッシュにコアが入る道は
// 「コストの支払い」だけ。そこから拾い直せるかを、支払いを本当に通して確かめる。
//
// 効果の中で条件を見ているものは、条件が成立する盤面と、しない盤面の両方を通す。
// 「条件を満たしていなかっただけ」と「本当に動かない」は、
// 画面からは区別が付かないため、ここで切り分ける。

function 試合を準備する(): 試合 {
  const m = new 試合(1);
  m.プレイヤーを準備する('p1', 'プレイヤー1');
  m.プレイヤーを準備する('p2', 'プレイヤー2');
  m.ボイドを準備する();
  m.デッキを設定する(
    'p1',
    Array.from({ length: 10 }, (_, i) => グンガタを作成(`p1-deck-${i + 1}`))
  );
  m.デッキを設定する(
    'p2',
    Array.from({ length: 10 }, (_, i) => グンガタを作成(`p2-deck-${i + 1}`))
  );
  m.準備を行う('p1');
  m.準備を行う('p2');
  m.先攻を決める('p1');
  m.試合を開始する();
  return m;
}

const リザーブ保持者 = (m: 試合, 誰 = 'p1') =>
  m.コア管理.ゾーンを保持者に(m.ゾーン管理.リザーブを取得(m.ゲーム, 誰)!);
const トラッシュ保持者 = (m: 試合, 誰 = 'p1') =>
  m.コア管理.ゾーンを保持者に(m.ゾーン管理.トラッシュを取得(m.ゲーム, 誰)!);

// 場に出す。Lv1を保てる最小限のコアを必ず乗せる（コア0で置くと消滅判定に引っかかる）
function 場に出す(m: 試合, カード: カード, 誰 = 'p1'): カード {
  m.ゾーン管理.フィールドを取得(m.ゲーム, 誰)!.カードを追加(カード);
  const 保持者 = m.コア管理.カードを保持者に(カード);
  保持者.コア数を設定(new 消滅判定().最小必要コア数を取得(カード));
  m.Lv管理.Lvを更新(カード, 保持者.コア数を取得(), 保持者.ソウルコアあるか());
  return カード;
}

function 手札に加える(m: 試合, カード: カード, 誰 = 'p1'): カード {
  m.ゾーン管理.手札を取得(m.ゲーム, 誰)!.カードを追加(カード);
  return カード;
}

// 実際に払う額。場のシンボルによる軽減が効くので、素のコストとは違う。
// コストはちょうど払う決まり（11-1-1-5）なので、ここを間違えると支払いが通らない。
function 実コスト(m: 試合, カード: カード, 誰 = 'p1'): number {
  const フィールドのシンボル = m.ゾーン管理
    .フィールドを取得(m.ゲーム, 誰)!
    .カード一覧を取得()
    .flatMap(c => m.シンボルルール.シンボルを取得(c).map(x => x.色));
  return new 軽減シンボルルール().軽減後のコストを計算(
    カード,
    new コストルール().コストを取得(カード),
    フィールドのシンボル
  );
}

// 指定したプレイヤーのアタックステップまで進める。
// 先攻の第1ターンはアタックステップが飛ばされるので、一巡させる必要がある。
function アタックステップへ進める(m: 試合, ターンプレイヤー = 'p1'): void {
  for (let 安全カウンタ = 0; 安全カウンタ < 60; 安全カウンタ++) {
    if (
      m.現在のステップ() === 'アタックステップ' &&
      m.ゲーム.現在のプレイヤーを取得()?.識別子 === ターンプレイヤー
    ) {
      return;
    }
    m.ステップを終了する();
  }
  throw new Error(`${ターンプレイヤー} のアタックステップに到達できませんでした`);
}

// === コストの支払いが、本当にトラッシュへコアを置いているか ===

test('コストを払うと、その分のコアがトラッシュに積まれる', () => {
  const m = 試合を準備する();
  const ネクサス = 手札に加える(m, 浮遊岩域を作成('置くネクサス'));
  リザーブ保持者(m).コア数を設定(10);

  const コスト = 実コスト(m, ネクサス);
  const 前 = トラッシュ保持者(m).コア数を取得();
  const 成功 = m.配置する(
    'p1',
    ネクサス,
    [{ 保持者: リザーブ保持者(m), 数: コスト }],
    [{ 保持者: リザーブ保持者(m), 数: 1 }]
  );

  assert.equal(成功, true);
  assert.equal(トラッシュ保持者(m).コア数を取得(), 前 + コスト, `払った${コスト}個がトラッシュに入る`);
});

// === ブレイククロー［メイン］ ===
//
// 「その後、疲労状態の自分の赤のスピリットがいるなら、
//   自分のトラッシュの{ソウルコア}以外のコア1個をリザーブに置く」
//
// 条件を満たさないと何も起きない。それが「働かない」に見えていた可能性がある。

test('ブレイククロー［メイン］：疲労した赤の味方がいれば、トラッシュのコアがリザーブに戻る', () => {
  const m = 試合を準備する();
  const マジック = 手札に加える(m, ブレイククローを作成('壊す'));
  // 壊す相手のネクサス（真界放していないもの）
  場に出す(m, 浮遊岩域を作成('相手のネクサス'), 'p2');
  // 条件：疲労状態の自分の赤のスピリット
  const 味方 = 場に出す(m, グンガタを作成('疲れた味方'));
  m.カードの表示形式管理.疲労にする(味方);

  リザーブ保持者(m).コア数を設定(10);

  const コスト = 実コスト(m, マジック);
  const 使用成功 = m.使用する('p1', マジック, [{ 保持者: リザーブ保持者(m), 数: コスト }], 0, 'メイン');
  assert.equal(使用成功, true, '使用できる');

  // 対象候補が1つしか無い指定は自動で決まるので、使用する の中で効果まで解決し終える。
  // つまりこの時点で「コストの支払いでコスト個入り、効果で1個戻った」状態になっている。
  const 進行 = m.効果実行器.キューを進める();
  if (進行.状態 === '選択待ち') {
    m.効果実行器.選択に答える([進行.候補[0].識別子]);
  }

  assert.equal(
    トラッシュ保持者(m).コア数を取得(),
    コスト - 1,
    `支払った${コスト}個のうち1個が回収され、トラッシュには${コスト - 1}個残る`
  );
  assert.equal(
    m.ゾーン管理.フィールドを取得(m.ゲーム, 'p2')!.カードを取得('相手のネクサス'),
    undefined,
    '相手のネクサスは破壊されて場から消える'
  );
});

test('ブレイククロー［メイン］：疲労した赤の味方がいなければ、コアは戻らない', () => {
  const m = 試合を準備する();
  const マジック = 手札に加える(m, ブレイククローを作成('壊す'));
  場に出す(m, 浮遊岩域を作成('相手のネクサス'), 'p2');
  // 味方はいるが回復状態＝条件を満たさない
  場に出す(m, グンガタを作成('元気な味方'));

  リザーブ保持者(m).コア数を設定(10);

  const コスト = 実コスト(m, マジック);
  m.使用する('p1', マジック, [{ 保持者: リザーブ保持者(m), 数: コスト }], 0, 'メイン');
  const 進行 = m.効果実行器.キューを進める();
  if (進行.状態 === '選択待ち') {
    m.効果実行器.選択に答える([進行.候補[0].識別子]);
  }

  assert.equal(
    トラッシュ保持者(m).コア数を取得(),
    コスト,
    '条件を満たさないので払った分がそのまま残る'
  );
});

// === 最奥：風牙岩Lv2 ===
//
// 「自分のトラッシュの{ソウルコア}以外のコア1個をそれに置く」。
// トラッシュに通常コアが1個も無ければ、選ぶ画面は出るのに何も起きない。
// これが「選択までは出るが効果は発動しない」の正体になりうる。

test('最奥：風牙岩Lv2：トラッシュに通常コアがあれば、選んだスピリットに1個置かれる', () => {
  const m = 試合を準備する();
  const 岩 = 場に出す(m, 最奥_風牙岩を作成('岩'));
  const 保持者 = m.コア管理.カードを保持者に(岩);
  保持者.コア数を設定(2);
  保持者.ソウルコアを設定(true); // Lv2《真界放》
  m.Lv管理.Lvを更新(岩, 保持者.コア数を取得(), 保持者.ソウルコアあるか());

  const 味方 = 場に出す(m, グンガタを作成('置き先'));
  const 味方の前 = m.コア管理.カードを保持者に(味方).コア数を取得();

  // 『自分のアタックステップ』の制限があるので、p1のアタックステップまで進める
  アタックステップへ進める(m, 'p1');
  // コストの支払いでトラッシュに溜まったコアを表す
  トラッシュ保持者(m).コア数を設定(2);

  m.効果実行器.事象を通知する('自分が相手のスピリットを破壊した時', undefined, 'p1');
  const 進行 = m.効果実行器.キューを進める();
  assert.equal(進行.状態, '選択待ち', '置き先を選ばせる');
  if (進行.状態 !== '選択待ち') return;
  m.効果実行器.選択に答える(['置き先']);

  assert.equal(
    m.コア管理.カードを保持者に(味方).コア数を取得(),
    味方の前 + 1,
    'トラッシュのコアが1個乗る'
  );
  assert.equal(トラッシュ保持者(m).コア数を取得(), 1, 'トラッシュは1個減る');
});

