function 試合を準備する(): 試合 {
  const 試合インスタンス = new 試合();
  試合インスタンス.プレイヤーを準備する('p1', 'プレイヤー1');
  試合インスタンス.プレイヤーを準備する('p2', 'プレイヤー2');
  試合インスタンス.ボイドを準備する();
  試合インスタンス.デッキを設定する(
    'p1',
    Array.from({ length: 10 }, (_, i) => グンガタを作成(`p1-deck-${i + 1}`))
  );
  試合インスタンス.デッキを設定する(
    'p2',
    Array.from({ length: 10 }, (_, i) => グンガタを作成(`p2-deck-${i + 1}`))
  );
  試合インスタンス.準備を行う('p1');
  試合インスタンス.準備を行う('p2');
  試合インスタンス.先攻を決める('p1');
  試合インスタンス.試合を開始する();
  return 試合インスタンス;
}

function 場に出す(試合インスタンス: 試合, 識別子: string, カード: any, BP?: number) {
  試合インスタンス.ゾーン管理.フィールドを取得(試合インスタンス.ゲーム, 識別子)!.カードを追加(カード);
  // 場のカードには必ずコアが乗っている。乗せずに置くと、ルール処理の消滅判定に
  // 引っかかって即トラッシュ行きになる（実戦では起こらない状態）。
  // Lv1を保てる最小限だけ乗せる。Lvを変えたいテストは、このあとで自分で乗せ直す。
  試合インスタンス.コア管理
    .カードを保持者に(カード)
    .コア数を設定(new 消滅判定().最小必要コア数を取得(カード));
  if (BP !== undefined) 試合インスタンス.BP管理.BPを設定(カード, BP);
  return カード;
}

// 破壊は「待機状態にする → トラッシュへ置く」の2段階。
// 最後まで、つまり場から消えてトラッシュにあることを見る。
const 破壊されたか = (試合インスタンス: 試合, 識別子: string): boolean => {
  const 場 = 試合インスタンス.ゾーン管理.フィールドを取得(試合インスタンス.ゲーム, 'p2')!;
  const トラッシュ = 試合インスタンス.ゾーン管理.トラッシュを取得(試合インスタンス.ゲーム, 'p2')!;
  return !場.カードを取得(識別子) && !!トラッシュ.カードを取得(識別子);
};

// 手札を指定の中身に入れ替える（初期ドローで何が入るか決まらないため）
function 手札を差し替える(試合インスタンス: 試合, カード一覧: any[]): void {
  const 手札 = 試合インスタンス.ゾーン管理.手札を取得(試合インスタンス.ゲーム, 'p1')!;
  for (const カード of 手札.カード一覧を取得()) {
    手札.カードを削除(カード.識別子);
  }
  for (const カード of カード一覧) {
    手札.カードを追加(カード);
  }
}

const 手札の識別子 = (試合インスタンス: 試合): string[] =>
  試合インスタンス.ゾーン管理
    .手札を取得(試合インスタンス.ゲーム, 'p1')!
    .カード一覧を取得()
    .map(c => c.識別子);

// アタック中のグライファーを場に置く。手札は指定の中身にする。
function アタック中のグライファー(試合インスタンス: 試合, 手札: any[], Lv = 1) {
  const 自身 = 場に出す(試合インスタンス, 'p1', グライファーを作成('自身'));
  試合インスタンス.Lv管理.Lvを上げる(自身, Lv);
  試合インスタンス.BP管理.Lvに対応したBPに更新(自身, Lv);
  自身.状態を設定('アタック中', true);
  手札を差し替える(試合インスタンス, 手札);
  return 自身;
}

test('グライファー：アタック中の【起動：フラッシュ】', async t => {
  await t.test('風牙を手札に持っていれば撃てる', () => {
    const 試合インスタンス = 試合を準備する();
    const 自身 = アタック中のグライファー(試合インスタンス, [グンガタを作成('手札の風牙')]);

    const 候補 = 試合インスタンス.効果実行器.発動できる起動効果を集める('p1', 'フラッシュ');
    assert.equal(候補.length, 1);
    assert.equal(候補[0].発揮源.識別子, '自身');

    const 前のBP = 試合インスタンス.BP管理.現在のBPを取得(自身);
    試合インスタンス.効果実行器.起動効果を発動する('p1', 候補[0].効果識別子);

    assert.equal(
      試合インスタンス.BP管理.現在のBPを取得(自身),
      前のBP + 3000,
      'BPが+3000される'
    );
    assert.deepEqual(手札の識別子(試合インスタンス), [], '代償として手札の風牙が破棄される');
    assert.ok(
      試合インスタンス.ゾーン管理
        .トラッシュを取得(試合インスタンス.ゲーム, 'p1')!
        .カード一覧を取得()
        .some(c => c.識別子 === '手札の風牙'),
      '破棄したカードはトラッシュへ'
    );
  });

  await t.test('アタック中でなければ撃てない', () => {
    const 試合インスタンス = 試合を準備する();
    const 自身 = アタック中のグライファー(試合インスタンス, [グンガタを作成('手札の風牙')]);
    自身.状態を設定('アタック中', false);

    assert.equal(試合インスタンス.効果実行器.発動できる起動効果を集める('p1').length, 0);
  });

  await t.test('メインタイミングでは撃てない', () => {
    const 試合インスタンス = 試合を準備する();
    アタック中のグライファー(試合インスタンス, [グンガタを作成('手札の風牙')]);

    assert.equal(試合インスタンス.効果実行器.発動できる起動効果を集める('p1', 'メイン').length, 0);
  });

  await t.test('〔ターン1回〕なので、同じターンに2回は撃てない', () => {
    const 試合インスタンス = 試合を準備する();
    アタック中のグライファー(試合インスタンス, [
      グンガタを作成('手札の風牙1'),
      グンガタを作成('手札の風牙2'),
    ]);

    const 候補 = 試合インスタンス.効果実行器.発動できる起動効果を集める('p1', 'フラッシュ');
    試合インスタンス.効果実行器.起動効果を発動する('p1', 候補[0].効果識別子);

    assert.equal(
      試合インスタンス.効果実行器.発動できる起動効果を集める('p1', 'フラッシュ').length,
      0,
      '手札にまだ風牙があっても2回目は撃てない'
    );
  });

  await t.test('Lv1でも撃てる（［Lv1-2］の効果）', () => {
    const 試合インスタンス = 試合を準備する();
    アタック中のグライファー(試合インスタンス, [グンガタを作成('手札の風牙')], 1);

    assert.equal(試合インスタンス.効果実行器.発動できる起動効果を集める('p1', 'フラッシュ').length, 1);
  });
});

test('グライファー：《真界放》『アタック時』の破壊', async t => {
  // 真界放状態か は「真界放指定のあるLvに今いるか」だけで決まる（12-2-1-1-3）。
  // ソウルコアが関わるのは 12-2-1-1-2（Lv2コストを満たさなくてもLv2へ到達できる）で、
  // 到達したあとの状態判定には関わらない。グライファーは Lv2 に真界放指定があるので Lv2 ＝ 真界放状態。
  // この規則そのものの網羅は 効果語彙/真界放.test.ts にある。
  function 真界放させる(試合インスタンス: 試合, カード: any) {
    試合インスタンス.Lv管理.Lvを上げる(カード, 2);
    試合インスタンス.BP管理.Lvに対応したBPに更新(カード, 2);
  }

  await t.test('真界放していればBP3000以下の相手を破壊できる', () => {
    const 試合インスタンス = 試合を準備する();
    const 自身 = 場に出す(試合インスタンス, 'p1', グライファーを作成('自身'));
    真界放させる(試合インスタンス, 自身);

    場に出す(試合インスタンス, 'p2', グンガタを作成('相手-弱'), 3000);
    場に出す(試合インスタンス, 'p2', グンガタを作成('相手-強'), 8000);

    const 積んだ = 試合インスタンス.効果実行器.事象を通知する('アタック時', 自身);
    assert.equal(積んだ, 1);

    const 進行 = 試合インスタンス.効果実行器.キューを進める();
    assert.equal(進行.状態, 'アイドル', '候補が1体なので選択を挟まず解決する');

    assert.equal(破壊されたか(試合インスタンス, '相手-弱'), true, 'BP3000以下がトラッシュへ行く');
    assert.equal(破壊されたか(試合インスタンス, '相手-強'), false, 'BP3000超は対象外');
  });

  await t.test('Lv1では真界放状態でないので誘発しない', () => {
    const 試合インスタンス = 試合を準備する();
    const 自身 = 場に出す(試合インスタンス, 'p1', グライファーを作成('自身'));
    // Lv1には真界放の指定が無いので、真界放状態ではない
    試合インスタンス.Lv管理.Lvを上げる(自身, 1);

    場に出す(試合インスタンス, 'p2', グンガタを作成('相手-弱'), 3000);

    試合インスタンス.効果実行器.事象を通知する('アタック時', 自身);
    const 進行 = 試合インスタンス.効果実行器.キューを進める();

    assert.equal(進行.状態, 'アイドル');
    assert.equal(破壊されたか(試合インスタンス, '相手-弱'), false, '《真界放》していないので破壊されない');
  });

  await t.test('候補が複数いれば選択待ちになる', () => {
    const 試合インスタンス = 試合を準備する();
    const 自身 = 場に出す(試合インスタンス, 'p1', グライファーを作成('自身'));
    真界放させる(試合インスタンス, 自身);

    場に出す(試合インスタンス, 'p2', 紫01を作成('相手1'), 2000);
    場に出す(試合インスタンス, 'p2', 紫01を作成('相手2'), 1000);

    試合インスタンス.効果実行器.事象を通知する('アタック時', 自身);
    const 進行 = 試合インスタンス.効果実行器.キューを進める();

    assert.equal(進行.状態, '選択待ち');
    if (進行.状態 !== '選択待ち') return;
    assert.deepEqual(進行.候補.map(c => c.識別子).sort(), ['相手1', '相手2']);

    試合インスタンス.効果実行器.選択に答える(['相手2']);

    assert.equal(破壊されたか(試合インスタンス, '相手2'), true);
  });
});
