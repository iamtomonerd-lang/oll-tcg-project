function 試合を準備する(): 試合 {
  const 試合インスタンス = new 試合();
  試合インスタンス.プレイヤーを準備する('p1', 'プレイヤー1');
  試合インスタンス.プレイヤーを準備する('p2', 'プレイヤー2');
  試合インスタンス.ボイドを準備する();
  試合インスタンス.デッキを設定する(
    'p1',
    Array.from({ length: 10 }, (_, i) => グンガタを作成(`p1-deck-${i + 1}`))
  );
  試合インスタンス.デッキを設定する(
    'p2',
    Array.from({ length: 10 }, (_, i) => グンガタを作成(`p2-deck-${i + 1}`))
  );
  試合インスタンス.準備を行う('p1');
  試合インスタンス.準備を行う('p2');
  試合インスタンス.先攻を決める('p1');
  試合インスタンス.試合を開始する();
  return 試合インスタンス;
}

function 場に出す(試合インスタンス: 試合, 識別子: string, カード: any, BP: number) {
  試合インスタンス.ゾーン管理.フィールドを取得(試合インスタンス.ゲーム, 識別子)!.カードを追加(カード);
  試合インスタンス.BP管理.BPを設定(カード, BP);
  return カード;
}

function 使う(試合インスタンス: 試合) {
  const 呪文 = フレイムハリケーンを作成('フレイムハリケーン');
  return 試合インスタンス.効果実行器.使用効果を発動する(呪文, 'p1', 'フラッシュ');
}

// 『このターンに自分のライフが減っていたなら』の前提を作る。
// 実戦ではバトルで減ったときに記録される。
function ライフが減ったことにする(試合インスタンス: 試合): void {
  試合インスタンス.ターン履歴管理.記録する('ライフが減った', 'p1');
}

const 待機状態か = (試合インスタンス: 試合, 識別子: string): boolean =>
  試合インスタンス.待機状態管理.待機状態か(
    試合インスタンス.ゾーン管理.フィールドを取得(試合インスタンス.ゲーム, 'p2')!.カードを取得(識別子)!
  );

test('フレイムハリケーン：ライフが減っていなければBP7000以下', async t => {
  await t.test('BP7000ちょうどは対象、7001は対象外', () => {
    const 試合インスタンス = 試合を準備する();
    場に出す(試合インスタンス, 'p2', グンガタを作成('BP7000'), 7000);
    場に出す(試合インスタンス, 'p2', グンガタを作成('BP7001'), 7001);

    const 進行 = 使う(試合インスタンス);
    assert.equal(進行.状態, 'アイドル', '候補が1体なので選択を挟まない');

    assert.equal(待機状態か(試合インスタンス, 'BP7000'), true);
    assert.equal(待機状態か(試合インスタンス, 'BP7001'), false);
  });

  await t.test('BP10000の相手は届かない', () => {
    const 試合インスタンス = 試合を準備する();
    場に出す(試合インスタンス, 'p2', グンガタを作成('BP10000'), 10000);

    使う(試合インスタンス);

    assert.equal(待機状態か(試合インスタンス, 'BP10000'), false);
  });
});

// 「かわりに指定するBPを10000以下にする」の部分。
// ここが効いていないと、ライフが減っていても7000のままになる。
test('フレイムハリケーン：ライフが減っていればBP10000以下', async t => {
  await t.test('BP10000ちょうどまで届く', () => {
    const 試合インスタンス = 試合を準備する();
    ライフが減ったことにする(試合インスタンス);
    場に出す(試合インスタンス, 'p2', グンガタを作成('BP10000'), 10000);

    使う(試合インスタンス);

    assert.equal(待機状態か(試合インスタンス, 'BP10000'), true);
  });

  await t.test('BP10001は届かない', () => {
    const 試合インスタンス = 試合を準備する();
    ライフが減ったことにする(試合インスタンス);
    場に出す(試合インスタンス, 'p2', グンガタを作成('BP10001'), 10001);

    使う(試合インスタンス);

    assert.equal(待機状態か(試合インスタンス, 'BP10001'), false);
  });

  await t.test('射程が広がるので、7000超も候補に入る', () => {
    const 試合インスタンス = 試合を準備する();
    ライフが減ったことにする(試合インスタンス);
    場に出す(試合インスタンス, 'p2', グンガタを作成('BP7000'), 7000);
    場に出す(試合インスタンス, 'p2', グンガタを作成('BP9000'), 9000);

    const 進行 = 使う(試合インスタンス);
    assert.equal(進行.状態, '選択待ち', '2体とも候補なので選ばせる');
    if (進行.状態 !== '選択待ち') return;
    assert.deepEqual(進行.候補.map(c => c.識別子).sort(), ['BP7000', 'BP9000']);

    試合インスタンス.効果実行器.選択に答える(['BP9000']);
    assert.equal(待機状態か(試合インスタンス, 'BP9000'), true);
    assert.equal(待機状態か(試合インスタンス, 'BP7000'), false);
  });

  // 『自分の』ライフなので、相手のライフが減っただけでは広がらない
  await t.test('相手のライフが減っただけでは射程は広がらない', () => {
    const 試合インスタンス = 試合を準備する();
    試合インスタンス.ターン履歴管理.記録する('ライフが減った', 'p2');
    場に出す(試合インスタンス, 'p2', グンガタを作成('BP9000'), 9000);

    使う(試合インスタンス);

    assert.equal(待機状態か(試合インスタンス, 'BP9000'), false, '7000以下のままなので届かない');
  });
});
