import { カード名称 } from '../../../データ/カード/カード.js';
import { シンボル情報 } from '../カードの情報/シンボル.js';
import { Lv情報 } from '../カードの情報/Lv.js';
import { 属性色 } from '../カードの情報/属性.js';
import { カード種別 } from '../カードの情報/カード種別.js';
import { 効果定義 } from '../../../効果解釈/効果定義.js';

// バトルスピリッツ・スタンのカード名称データ
// カードの情報/ の各ルールクラス（カード名ルール・コストルール・Lvルール等）が
// `カード.名称 as any` で読み取るフィールドを、型安全に書けるようまとめた入力用の型。
// 実際のカードデータ（カードデータ/ 配下の各ファイル）はこの型でオブジェクトを作り、
// カード のコンストラクタに渡す。
export interface カード名称データ extends カード名称 {
  カード名: string;
  カードナンバー: string;
  カード種別: カード種別;
  レアリティ: string;
  コスト: number;
  系統: string[];
  ブロックアイコン: string;
  作品アイコン?: string;
  属性: 属性色[];
  軽減シンボル?: string[];
  シンボル?: シンボル情報[];
  Lv?: Lv情報[];
  // 《継召》《ソウルマジック》などカード自身が持つキーワード能力
  // （《真界放》はLv情報側に書かれるため、ここには含めない）
  キーワード?: string[];
  // カードの効果。クラスではなくデータで書き、効果インタプリタが解釈する。
  効果?: 効果定義[];
  カードテキスト?: string;
}
