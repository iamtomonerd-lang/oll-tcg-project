// === 召喚とエンドステップを通しで確認する ===

function 試合を準備する(): 試合 {
  const 試合インスタンス = new 試合();
  試合インスタンス.プレイヤーを準備する('p1', 'プレイヤー1');
  試合インスタンス.プレイヤーを準備する('p2', 'プレイヤー2');
  試合インスタンス.ボイドを準備する();
  試合インスタンス.デッキを設定する(
    'p1',
    Array.from({ length: 10 }, (_, i) => グンガタを作成(`p1-deck-${i + 1}`))
  );
  試合インスタンス.デッキを設定する(
    'p2',
    Array.from({ length: 10 }, (_, i) => グンガタを作成(`p2-deck-${i + 1}`))
  );
  試合インスタンス.準備を行う('p1');
  試合インスタンス.準備を行う('p2');
  試合インスタンス.先攻を決める('p1');
  return 試合インスタンス;
}

// トラッシュに通常コアN個（＋必要ならソウルコア）を置く
function トラッシュにコアを積む(
  試合インスタンス: 試合,
  通常コア: number,
  ソウルコア = false
): void {
  const トラッシュ = 試合インスタンス.ゾーン管理.トラッシュを取得(試合インスタンス.ゲーム, 'p1')!;
  const 保持者 = 試合インスタンス.コア管理.ゾーンを保持者に(トラッシュ);
  保持者.コア数を設定(通常コア + (ソウルコア ? 1 : 0));
  保持者.ソウルコアを設定(ソウルコア);
}

function 場に出す(試合インスタンス: 試合, 識別子: string, カード: any) {
  試合インスタンス.ゾーン管理.フィールドを取得(試合インスタンス.ゲーム, 識別子)!.カードを追加(カード);
  return カード;
}

const コア数 = (試合インスタンス: 試合, カード: any): number =>
  試合インスタンス.コア管理.カードを保持者に(カード).コア数を取得();

const トラッシュのコア数 = (試合インスタンス: 試合): number =>
  試合インスタンス.コア管理
    .ゾーンを保持者に(試合インスタンス.ゾーン管理.トラッシュを取得(試合インスタンス.ゲーム, 'p1')!)
    .コア数を取得();

test('キュペル：召喚時にトラッシュのコアを自分に置く', async t => {
  await t.test('トラッシュに通常コアが2個以上あれば、2個が自分に乗る', () => {
    const 試合インスタンス = 試合を準備する();
    トラッシュにコアを積む(試合インスタンス, 3);

    const 自身 = 場に出す(試合インスタンス, 'p1', キュペルを作成('自身'));
    試合インスタンス.効果実行器.事象を通知する('召喚時', 自身);
    const 進行 = 試合インスタンス.効果実行器.キューを進める();

    assert.equal(進行.状態, 'アイドル');
    assert.equal(コア数(試合インスタンス, 自身), 2, '2個ちょうど乗る');
    assert.equal(トラッシュのコア数(試合インスタンス), 1, 'トラッシュからは2個減る');
  });

  await t.test('「2個まで」なので、1個しかなければ1個だけ乗る', () => {
    const 試合インスタンス = 試合を準備する();
    トラッシュにコアを積む(試合インスタンス, 1);

    const 自身 = 場に出す(試合インスタンス, 'p1', キュペルを作成('自身'));
    試合インスタンス.効果実行器.事象を通知する('召喚時', 自身);
    const 進行 = 試合インスタンス.効果実行器.キューを進める();

    assert.equal(進行.状態, 'アイドル', '足りなくても失敗しない');
    assert.equal(コア数(試合インスタンス, 自身), 1);
    assert.equal(トラッシュのコア数(試合インスタンス), 0);
  });

  await t.test('ソウルコアは除くので、ソウルコアしかなければ何も乗らない', () => {
    const 試合インスタンス = 試合を準備する();
    トラッシュにコアを積む(試合インスタンス, 0, true);

    const 自身 = 場に出す(試合インスタンス, 'p1', キュペルを作成('自身'));
    試合インスタンス.効果実行器.事象を通知する('召喚時', 自身);
    試合インスタンス.効果実行器.キューを進める();

    assert.equal(コア数(試合インスタンス, 自身), 0, 'ソウルコアは対象外');
    assert.equal(トラッシュのコア数(試合インスタンス), 1, 'トラッシュに残ったまま');
  });
});

test('キュペル：自分のエンドステップにソウルコアを渡す', async t => {
  await t.test('風牙の味方を指定すると、トラッシュのソウルコアがそれに乗る', () => {
    const 試合インスタンス = 試合を準備する();
    トラッシュにコアを積む(試合インスタンス, 0, true);

    const 自身 = 場に出す(試合インスタンス, 'p1', キュペルを作成('自身'));
    試合インスタンス.Lv管理.Lvを上げる(自身, 2);
    // グンガタは系統：紅雲・風牙なので指定できる
    const 味方 = 場に出す(試合インスタンス, 'p1', グンガタを作成('風牙の味方'));

    試合インスタンス.効果実行器.事象を通知する('自分のエンドステップ', undefined, 'p1');
    const 進行 = 試合インスタンス.効果実行器.キューを進める();

    assert.equal(進行.状態, '選択待ち', '「指定できる」なので選ばせる');
    if (進行.状態 !== '選択待ち') return;
    assert.deepEqual(
      進行.候補.map(c => c.識別子).sort(),
      ['自身', '風牙の味方'],
      'キュペル自身も風牙なので候補に入る'
    );

    試合インスタンス.効果実行器.選択に答える(['風牙の味方']);

    assert.equal(コア数(試合インスタンス, 味方), 1, 'ソウルコアが乗る');
    assert.equal(
      試合インスタンス.コア管理.カードを保持者に(味方).ソウルコアあるか(),
      true,
      '乗ったのはソウルコア'
    );
    assert.equal(トラッシュのコア数(試合インスタンス), 0);
  });

  await t.test('「指定できる」なので、指定しなければコアは動かない', () => {
    const 試合インスタンス = 試合を準備する();
    トラッシュにコアを積む(試合インスタンス, 0, true);

    const 自身 = 場に出す(試合インスタンス, 'p1', キュペルを作成('自身'));
    試合インスタンス.Lv管理.Lvを上げる(自身, 2);
    場に出す(試合インスタンス, 'p1', グンガタを作成('風牙の味方'));

    試合インスタンス.効果実行器.事象を通知する('自分のエンドステップ', undefined, 'p1');
    試合インスタンス.効果実行器.キューを進める();
    試合インスタンス.効果実行器.選択に答える([]);

    assert.equal(トラッシュのコア数(試合インスタンス), 1, 'ソウルコアはトラッシュに残る');
  });

  await t.test('風牙を持たない味方は指定できない', () => {
    const 試合インスタンス = 試合を準備する();
    トラッシュにコアを積む(試合インスタンス, 0, true);

    const 自身 = 場に出す(試合インスタンス, 'p1', キュペルを作成('自身'));
    試合インスタンス.Lv管理.Lvを上げる(自身, 2);
    // 紫01は系統：血醒で、風牙を持たない
    場に出す(試合インスタンス, 'p1', 紫01を作成('風牙でない味方'));

    試合インスタンス.効果実行器.事象を通知する('自分のエンドステップ', undefined, 'p1');
    const 進行 = 試合インスタンス.効果実行器.キューを進める();

    assert.equal(進行.状態, '選択待ち');
    if (進行.状態 !== '選択待ち') return;
    assert.deepEqual(進行.候補.map(c => c.識別子), ['自身'], 'キュペル自身だけが候補');
  });

  await t.test('Lv1では誘発しない', () => {
    const 試合インスタンス = 試合を準備する();
    トラッシュにコアを積む(試合インスタンス, 0, true);

    const 自身 = 場に出す(試合インスタンス, 'p1', キュペルを作成('自身'));
    試合インスタンス.Lv管理.Lvを上げる(自身, 1);
    場に出す(試合インスタンス, 'p1', グンガタを作成('風牙の味方'));

    試合インスタンス.効果実行器.事象を通知する('自分のエンドステップ', undefined, 'p1');
    const 進行 = 試合インスタンス.効果実行器.キューを進める();

    assert.equal(進行.状態, 'アイドル', 'Lv2の効果なので何も起きない');
    assert.equal(トラッシュのコア数(試合インスタンス), 1);
  });
});
