function 試合を準備する(): 試合 {
  const 試合インスタンス = new 試合();
  試合インスタンス.プレイヤーを準備する('p1', 'プレイヤー1');
  試合インスタンス.プレイヤーを準備する('p2', 'プレイヤー2');
  試合インスタンス.ボイドを準備する();
  試合インスタンス.デッキを設定する(
    'p1',
    Array.from({ length: 10 }, (_, i) => グンガタを作成(`p1-deck-${i + 1}`))
  );
  試合インスタンス.デッキを設定する(
    'p2',
    Array.from({ length: 10 }, (_, i) => グンガタを作成(`p2-deck-${i + 1}`))
  );
  // 準備はデッキをシャッフルして初期ドローまで行うので、先に済ませてから
  // デッキや手札の中身を入れ替える。そうしないと積んだカードが手札に流れてしまう。
  試合インスタンス.準備を行う('p1');
  試合インスタンス.準備を行う('p2');
  試合インスタンス.先攻を決める('p1');
  試合インスタンス.試合を開始する();
  return 試合インスタンス;
}

// 手札を指定の中身に入れ替える（初期ドローで何が入るか決まらないため）
function 手札を差し替える(試合インスタンス: 試合, カード一覧: any[]): void {
  const 手札 = 試合インスタンス.ゾーン管理.手札を取得(試合インスタンス.ゲーム, 'p1')!;
  for (const カード of 手札.カード一覧を取得()) 手札.カードを削除(カード.識別子);
  for (const カード of カード一覧) 手札.カードを追加(カード);
}

// デッキを指定の中身に入れ替える
function デッキを差し替える(試合インスタンス: 試合, カード一覧: any[]): void {
  const デッキ = 試合インスタンス.ゾーン管理.デッキエリアを取得(試合インスタンス.ゲーム, 'p1')!;
  for (const カード of デッキ.カード一覧を取得()) デッキ.カードを削除(カード.識別子);
  for (const カード of カード一覧) デッキ.カードを追加(カード);
}

const 手札の識別子 = (試合インスタンス: 試合): string[] =>
  試合インスタンス.ゾーン管理
    .手札を取得(試合インスタンス.ゲーム, 'p1')!
    .カード一覧を取得()
    .map(c => c.識別子);

const トラッシュの識別子 = (試合インスタンス: 試合): string[] =>
  試合インスタンス.ゾーン管理
    .トラッシュを取得(試合インスタンス.ゲーム, 'p1')!
    .カード一覧を取得()
    .map(c => c.識別子);

// アタック中のアクライを場に置く。手札は指定の中身にする。
function アタック中のアクライ(試合インスタンス: 試合, 手札: any[], Lv = 1) {
  const 自身 = 飛剛アクライを作成('自身');
  試合インスタンス.ゾーン管理.フィールドを取得(試合インスタンス.ゲーム, 'p1')!.カードを追加(自身);
  試合インスタンス.Lv管理.Lvを上げる(自身, Lv);
  試合インスタンス.BP管理.Lvに対応したBPに更新(自身, Lv);
  自身.状態を設定('アタック中', true);
  手札を差し替える(試合インスタンス, 手札);
  return 自身;
}

test('飛剛アクライ：アタック中の【起動：フラッシュ】でBP+3000', async t => {
  await t.test('風牙を手札に持っていれば撃てて、BPが+3000される', () => {
    const 試合インスタンス = 試合を準備する();
    const 自身 = アタック中のアクライ(試合インスタンス, [グンガタを作成('手札の風牙')]);

    const 候補 = 試合インスタンス.効果実行器.発動できる起動効果を集める('p1', 'フラッシュ');
    assert.equal(候補.length, 1);
    assert.equal(候補[0].発揮源.識別子, '自身');

    const 前のBP = 試合インスタンス.BP管理.現在のBPを取得(自身);
    試合インスタンス.効果実行器.起動効果を発動する('p1', 候補[0].効果識別子);

    assert.equal(試合インスタンス.BP管理.現在のBPを取得(自身), 前のBP + 3000);
    assert.deepEqual(手札の識別子(試合インスタンス), [], '代償として手札の風牙が破棄される');
    assert.ok(トラッシュの識別子(試合インスタンス).includes('手札の風牙'));
  });

  await t.test('Lv1のBP7000から撃つと10000になる', () => {
    const 試合インスタンス = 試合を準備する();
    const 自身 = アタック中のアクライ(試合インスタンス, [グンガタを作成('手札の風牙')], 1);

    assert.equal(試合インスタンス.BP管理.現在のBPを取得(自身), 7000);
    const 候補 = 試合インスタンス.効果実行器.発動できる起動効果を集める('p1', 'フラッシュ');
    試合インスタンス.効果実行器.起動効果を発動する('p1', 候補[0].効果識別子);
    assert.equal(試合インスタンス.BP管理.現在のBPを取得(自身), 10000);
  });

  await t.test('Lv2のBP10000から撃つと13000になる', () => {
    const 試合インスタンス = 試合を準備する();
    const 自身 = アタック中のアクライ(試合インスタンス, [グンガタを作成('手札の風牙')], 2);

    assert.equal(試合インスタンス.BP管理.現在のBPを取得(自身), 10000);
    const 候補 = 試合インスタンス.効果実行器.発動できる起動効果を集める('p1', 'フラッシュ');
    試合インスタンス.効果実行器.起動効果を発動する('p1', 候補[0].効果識別子);
    assert.equal(試合インスタンス.BP管理.現在のBPを取得(自身), 13000);
  });

  await t.test('アタック中でなければ撃てない', () => {
    const 試合インスタンス = 試合を準備する();
    const 自身 = アタック中のアクライ(試合インスタンス, [グンガタを作成('手札の風牙')]);
    自身.状態を設定('アタック中', false);

    assert.equal(試合インスタンス.効果実行器.発動できる起動効果を集める('p1', 'フラッシュ').length, 0);
  });

  await t.test('メインタイミングでは撃てない', () => {
    const 試合インスタンス = 試合を準備する();
    アタック中のアクライ(試合インスタンス, [グンガタを作成('手札の風牙')]);

    assert.equal(試合インスタンス.効果実行器.発動できる起動効果を集める('p1', 'メイン').length, 0);
  });

  await t.test('手札に風牙が無ければ代償を払えないので撃てない', () => {
    const 試合インスタンス = 試合を準備する();
    アタック中のアクライ(試合インスタンス, [風牙以外を作成('手札の風牙以外')]);

    assert.equal(試合インスタンス.効果実行器.発動できる起動効果を集める('p1', 'フラッシュ').length, 0);
  });

  await t.test('〔ターン1回〕なので、同じターンに2回は撃てない', () => {
    const 試合インスタンス = 試合を準備する();
    アタック中のアクライ(試合インスタンス, [
      グンガタを作成('手札の風牙1'),
      グンガタを作成('手札の風牙2'),
    ]);

    const 候補 = 試合インスタンス.効果実行器.発動できる起動効果を集める('p1', 'フラッシュ');
    試合インスタンス.効果実行器.起動効果を発動する('p1', 候補[0].効果識別子);

    assert.equal(
      試合インスタンス.効果実行器.発動できる起動効果を集める('p1', 'フラッシュ').length,
      0,
      '手札にまだ風牙があっても2回目は撃てない'
    );
  });
});

test('飛剛アクライ：《真界放》のアタック時にデッキの上3枚をめくる', async t => {
  // Lv2にすると真界放状態になる（12-2-1-1-3）。規則の網羅は 効果語彙/真界放.test.ts。
  function アタックさせる(試合インスタンス: 試合, デッキの上3枚: any[], Lv = 2) {
    デッキを差し替える(試合インスタンス, デッキの上3枚);
    const 自身 = 飛剛アクライを作成('自身');
    試合インスタンス.ゾーン管理.フィールドを取得(試合インスタンス.ゲーム, 'p1')!.カードを追加(自身);
    試合インスタンス.Lv管理.Lvを上げる(自身, Lv);
    試合インスタンス.BP管理.Lvに対応したBPに更新(自身, Lv);
    const 積んだ = 試合インスタンス.効果実行器.事象を通知する('アタック時', 自身);
    return { 自身, 積んだ, 進行: 試合インスタンス.効果実行器.キューを進める() };
  }

  await t.test('風牙が1枚だけなら、選択を挟まず手札に加わり残り2枚は破棄される', () => {
    const 試合インスタンス = 試合を準備する();
    const 手札の元 = 手札の識別子(試合インスタンス);

    const { 積んだ, 進行 } = アタックさせる(試合インスタンス, [
      グンガタを作成('上1-風牙'),
      風牙以外を作成('上2-他'),
      風牙以外を作成('上3-他'),
    ]);

    assert.equal(積んだ, 1, 'アタック時効果が1件キューに積まれる');
    assert.equal(進行.状態, 'アイドル', '候補が1枚なので選択を挟まず解決する');

    const 増えた手札 = 手札の識別子(試合インスタンス).filter(id => !手札の元.includes(id));
    assert.deepEqual(増えた手札, ['上1-風牙']);
    assert.deepEqual(トラッシュの識別子(試合インスタンス).sort(), ['上2-他', '上3-他']);
  });

  // ハーリア（2枚めくり）との違い。3枚めくるので候補も残りも1枚多い。
  await t.test('風牙が複数あれば選択待ちになり、選ばなかった分は破棄される', () => {
    const 試合インスタンス = 試合を準備する();
    const 手札の元 = 手札の識別子(試合インスタンス);

    const { 進行 } = アタックさせる(試合インスタンス, [
      グンガタを作成('上1-風牙'),
      グンガタを作成('上2-風牙'),
      グンガタを作成('上3-風牙'),
    ]);

    assert.equal(進行.状態, '選択待ち');
    if (進行.状態 !== '選択待ち') return;
    assert.deepEqual(進行.候補.map(c => c.識別子).sort(), ['上1-風牙', '上2-風牙', '上3-風牙']);

    試合インスタンス.効果実行器.選択に答える(['上2-風牙']);

    const 増えた手札 = 手札の識別子(試合インスタンス).filter(id => !手札の元.includes(id));
    assert.deepEqual(増えた手札, ['上2-風牙']);
    assert.deepEqual(トラッシュの識別子(試合インスタンス).sort(), ['上1-風牙', '上3-風牙']);
  });

  await t.test('風牙が1枚も無ければ、3枚とも破棄される', () => {
    const 試合インスタンス = 試合を準備する();
    const 手札の元 = 手札の識別子(試合インスタンス);

    const { 進行 } = アタックさせる(試合インスタンス, [
      風牙以外を作成('上1-他'),
      風牙以外を作成('上2-他'),
      風牙以外を作成('上3-他'),
    ]);

    assert.equal(進行.状態, 'アイドル', '候補ゼロは選択を挟まず飛ばす');
    assert.deepEqual(手札の識別子(試合インスタンス), 手札の元, '手札は増えない');
    assert.deepEqual(トラッシュの識別子(試合インスタンス).sort(), ['上1-他', '上2-他', '上3-他']);
  });

  await t.test('Lv1では真界放状態でないので誘発しない', () => {
    const 試合インスタンス = 試合を準備する();
    const 手札の元 = 手札の識別子(試合インスタンス);

    const { 積んだ } = アタックさせる(
      試合インスタンス,
      [グンガタを作成('上1-風牙'), グンガタを作成('上2-風牙'), グンガタを作成('上3-風牙')],
      1
    );

    assert.equal(積んだ, 0, 'Lv2の《真界放》効果なので積まれない');
    assert.deepEqual(手札の識別子(試合インスタンス), 手札の元);
    assert.deepEqual(トラッシュの識別子(試合インスタンス), []);
  });
});
