test('ムーシャッコ（26RSD01-001）が正しく生成される', () => {
  const カード = ムーシャッコを作成('test-mushaako-1');
  assert.equal(カード.識別子, 'test-mushaako-1');
  assert.equal(new カード名ルール().カード名を取得(カード), 'ムーシャッコ');
  assert.equal(new カードナンバールール().カードナンバーを取得(カード), '26RSD01-001');
});

test('ムーシャッコのレベル情報が正しく設定されている', () => {
  const カード = ムーシャッコを作成('test-mushaako-2');
  const Lv一覧 = new Lvルール().Lvを取得(カード);
  assert.equal(Lv一覧.length, 2);
  assert.deepEqual(Lv一覧[0], { level: 1, cost: 1, bp: 2000 });
  assert.deepEqual(Lv一覧[1], { level: 2, cost: 2, bp: 3000 });
});

test('ムーシャッコにバトル終了時の効果がデータとして宣言されている', () => {
  const カード = ムーシャッコを作成('test-mushaako-3');
  const 効果一覧 = new 効果ルール().効果を取得(カード);

  assert.equal(効果一覧.length, 1, '効果が1つ宣言されているべき');
  const 効果 = 効果一覧[0];
  assert.deepEqual(効果.Lv, [2], 'Lv2で発動するべき');
  assert.equal(効果.トリガー, 'バトル終了時', 'バトル終了時に発動するべき');
  assert.equal(効果.状態, 'アタック中', 'アタック中であることを要求するべき');
  assert.deepEqual(効果.条件, { 数量: { 場: '自分', ゾーン: '手札', 以下: 5 } });
  assert.deepEqual(効果.処理, [{ ドロー: 1 }]);
});

// 実際に報告された不具合の再現。
// 「ムーシャッコで試し、消滅はしたが常に軽減は1つ満たされている状態になっている」。
//
// 消滅も破壊と同じ2段階（待機状態にする → トラッシュへ置く）で、
// 第2段階を誰も呼んでいなかった。画面は待機理由「消滅」のカードを描かないので、
// 消えたように見えるのに、中身では場に残ってシンボルが数えられ続けていた。
//
// 待機状態になったことだけを見ていると、この不具合は見つからない。
// ここでは盤面に見えるもの（場から消える・軽減が減る・アタックできない）だけを見る。
test('ムーシャッコ：コアを失うと場から消え、軽減シンボルにも数えられなくなる', () => {
  const 試合インスタンス = new 試合();
  試合インスタンス.プレイヤーを準備する('p1', 'プレイヤー1');
  試合インスタンス.プレイヤーを準備する('p2', 'プレイヤー2');
  試合インスタンス.ボイドを準備する();
  for (const プレイヤー識別子 of ['p1', 'p2']) {
    試合インスタンス.デッキを設定する(
      プレイヤー識別子,
      Array.from({ length: 10 }, (_, i) => ムーシャッコを作成(`${プレイヤー識別子}-deck-${i + 1}`))
    );
  }
  試合インスタンス.準備を行う('p1');
  試合インスタンス.準備を行う('p2');
  試合インスタンス.先攻を決める('p1');
  試合インスタンス.試合を開始する();

  const フィールド = 試合インスタンス.ゾーン管理.フィールドを取得(試合インスタンス.ゲーム, 'p1')!;
  const トラッシュ = 試合インスタンス.ゾーン管理.トラッシュを取得(試合インスタンス.ゲーム, 'p1')!;
  const リザーブ = 試合インスタンス.ゾーン管理.リザーブを取得(試合インスタンス.ゲーム, 'p1')!;

  const 自身 = ムーシャッコを作成('自身');
  フィールド.カードを追加(自身);
  試合インスタンス.コア管理.カードを保持者に(自身).コア数を設定(1);
  試合インスタンス.Lv管理.Lvを更新(自身, 1, false);

  // 画面が軽減の計算に使っているのと同じ、場のシンボルの数え方
  const 場のシンボル数 = (): number =>
    フィールド
      .カード一覧を取得()
      .flatMap(c => new シンボルルール().シンボルを取得(c)).length;

  assert.equal(場のシンボル数(), 1, '前提：場に出ているあいだは軽減に1つ数えられる');

  // 最後のコアを外す＝Lv1コスト未満になって消滅する
  assert.equal(試合インスタンス.コアを移動する(自身, リザーブ, 1), true);

  assert.equal(フィールド.カードを取得('自身'), undefined, '場から消える');
  assert.ok(トラッシュ.カードを取得('自身'), 'トラッシュにある');
  assert.equal(場のシンボル数(), 0, '軽減シンボルにも数えられなくなる');
  assert.equal(試合インスタンス.アタック宣言する(自身), false, '消滅した体ではアタックできない');
});

// 実際に報告された不具合の再現。
// 「ムーシャッコで試し、消滅はしたが常に軽減は1つ満たされている状態になっている」。
//
// 消滅も破壊と同じ2段階で、第2段階（トラッシュへ置く）を誰も呼んでいなかった。
// 画面は待機理由「消滅」のカードを描かないので消えたように見えるが、
// 中身では場に残っていて、シンボルが軽減に数えられ続けていた。
//
// ここでは中の状態ではなく、盤面に見えるところだけを見る。
test('ムーシャッコ：コアを失って消滅したら、場から消えて軽減にも数えられない', () => {
  const 試合インスタンス = new 試合();
  試合インスタンス.プレイヤーを準備する('p1', 'プレイヤー1');
  試合インスタンス.プレイヤーを準備する('p2', 'プレイヤー2');
  試合インスタンス.ボイドを準備する();
  for (const p of ['p1', 'p2']) {
    試合インスタンス.デッキを設定する(
      p,
      Array.from({ length: 10 }, (_, i) => ムーシャッコを作成(`${p}-deck-${i + 1}`))
    );
  }
  試合インスタンス.準備を行う('p1');
  試合インスタンス.準備を行う('p2');
  試合インスタンス.先攻を決める('p1');
  試合インスタンス.試合を開始する();

  const フィールド = 試合インスタンス.ゾーン管理.フィールドを取得(試合インスタンス.ゲーム, 'p1')!;
  const トラッシュ = 試合インスタンス.ゾーン管理.トラッシュを取得(試合インスタンス.ゲーム, 'p1')!;
  const リザーブ = 試合インスタンス.ゾーン管理.リザーブを取得(試合インスタンス.ゲーム, 'p1')!;

  // 場のシンボルを数える（軽減に使われるのと同じ見方）
  const 場のシンボル数 = () =>
    フィールド
      .カード一覧を取得()
      .flatMap(c => new シンボルルール().シンボルを取得(c)).length;

  const 自身 = ムーシャッコを作成('自身');
  フィールド.カードを追加(自身);
  試合インスタンス.コア管理.カードを保持者に(自身).コア数を設定(1);
  試合インスタンス.Lv管理.Lvを更新(自身, 1, false);
  試合インスタンス.ルール処理を実行する();

  assert.equal(場のシンボル数(), 1, '前提：場に出ているので軽減が1つ満たされる');

  // 最後のコアを外す＝Lv1コスト未満になって消滅する
  試合インスタンス.コアを移動する(自身, リザーブ, 1);

  assert.equal(フィールド.カードを取得('自身'), undefined, '場から消える');
  assert.ok(トラッシュ.カードを取得('自身'), 'トラッシュにある');
  assert.equal(場のシンボル数(), 0, '軽減にも数えられなくなる');
});
