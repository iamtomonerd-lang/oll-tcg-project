import { カード } from '../../../データ/カード/カード.js';
import { カード名称データ } from './カード名称データ.js';
import { 召喚時条件 } from '../効果/条件/召喚時.js';
import { 疲労状態の自分の赤いスピリット条件 } from '../効果/条件/疲労状態の自分の赤いスピリット.js';
import { BP制限相手スピリット指定効果 } from '../効果/行動/BP制限相手スピリット指定効果.js';
import { 破壊効果 } from '../効果/行動/破壊効果.js';

// ロワミーク（26RSD01-003）
// スピリット／赤／C／コスト3／系統：紅雲・風牙／ブロックアイコンA
// Lv1：コスト1・BP3000、Lv2：コスト3・BP5000
// 軽減シンボル：赤赤／シンボル：赤1個（EX）
// 効果：［Lv1-2］『召喚時』疲労状態の自分の赤のスピリットがいるなら、
//       BP3000以下の相手のスピリット1体を指定する。それを破壊する。
export const ロワミーク名称: Omit<カード名称データ, '識別子'> = {
  表示名: 'ロワミーク',
  説明: '素早い身のこなしで敵の隙をついて食らいつく。',
  カード名: 'ロワミーク',
  カードナンバー: '26RSD01-003',
  カード種別: 'スピリット',
  レアリティ: 'C',
  コスト: 3,
  系統: ['紅雲', '風牙'],
  ブロックアイコン: 'A',
  属性: ['赤'],
  軽減シンボル: ['赤', '赤'],
  シンボル: [{ 色: '赤', タイプ: 'EX' }],
  Lv: [
    { level: 1, cost: 1, bp: 3000 },
    { level: 2, cost: 3, bp: 5000 },
  ],
  カードテキスト: '［Lv1-2］《召喚時》疲労状態の自分の赤のスピリットがいるなら、BP3000以下の相手のスピリット1体を指定する。それを破壊する。',
};

// カード1枚分のインスタンスを生成する
export function ロワミークを作成(識別子: string): カード {
  const カード1 = new カード(識別子, { 識別子, ...ロワミーク名称 });

  // ［Lv1-2］『召喚時』疲労状態の自分の赤のスピリットがいるなら、
  // BP3000以下の相手のスピリット1体を指定する。それを破壊する。
  const 召喚時効果 = {
    条件: new 召喚時条件(),
    効果追加条件: new 疲労状態の自分の赤いスピリット条件(),
    対象選択効果: new BP制限相手スピリット指定効果(3000),
    実行効果: new 破壊効果(),
    発動Lv: [1, 2], // Lv1-2で発動
    発動タイミング: '召喚時',
  };

  カード1.状態を設定('召喚時_破壊効果', 召喚時効果);

  return カード1;
}
