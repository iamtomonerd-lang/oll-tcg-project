function 試合を準備する(): 試合 {
  const 試合インスタンス = new 試合();
  試合インスタンス.プレイヤーを準備する('p1', 'プレイヤー1');
  試合インスタンス.プレイヤーを準備する('p2', 'プレイヤー2');
  試合インスタンス.ボイドを準備する();
  試合インスタンス.デッキを設定する(
    'p1',
    Array.from({ length: 10 }, (_, i) => グンガタを作成(`p1-deck-${i + 1}`))
  );
  試合インスタンス.デッキを設定する(
    'p2',
    Array.from({ length: 10 }, (_, i) => グンガタを作成(`p2-deck-${i + 1}`))
  );
  試合インスタンス.準備を行う('p1');
  試合インスタンス.準備を行う('p2');
  試合インスタンス.先攻を決める('p1');
  試合インスタンス.試合を開始する();
  return 試合インスタンス;
}

function 場に出す(試合インスタンス: 試合, 識別子: string, カード: any, BP?: number) {
  試合インスタンス.ゾーン管理.フィールドを取得(試合インスタンス.ゲーム, 識別子)!.カードを追加(カード);
  // 場のカードには必ずコアが乗っている。乗せずに置くと、ルール処理の消滅判定に
  // 引っかかって即トラッシュ行きになる（実戦では起こらない状態）。
  // Lv1を保てる最小限だけ乗せる。Lvを変えたいテストは、このあとで自分で乗せ直す。
  試合インスタンス.コア管理
    .カードを保持者に(カード)
    .コア数を設定(new 消滅判定().最小必要コア数を取得(カード));
  if (BP !== undefined) 試合インスタンス.BP管理.BPを設定(カード, BP);
  return カード;
}

// 破壊は「待機状態にする → トラッシュへ置く」の2段階。
// 最後まで、つまり場から消えてトラッシュにあることを見る。
const 破壊されたか = (試合インスタンス: 試合, 識別子: string): boolean => {
  const 場 = 試合インスタンス.ゾーン管理.フィールドを取得(試合インスタンス.ゲーム, 'p2')!;
  const トラッシュ = 試合インスタンス.ゾーン管理.トラッシュを取得(試合インスタンス.ゲーム, 'p2')!;
  return !場.カードを取得(識別子) && !!トラッシュ.カードを取得(識別子);
};

// 召喚時効果を、召喚と同じ経路（場に置いてから事象を通知）で誘発させる
function 召喚する(試合インスタンス: 試合) {
  const 自身 = 場に出す(試合インスタンス, 'p1', 飛傑レウファルスを作成('自身'), 6000);
  試合インスタンス.効果実行器.事象を通知する('召喚時', 自身);
  return { 自身, 進行: 試合インスタンス.効果実行器.キューを進める() };
}

test('飛傑レウファルス：召喚時にBP5000以下を破壊する', async t => {
  await t.test('疲労した風牙の味方がいれば、BP5000以下を破壊できる', () => {
    const 試合インスタンス = 試合を準備する();
    // グンガタは系統：紅雲・風牙
    const 味方 = 場に出す(試合インスタンス, 'p1', グンガタを作成('風牙の味方'), 5000);
    試合インスタンス.カードの表示形式管理.疲労する(味方);

    場に出す(試合インスタンス, 'p2', グンガタを作成('相手-弱'), 5000);
    場に出す(試合インスタンス, 'p2', グンガタを作成('相手-強'), 6000);

    const { 進行 } = 召喚する(試合インスタンス);
    assert.equal(進行.状態, 'アイドル', '候補が1体なので選択を挟まない');

    assert.equal(破壊されたか(試合インスタンス, '相手-弱'), true, 'BP5000ちょうどは対象');
    assert.equal(破壊されたか(試合インスタンス, '相手-強'), false, 'BP5000超は対象外');
  });

  // ロワミーク（BP3000以下）との違い。ここを取り違えると射程が変わる。
  await t.test('BP5000ちょうどまでが射程で、5001以上は対象にならない', () => {
    const 試合インスタンス = 試合を準備する();
    const 味方 = 場に出す(試合インスタンス, 'p1', グンガタを作成('風牙の味方'), 5000);
    試合インスタンス.カードの表示形式管理.疲労する(味方);

    場に出す(試合インスタンス, 'p2', グンガタを作成('相手-5001'), 5001);

    const { 進行 } = 召喚する(試合インスタンス);
    assert.equal(進行.状態, 'アイドル');
    assert.equal(破壊されたか(試合インスタンス, '相手-5001'), false);
  });

  await t.test('味方が回復状態なら条件を満たさず、何も起きない', () => {
    const 試合インスタンス = 試合を準備する();
    // 疲労させないので条件不成立
    場に出す(試合インスタンス, 'p1', グンガタを作成('風牙の味方'), 5000);
    場に出す(試合インスタンス, 'p2', グンガタを作成('相手-弱'), 5000);

    const { 進行 } = 召喚する(試合インスタンス);
    assert.equal(進行.状態, 'アイドル');
    assert.equal(破壊されたか(試合インスタンス, '相手-弱'), false);
  });

  // ロワミークは「赤の味方」だが、こちらは「風牙の味方」。
  // 赤でも風牙を持たない味方では条件を満たさない。
  await t.test('疲労していても、風牙を持たない味方では条件を満たさない', () => {
    const 試合インスタンス = 試合を準備する();
    // 紫01は系統：血醒
    const 味方 = 場に出す(試合インスタンス, 'p1', 紫01を作成('風牙でない味方'), 5000);
    試合インスタンス.カードの表示形式管理.疲労する(味方);

    場に出す(試合インスタンス, 'p2', グンガタを作成('相手-弱'), 5000);

    const { 進行 } = 召喚する(試合インスタンス);
    assert.equal(進行.状態, 'アイドル');
    assert.equal(破壊されたか(試合インスタンス, '相手-弱'), false);
  });

  await t.test('候補が複数いれば選択待ちになる', () => {
    const 試合インスタンス = 試合を準備する();
    // セルタリウスは系統：風牙
    const 味方 = 場に出す(試合インスタンス, 'p1', セルタリウスを作成('風牙の味方'), 6000);
    試合インスタンス.カードの表示形式管理.疲労する(味方);

    場に出す(試合インスタンス, 'p2', グンガタを作成('相手1'), 4000);
    場に出す(試合インスタンス, 'p2', グンガタを作成('相手2'), 3000);

    const { 進行 } = 召喚する(試合インスタンス);
    assert.equal(進行.状態, '選択待ち');
    if (進行.状態 !== '選択待ち') return;
    assert.deepEqual(進行.候補.map(c => c.識別子).sort(), ['相手1', '相手2']);

    試合インスタンス.効果実行器.選択に答える(['相手2']);
    assert.equal(破壊されたか(試合インスタンス, '相手2'), true);
    assert.equal(破壊されたか(試合インスタンス, '相手1'), false);
  });
});

test('飛傑レウファルス：《真界放》『アタック中』のBP+2000', async t => {
  // 真界放状態は「真界放指定のあるLvにいるか」だけで決まる（12-2-1-1-3）。
  // 規則そのものの網羅は 効果語彙/真界放.test.ts。
  function 場に置く(試合インスタンス: 試合, Lv: number) {
    const 自身 = 場に出す(試合インスタンス, 'p1', 飛傑レウファルスを作成('自身'));
    試合インスタンス.Lv管理.Lvを上げる(自身, Lv);
    試合インスタンス.BP管理.Lvに対応したBPに更新(自身, Lv);
    return 自身;
  }

  await t.test('Lv2でアタック中なら BP8000 + 2000 = 10000', () => {
    const 試合インスタンス = 試合を準備する();
    const 自身 = 場に置く(試合インスタンス, 2);
    自身.状態を設定('アタック中', true);

    assert.equal(試合インスタンス.BP管理.現在のBPを取得(自身), 10000);
  });

  await t.test('アタック中でなければ BP8000 のまま', () => {
    const 試合インスタンス = 試合を準備する();
    const 自身 = 場に置く(試合インスタンス, 2);

    assert.equal(試合インスタンス.BP管理.現在のBPを取得(自身), 8000);
  });

  await t.test('Lv1では真界放状態でないので、アタック中でも上がらない', () => {
    const 試合インスタンス = 試合を準備する();
    const 自身 = 場に置く(試合インスタンス, 1);
    自身.状態を設定('アタック中', true);

    assert.equal(試合インスタンス.BP管理.現在のBPを取得(自身), 6000);
  });
});
