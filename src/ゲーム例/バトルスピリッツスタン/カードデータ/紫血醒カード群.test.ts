// 払えないコストの【起動】効果は候補に出してはいけない。
// 出したままにすると「選んでも何も起きない手」が延々と残り、対戦が終わらなくなる。
test('払えないコストの起動効果は候補から消える', () => {
  // 紫09：このネクサスを疲労させる▶…（既に疲労していたら払えない）
  {
    const 試合インスタンス = 試合を準備する();
    const ネクサス = 場に出す(試合インスタンス, 'p1', 紫09を作成('ネクサス'), 1);

    assert.equal(
      試合インスタンス.効果実行器.発動できる起動効果を集める('p1').length,
      1,
      '回復状態なら撃てる'
    );

    試合インスタンス.カードの表示形式管理.疲労する(ネクサス);
    assert.equal(
      試合インスタンス.効果実行器.発動できる起動効果を集める('p1').length,
      0,
      '疲労させるコストが払えないので候補から消える'
    );
  }

  // 紫12：このネクサスを破壊する▶…（既に待機状態なら払えない）
  {
    const 試合インスタンス = 試合を準備する();
    const ネクサス = 場に出す(試合インスタンス, 'p1', 紫12を作成('ネクサス'), 3);

    assert.equal(
      試合インスタンス.効果実行器.発動できる起動効果を集める('p1').length,
      1,
      'Lv2で場にいれば撃てる'
    );

    試合インスタンス.破壊管理.破壊する(ネクサス, { 由来: '自分の効果', 効果識別子: 'テスト' });
    assert.equal(
      試合インスタンス.効果実行器.発動できる起動効果を集める('p1').length,
      0,
      '待機状態のカードは効果を撃てない'
    );
  }
});
