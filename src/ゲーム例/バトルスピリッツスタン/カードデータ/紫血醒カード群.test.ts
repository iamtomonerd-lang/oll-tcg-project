function 相手スピリットを作る(識別子: string): カード {
  return new カード(識別子, {
    識別子,
    表示名: '相手スピリット',
    カード名: '相手スピリット',
    カードナンバー: 'TEST-001',
    カード種別: 'スピリット',
    レアリティ: 'C',
    コスト: 3,
    系統: ['血醒'],
    ブロックアイコン: 'A',
    属性: ['紫'],
    軽減シンボル: ['紫'],
    シンボル: [{ 色: '紫' }],
    Lv: [
      { level: 1, cost: 1, bp: 3000 },
      { level: 2, cost: 3, bp: 5000 },
    ],
  } as any);
}

function 試合を準備する(): 試合 {
  const 試合インスタンス = new 試合();
  試合インスタンス.プレイヤーを準備する('p1', 'プレイヤー1');
  試合インスタンス.プレイヤーを準備する('p2', 'プレイヤー2');
  試合インスタンス.ボイドを準備する();
  試合インスタンス.デッキを設定する(
    'p1',
    Array.from({ length: 12 }, (_, i) => グンガタを作成(`p1-deck-${i + 1}`))
  );
  試合インスタンス.デッキを設定する(
    'p2',
    Array.from({ length: 12 }, (_, i) => グンガタを作成(`p2-deck-${i + 1}`))
  );
  試合インスタンス.準備を行う('p1');
  試合インスタンス.準備を行う('p2');
  試合インスタンス.先攻を決める('p1');
  return 試合インスタンス;
}

function 環境を作る() {
  const 試合インスタンス = 試合を準備する();
  return { 試合: 試合インスタンス, インタプリタ: new 効果インタプリタ(new バトスピ接続(試合インスタンス)) };
}

function 場に出す(
  試合インスタンス: 試合,
  プレイヤー識別子: string,
  対象: カード,
  コア数 = 0
): カード {
  const フィールド = 試合インスタンス.ゾーン管理.フィールドを取得(
    試合インスタンス.ゲーム,
    プレイヤー識別子
  )!;
  フィールド.カードを追加(対象);
  if (コア数 > 0) {
    const 保持者 = 試合インスタンス.コア管理.カードを保持者に(対象);
    保持者.コア数を設定(コア数);
    試合インスタンス.Lv管理.Lvを更新(対象, コア数, 保持者.ソウルコアあるか());
  }
  return 対象;
}

function 最後まで実行する(
  インタプリタ: 効果インタプリタ,
  効果: 効果定義,
  自身: カード,
  プレイヤー識別子: string
): 実行結果 {
  let 結果 = インタプリタ.実行(効果, 自身, プレイヤー識別子);
  let 安全カウンタ = 0;
  while (結果.状態 === '選択待ち' && 安全カウンタ++ < 10) {
    結果 = インタプリタ.再開(結果.中断状態, 結果.候補.slice(0, 結果.最大).map(c => c.識別子));
  }
  return 結果;
}

const 空振りを示すログ = [
  '未知のアクション',
  'できませんでした',
  '動かせませんでした',
  '定まりません',
  '対象がいません',
  '対象がありません',
];

// 効果を持つカードすべてを、対象が揃った盤面で走らせる
test('紫／血醒のカードが実データのまま最後まで走る', async t => {
  for (const { 名, 作成 } of 紫血醒カード一覧) {
    const 見本 = 作成('見本');
    const 効果一覧 = 効果ルールの実体.効果を取得(見本);
    if (効果一覧.length === 0) {
      continue; // 紫17（キーワードのみ）は効果を持たない
    }

    await t.test(`${名} が空振りせずに完了する`, () => {
      const { 試合: 試合インスタンス, インタプリタ } = 環境を作る();

      // 自分側：疲労した血醒スピリット（条件用）と、アタック中の血醒スピリット
      const 味方疲労 = 場に出す(試合インスタンス, 'p1', 相手スピリットを作る('味方疲労'), 3);
      試合インスタンス.カードの表示形式管理.疲労する(味方疲労);
      const 味方アタック中 = 場に出す(試合インスタンス, 'p1', 相手スピリットを作る('味方攻'), 3);
      味方アタック中.状態を設定('アタック中', true);

      // 相手側：コアを多めに乗せて、コアを剥がしても消滅しないようにする
      場に出す(試合インスタンス, 'p2', 相手スピリットを作る('相手1'), 5);

      const 自身 = 場に出す(試合インスタンス, 'p1', 作成('自身'), 6);

      for (let 添字 = 0; 添字 < 効果一覧.length; 添字++) {
        const 結果 = 最後まで実行する(インタプリタ, 効果一覧[添字], 自身, 'p1');

        assert.equal(結果.状態, '完了', `${名} の効果${添字} が完了しなかった`);
        if (結果.状態 !== '完了') return;
        assert.equal(結果.発動した, true, `${名} の効果${添字} が発動しなかった`);

        const 問題 = 結果.ログ.filter(行 => 空振りを示すログ.some(語 => 行.includes(語)));
        assert.deepEqual(問題, [], `${名} の効果${添字} が空振りしている`);
      }
    });
  }
});

