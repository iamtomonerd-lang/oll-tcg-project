import { カード } from '../../../データ/カード/カード.js';
import { カード名称データ } from './カード名称データ.js';
import {
  配置時,
  自分のアタックステップずっと,
  疲労している味方がいる,
  自分のトラッシュから選ぶ,
  自分のスピリットを選ぶ,
  それを手札に戻す,
  それのBPを変える,
} from '../効果部品/index.js';

// 浮遊岩域（26RSD01-011）
// ネクサス／赤／C／コスト4／系統：風牙
// Lv1：コスト0、Lv2：コスト2
// 軽減シンボル：赤赤／シンボル：赤1個（通常）
//
// ［Lv1-2］『配置時』疲労状態の自分の赤のスピリットがいるなら、
//          自分のトラッシュのコスト4以下で系統：「風牙」を持つスピリットカード1枚を
//          指定する。それを手札に戻す。
// ［Lv2］『自分のアタックステップ』継召を持つ自分のスピリットすべてをBP+2000する。
//
// 2つ目は「アタックステップのあいだ、条件に合う味方のBPが上がっている」という常在効果。
// 誘発（1回きり）として書くと、毎ターン+2000が積み上がって元に戻らなくなる。
// 常在にしておけば、アタックステップを抜けた時点で自然に元のBPへ戻る。
export const 浮遊岩域名称: Omit<カード名称データ, '識別子'> = {
  表示名: '浮遊岩域',
  説明: 'ここが赤き空の領域、羽ばたき、浮き、飛行する者たちの楽土なり。',
  カード名: '浮遊岩域',
  カードナンバー: '26RSD01-011',
  カード種別: 'ネクサス',
  レアリティ: 'C',
  コスト: 4,
  系統: ['風牙'],
  ブロックアイコン: 'A',
  属性: ['赤'],
  軽減シンボル: ['赤', '赤'],
  シンボル: [{ 色: '赤', タイプ: '通常' }],
  Lv: [
    { level: 1, cost: 0 },
    { level: 2, cost: 2 },
  ],
  カードテキスト:
    '［Lv1-2］『配置時』疲労状態の自分の赤のスピリットがいるなら、自分のトラッシュのコスト4以下で系統：「風牙」を持つスピリットカード1枚を指定する。それを手札に戻す。' +
    '［Lv2］『自分のアタックステップ』継召を持つ自分のスピリットすべてをBP+2000する。',
  効果: [
    {
      Lv: [1, 2],
      ...配置時,
      条件: 疲労している味方がいる({ 属性: '赤' }),
      処理: [
        自分のトラッシュから選ぶ({ 種別: 'スピリット', 系統: '風牙', コスト以下: 4 }),
        それを手札に戻す,
      ],
    },
    {
      Lv: [2],
      ...自分のアタックステップずっと,
      処理: [
        自分のスピリットを選ぶ({ キーワード: '継召', 体数: 'すべて' }),
        それのBPを変える(2000),
      ],
    },
  ],
};

export function 浮遊岩域を作成(識別子: string): カード {
  return new カード(識別子, { 識別子, ...浮遊岩域名称 });
}
