// 画面やデッキ構築が使う、カード1種類ぶんの見出し。
export interface カードの見出し {
  カードナンバー: string;
  カード名: string;
  表示名: string;
  カード種別: カード種別;
  コスト: number;
  属性: string[];
  系統: string[];
}

export interface 帳の項目 extends カードの見出し {
  作る: カードを作る;
}

const カード名ルール個体 = new カード名ルール();
const カードナンバールール個体 = new カードナンバールール();
const カード種別ルール個体 = new カード種別ルール();
const コストルール個体 = new コストルール();
const 属性ルール個体 = new 属性ルール();
const 系統ルール個体 = new 系統ルール();

// 見本を1枚作って、そこから見出しを読み取る。
// 見本の識別子は実際の対戦では使わない形にしておく。
function 見出しを読む(作る: カードを作る, 順番: number): 帳の項目 {
  const 見本 = 作る(`見本-${順番}`);
  const 名称 = 見本.名称 as { 表示名?: string };
  return {
    カードナンバー: カードナンバールール個体.カードナンバーを取得(見本),
    カード名: カード名ルール個体.カード名を取得(見本),
    表示名: 名称.表示名 ?? カード名ルール個体.カード名を取得(見本),
    // ルール側は string を返すが、カードデータの側では3種類に限られている
    カード種別: カード種別ルール個体.カード種別を取得(見本) as カード種別,
    コスト: コストルール個体.コストを取得(見本),
    属性: 属性ルール個体.属性を取得(見本),
    系統: 系統ルール個体.系統を取得(見本),
    作る,
  };
}

export const カード帳: 帳の項目[] = 作成関数一覧.map(見出しを読む);

// カードナンバーで引く
const 番号の索引 = new Map<string, 帳の項目>(カード帳.map(項 => [項.カードナンバー, 項]));

export function 番号で引く(カードナンバー: string): 帳の項目 | undefined {
  return 番号の索引.get(カードナンバー);
}

export function 番号は実在するか(カードナンバー: string): boolean {
  return 番号の索引.has(カードナンバー);
}

// 「同名は3枚まで」を数えるのに使う。カードナンバーではなくカード名で数えること。
export function 番号からカード名を引く(カードナンバー: string): string | undefined {
  return 番号の索引.get(カードナンバー)?.カード名;
}

// 画面に渡すぶん（作成関数は渡さない）
export function 見出し一覧を取得(): カードの見出し[] {
  return カード帳.map(({ 作る: _作る, ...見出し }) => 見出し);
}
