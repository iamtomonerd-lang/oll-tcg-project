test('セルタリウス（26RSD01-008）', async t => {
  await t.test('カード情報が正しく設定されている', () => {
    const カード = セルタリウスを作成('test-1');

    assert.equal(new カード名ルール().カード名を取得(カード), 'セルタリウス');
    assert.equal(new カードナンバールール().カードナンバーを取得(カード), '26RSD01-008');
    assert.equal(new カード種別ルール().スピリットか(カード), true);
    assert.equal(new レアリティルール().レアリティを取得(カード), 'C');
    assert.deepEqual(new 属性ルール().属性を取得(カード), ['赤']);
    assert.equal(new コストルール().コストを取得(カード), 6);
    assert.deepEqual(new 系統ルール().系統を取得(カード), ['風牙']);
  });

  await t.test('レベル情報が Lv1:6000 / Lv2:7000', () => {
    const Lv一覧 = new Lvルール().Lvを取得(セルタリウスを作成('test-2'));
    assert.equal(Lv一覧.length, 2);
    assert.deepEqual(Lv一覧[0], { level: 1, cost: 1, bp: 6000 });
    assert.deepEqual(Lv一覧[1], { level: 2, cost: 2, bp: 7000 });
  });

  await t.test('軽減シンボルが赤赤赤、シンボルは通常の赤1個', () => {
    const カード = セルタリウスを作成('test-3');
    assert.deepEqual(new 軽減シンボルルール().軽減シンボルを取得(カード), ['赤', '赤', '赤']);
    assert.equal(new シンボルルール().シンボル数を取得(カード), 1);
    assert.equal(new シンボルルール().EXシンボルを持つ(カード), false);
  });

  await t.test('《継召》をキーワードとして持つ', () => {
    const カード = セルタリウスを作成('test-4');
    assert.equal(new キーワードルール().キーワードを持つ(カード, '継召'), true);
  });

  // 《継召》はトラッシュのEXシンボルを除外して軽減する仕組み。
  // セルタリウス自身はEXシンボルを持たないので、自分を除外して軽減はできない。
  await t.test('自身はEXシンボルを持たないので、継召の除外元にはならない', () => {
    assert.equal(new 継召判定().除外できるか(セルタリウスを作成('test-5')), false);
    assert.equal(new 継召判定().除外できるか(グンガタを作成('EX持ち')), true);
  });

  await t.test('効果が語彙調査の カード10 と一致する', () => {
    const 効果一覧 = new 効果ルール().効果を取得(セルタリウスを作成('test-6'));

    assert.equal(効果一覧.length, 1);
    assert.deepEqual(効果一覧[0], カード10);
  });
});

// === 召喚時効果を通しで確認する ===

function 試合を準備する(): 試合 {
  const 試合インスタンス = new 試合();
  試合インスタンス.プレイヤーを準備する('p1', 'プレイヤー1');
  試合インスタンス.プレイヤーを準備する('p2', 'プレイヤー2');
  試合インスタンス.ボイドを準備する();
  試合インスタンス.デッキを設定する(
    'p1',
    Array.from({ length: 10 }, (_, i) => グンガタを作成(`p1-deck-${i + 1}`))
  );
  試合インスタンス.デッキを設定する(
    'p2',
    Array.from({ length: 10 }, (_, i) => グンガタを作成(`p2-deck-${i + 1}`))
  );
  試合インスタンス.準備を行う('p1');
  試合インスタンス.準備を行う('p2');
  試合インスタンス.先攻を決める('p1');
  試合インスタンス.試合を開始する();
  return 試合インスタンス;
}

function トラッシュに積む(試合インスタンス: 試合, カード一覧: any[]): void {
  const トラッシュ = 試合インスタンス.ゾーン管理.トラッシュを取得(試合インスタンス.ゲーム, 'p1')!;
  for (const カード of カード一覧) {
    トラッシュ.カードを追加(カード);
  }
}

// 場に出して『召喚時』を通知する（召喚と同じ経路）
function 召喚する(試合インスタンス: 試合) {
  const 自身 = セルタリウスを作成('自身');
  試合インスタンス.ゾーン管理.フィールドを取得(試合インスタンス.ゲーム, 'p1')!.カードを追加(自身);
  試合インスタンス.効果実行器.事象を通知する('召喚時', 自身);
  return 試合インスタンス.効果実行器.キューを進める();
}

const 手札の識別子 = (試合インスタンス: 試合): string[] =>
  試合インスタンス.ゾーン管理
    .手札を取得(試合インスタンス.ゲーム, 'p1')!
    .カード一覧を取得()
    .map(c => c.識別子);

test('セルタリウス：召喚時にトラッシュの風牙を手札に戻す', async t => {
  // 「指定できる」なので、候補が1枚でも必ず選ばせる。
  // 断る余地があるぶん、候補数が必要数と一致する自動確定は働かない。
  await t.test('候補が1枚でも選択待ちになり、選べば手札に戻る', () => {
    const 試合インスタンス = 試合を準備する();
    トラッシュに積む(試合インスタンス, [グンガタを作成('トラッシュの風牙')]);
    const 手札の元 = 手札の識別子(試合インスタンス);

    const 進行 = 召喚する(試合インスタンス);
    assert.equal(進行.状態, '選択待ち');
    if (進行.状態 !== '選択待ち') return;
    assert.equal(進行.最小, 0, '0枚でもよい');
    assert.equal(進行.最大, 1);

    試合インスタンス.効果実行器.選択に答える(['トラッシュの風牙']);

    const 増えた = 手札の識別子(試合インスタンス).filter(id => !手札の元.includes(id));
    assert.deepEqual(増えた, ['トラッシュの風牙']);
  });

  // 「「セルタリウス」以外の」の部分。ここが効いていないと、
  // トラッシュのセルタリウスを釣り上げ続けられてしまう。
  await t.test('トラッシュのセルタリウスは対象にならない', () => {
    const 試合インスタンス = 試合を準備する();
    トラッシュに積む(試合インスタンス, [
      セルタリウスを作成('トラッシュのセルタリウス'),
      グンガタを作成('トラッシュの風牙'),
    ]);
    const 手札の元 = 手札の識別子(試合インスタンス);

    const 進行 = 召喚する(試合インスタンス);
    assert.equal(進行.状態, '選択待ち');
    if (進行.状態 !== '選択待ち') return;
    assert.deepEqual(
      進行.候補.map(c => c.識別子),
      ['トラッシュの風牙'],
      'セルタリウスは候補に入らない'
    );

    試合インスタンス.効果実行器.選択に答える(['トラッシュの風牙']);

    const 増えた = 手札の識別子(試合インスタンス).filter(id => !手札の元.includes(id));
    assert.deepEqual(増えた, ['トラッシュの風牙'], 'セルタリウスは戻らない');
  });

  await t.test('風牙を持たないスピリットは対象にならない', () => {
    const 試合インスタンス = 試合を準備する();
    // 紫01は系統：血醒
    トラッシュに積む(試合インスタンス, [紫01を作成('風牙でないスピリット')]);
    const 手札の元 = 手札の識別子(試合インスタンス);

    召喚する(試合インスタンス);

    assert.deepEqual(
      手札の識別子(試合インスタンス).filter(id => !手札の元.includes(id)),
      [],
      '手札は増えない'
    );
  });

  await t.test('候補が複数あれば、どれを戻すか選択待ちになる', () => {
    const 試合インスタンス = 試合を準備する();
    トラッシュに積む(試合インスタンス, [
      グンガタを作成('風牙1'),
      グンガタを作成('風牙2'),
    ]);
    const 手札の元 = 手札の識別子(試合インスタンス);

    const 進行 = 召喚する(試合インスタンス);
    assert.equal(進行.状態, '選択待ち');
    if (進行.状態 !== '選択待ち') return;
    assert.deepEqual(進行.候補.map(c => c.識別子).sort(), ['風牙1', '風牙2']);

    試合インスタンス.効果実行器.選択に答える(['風牙2']);

    assert.deepEqual(
      手札の識別子(試合インスタンス).filter(id => !手札の元.includes(id)),
      ['風牙2'],
      '選んだほうだけ戻る'
    );
  });

  // 「指定できる」なので0枚でもよい
  await t.test('指定しなければ何も戻らない', () => {
    const 試合インスタンス = 試合を準備する();
    トラッシュに積む(試合インスタンス, [グンガタを作成('風牙1'), グンガタを作成('風牙2')]);
    const 手札の元 = 手札の識別子(試合インスタンス);

    召喚する(試合インスタンス);
    試合インスタンス.効果実行器.選択に答える([]);

    assert.deepEqual(
      手札の識別子(試合インスタンス).filter(id => !手札の元.includes(id)),
      [],
      '手札は増えない'
    );
  });

  await t.test('トラッシュが空でも失敗しない', () => {
    const 試合インスタンス = 試合を準備する();
    const 進行 = 召喚する(試合インスタンス);

    assert.equal(進行.状態, 'アイドル', '候補がいないので止まらず進む');
  });
});
