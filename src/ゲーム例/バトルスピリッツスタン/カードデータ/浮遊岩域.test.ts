// アタックステップは先攻の第1ターンではスキップされるので、一巡させる必要がある
function アタックステップへ進める(試合インスタンス: 試合, ターンプレイヤー = 'p1'): void {
  試合インスタンス.試合を開始する();
  for (let 安全カウンタ = 0; 安全カウンタ < 60; 安全カウンタ++) {
    if (
      試合インスタンス.現在のステップ() === 'アタックステップ' &&
      試合インスタンス.ゲーム.現在のプレイヤーを取得()?.識別子 === ターンプレイヤー
    ) {
      return;
    }
    試合インスタンス.ステップを終了する();
  }
  throw new Error(`${ターンプレイヤー} のアタックステップに到達できませんでした`);
}

const BP = (試合インスタンス: 試合, カード: any): number =>
  試合インスタンス.BP管理.現在のBPを取得(カード);

test('浮遊岩域：自分のアタックステップに《継召》持ちをBP+2000する', async t => {
  await t.test('アタックステップのあいだだけ上がり、抜ければ元に戻る', () => {
    const 試合インスタンス = 試合を準備する();
    const 岩域 = 場に出す(試合インスタンス, 'p1', 浮遊岩域を作成('岩域'));
    試合インスタンス.Lv管理.Lvを上げる(岩域, 2);
    // セルタリウスは《継召》持ち
    const 継召持ち = 場に出す(試合インスタンス, 'p1', セルタリウスを作成('継召持ち'), 6000);

    試合インスタンス.試合を開始する();
    assert.equal(BP(試合インスタンス, 継召持ち), 6000, 'メインステップでは上がらない');

    アタックステップへ進める(試合インスタンス);
    assert.equal(BP(試合インスタンス, 継召持ち), 8000, 'アタックステップで+2000');

    // アタックステップを抜ける
    試合インスタンス.ステップを終了する();
    assert.notEqual(試合インスタンス.現在のステップ(), 'アタックステップ');
    assert.equal(BP(試合インスタンス, 継召持ち), 6000, '抜ければ元に戻る');
  });

  // ここが誘発（1回きり）だと、ターンをまたぐたびに+2000が積み上がってしまう。
  await t.test('ターンをまたいでも積み上がらない', () => {
    const 試合インスタンス = 試合を準備する();
    const 岩域 = 場に出す(試合インスタンス, 'p1', 浮遊岩域を作成('岩域'));
    試合インスタンス.Lv管理.Lvを上げる(岩域, 2);
    const 継召持ち = 場に出す(試合インスタンス, 'p1', セルタリウスを作成('継召持ち'), 6000);

    アタックステップへ進める(試合インスタンス, 'p1');
    assert.equal(BP(試合インスタンス, 継召持ち), 8000);

    // 一巡させて、もう一度自分のアタックステップへ
    アタックステップへ進める(試合インスタンス, 'p2');
    assert.equal(BP(試合インスタンス, 継召持ち), 6000, '相手のターンでは上がらない');

    アタックステップへ進める(試合インスタンス, 'p1');
    assert.equal(BP(試合インスタンス, 継召持ち), 8000, '2巡目も+2000のまま（積み上がらない）');
  });

  await t.test('《継召》を持たない味方は上がらない', () => {
    const 試合インスタンス = 試合を準備する();
    const 岩域 = 場に出す(試合インスタンス, 'p1', 浮遊岩域を作成('岩域'));
    試合インスタンス.Lv管理.Lvを上げる(岩域, 2);
    // グンガタは《継召》を持たない
    const 継召なし = 場に出す(試合インスタンス, 'p1', グンガタを作成('継召なし'), 5000);

    アタックステップへ進める(試合インスタンス);

    assert.equal(BP(試合インスタンス, 継召なし), 5000);
  });

  await t.test('相手の《継召》持ちは上がらない', () => {
    const 試合インスタンス = 試合を準備する();
    const 岩域 = 場に出す(試合インスタンス, 'p1', 浮遊岩域を作成('岩域'));
    試合インスタンス.Lv管理.Lvを上げる(岩域, 2);
    const 相手の継召持ち = 場に出す(試合インスタンス, 'p2', セルタリウスを作成('相手'), 6000);

    アタックステップへ進める(試合インスタンス);

    assert.equal(BP(試合インスタンス, 相手の継召持ち), 6000, '「自分の」なので相手は対象外');
  });

  await t.test('複数体いれば全員が上がる（「すべて」）', () => {
    const 試合インスタンス = 試合を準備する();
    const 岩域 = 場に出す(試合インスタンス, 'p1', 浮遊岩域を作成('岩域'));
    試合インスタンス.Lv管理.Lvを上げる(岩域, 2);
    const 継召1 = 場に出す(試合インスタンス, 'p1', セルタリウスを作成('継召1'), 6000);
    const 継召2 = 場に出す(試合インスタンス, 'p1', セルタリウスを作成('継召2'), 7000);
    const 継召なし = 場に出す(試合インスタンス, 'p1', 紫01を作成('継召なし'), 3000);

    アタックステップへ進める(試合インスタンス);

    assert.equal(BP(試合インスタンス, 継召1), 8000);
    assert.equal(BP(試合インスタンス, 継召2), 9000);
    assert.equal(BP(試合インスタンス, 継召なし), 3000);
  });

  await t.test('Lv1では働かない', () => {
    const 試合インスタンス = 試合を準備する();
    const 岩域 = 場に出す(試合インスタンス, 'p1', 浮遊岩域を作成('岩域'));
    試合インスタンス.Lv管理.Lvを上げる(岩域, 1);
    const 継召持ち = 場に出す(試合インスタンス, 'p1', セルタリウスを作成('継召持ち'), 6000);

    アタックステップへ進める(試合インスタンス);

    assert.equal(BP(試合インスタンス, 継召持ち), 6000);
  });
});
