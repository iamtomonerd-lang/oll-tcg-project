function 試合を準備する(): 試合 {
  const 試合インスタンス = new 試合();
  試合インスタンス.プレイヤーを準備する('p1', 'プレイヤー1');
  試合インスタンス.プレイヤーを準備する('p2', 'プレイヤー2');
  試合インスタンス.ボイドを準備する();
  試合インスタンス.デッキを設定する(
    'p1',
    Array.from({ length: 10 }, (_, i) => グンガタを作成(`p1-deck-${i + 1}`))
  );
  試合インスタンス.デッキを設定する(
    'p2',
    Array.from({ length: 10 }, (_, i) => グンガタを作成(`p2-deck-${i + 1}`))
  );
  試合インスタンス.準備を行う('p1');
  試合インスタンス.準備を行う('p2');
  試合インスタンス.先攻を決める('p1');
  return 試合インスタンス;
}

function 場に出す(試合インスタンス: 試合, 識別子: string, カード: any, BP?: number) {
  試合インスタンス.ゾーン管理.フィールドを取得(試合インスタンス.ゲーム, 識別子)!.カードを追加(カード);
  // 場のカードには必ずコアが乗っている。乗せずに置くと、ルール処理の消滅判定に
  // 引っかかって即トラッシュ行きになる（実戦では起こらない状態）。
  // Lv1を保てる最小限だけ乗せる。Lvを変えたいテストは、このあとで自分で乗せ直す。
  試合インスタンス.コア管理
    .カードを保持者に(カード)
    .コア数を設定(new 消滅判定().最小必要コア数を取得(カード));
  if (BP !== undefined) 試合インスタンス.BP管理.BPを設定(カード, BP);
  return カード;
}

function トラッシュに積む(試合インスタンス: 試合, カード一覧: any[]): void {
  const トラッシュ = 試合インスタンス.ゾーン管理.トラッシュを取得(試合インスタンス.ゲーム, 'p1')!;
  for (const カード of カード一覧) {
    トラッシュ.カードを追加(カード);
  }
}

const 手札の識別子 = (試合インスタンス: 試合): string[] =>
  試合インスタンス.ゾーン管理
    .手札を取得(試合インスタンス.ゲーム, 'p1')!
    .カード一覧を取得()
    .map(c => c.識別子);

// 場に置いて『配置時』を通知する（配置と同じ経路）
function 配置する(試合インスタンス: 試合, Lv = 1) {
  const 自身 = 場に出す(試合インスタンス, 'p1', 浮遊岩域を作成('岩域'));
  試合インスタンス.Lv管理.Lvを上げる(自身, Lv);
  試合インスタンス.効果実行器.事象を通知する('配置時', 自身);
  return { 自身, 進行: 試合インスタンス.効果実行器.キューを進める() };
}

test('浮遊岩域：配置時にトラッシュの風牙を手札に戻す', async t => {
  await t.test('疲労した赤の味方がいれば、条件を満たして手札に戻る', () => {
    const 試合インスタンス = 試合を準備する();
    const 味方 = 場に出す(試合インスタンス, 'p1', グンガタを作成('赤の味方'), 5000);
    試合インスタンス.カードの表示形式管理.疲労する(味方);
    // グンガタはコスト4、系統：紅雲・風牙なので「コスト4以下の風牙」に合う
    トラッシュに積む(試合インスタンス, [グンガタを作成('トラッシュの風牙')]);
    const 手札の元 = 手札の識別子(試合インスタンス);

    const { 進行 } = 配置する(試合インスタンス);
    assert.equal(進行.状態, 'アイドル', '候補が1枚なので選択を挟まない');

    assert.deepEqual(
      手札の識別子(試合インスタンス).filter(id => !手札の元.includes(id)),
      ['トラッシュの風牙']
    );
  });

  await t.test('味方が回復状態なら条件を満たさず、何も起きない', () => {
    const 試合インスタンス = 試合を準備する();
    場に出す(試合インスタンス, 'p1', グンガタを作成('赤の味方'), 5000);
    トラッシュに積む(試合インスタンス, [グンガタを作成('トラッシュの風牙')]);
    const 手札の元 = 手札の識別子(試合インスタンス);

    配置する(試合インスタンス);

    assert.deepEqual(手札の識別子(試合インスタンス).filter(id => !手札の元.includes(id)), []);
  });

  // 「コスト4以下」の部分。セルタリウスはコスト6なので釣れない。
  await t.test('コスト5以上の風牙は対象にならない', () => {
    const 試合インスタンス = 試合を準備する();
    const 味方 = 場に出す(試合インスタンス, 'p1', グンガタを作成('赤の味方'), 5000);
    試合インスタンス.カードの表示形式管理.疲労する(味方);
    トラッシュに積む(試合インスタンス, [セルタリウスを作成('コスト6の風牙')]);
    const 手札の元 = 手札の識別子(試合インスタンス);

    配置する(試合インスタンス);

    assert.deepEqual(
      手札の識別子(試合インスタンス).filter(id => !手札の元.includes(id)),
      [],
      'コスト6は釣れない'
    );
  });
});

