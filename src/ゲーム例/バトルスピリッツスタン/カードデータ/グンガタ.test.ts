function モノデッキを作成(接頭辞: string, 枚数 = 40) {
  return Array.from({ length: 枚数 }, (_, i) => グンガタを作成(`${接頭辞}-${i + 1}`));
}

test('グン＝ガタのカード情報が正しく読み取れる', () => {
  const カード = グンガタを作成('test-1');

  assert.equal(new カード名ルール().カード名を取得(カード), 'グン＝ガタ');
  assert.equal(new コストルール().コストを取得(カード), 4);
  assert.deepEqual(new 系統ルール().系統を取得(カード), ['紅雲', '風牙']);
  assert.equal(new ブロックアイコンルール().ブロックアイコンを取得(カード), 'A');
  assert.deepEqual(new 属性ルール().属性を取得(カード), ['赤']);
  assert.equal(new レアリティルール().レアリティを取得(カード), 'C');
  assert.equal(new カードナンバールール().カードナンバーを取得(カード), '26RSD01-005');
  assert.deepEqual(new 軽減シンボルルール().軽減シンボルを取得(カード), ['赤', '赤', '赤']);
  assert.equal(new シンボルルール().シンボル数を取得(カード), 2);
  assert.equal(new シンボルルール().EXシンボルを持つ(カード), true);
  assert.equal(new カード種別ルール().スピリットか(カード), true);

  const Lv一覧 = new Lvルール().Lvを取得(カード);
  assert.equal(Lv一覧.length, 2);
  assert.deepEqual(Lv一覧[0], { level: 1, cost: 1, bp: 5000 });
  assert.deepEqual(Lv一覧[1], { level: 2, cost: 3, bp: 8000 });
});

