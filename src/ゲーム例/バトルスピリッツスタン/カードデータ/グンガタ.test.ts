test('コアを十分に用意すればグン＝ガタを召喚でき、Lv1のBPが自動で設定される', () => {
  const 試合インスタンス = new 試合();
  試合インスタンス.プレイヤーを準備する('p1', 'プレイヤー1');
  試合インスタンス.プレイヤーを準備する('p2', 'プレイヤー2');
  試合インスタンス.ボイドを準備する();

  試合インスタンス.デッキを設定する('p1', モノデッキを作成('p1'));
  試合インスタンス.デッキを設定する('p2', モノデッキを作成('p2'));
  試合インスタンス.準備を行う('p1');
  試合インスタンス.準備を行う('p2');
  試合インスタンス.先攻を決める('p1');
  試合インスタンス.試合を開始する();
  試合インスタンス.次の行動可能なステップまで進める(); // メインステップまで進む

  // 初期リザーブ（通常3+ソウル1）だけではコスト4を通常コアだけで支払えないため、
  // テスト用に通常コアを追加で積む（複数ターンのコアステップ相当）。
  const リザーブ = 試合インスタンス.ゾーン管理.リザーブを取得(試合インスタンス.ゲーム, 'p1')!;
  const リザーブ保持者 = 試合インスタンス.コア管理.ゾーンを保持者に(リザーブ);
  リザーブ保持者.コア数を設定(リザーブ保持者.コア数を取得() + 10);

  const 手札 = 試合インスタンス.ゾーン管理.手札を取得(試合インスタンス.ゲーム, 'p1')!;
  const 召喚するカード = 手札.カード一覧を取得()[0];
  assert.ok(召喚するカード);

  const 成功 = 試合インスタンス.召喚管理.召喚する(
    試合インスタンス.ゲーム,
    'p1',
    召喚するカード,
    [{ 保持者: リザーブ保持者, 数: 4 }], // 召喚コスト4を支払う
    [{ 保持者: リザーブ保持者, 数: 1 }]  // 最低Lv（Lv1コスト=1）分のコアを置く
  );
  assert.equal(成功, true);

  const フィールド = 試合インスタンス.ゾーン管理.フィールドを取得(試合インスタンス.ゲーム, 'p1');
  assert.ok(フィールド?.カードを取得(召喚するカード.識別子));

  assert.equal(試合インスタンス.Lv管理.現在のLvを取得(召喚するカード), 1);
  assert.equal(試合インスタンス.BP管理.現在のBPを取得(召喚するカード), 5000);
});

