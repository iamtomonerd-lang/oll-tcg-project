test('軽減シンボルはフィールドの実際の枚数分しか消費されない（存在するだけでは満たされない）', () => {
  const カード = グンガタを作成('test-reduce');
  const 軽減シンボルルール個体 = new 軽減シンボルルール();

  // 赤シンボルが1個だけなら、軽減シンボル赤×3のうち1枠しか満たさない
  assert.equal(軽減シンボルルール個体.軽減可能な数を計算(カード, ['赤']), 1);
  assert.equal(軽減シンボルルール個体.軽減後のコストを計算(カード, 4, ['赤']), 3);

  // 赤シンボルが3個あれば3枠すべて満たす
  assert.equal(軽減シンボルルール個体.軽減可能な数を計算(カード, ['赤', '赤', '赤']), 3);
  assert.equal(軽減シンボルルール個体.軽減後のコストを計算(カード, 4, ['赤', '赤', '赤']), 1);

  // 赤シンボルが4個以上あっても、軽減シンボルの枠数（3）を超えては軽減されない
  assert.equal(軽減シンボルルール個体.軽減後のコストを計算(カード, 4, ['赤', '赤', '赤', '赤']), 1);
});

