import { カード } from '../../../データ/カード/カード.js';
import { カード名称データ } from './カード名称データ.js';
import { バトル終了時条件 } from '../効果/条件/バトル終了時.js';
import { ドロー効果 } from '../効果/行動/ドロー効果.js';
import { ムーシャッコ条件 } from '../効果/条件/ムーシャッコ条件.js';

// ムーシャッコ（26RSD01-001）
// スピリット／赤／C／コスト3／系統：風牙／ブロックアイコンA
// Lv1：コスト1・BP2000、Lv2：コスト2・BP3000
// 軽減シンボル：赤／シンボル：赤1個
// 効果：［Lv2］『アタック中』バトル終了時、自分の手札が5枚以下なら、1枚ドローする。
export const ムーシャッコ名称: Omit<カード名称データ, '識別子'> = {
  表示名: 'ムーシャッコ',
  説明: '素早い身のこなしで敵の隙をついて食らいつく。',
  カード名: 'ムーシャッコ',
  カードナンバー: '26RSD01-001',
  カード種別: 'スピリット',
  レアリティ: 'C',
  コスト: 3,
  系統: ['風牙'],
  ブロックアイコン: 'A',
  属性: ['赤'],
  軽減シンボル: ['赤'],
  シンボル: [{ 色: '赤', タイプ: 'EX' }],
  Lv: [
    { level: 1, cost: 1, bp: 2000 },
    { level: 2, cost: 2, bp: 3000 },
  ],
  カードテキスト: '［Lv2］《アタック中》バトル終了時、自分の手札が5枚以下なら、1枚ドローする。',
};

// カード1枚分のインスタンスを生成する（デッキに入れる枚数分、識別子を変えて呼び出す）
export function ムーシャッコを作成(識別子: string): カード {
  const カード1 = new カード(識別子, { 識別子, ...ムーシャッコ名称 });

  // ［Lv2］『アタック中』バトル終了時、自分の手札が5枚以下なら、1枚ドローする
  const バトル終了時効果 = {
    条件: new ムーシャッコ条件(),
    効果: new ドロー効果(1),
    発動Lv: 2,
    発動タイミング: 'バトル終了時',
  };

  カード1.状態を設定('バトル終了時_ドロー効果', バトル終了時効果);

  return カード1;
}
