import { 試合 } from './試合.js';

// 盤面を1本の文字列にする。
//
// 複製が本物と同じかを確かめるために要る。目で見比べると必ず見落とすので、
// 「同じなら同じ文字列になる」ものを作って機械に比べさせる。
//
// **ここに出ていない状態は、複製が壊れていても気づけない。**
// 新しく盤面に関わる状態を足したときは、ここにも足すこと。
export function 盤面の指紋(試合インスタンス: 試合): string {
  const ゲーム = 試合インスタンス.ゲーム;
  const 行: string[] = [];

  行.push(`ステップ=${試合インスタンス.現在のステップ() ?? 'なし'}`);
  行.push(`ターンプレイヤー=${ゲーム.現在のプレイヤーを取得()?.識別子 ?? 'なし'}`);
  行.push(`終了=${試合インスタンス.試合終了か()}`);
  const 結果 = 試合インスタンス.勝敗結果を取得();
  行.push(`勝者=${結果?.勝者?.識別子 ?? 'なし'}`);

  // プレイヤーごとに、全領域の中身とコアを並べる。
  // 識別子で並べ替えるので、内部の持ち方が変わっても比べられる。
  for (const プレイヤー個体 of [...ゲーム.全プレイヤーを取得()].sort((a, b) =>
    a.識別子.localeCompare(b.識別子)
  )) {
    const 識別子 = プレイヤー個体.識別子;
    行.push(`--- ${識別子} ---`);
    行.push(`ターン数=${プレイヤー個体.数値を取得('ターン数')}`);

    for (const 領域 of [...試合インスタンス.ゾーン管理.プレイヤーの全領域を取得(ゲーム, 識別子)].sort(
      (a, b) => a.識別子.localeCompare(b.識別子)
    )) {
      const 保持者 = 試合インスタンス.コア管理.ゾーンを保持者に(領域);
      const カード一覧 = 領域
        .カード一覧を取得()
        .map(c => {
          const カード保持者 = 試合インスタンス.コア管理.カードを保持者に(c);
          // 場のカードは Lv・BP・疲労／回復まで見る。
          // ここを省くと「コアの数は合っているのにLvが違う」を見逃す。
          const 場か = 領域.名称.識別子 === 'フィールド';
          const 詳しく = 場か
            ? `/Lv${試合インスタンス.Lv管理.現在のLvを取得(c)}` +
              `/BP${試合インスタンス.BP管理.現在のBPを取得(c)}` +
              `/${試合インスタンス.カードの表示形式管理.現在の表示形式を取得(c)}` +
              `/待機${試合インスタンス.待機状態管理.待機状態か(c)}`
            : '';
          return (
            `${c.識別子}(${c.名称.表示名})` +
            `コア${カード保持者.コア数を取得()}${カード保持者.ソウルコアあるか() ? '+ソウル' : ''}` +
            詳しく
          );
        })
        // デッキの並び順は伏せられた情報だが、複製が同じかを見るには順序も見たい。
        // 並べ替えずにそのまま出す。
        .join(',');
      行.push(
        `${領域.名称.識別子}: コア${保持者.コア数を取得()}` +
          `${保持者.ソウルコアあるか() ? '+ソウル' : ''} [${カード一覧}]`
      );
    }
  }

  return 行.join('\n');
}
