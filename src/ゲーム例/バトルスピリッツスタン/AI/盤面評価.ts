import { 試合 } from '../試合.js';
import { カード種別ルール } from '../カードの情報/カード種別.js';
import { シンボルルール } from '../カードの情報/シンボル.js';
import { コア判定 } from '../判定/コア判定.js';

// 盤面を1つの数字にする。
//
// AIは「この数字がいちばん大きくなる手」を選ぶ。だから**強さの正体はこの数字**で、
// 学習とは この重みを自己対戦で調整すること にほかならない。
//
// 重みを外から差し替えられるようにしてあるのは、
// 鍛えた重みをそのまま流し込めるようにするため。
// 重みを固定してコードに埋め込むと、学習の結果を反映する先が無くなる。
//
// 数字は**必ず「自分から見た有利さ」**で、大きいほど自分が良い。
// 相手側の項目は引き算で入れる（引かずに足すと、相手が育つほど喜ぶAIになる）。

export interface 評価の重み {
  // 勝敗に直結するもの
  自分のライフ: number;
  相手のライフ: number;

  // 打点（アタックで相手のライフを削れる量）
  自分のシンボル数: number;
  相手のシンボル数: number;

  // 盤面の厚み
  自分のBP合計: number;
  相手のBP合計: number;
  自分の回復スピリット数: number; // ブロックできる数
  相手の回復スピリット数: number;

  // 次に動ける量
  自分の手札枚数: number;
  自分のリザーブのコア: number;
  自分の場のコア: number;
  // トラッシュのコアは、リフレッシュまで使えない死にコア
  自分のトラッシュのコア: number;

  // 相手のいちばん強いスピリットを、BPで上回っている自分のスピリットの数。
  //
  // BPを1点いくらで足すだけでは、**勝つか負けるかの段差**が表せない。
  // BP5000どうしは相打ちだが、5000対7000は一方的に取れる。
  // その差はBP2000ぶん（重み換算で数点）では到底足りない。
  //
  // ここが無かったせいで、AIはLvアップをほとんどしなかった
  // （場のスピリットの96%がLv1のままだった）。
  自分のBPで勝てるスピリット数: number;
  相手のBPで勝てるスピリット数: number;

  // ソウルコアが使える位置（リザーブか場）にあるか。
  // トラッシュに落ちていると《ソウルマジック》も真界放も撃てない。
  自分のソウルコアが使えるか: number;

  // === 効果の値打ち ===
  //
  // 盤面には現れないが、手を選ぶときには要る2つ。
  // いまの土台は盤面を複製できないので「その手を打つと効果で何が起きるか」を
  // 読み切れない。読めないぶんを、この2つの下駄で表す。
  //
  // ここを小さく見積もっていたせいで、AIはマジックを一度も撃たなかった。
  // 手札とコアが減るぶんの引き算だけが効いて、撃つ手がいつも損に見えていた。
  マジックを撃つ値打ち: number;
  // 『召喚時』『配置時』の効果が、いま出せば条件を満たす場合の下駄
  召喚時効果が当たる値打ち: number;
  // ［フラッシュ］のマジックをメインステップで撃つときの割引。
  // 取っておけば相手のアタックに合わせて撃てるぶん、いま撃つのは少し損。
  // どれくらい損かは分からないので、値は自己対戦で決める。
  フラッシュ専用をメインで撃つ割引: number;
}

// 既定の重み。
// 学習前でも筋の通った手を選べるように、人が見て納得する比で置いてある。
// 学習はここを出発点にして山を登る。
export const 既定の重み: 評価の重み = {
  自分のライフ: 100,
  相手のライフ: -120, // 相手を削るほうを少し重く見る（受け身にならないように）

  自分のシンボル数: 22,
  相手のシンボル数: -20,

  自分のBP合計: 0.0015, // BPは千の位なので、他と釣り合う桁まで落とす
  相手のBP合計: -0.0013,
  自分の回復スピリット数: 6,
  相手の回復スピリット数: -5,

  自分の手札枚数: 8,
  自分のリザーブのコア: 4,
  自分の場のコア: 3,
  // トラッシュのコアは 0。
  //
  // はじめ -2 にしていたが、これは**同じ代金を二重に取っていた**。
  // コアを払うとリザーブから減り（-4）、そのうえトラッシュで罰を受ける（-2）ので、
  // 1個あたり6の値段が付いていた。そのせいでコストの重い手が軒並み損に見え、
  // AIはマジックを1枚も撃たなくなっていた。
  //
  // 払った痛みは「リザーブから消えたこと」で既に表せている。
  // 800試合×3つの種の範囲で測って、どれも約7ポイント勝率が上がった。
  自分のトラッシュのコア: 0,

  自分のBPで勝てるスピリット数: 14,
  相手のBPで勝てるスピリット数: -12,

  自分のソウルコアが使えるか: 6,

  // 相手のスピリットを1体壊すマジックは、盤面のシンボル1つよりずっと重い。
  // 「スピリット1体ぶん」に近い値を置く。
  マジックを撃つ値打ち: 60,
  召喚時効果が当たる値打ち: 30,
  フラッシュ専用をメインで撃つ割引: 0,
};

// 勝ち負けが決まっているときの点。
// 他のどの項目を足し引きしても届かない大きさにしておく
// （そうしないと「負けるが手札は多い」を良しとしてしまう）。
export const 勝ちの点 = 1_000_000;

export class 盤面評価 {
  private カード種別ルール = new カード種別ルール();
  private シンボルルール = new シンボルルール();
  private コア判定 = new コア判定();

  constructor(private 重み: 評価の重み = 既定の重み) {}

  重みを取得(): 評価の重み {
    return this.重み;
  }

  // 盤面を、自分から見た有利さの数字にする。
  評価する(試合インスタンス: 試合, 自分の識別子: string, 相手の識別子: string): number {
    // 決着がついているなら、そこで打ち切る。
    // 中身を数えても意味が無いうえ、勝ち負けを取り違える危険がある。
    if (試合インスタンス.試合終了か()) {
      const 結果 = 試合インスタンス.勝敗結果を取得();
      if (結果) {
        return 結果.勝者?.識別子 === 自分の識別子 ? 勝ちの点 : -勝ちの点;
      }
    }

    const 自分 = this.片側を数える(試合インスタンス, 自分の識別子);
    const 相手 = this.片側を数える(試合インスタンス, 相手の識別子);
    const w = this.重み;

    // BPの段差。相手のいちばん強いスピリットを上回っている数を、互いに数える。
    const 自分が勝てる数 = 自分.スピリットのBP一覧.filter(bp => bp > 相手.最大BP).length;
    const 相手が勝てる数 = 相手.スピリットのBP一覧.filter(bp => bp > 自分.最大BP).length;

    return (
      自分.ライフ * w.自分のライフ +
      相手.ライフ * w.相手のライフ +
      自分.シンボル数 * w.自分のシンボル数 +
      相手.シンボル数 * w.相手のシンボル数 +
      自分.BP合計 * w.自分のBP合計 +
      相手.BP合計 * w.相手のBP合計 +
      自分.回復スピリット数 * w.自分の回復スピリット数 +
      相手.回復スピリット数 * w.相手の回復スピリット数 +
      自分.手札枚数 * w.自分の手札枚数 +
      自分.リザーブのコア * w.自分のリザーブのコア +
      自分.場のコア * w.自分の場のコア +
      自分.トラッシュのコア * w.自分のトラッシュのコア +
      自分が勝てる数 * w.自分のBPで勝てるスピリット数 +
      相手が勝てる数 * w.相手のBPで勝てるスピリット数 +
      (自分.ソウルコアが使えるか ? 1 : 0) * w.自分のソウルコアが使えるか
    );
  }

  // 片方のプレイヤーについて、評価に使う数を1回で数える。
  // 同じゾーンを何度も引き直さないよう、ここでまとめて取る。
  private 片側を数える(試合インスタンス: 試合, 識別子: string) {
    const ゾーン管理 = 試合インスタンス.ゾーン管理;
    const ゲーム = 試合インスタンス.ゲーム;
    const コア管理 = 試合インスタンス.コア管理;

    const ライフ = ゾーン管理.ライフを取得(ゲーム, 識別子);
    const リザーブ = ゾーン管理.リザーブを取得(ゲーム, 識別子);
    const 手札 = ゾーン管理.手札を取得(ゲーム, 識別子);
    const トラッシュ = ゾーン管理.トラッシュを取得(ゲーム, 識別子);
    const フィールド = ゾーン管理.フィールドを取得(ゲーム, 識別子);

    // 待機状態のカードは、壊れたが場から消える前の段階（破壊の第1段階）。
    // これを生きているものとして数えると、
    // 「壊したのに盤面が良くならない」ように見えて、除去の手が全部損に見える。
    const 場のカード = (フィールド?.カード一覧を取得() ?? []).filter(
      c => !試合インスタンス.待機状態管理.待機状態か(c)
    );
    const スピリット一覧 = 場のカード.filter(c => this.カード種別ルール.スピリットか(c));

    let シンボル数 = 0;
    let BP合計 = 0;
    const スピリットのBP一覧: number[] = [];
    let 回復スピリット数 = 0;
    let 場のコア = 0;
    let 場にソウルコア = false;

    // ネクサスもシンボルを持つのでシンボル数には数える（軽減とライフ以外の意味を持つ）。
    // BPと回復状態はスピリットだけ。
    for (const カード of 場のカード) {
      シンボル数 += this.シンボルルール.シンボル数を取得(カード);
      const 保持者 = コア管理.カードを保持者に(カード);
      場のコア += this.コア判定.総コア数を取得(保持者);
      if (this.コア判定.ソウルコアあるか(保持者)) {
        場にソウルコア = true;
      }
    }
    for (const カード of スピリット一覧) {
      const bp = 試合インスタンス.BP管理.現在のBPを取得(カード);
      BP合計 += bp;
      スピリットのBP一覧.push(bp);
      if (試合インスタンス.カードの表示形式管理.現在の表示形式を取得(カード) === '回復') {
        回復スピリット数++;
      }
    }

    const リザーブ保持者 = リザーブ ? コア管理.ゾーンを保持者に(リザーブ) : null;

    return {
      ライフ: ライフ ? this.コア判定.総コア数を取得(コア管理.ゾーンを保持者に(ライフ)) : 0,
      シンボル数,
      BP合計,
      回復スピリット数,
      手札枚数: 手札?.カード枚数を取得() ?? 0,
      リザーブのコア: リザーブ保持者 ? this.コア判定.総コア数を取得(リザーブ保持者) : 0,
      場のコア,
      トラッシュのコア: トラッシュ
        ? this.コア判定.総コア数を取得(コア管理.ゾーンを保持者に(トラッシュ))
        : 0,
      // リザーブか場にあれば「使える」。トラッシュにあると次のリフレッシュまで動かせない。
      ソウルコアが使えるか:
        (リザーブ保持者 ? this.コア判定.ソウルコアあるか(リザーブ保持者) : false) || 場にソウルコア,
      スピリットのBP一覧,
      最大BP: スピリットのBP一覧.length > 0 ? Math.max(...スピリットのBP一覧) : 0,
    };
  }
}
