import { カード } from '../../../データ/カード/カード.js';
import { 思考AI } from './思考AI.js';
import { 評価の重み, 既定の重み } from './盤面評価.js';
import { 腕試しする } from './腕試し.js';
import { 種から乱数を作る } from '../乱数.js';

// 自己対戦で評価の重みを鍛える。
//
// 強さの正体は 盤面評価 の重みなので、学習とは**この重みを動かすこと**にほかならない。
// 思考AI（判断の骨組み）には手を入れない。
//
// やり方は山登り（(1+λ)進化戦略）。
//   1. いまいちばん強い重み＝王者 を持つ
//   2. 王者の重みに、少しずつ乱れを足した挑戦者を何人か作る
//   3. 王者と挑戦者を戦わせ、はっきり勝ち越した者がいれば王者を交代する
//   4. 交代が続くほど乱れを小さく、続かないほど大きくして探し方を変える
//
// **勝ったかどうかは必ず勝率で決める。** 「良さそう」で動かすと、
// 実際には弱くなっていても気づけない。

export interface 学習の設定 {
  デッキを作る: (接頭辞: string) => カード[];
  世代数?: number;
  挑戦者の数?: number;
  // 1回の比較に使う試合数。少ないとばらつきに騙され、多いと時間がかかる。
  比較の試合数?: number;
  // 勝ち越しをどれだけ超えたら交代するか。
  // ちょうど50%を境にすると、ばらつきだけで王者が入れ替わり続ける。
  交代の閾値?: number;
  種?: number;
  // 最後の確かめに使う試合数。学習に使っていない種で測る。
  確かめの試合数?: number;
  // 1世代ごとの経過を受け取る（画面や標準出力に出すため）
  進み具合?: (報告: 世代の報告) => void;
}

export interface 世代の報告 {
  世代: number;
  交代したか: number; // 何人の挑戦者が王者を超えたか
  最高勝率: number;
  乱れの大きさ: number;
}

export interface 学習の結果 {
  重み: 評価の重み;
  世代数: number;
  // 鍛える前の重みに対して、鍛えた重みがどれだけ勝つか（別の種で測り直したもの）
  元の重みに対する勝率: number;
}

// 重みの各項目をどれくらい動かすか。
// 桁が違う項目（BPは0.001台、ライフは100台）を同じ幅で動かすと、
// 小さい項目だけが吹き飛ぶので、**その項目自身の大きさに比例**して動かす。
function 乱れを足す(重み: 評価の重み, 大きさ: number, 乱数: () => number): 評価の重み {
  const 新しい重み = { ...重み } as Record<string, number>;
  for (const 鍵 of Object.keys(新しい重み)) {
    const 元の値 = 新しい重み[鍵];
    // 0 の項目は比例では動かせないので、小さな絶対値で動かす
    const 幅 = 元の値 === 0 ? 大きさ : Math.abs(元の値) * 大きさ;
    // ざっくり正規分布（一様乱数を2つ足して中央に寄せる）
    const ゆらぎ = 乱数() + 乱数() - 1;
    新しい重み[鍵] = 元の値 + 幅 * ゆらぎ;
  }
  return 新しい重み as unknown as 評価の重み;
}

// 2つの重みを戦わせて、左側の勝率を返す。
//
// 先攻・後攻を入れ替えて半分ずつ戦わせる（腕試しする がそうしている）。
// 種を変えながら測るので、同じ組み合わせでも世代ごとに違う試合を見る
// （同じ試合ばかり見ていると、その試合にだけ強い重みが育つ）。
export function 重みを戦わせる(
  左: 評価の重み,
  右: 評価の重み,
  デッキを作る: (接頭辞: string) => カード[],
  試合数: number,
  最初の種: number
): number {
  const 作る = (重み: 評価の重み) => (自分: string, 相手: string, 種: number) =>
    new 思考AI(自分, 相手, { 重み, 乱数: 種から乱数を作る(種) });
  return 腕試しする(作る(左), 作る(右), デッキを作る, 試合数, 最初の種).先の勝率;
}

export function 学習する(設定: 学習の設定): 学習の結果 {
  const 世代数 = 設定.世代数 ?? 20;
  const 挑戦者の数 = 設定.挑戦者の数 ?? 6;
  const 比較の試合数 = 設定.比較の試合数 ?? 300;
  const 交代の閾値 = 設定.交代の閾値 ?? 0.54;
  const 乱数 = 種から乱数を作る(設定.種 ?? 1);

  let 王者: 評価の重み = { ...既定の重み };
  let 乱れの大きさ = 0.3;

  for (let 世代 = 1; 世代 <= 世代数; 世代++) {
    // 世代ごとに違う種の範囲で測る。同じ試合を見続けると、
    // 「強い重み」ではなく「その試合に噛み合う重み」が育つ。
    const 最初の種 = 世代 * 10_000 + 1;

    let 一番強い挑戦者: 評価の重み | null = null;
    let 最高勝率 = 0;
    let 超えた数 = 0;

    for (let 番 = 0; 番 < 挑戦者の数; 番++) {
      const 挑戦者 = 乱れを足す(王者, 乱れの大きさ, 乱数);
      const 勝率 = 重みを戦わせる(
        挑戦者,
        王者,
        設定.デッキを作る,
        比較の試合数,
        最初の種 + 番 * 1_000
      );
      if (勝率 >= 交代の閾値) 超えた数++;
      if (勝率 > 最高勝率) {
        最高勝率 = 勝率;
        一番強い挑戦者 = 挑戦者;
      }
    }

    if (一番強い挑戦者 && 最高勝率 >= 交代の閾値) {
      王者 = 一番強い挑戦者;
      // 当たりが出ているうちは、その方向をもう少し大きく探る
      乱れの大きさ = Math.min(0.6, 乱れの大きさ * 1.2);
    } else {
      // 当たりが出ないときは、探す幅を狭めて細かく見る
      乱れの大きさ = Math.max(0.05, 乱れの大きさ * 0.8);
    }

    設定.進み具合?.({ 世代, 交代したか: 超えた数, 最高勝率, 乱れの大きさ });
  }

  // 鍛えるのに使っていない種で測り直す。
  // 学習に使った種で測ると、その試合に噛み合っただけでも「強くなった」と出る。
  const 元の重みに対する勝率 = 重みを戦わせる(
    王者,
    既定の重み,
    設定.デッキを作る,
    設定.確かめの試合数 ?? 1000,
    900_001
  );

  return { 重み: 王者, 世代数, 元の重みに対する勝率 };
}
