// 対象選択の要る効果をAIが撃てないと、選択待ちのまま試合が止まる。
// 既存のAI対戦テストは効果を持たないカードだけを使っていたため、この不具合を検出できなかった。
// ここでは必ず効果入りのデッキで走らせ、進行が止まらないことを保証する。

function 効果入りデッキを作成(接頭辞: string, 枚数 = 40): カード[] {
  const デッキ: カード[] = [];
  for (let i = 0; i < 枚数; i++) {
    const 番号 = `${接頭辞}-${i + 1}`;
    switch (i % 4) {
      case 0:
        デッキ.push(ロワミークを作成(番号)); // 召喚時に対象選択（選択待ちになる）
        break;
      case 1:
        デッキ.push(ムーシャッコを作成(番号)); // バトル終了時にドロー
        break;
      case 2:
        デッキ.push(ゲン_ボーを作成(番号)); // 真界放の常在効果
        break;
      default:
        デッキ.push(グンガタを作成(番号)); // 効果なし
        break;
    }
  }
  return デッキ;
}

function 試合を準備する(): 試合 {
  const 試合インスタンス = new 試合();
  試合インスタンス.プレイヤーを準備する('p1', 'プレイヤー1');
  試合インスタンス.プレイヤーを準備する('p2', 'プレイヤー2');
  試合インスタンス.ボイドを準備する();
  試合インスタンス.デッキを設定する('p1', 効果入りデッキを作成('p1'));
  試合インスタンス.デッキを設定する('p2', 効果入りデッキを作成('p2'));
  試合インスタンス.準備を行う('p1');
  試合インスタンス.準備を行う('p2');
  試合インスタンス.先攻を決める('p1');
  試合インスタンス.試合を開始する();
  return 試合インスタンス;
}

// 盤面を作り込み、AIの効果が必ず選択待ちになる状態から進行させる。
// 通し対戦に任せると、条件が揃わず選択待ちが一度も起きないまま通ってしまうため
// （実測で、40枚の効果入りデッキ同士でも選択待ちは0回だった）、状態を直接作る。
function 選択待ちを作る(): { 試合: 試合; AIマップ: Map<string, 練習用AI> } {
  const 試合インスタンス = 試合を準備する();

  // p1（AI）の場に疲労した赤スピリット＝ロワミークの発動条件
  const 味方 = グンガタを作成('p1-味方');
  試合インスタンス.ゾーン管理.フィールドを取得(試合インスタンス.ゲーム, 'p1')!.カードを追加(味方);
  試合インスタンス.BP管理.BPを設定(味方, 5000);
  試合インスタンス.カードの表示形式管理.疲労する(味方);

  // 相手に候補を2体置く（1体だと自動確定してしまい、選択待ちにならない）
  for (const 識別子 of ['p2-標的A', 'p2-標的B']) {
    const 標的 = グンガタを作成(識別子);
    試合インスタンス.ゾーン管理.フィールドを取得(試合インスタンス.ゲーム, 'p2')!.カードを追加(標的);
    試合インスタンス.BP管理.BPを設定(標的, 3000);
  }

  const ロワミーク = ロワミークを作成('p1-ロワミーク');
  試合インスタンス.ゾーン管理.フィールドを取得(試合インスタンス.ゲーム, 'p1')!.カードを追加(ロワミーク);
  試合インスタンス.効果実行器.事象を通知する('召喚時', ロワミーク);
  試合インスタンス.効果実行器.キューを進める();

  const AIマップ = new Map([
    ['p1', new 練習用AI('p1', 'p2')],
    ['p2', new 練習用AI('p2', 'p1')],
  ]);
  return { 試合: 試合インスタンス, AIマップ };
}

test('AIの効果が選択待ちになっても、進行が止まらず決着がつく', () => {
  const { 試合: 試合インスタンス, AIマップ } = 選択待ちを作る();

  // 前提：この時点で確かに選択待ちになっている
  assert.equal(試合インスタンス.効果実行器.選択待ちか(), true, '選択待ちの状態から始める');

  const 結果 = 対戦を進行する(試合インスタンス, AIマップ);

  assert.equal(
    試合インスタンス.効果実行器.選択待ちか(),
    false,
    'AIが選択に答え、待ちが解消されている'
  );
  assert.ok(結果, '決着がつく（選択待ちのまま空回りしていない）');
  assert.equal(試合インスタンス.試合終了か(), true);
});

test('効果入りデッキでAI同士が最後まで対戦できる（通しの煙テスト）', () => {
  const 試合インスタンス = 試合を準備する();
  const AIマップ = new Map([
    ['p1', new 練習用AI('p1', 'p2')],
    ['p2', new 練習用AI('p2', 'p1')],
  ]);

  const 結果 = 対戦を進行する(試合インスタンス, AIマップ);

  assert.ok(結果, '決着がつく');
  assert.equal(試合インスタンス.試合終了か(), true);
  assert.equal(試合インスタンス.効果実行器.選択待ちか(), false);
});

// === 召喚タイミングの判断 ===

// 手札を空にしてから指定のカードだけを持たせ、コアを十分に与える
function 手札を差し替える(試合インスタンス: 試合, プレイヤー識別子: string, カード一覧: カード[]): void {
  const 手札 = 試合インスタンス.ゾーン管理.手札を取得(試合インスタンス.ゲーム, プレイヤー識別子)!;
  for (const 既存 of [...手札.カード一覧を取得()]) {
    手札.カードを削除(既存.識別子);
  }
  for (const カード of カード一覧) {
    手札.カードを追加(カード);
  }
  const リザーブ = 試合インスタンス.ゾーン管理.リザーブを取得(試合インスタンス.ゲーム, プレイヤー識別子)!;
  const 保持者 = 試合インスタンス.コア管理.ゾーンを保持者に(リザーブ);
  保持者.コア数を設定(保持者.コア数を取得() + 10);
}

test('AIは召喚時効果が不発になるカードを、アタック後まで温存する', async t => {
  await t.test('条件を満たさず、攻撃できる味方がいるなら、メイン1では出さない', () => {
    const 試合インスタンス = 試合を準備する();
    const AI = new 練習用AI('p1', 'p2');

    // 回復状態の味方＝これから攻撃でき、攻撃すれば疲労する
    const 味方 = グンガタを作成('p1-味方');
    試合インスタンス.ゾーン管理.フィールドを取得(試合インスタンス.ゲーム, 'p1')!.カードを追加(味方);
    試合インスタンス.BP管理.BPを設定(味方, 5000);

    手札を差し替える(試合インスタンス, 'p1', [ロワミークを作成('温存されるはず')]);

    AI.メイン1を行動する(試合インスタンス);

    const 手札 = 試合インスタンス.ゾーン管理.手札を取得(試合インスタンス.ゲーム, 'p1')!;
    assert.ok(
      手札.カードを取得('温存されるはず'),
      'メイン1では出さず、疲労した味方を作れる第2メインまで待つ'
    );
  });

  await t.test('条件を満たしていれば、メイン1でそのまま出す', () => {
    const 試合インスタンス = 試合を準備する();
    const AI = new 練習用AI('p1', 'p2');

    // 疲労した赤スピリット＝ロワミークの条件を既に満たしている
    const 味方 = グンガタを作成('p1-味方');
    試合インスタンス.ゾーン管理.フィールドを取得(試合インスタンス.ゲーム, 'p1')!.カードを追加(味方);
    試合インスタンス.BP管理.BPを設定(味方, 5000);
    試合インスタンス.カードの表示形式管理.疲労する(味方);

    手札を差し替える(試合インスタンス, 'p1', [ロワミークを作成('すぐ出るはず')]);

    AI.メイン1を行動する(試合インスタンス);

    const フィールド = 試合インスタンス.ゾーン管理.フィールドを取得(試合インスタンス.ゲーム, 'p1')!;
    assert.ok(フィールド.カードを取得('すぐ出るはず'), '条件を満たすので待たずに出す');
  });

  await t.test('温存しても意味がない（攻撃できる味方がいない）なら出す', () => {
    const 試合インスタンス = 試合を準備する();
    const AI = new 練習用AI('p1', 'p2');

    // 場が空＝攻撃できないので、待っても条件は変わらない
    手札を差し替える(試合インスタンス, 'p1', [ロワミークを作成('待っても無駄')]);

    AI.メイン1を行動する(試合インスタンス);

    const フィールド = 試合インスタンス.ゾーン管理.フィールドを取得(試合インスタンス.ゲーム, 'p1')!;
    assert.ok(フィールド.カードを取得('待っても無駄'), '盤面が変わらないなら待たずに出す');
  });

  await t.test('条件を持たないカードは温存しない', () => {
    const 試合インスタンス = 試合を準備する();
    const AI = new 練習用AI('p1', 'p2');

    const 味方 = グンガタを作成('p1-味方');
    試合インスタンス.ゾーン管理.フィールドを取得(試合インスタンス.ゲーム, 'p1')!.カードを追加(味方);
    試合インスタンス.BP管理.BPを設定(味方, 5000);

    手札を差し替える(試合インスタンス, 'p1', [グンガタを作成('効果なし')]);

    AI.メイン1を行動する(試合インスタンス);

    const フィールド = 試合インスタンス.ゾーン管理.フィールドを取得(試合インスタンス.ゲーム, 'p1')!;
    assert.ok(フィールド.カードを取得('効果なし'), '召喚時効果がないので普通に出す');
  });
});

test('AIは対象選択に必ず有効な答えを返す', async t => {
  await t.test('候補があれば範囲内の枚数を選ぶ', () => {
    const 試合インスタンス = 試合を準備する();
    const AI = new 練習用AI('p1', 'p2');

    const 候補 = [グンガタを作成('候補1'), グンガタを作成('候補2'), グンガタを作成('候補3')];
    const 選択 = AI.効果対象を選ぶ(試合インスタンス, {
      候補,
      最小: 1,
      最大: 2,
      任意: false,
    });

    assert.ok(選択.length >= 1 && 選択.length <= 2, '必要な範囲に収まっている');
    for (const 識別子 of 選択) {
      assert.ok(
        候補.some(c => c.識別子 === 識別子),
        '候補の中から選んでいる'
      );
    }
  });

  await t.test('候補が空でも壊れない', () => {
    const 試合インスタンス = 試合を準備する();
    const AI = new 練習用AI('p1', 'p2');

    const 選択 = AI.効果対象を選ぶ(試合インスタンス, { 候補: [], 最小: 0, 最大: 0, 任意: true });
    assert.deepEqual(選択, []);
  });

  await t.test('相手のカードを優先して選ぶ', () => {
    const 試合インスタンス = 試合を準備する();
    const AI = new 練習用AI('p1', 'p2');

    const 自分のカード = グンガタを作成('自分のカード');
    const 相手のカード = グンガタを作成('相手のカード');
    試合インスタンス.ゾーン管理
      .フィールドを取得(試合インスタンス.ゲーム, 'p1')!
      .カードを追加(自分のカード);
    試合インスタンス.ゾーン管理
      .フィールドを取得(試合インスタンス.ゲーム, 'p2')!
      .カードを追加(相手のカード);

    const 選択 = AI.効果対象を選ぶ(試合インスタンス, {
      候補: [自分のカード, 相手のカード],
      最小: 1,
      最大: 1,
      任意: false,
    });

    assert.deepEqual(選択, ['相手のカード'], '除去を想定して相手を選ぶ');
  });
});

test('選択待ちの間は、その効果の持ち主が実行者になる', () => {
  const 試合インスタンス = 試合を準備する();

  // p1のターン中に、p2のカードの効果を選択待ちにする
  const 味方 = グンガタを作成('p2-味方');
  試合インスタンス.ゾーン管理.フィールドを取得(試合インスタンス.ゲーム, 'p2')!.カードを追加(味方);
  試合インスタンス.BP管理.BPを設定(味方, 5000);
  試合インスタンス.カードの表示形式管理.疲労する(味方);

  for (const 識別子 of ['標的A', '標的B']) {
    const 標的 = グンガタを作成(識別子);
    試合インスタンス.ゾーン管理.フィールドを取得(試合インスタンス.ゲーム, 'p1')!.カードを追加(標的);
    試合インスタンス.BP管理.BPを設定(標的, 3000);
  }

  const ロワミーク = ロワミークを作成('p2-ロワミーク');
  試合インスタンス.ゾーン管理.フィールドを取得(試合インスタンス.ゲーム, 'p2')!.カードを追加(ロワミーク);
  試合インスタンス.効果実行器.事象を通知する('召喚時', ロワミーク);
  試合インスタンス.効果実行器.キューを進める();

  assert.equal(試合インスタンス.効果実行器.選択待ちか(), true);

  const 情報 = 試合インスタンス.効果実行器.選択待ち情報を取得()!;
  assert.equal(情報.発揮源.識別子, 'p2-ロワミーク');

  // ターンプレイヤーはp1だが、答えるべきなのは効果の持ち主であるp2
  assert.equal(試合インスタンス.ゲーム.現在のプレイヤーを取得()?.識別子, 'p1');

  const 持ち主 = 試合インスタンス.ゾーン管理
    .フィールドを取得(試合インスタンス.ゲーム, 'p2')!
    .カードを取得('p2-ロワミーク');
  assert.ok(持ち主, '効果の持ち主はp2側にいる');
});
