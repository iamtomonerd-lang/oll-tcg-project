import { test } from 'node:test';
import assert from 'node:assert/strict';

import { グンガタを作成 } from '../カードデータ/グンガタ.js';
import { 試合 } from '../試合.js';
import { 練習用AI } from './練習用AI.js';
import { 対戦を進行する } from './対戦進行.js';

function モノデッキを作成(接頭辞: string, 枚数 = 40) {
  return Array.from({ length: 枚数 }, (_, i) => グンガタを作成(`${接頭辞}-${i + 1}`));
}

function 試合を準備する(): 試合 {
  const 試合インスタンス = new 試合();
  試合インスタンス.プレイヤーを準備する('p1', 'プレイヤー1');
  試合インスタンス.プレイヤーを準備する('p2', 'プレイヤー2');
  試合インスタンス.ボイドを準備する();
  試合インスタンス.デッキを設定する('p1', モノデッキを作成('p1'));
  試合インスタンス.デッキを設定する('p2', モノデッキを作成('p2'));
  試合インスタンス.準備を行う('p1');
  試合インスタンス.準備を行う('p2');
  試合インスタンス.先攻を決める('p1');
  試合インスタンス.試合を開始する();
  return 試合インスタンス;
}

test('グン＝ガタのモノデッキ同士でAIが最後まで対戦し、決着がつく', () => {
  const 試合インスタンス = 試合を準備する();
  const AIマップ = new Map([
    ['p1', new 練習用AI('p1')],
    ['p2', new 練習用AI('p2')],
  ]);

  const 結果 = 対戦を進行する(試合インスタンス, AIマップ);

  assert.ok(結果, '勝敗結果が返る');
  assert.equal(結果?.勝利, true);
  assert.ok(結果?.勝者, '勝者が存在する');
  assert.ok(結果?.敗者, '敗者が存在する');
  assert.notEqual(結果?.勝者?.識別子, 結果?.敗者?.識別子);
  assert.ok(
    ['p1', 'p2'].includes(結果!.勝者!.識別子) && ['p1', 'p2'].includes(結果!.敗者!.識別子),
    '勝者・敗者はp1かp2のいずれか'
  );

  // 試合終了フラグと勝敗結果取得の整合性を確認
  assert.equal(試合インスタンス.試合終了か(), true);
  assert.deepEqual(試合インスタンス.勝敗結果を取得(), 結果);
});

test('両者が序盤から召喚できる状況では、AI同士の対戦でBP比べの相打ちが実際に発生する', () => {
  // コスト4は重く、双方のコアが乏しいままだと片方が一度もブロックできずライフのみで決着する
  // こともあり得るため、このテストでは両者のリザーブに十分なコアを先に与えて、
  // 早期に召喚とブロックの応酬（＝BP比べによる相打ち）が起こる状況を作る。
  const 試合インスタンス = 試合を準備する();

  for (const プレイヤー識別子 of ['p1', 'p2']) {
    const リザーブ = 試合インスタンス.ゾーン管理.リザーブを取得(試合インスタンス.ゲーム, プレイヤー識別子)!;
    const リザーブ保持者 = 試合インスタンス.コア管理.ゾーンを保持者に(リザーブ);
    リザーブ保持者.コア数を設定(リザーブ保持者.コア数を取得() + 20);
  }

  const AIマップ = new Map([
    ['p1', new 練習用AI('p1')],
    ['p2', new 練習用AI('p2')],
  ]);

  対戦を進行する(試合インスタンス, AIマップ);

  const p1トラッシュ = 試合インスタンス.ゾーン管理.トラッシュを取得(試合インスタンス.ゲーム, 'p1');
  const p2トラッシュ = 試合インスタンス.ゾーン管理.トラッシュを取得(試合インスタンス.ゲーム, 'p2');
  const 破壊されたカードがある =
    (p1トラッシュ?.カード枚数を取得() ?? 0) > 0 || (p2トラッシュ?.カード枚数を取得() ?? 0) > 0;

  assert.equal(破壊されたカードがある, true);
});
