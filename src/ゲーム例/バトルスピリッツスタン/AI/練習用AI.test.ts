import { test } from 'node:test';
import assert from 'node:assert/strict';

import { グンガタを作成 } from '../カードデータ/グンガタ.js';
import { 試合 } from '../試合.js';
import { 練習用AI } from './練習用AI.js';
import { 対戦を進行する } from './対戦進行.js';

function モノデッキを作成(接頭辞: string, 枚数 = 40) {
  return Array.from({ length: 枚数 }, (_, i) => グンガタを作成(`${接頭辞}-${i + 1}`));
}

function 試合を準備する(): 試合 {
  const 試合インスタンス = new 試合();
  試合インスタンス.プレイヤーを準備する('p1', 'プレイヤー1');
  試合インスタンス.プレイヤーを準備する('p2', 'プレイヤー2');
  試合インスタンス.ボイドを準備する();
  試合インスタンス.デッキを設定する('p1', モノデッキを作成('p1'));
  試合インスタンス.デッキを設定する('p2', モノデッキを作成('p2'));
  試合インスタンス.準備を行う('p1');
  試合インスタンス.準備を行う('p2');
  試合インスタンス.先攻を決める('p1');
  試合インスタンス.試合を開始する();
  return 試合インスタンス;
}

test('グン＝ガタのモノデッキ同士でAIが最後まで対戦し、決着がつく', () => {
  const 試合インスタンス = 試合を準備する();
  const AIマップ = new Map([
    ['p1', new 練習用AI('p1', 'p2')],
    ['p2', new 練習用AI('p2', 'p1')],
  ]);

  const 結果 = 対戦を進行する(試合インスタンス, AIマップ);

  assert.ok(結果, '勝敗結果が返る');
  assert.equal(結果?.勝利, true);
  assert.ok(結果?.勝者, '勝者が存在する');
  assert.ok(結果?.敗者, '敗者が存在する');
  assert.notEqual(結果?.勝者?.識別子, 結果?.敗者?.識別子);
  assert.ok(
    ['p1', 'p2'].includes(結果!.勝者!.識別子) && ['p1', 'p2'].includes(結果!.敗者!.識別子),
    '勝者・敗者はp1かp2のいずれか'
  );

  // 試合終了フラグと勝敗結果取得の整合性を確認
  assert.equal(試合インスタンス.試合終了か(), true);
  assert.deepEqual(試合インスタンス.勝敗結果を取得(), 結果);
});

test('両者が序盤から召喚できる状況では、AI同士の対戦でBP比べの相打ちが実際に発生する', () => {
  // コスト4は重く、双方のコアが乏しいままだと片方が一度もブロックできずライフのみで決着する
  // こともあり得るため、このテストでは両者のリザーブに十分なコアを先に与えて、
  // 早期に召喚とブロックの応酬（＝BP比べによる相打ち）が起こる状況を作る。
  const 試合インスタンス = 試合を準備する();

  for (const プレイヤー識別子 of ['p1', 'p2']) {
    const リザーブ = 試合インスタンス.ゾーン管理.リザーブを取得(試合インスタンス.ゲーム, プレイヤー識別子)!;
    const リザーブ保持者 = 試合インスタンス.コア管理.ゾーンを保持者に(リザーブ);
    リザーブ保持者.コア数を設定(リザーブ保持者.コア数を取得() + 20);
  }

  const AIマップ = new Map([
    ['p1', new 練習用AI('p1', 'p2')],
    ['p2', new 練習用AI('p2', 'p1')],
  ]);

  対戦を進行する(試合インスタンス, AIマップ);

  const p1トラッシュ = 試合インスタンス.ゾーン管理.トラッシュを取得(試合インスタンス.ゲーム, 'p1');
  const p2トラッシュ = 試合インスタンス.ゾーン管理.トラッシュを取得(試合インスタンス.ゲーム, 'p2');
  const 破壊されたカードがある =
    (p1トラッシュ?.カード枚数を取得() ?? 0) > 0 || (p2トラッシュ?.カード枚数を取得() ?? 0) > 0;

  assert.equal(破壊されたカードがある, true);
});

test('リーサルが無い場合、メイン1では召喚よりも回復状態スピリットのLvアップが優先される', () => {
  const 試合インスタンス = 試合を準備する();
  試合インスタンス.次の行動可能なステップまで進める(); // メインステップまで進む

  const リザーブ = 試合インスタンス.ゾーン管理.リザーブを取得(試合インスタンス.ゲーム, 'p1')!;
  const リザーブ保持者 = 試合インスタンス.コア管理.ゾーンを保持者に(リザーブ);
  リザーブ保持者.コア数を設定(リザーブ保持者.コア数を取得() + 20);

  const 手札 = 試合インスタンス.ゾーン管理.手札を取得(試合インスタンス.ゲーム, 'p1')!;
  const [召喚するカード, ...残り] = 手札.カード一覧を取得();
  試合インスタンス.召喚する(
    'p1',
    召喚するカード,
    [{ 保持者: リザーブ保持者, 数: 4 }],
    [{ 保持者: リザーブ保持者, 数: 1 }]
  );
  assert.equal(試合インスタンス.Lv管理.現在のLvを取得(召喚するカード), 1);

  // 追加召喚可能数の見積もりでリーサル扱いにならないよう、残りの手札は捨てておく
  const トラッシュ = 試合インスタンス.ゾーン管理.トラッシュを取得(試合インスタンス.ゲーム, 'p1')!;
  for (const カード of 残り) {
    手札.カードを削除(カード.識別子);
    トラッシュ.カードを追加(カード);
  }

  const p1AI = new 練習用AI('p1', 'p2');
  p1AI.メイン1を行動する(試合インスタンス);

  assert.equal(試合インスタンス.Lv管理.現在のLvを取得(召喚するカード), 2);
  assert.equal(試合インスタンス.BP管理.現在のBPを取得(召喚するカード), 8000);
});

test('リーサルが無い場合、攻撃者を選ぶ は回復状態のスピリットを1体温存する', () => {
  const 試合インスタンス = 試合を準備する();
  試合インスタンス.次の行動可能なステップまで進める(); // メインステップまで進む

  const リザーブ = 試合インスタンス.ゾーン管理.リザーブを取得(試合インスタンス.ゲーム, 'p1')!;
  const リザーブ保持者 = 試合インスタンス.コア管理.ゾーンを保持者に(リザーブ);
  リザーブ保持者.コア数を設定(リザーブ保持者.コア数を取得() + 20);

  const 手札 = 試合インスタンス.ゾーン管理.手札を取得(試合インスタンス.ゲーム, 'p1')!;
  const [カード1, カード2, ...残り] = 手札.カード一覧を取得();
  試合インスタンス.召喚する('p1', カード1, [{ 保持者: リザーブ保持者, 数: 4 }], [{ 保持者: リザーブ保持者, 数: 1 }]);
  試合インスタンス.召喚する('p1', カード2, [{ 保持者: リザーブ保持者, 数: 2 }], [{ 保持者: リザーブ保持者, 数: 1 }]);

  // 追加召喚可能数の見積もりでリーサル扱いにならないよう、残りの手札は捨てておく
  const トラッシュ = 試合インスタンス.ゾーン管理.トラッシュを取得(試合インスタンス.ゲーム, 'p1')!;
  for (const カード of 残り) {
    手札.カードを削除(カード.識別子);
    トラッシュ.カードを追加(カード);
  }

  const p1AI = new 練習用AI('p1', 'p2');
  p1AI.攻撃ステップを開始する(試合インスタンス);

  const 選ばれた攻撃者一覧: string[] = [];
  let 攻撃者 = p1AI.攻撃者を選ぶ(試合インスタンス);
  while (攻撃者) {
    選ばれた攻撃者一覧.push(攻撃者.識別子);
    // 選定ロジックのみ検証するため、実際の宣言は行わず疲労させて次の候補へ進める
    試合インスタンス.カードの表示形式管理.疲労する(攻撃者);
    攻撃者 = p1AI.攻撃者を選ぶ(試合インスタンス);
  }

  assert.equal(選ばれた攻撃者一覧.length, 1, '2体のうち1体は温存され、攻撃には選ばれない');
});

test('相手がリーサルを持つ場合、ブロッカーを選ぶ はBP条件を無視して可能な限りブロックする', () => {
  const 試合インスタンス = 試合を準備する();
  試合インスタンス.次の行動可能なステップまで進める(); // メインステップまで進む

  const p1リザーブ = 試合インスタンス.ゾーン管理.リザーブを取得(試合インスタンス.ゲーム, 'p1')!;
  const p1リザーブ保持者 = 試合インスタンス.コア管理.ゾーンを保持者に(p1リザーブ);
  p1リザーブ保持者.コア数を設定(p1リザーブ保持者.コア数を取得() + 20);
  const p2リザーブ = 試合インスタンス.ゾーン管理.リザーブを取得(試合インスタンス.ゲーム, 'p2')!;
  const p2リザーブ保持者 = 試合インスタンス.コア管理.ゾーンを保持者に(p2リザーブ);
  p2リザーブ保持者.コア数を設定(p2リザーブ保持者.コア数を取得() + 20);

  // p1（攻撃側）：1体をLv2（BP8000）まで育てる
  const p1手札 = 試合インスタンス.ゾーン管理.手札を取得(試合インスタンス.ゲーム, 'p1')!;
  const [p1カード, ...p1残り] = p1手札.カード一覧を取得();
  試合インスタンス.召喚する('p1', p1カード, [{ 保持者: p1リザーブ保持者, 数: 4 }], [{ 保持者: p1リザーブ保持者, 数: 1 }]);
  試合インスタンス.コアを移動する(p1リザーブ, p1カード, 2); // Lv2到達（コスト3）
  assert.equal(試合インスタンス.Lv管理.現在のLvを取得(p1カード), 2);
  assert.equal(試合インスタンス.BP管理.現在のBPを取得(p1カード), 8000);

  const p1トラッシュ = 試合インスタンス.ゾーン管理.トラッシュを取得(試合インスタンス.ゲーム, 'p1')!;
  for (const カード of p1残り) {
    p1手札.カードを削除(カード.識別子);
    p1トラッシュ.カードを追加(カード);
  }

  // p2（防御側）：Lv1（BP5000）のスピリットのみで、通常のBP条件ではブロック候補にならない
  const p2手札 = 試合インスタンス.ゾーン管理.手札を取得(試合インスタンス.ゲーム, 'p2')!;
  const p2カード = p2手札.カード一覧を取得()[0];
  試合インスタンス.召喚する('p2', p2カード, [{ 保持者: p2リザーブ保持者, 数: 4 }], [{ 保持者: p2リザーブ保持者, 数: 1 }]);
  assert.equal(試合インスタンス.Lv管理.現在のLvを取得(p2カード), 1);
  assert.equal(試合インスタンス.BP管理.現在のBPを取得(p2カード), 5000);

  // p2のライフを0にする。p1のシンボル合計(1)だけでp2へのリーサルが成立する状況を作る。
  const p2ライフ = 試合インスタンス.ゾーン管理.ライフを取得(試合インスタンス.ゲーム, 'p2')!;
  const p2ライフ保持者 = 試合インスタンス.コア管理.ゾーンを保持者に(p2ライフ);
  p2ライフ保持者.コア数を設定(0);

  const p2AI = new 練習用AI('p2', 'p1');
  const 選ばれたブロッカー = p2AI.ブロッカーを選ぶ(試合インスタンス, p1カード);

  assert.ok(選ばれたブロッカー, 'BPが足りなくてもブロッカーが選ばれる');
  assert.equal(選ばれたブロッカー?.識別子, p2カード.識別子);
});
