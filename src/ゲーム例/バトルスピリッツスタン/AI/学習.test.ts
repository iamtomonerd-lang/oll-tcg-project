import { test } from 'node:test';
import assert from 'node:assert/strict';

import { 学習する, 重みを戦わせる } from './学習.js';
import { 既定の重み, 評価の重み } from './盤面評価.js';
import { 学習した重み } from './学習した重み.js';
import { 物差しの重み } from './物差しの重み.js';
import { カード } from '../../../データ/カード/カード.js';
import { カード帳 } from '../カードデータ/カード帳.js';

// 学習は「回ったこと」ではなく「強くなったこと」で確かめる。
// 回っただけで満足すると、乱数を振っているだけの仕掛けができあがる。

const 風牙のカード = カード帳.filter(x => !/^紫/.test(x.カード名));

function デッキを作る(接頭辞: string): カード[] {
  const デッキ: カード[] = [];
  for (let i = 0; i < 40; i++) {
    デッキ.push(風牙のカード[i % 風牙のカード.length].作る(`${接頭辞}-${i}`));
  }
  return デッキ;
}

// 学習の物差しそのもの。ここが傾いていたら、鍛えた結果はすべて疑わしい。
test('同じ重みどうしを戦わせると五分に近い（学習の物差しが傾いていない）', () => {
  const 勝率 = 重みを戦わせる(既定の重み, 既定の重み, デッキを作る, 300, 1);
  assert.ok(
    Math.abs(勝率 - 0.5) < 0.1,
    `同じ重みなのに勝率が ${(勝率 * 100).toFixed(1)}%（物差しが傾いている）`
  );
});

test('学習は重みを動かし、形は保つ', () => {
  const 結果 = 学習する({
    デッキを作る,
    世代数: 1,
    挑戦者の数: 2,
    比較の試合数: 40,
    確かめの試合数: 40,
    種: 1,
  });

  // 項目が増減していないこと。増えた項目を写し忘れると、
  // 焼き込んだ重みに欠けが出て、既定値に静かに落ちる。
  assert.deepEqual(
    Object.keys(結果.重み).sort(),
    Object.keys(既定の重み).sort(),
    '学習した重みの項目が、評価の重みと食い違っている'
  );
  for (const [鍵, 値] of Object.entries(結果.重み)) {
    assert.equal(Number.isFinite(値), true, `${鍵} が数ではない`);
  }
});

// 焼き込んだ重みが、いまの 評価の重み と食い違っていないこと。
//
// 重みに項目を足したあと学習を回し直さないと、焼き込んだ側に項目が無く、
// **その項目だけ既定値のまま**という中途半端な状態になる。
// 気づけないので、ここで止める。
test('焼き込んだ重みは、いまの評価の重みと同じ項目を持つ', () => {
  assert.deepEqual(
    Object.keys(学習した重み).sort(),
    Object.keys(既定の重み).sort(),
    '学習した重み.ts が古い（npm run 学習 を回し直すこと）'
  );
  for (const [鍵, 値] of Object.entries(学習した重み as unknown as Record<string, number>)) {
    assert.equal(Number.isFinite(値), true, `${鍵} が数ではない`);
  }
});

// 本丸。焼き込んだ重みが、手で置いた重みより本当に強いか。
//
// 学習に使っていない種で測る。学習に使った種で測ると、
// その試合に噛み合っただけでも「強くなった」と出てしまう。
test('焼き込んだ重みは、手で置いた重みより強い', () => {
  const 勝率 = 重みを戦わせる(
    学習した重み as 評価の重み,
    既定の重み,
    デッキを作る,
    400,
    770_001
  );
  assert.ok(
    勝率 > 0.5,
    `鍛えた重みが手で置いた重みに勝てていない: ${(勝率 * 100).toFixed(1)}%`
  );
});

// === 歴代の物差しに対する見張り ===
//
// 練習用AIだけを物差しにしていたら、AIが起動効果を1度も撃たないことに
// 数百試合ぶんの数字を見ても気づけなかった。練習用AIも同じ穴を持っていたため。
//
// そこで「そのとき一番強かったAI」を凍らせて物差しに置いてある。
// 弱くなったらここで落ちる。
test('いまのAIは、歴代の物差しに負け越さない', () => {
  const 勝率 = 重みを戦わせる(
    学習した重み as 評価の重み,
    物差しの重み,
    デッキを作る,
    400,
    660_001
  );
  // 同じ重みなら五分。ばらつきの幅（400試合で標準誤差 約2.5%）を見て、
  // はっきり負け越したときだけ落とす。
  assert.ok(
    勝率 >= 0.45,
    `歴代の物差しに負け越している: ${(勝率 * 100).toFixed(1)}%（弱くなった疑い）`
  );
});
