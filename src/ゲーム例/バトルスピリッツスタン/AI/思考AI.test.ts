// 「強くなった」を口で言わずに数字で言う。
//
// 種を固定してあるので、この数字は何度回しても同じになる。
// 落ちたときは「たまたま」ではなく、本当に弱くなったということ。

// 赫焔ノ風牙の実装済みカードで40枚。スピリット・ネクサス・マジックが混ざる。
// スピリットだけのデッキで測ると、いちばん効いている「マジックを使えるようになった」が
// まるごと測定から抜け落ちる。
const 風牙のカード = カード帳.filter(x => !/^紫/.test(x.カード名));

function デッキを作る(接頭辞: string): カード[] {
  const デッキ: カード[] = [];
  for (let i = 0; i < 40; i++) {
    デッキ.push(風牙のカード[i % 風牙のカード.length].作る(`${接頭辞}-${i}`));
  }
  return デッキ;
}

const 練習 = (自分: string, 相手: string): 対戦相手 => new 練習用AI(自分, 相手);
const 思考 = (自分: string, 相手: string, 種: number): 対戦相手 =>
  new 思考AI(自分, 相手, { 乱数: 種から乱数を作る(種) });

test('思考AIは練習用AIに勝ち越す', () => {
  // 先攻は有利なので、先攻・後攻を入れ替えて半分ずつ戦わせている（腕試しする の中）。
  // 入れ替えないと「強いAI」ではなく「先攻」を測ってしまう。
  const 結果 = 腕試しする(思考, 練習, デッキを作る, 200, 1);
  assert.equal(結果.決着せず, 0, '決着しない試合がある（進行が詰まっている疑い）');
  assert.ok(
    結果.先の勝率 >= 0.65,
    `思考AIの勝率が ${(結果.先の勝率 * 100).toFixed(1)}% しかない（65%を下回った）`
  );
});

// 盤面を複製できるようになったので、手の良し悪しを
// 「見込みの足し引き」ではなく**複製の上で実際に打って**測れる。
// 効果が何をしたかまで盤面に出るぶん、読みが正確になる。
//
// 複製を入れただけでは強くなったことにならないので、直接戦わせて確かめる。
// ここが五分に戻ったら、複製が効いていない（または壊れている）。
test('先読みする思考AIは、見込みで選ぶ思考AIに勝ち越す', () => {
  const 見込み = (自分: string, 相手: string, 種: number): 対戦相手 =>
    new 思考AI(自分, 相手, { 先読みする: false, 乱数: 種から乱数を作る(種) });
  const 先読み = (自分: string, 相手: string, 種: number): 対戦相手 =>
    new 思考AI(自分, 相手, { 先読みする: true, 乱数: 種から乱数を作る(種) });

  const 結果 = 腕試しする(先読み, 見込み, デッキを作る, 200, 1);
  assert.equal(結果.決着せず, 0, '決着しない試合がある');
  assert.ok(
    結果.先の勝率 >= 0.55,
    `先読みが効いていない: 勝率 ${(結果.先の勝率 * 100).toFixed(1)}%`
  );
});

// 土俵が傾いていないことの確認。
// これが5割から外れていたら、上の勝率は強さではなく測り方を見ている。
test('同じAI同士なら勝率は五分に近い（測り方が傾いていない）', () => {
  const 結果 = 腕試しする(練習, 練習, デッキを作る, 200, 1);
  assert.ok(
    Math.abs(結果.先の勝率 - 0.5) < 0.1,
    `同じAI同士なのに勝率が ${(結果.先の勝率 * 100).toFixed(1)}%`
  );
});

// 強さのつまみ。あとでレート戦を入れるとき、レートからこの数値を作る。
// 「つまみはあるが効いていない」を防ぐため、両端で差が出ることを見る。
test('強さを下げると弱くなる', () => {
  const 最強 = 腕試しする(思考, 練習, デッキを作る, 200, 1);
  const 最弱 = 腕試しする(
    (自分, 相手, 種) => new 思考AI(自分, 相手, { 強さ: 0, 乱数: 種から乱数を作る(種) }),
    練習,
    デッキを作る,
    200,
    1
  );
  assert.ok(
    最強.先の勝率 - 最弱.先の勝率 > 0.2,
    `強さのつまみが効いていない: 最強 ${(最強.先の勝率 * 100).toFixed(1)}% / 最弱 ${(最弱.先の勝率 * 100).toFixed(1)}%`
  );
});

// AIが手札とコアを遊ばせないこと。
//
// 実戦を1試合ずつ見たときに見つかった穴。重みに任せていたら、
// 245ターンでLvアップが9回しか起きず、場のスピリットの96%がLv1のままだった。
// BPは1点あたりの重みが小さく、コアを払う損のほうが常に大きく見えていたため。
//
// 「手札のどれにも使えないコアはLvアップに回す」を規則として置いてある。
// 重みがどう変わっても守られてほしいので、ここで固定する。
test('手札に使えない余ったコアは、Lvアップに回す', () => {
  let Lvアップの回数 = 0;
  let ターン合計 = 0;

  for (let 種 = 1; 種 <= 20; 種++) {
    const 試合インスタンス = 試合を用意する(デッキを作る, 種);
    const 元コアを移動する = 試合インスタンス.コアを移動する.bind(試合インスタンス);
    試合インスタンス.コアを移動する = (元: any, 先: any, 数: number) => {
      const 成功 = 元コアを移動する(元, 先, 数);
      // リザーブから場のカードへ動いたら、それがLvアップ
      if (成功 && 先 && typeof 先.名称?.表示名 === 'string') Lvアップの回数++;
      return 成功;
    };
    const AIマップ = new Map<string, 対戦相手>([
      ['p1', 思考('p1', 'p2', 種)],
      ['p2', 練習('p2', 'p1')],
    ]);
    対戦を進行する(試合インスタンス, AIマップ);
    ターン合計 += 試合インスタンス.ゲーム.プレイヤーを取得('p1')?.数値を取得('ターン数') ?? 0;
  }

  // 直す前は 0.04回/ターン。規則を入れて 0.11回/ターン（実測）。
  // 「手札でいちばん高い札のぶんは残す」ので、回数は控えめになる。
  // そのぶん勝率の損がゼロで済んでいる（安いほうに合わせると約2ポイント負ける）。
  // 0.08 を下回ったら、また余らせている。
  assert.ok(
    Lvアップの回数 / ターン合計 > 0.08,
    `Lvアップが少なすぎる: ${Lvアップの回数}回 / ${ターン合計}ターン`
  );
});

// いちばん効いている変更。
// 練習用AIはスピリットしか出せず、ネクサスとマジックは一度も使われなかった。
test('思考AIはネクサスもマジックも実際に使う', () => {
  const 数え = { 召喚: 0, 配置: 0, 使用: 0 };

  for (let 種 = 1; 種 <= 30; 種++) {
    const 試合インスタンス = 試合を用意する(デッキを作る, 種);
    // 本物の経路（試合.召喚する／配置する／使用する）を通った回数を数える。
    // AIの中を覗いて「選んだ手」を数えると、選んだのに通らなかった場合に気づけない。
    const 元召喚 = 試合インスタンス.召喚する.bind(試合インスタンス);
    const 元配置 = 試合インスタンス.配置する.bind(試合インスタンス);
    const 元使用 = 試合インスタンス.使用する.bind(試合インスタンス);
    試合インスタンス.召喚する = (...引数: any) => {
      const 成功 = 元召喚(...(引数 as [any, any, any, any]));
      if (成功) 数え.召喚++;
      return 成功;
    };
    試合インスタンス.配置する = (...引数: any) => {
      const 成功 = 元配置(...(引数 as [any, any, any, any]));
      if (成功) 数え.配置++;
      return 成功;
    };
    試合インスタンス.使用する = (...引数: any) => {
      const 成功 = 元使用(...(引数 as [any, any, any]));
      if (成功) 数え.使用++;
      return 成功;
    };

    const AIマップ = new Map<string, 対戦相手>([
      ['p1', 思考('p1', 'p2', 種)],
      ['p2', 練習('p2', 'p1')],
    ]);
    対戦を進行する(試合インスタンス, AIマップ);
  }

  assert.ok(数え.召喚 > 0, 'スピリットを1体も召喚していない');
  assert.ok(数え.配置 > 0, 'ネクサスを1枚も配置していない（練習用AIと同じまま）');
  assert.ok(数え.使用 > 0, 'マジックを1枚も使っていない（練習用AIと同じまま）');
});

test('効果の選択には必ず答える（答えないと試合が止まる）', () => {
  // 選択肢（カードではない判断）には1つ返す
  const AI = new 思考AI('p1', 'p2');
  const 試合インスタンス = 試合を用意する(デッキを作る, 1);
  const 答え = AI.効果対象を選ぶ(試合インスタンス, {
    候補: [],
    最小: 1,
    最大: 1,
    任意: false,
    選択肢: [
      { 識別子: 'ソウルコアも置く', 表示: 'ソウルコアも置く' },
      { 識別子: '通常コアだけ置く', 表示: '通常コアだけ置く' },
    ],
  });
  // ソウルコアは手元に残すのが基本的に得（《ソウルマジック》と真界放に使える）
  assert.deepEqual(答え, ['通常コアだけ置く']);
});

// 返しまで読むと強くなること。
//
// ここは2度しくじった。1度目は読みの中の相手が弱すぎて（先読みなし）効かず、
// 2度目は読みが完全に決定的で「何回か読んで平均する」が何も働いていなかった
// （1回と5回が小数点まで同じ数字になった）。
//
// いまは強い相手で読み、読みを少し散らして平均している。
// ここが五分に戻ったら、そのどちらかがまた壊れている。
test('返しまで読む思考AIは、1手だけ読む思考AIに勝ち越す', () => {
  const 浅い = (自分: string, 相手: string, 種: number): 対戦相手 =>
    new 思考AI(自分, 相手, { 読む深さ: 1, 乱数: 種から乱数を作る(種) });
  const 深い = (自分: string, 相手: string, 種: number): 対戦相手 =>
    new 思考AI(自分, 相手, { 読む深さ: 2, 乱数: 種から乱数を作る(種) });

  const 結果 = 腕試しする(深い, 浅い, デッキを作る, 200, 880_001);
  assert.equal(結果.決着せず, 0, '決着しない試合がある');
  assert.ok(
    結果.先の勝率 >= 0.52,
    `返しまで読んでも強くなっていない: ${(結果.先の勝率 * 100).toFixed(1)}%`
  );
});
