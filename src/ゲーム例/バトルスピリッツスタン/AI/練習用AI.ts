import { カード } from '../../../データ/カード/カード.js';
import { 試合 } from '../試合.js';
import { カード種別ルール } from '../カードの情報/カード種別.js';
import { コストルール } from '../カードの情報/コスト.js';
import { 軽減シンボルルール } from '../カードの情報/軽減シンボル.js';
import { シンボルルール } from '../カードの情報/シンボル.js';
import { 消滅判定 } from '../判定/消滅判定.js';
import { コア判定 } from '../判定/コア判定.js';

// 練習用AI（ルールベースの単純な対戦相手）
// 「試合」を外から操作する存在として実装し、試合クラス自体には手を加えない。
// 方針（フェーズ1・カード1種類のみを前提とした最小限のロジック）：
//  - メインステップ／第2メインステップ：手札から支払えるスピリットを見つかる限り召喚する
//  - アタックステップ：回復状態の自分のスピリットで見つかる限り攻撃する（アグレッシブ戦略）
//  - ブロック：BPが相手以上のスピリットがあれば、その中でBPが最も低いものでブロックする
//    （不利なトレードを避けつつ、より強いスピリットを温存する）。無ければブロックしない。
export class 練習用AI {
  private カード種別ルール = new カード種別ルール();
  private コストルール = new コストルール();
  private 軽減シンボルルール = new 軽減シンボルルール();
  private シンボルルール = new シンボルルール();
  private 消滅判定 = new 消滅判定();
  private コア判定 = new コア判定();

  constructor(private 自分の識別子: string) {}

  識別子を取得(): string {
    return this.自分の識別子;
  }

  // メインステップ／第2メインステップの行動。支払えるカードが無くなるまで召喚し、ステップを終了する。
  メインステップを行動する(試合: 試合): void {
    while (this.召喚を試みる(試合)) {
      // 支払えるカードが無くなるまで繰り返す
    }
    試合.ステップを終了する();
  }

  private 召喚を試みる(試合: 試合): boolean {
    const 手札 = 試合.ゾーン管理.手札を取得(試合.ゲーム, this.自分の識別子);
    const フィールド = 試合.ゾーン管理.フィールドを取得(試合.ゲーム, this.自分の識別子);
    const リザーブ = 試合.ゾーン管理.リザーブを取得(試合.ゲーム, this.自分の識別子);
    if (!手札 || !フィールド || !リザーブ) {
      return false;
    }

    const リザーブ保持者 = 試合.コア管理.ゾーンを保持者に(リザーブ);
    const フィールドのシンボル: string[] = [];
    for (const カード of フィールド.カード一覧を取得()) {
      for (const シンボル of this.シンボルルール.シンボルを取得(カード)) {
        フィールドのシンボル.push(シンボル.色);
      }
    }

    for (const カード of 手札.カード一覧を取得()) {
      if (!this.カード種別ルール.スピリットか(カード)) {
        continue; // フェーズ1はスピリットの召喚のみ対応
      }

      const 基本コスト = this.コストルール.コストを取得(カード);
      const コスト = this.軽減シンボルルール.軽減後のコストを計算(カード, 基本コスト, フィールドのシンボル);
      const 最低必要数 = this.消滅判定.最小必要コア数を取得(カード);
      const 必要合計 = コスト + 最低必要数;

      if (this.コア判定.通常コア数を取得(リザーブ保持者) < 必要合計) {
        continue; // このカードは支払えない、次の候補へ
      }

      const 成功 = 試合.召喚する(
        this.自分の識別子,
        カード,
        [{ 保持者: リザーブ保持者, 数: コスト }],
        [{ 保持者: リザーブ保持者, 数: 最低必要数 }]
      );
      if (成功) {
        return true;
      }
    }
    return false;
  }

  // アタックステップで、次に攻撃させるスピリットを1体選ぶ（居なければnull＝これ以上攻撃しない）
  攻撃者を選ぶ(試合: 試合): カード | null {
    const フィールド = 試合.ゾーン管理.フィールドを取得(試合.ゲーム, this.自分の識別子);
    if (!フィールド) {
      return null;
    }
    return (
      フィールド.カード一覧を取得().find(カード => this.回復状態のスピリットか(試合, カード)) ?? null
    );
  }

  // 相手の攻撃に対して、ブロックするスピリットを選ぶ（居なければnull＝ブロックしない）
  ブロッカーを選ぶ(試合: 試合, アタッカー: カード): カード | null {
    const フィールド = 試合.ゾーン管理.フィールドを取得(試合.ゲーム, this.自分の識別子);
    if (!フィールド) {
      return null;
    }
    const アタッカーBP = 試合.BP管理.現在のBPを取得(アタッカー);
    const 候補 = フィールド
      .カード一覧を取得()
      .filter(カード => this.回復状態のスピリットか(試合, カード))
      .filter(カード => 試合.BP管理.現在のBPを取得(カード) >= アタッカーBP)
      .sort((a, b) => 試合.BP管理.現在のBPを取得(a) - 試合.BP管理.現在のBPを取得(b));
    return 候補[0] ?? null;
  }

  private 回復状態のスピリットか(試合: 試合, カード: カード): boolean {
    if (!this.カード種別ルール.スピリットか(カード)) {
      return false;
    }
    return 試合.カードの表示形式管理.現在の表示形式を取得(カード) === '回復';
  }
}
