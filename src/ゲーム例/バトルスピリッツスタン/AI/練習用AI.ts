import { ゾーン } from '../../../データ/ゾーン/ゾーン.js';
import { 試合 } from '../試合.js';
import { カード種別ルール } from '../カードの情報/カード種別.js';
import { コストルール } from '../カードの情報/コスト.js';
import { 軽減シンボルルール } from '../カードの情報/軽減シンボル.js';
import { シンボルルール } from '../カードの情報/シンボル.js';
import { Lvルール, Lv情報 } from '../カードの情報/Lv.js';
import { 消滅判定 } from '../判定/消滅判定.js';
import { コア判定 } from '../判定/コア判定.js';

// 練習用AI（ルールベースの単純な対戦相手）
// 「試合」を外から操作する存在として実装し、試合クラス自体には手を加えない。
//
// 方針（カード1種類のみを前提とした最小限のロジック）：
//  - リーサル判定：
//      (自分の回復状態スピリットのシンボル数合計 + 自分の追加召喚可能数)
//        >= (相手のライフのコア数 + 相手の回復状態スピリット数)
//  - メインステップ：リーサルなら召喚（対数追加）に専念。リーサルでなければ、
//    回復状態スピリットのLvアップ（リザーブから）を優先し、その後に召喚する。
//  - 第2メインステップ：リーサルなら召喚（対数追加）に専念。リーサルでなければ、
//    召喚 → 回復状態スピリットのLvアップ（リザーブから）
//        → 疲労状態スピリットのLvアップ（リザーブから、足りなければ他の回復状態
//          スピリットの余剰コアから。供給元は1個残しまで引き剥がせる）の順に行う。
//  - アタックステップ：自分にリーサルがあれば全ての回復状態スピリットで攻撃する。
//    無ければ1体を温存し、残りで攻撃する（攻撃者を選ぶ前に一度だけリーサルを
//    計算してキャッシュしておく。攻撃が進むほど回復状態のスピリットが減るため）。
//  - ブロック：相手（攻撃側）が自分に対してリーサルを持つ場合は、通常のBP条件を
//    無視して可能な限りブロックする。そうでなければ、BPが相手以上のスピリットの
//    うち最もBPが低いものでブロックする（不利なトレードを避けつつ主力を温存）。
// AIに渡す「効果の対象を選んでほしい」という依頼。
// 効果実行器の選択待ち情報のうち、選ぶのに必要な分だけを受け取る。
export interface 効果選択の依頼 {
  候補: カード[];
  最小: number;
  最大: number;
  任意: boolean;
}

export class 練習用AI {
  private カード種別ルール = new カード種別ルール();
  private コストルール = new コストルール();
  private 軽減シンボルルール = new 軽減シンボルルール();
  private シンボルルール = new シンボルルール();
  private Lvルール = new Lvルール();
  private 消滅判定 = new 消滅判定();
  private コア判定 = new コア判定();

  private 攻撃ステップのリーサルキャッシュ = false;

  constructor(
    private 自分の識別子: string,
    private 相手の識別子: string
  ) {}

  識別子を取得(): string {
    return this.自分の識別子;
  }

  // メインステップの行動：リーサルなら召喚（対数追加）に専念。
  // リーサルでなければ、回復状態スピリットのLvアップを優先し、その後に召喚する。
  メイン1を行動する(試合: 試合): void {
    const リーサル = this.リーサルを判定する(試合, this.自分の識別子, this.相手の識別子);
    if (リーサル) {
      while (this.召喚を試みる(試合)) {
        // 支払えるカードが無くなるまで繰り返す
      }
    } else {
      while (this.回復スピリットのレベルアップを試みる(試合)) {
        // レベルアップできる回復状態スピリットが無くなるまで繰り返す
      }
      // 召喚時効果が今は不発になるカードは、アタック後の第2メインステップまで温存する
      while (this.召喚を試みる(試合, true)) {
        // 支払えるカードが無くなるまで繰り返す
      }
    }
    試合.ステップを終了する();
  }

  // 第2メインステップの行動：リーサルなら召喚（対数追加）に専念。
  // リーサルでなければ、召喚 → 回復状態スピリットのLvアップ → 疲労状態スピリットのLvアップ の順。
  メイン2を行動する(試合: 試合): void {
    const リーサル = this.リーサルを判定する(試合, this.自分の識別子, this.相手の識別子);
    if (リーサル) {
      while (this.召喚を試みる(試合)) {
        // 支払えるカードが無くなるまで繰り返す
      }
    } else {
      while (this.召喚を試みる(試合)) {
        // 支払えるカードが無くなるまで繰り返す
      }
      while (this.回復スピリットのレベルアップを試みる(試合)) {
        // レベルアップできる回復状態スピリットが無くなるまで繰り返す
      }
      while (this.疲労スピリットのレベルアップを試みる(試合)) {
        // レベルアップできる疲労状態スピリットが無くなるまで繰り返す
      }
    }
    試合.ステップを終了する();
  }

  // 召喚を1体試みる。
  // 温存する を渡すと、「今出しても召喚時効果が不発になるカード」を後回しにする。
  // 例：ロワミークの『疲労状態の自分の赤のスピリットがいるなら』は、
  //     メイン1では自分のスピリットが回復状態のため成立しない。
  //     アタック後の第2メインステップまで待てば、攻撃で疲労した味方が条件を満たす。
  private 召喚を試みる(試合: 試合, 温存する = false): boolean {
    const 手札 = 試合.ゾーン管理.手札を取得(試合.ゲーム, this.自分の識別子);
    const フィールド = 試合.ゾーン管理.フィールドを取得(試合.ゲーム, this.自分の識別子);
    const リザーブ = 試合.ゾーン管理.リザーブを取得(試合.ゲーム, this.自分の識別子);
    if (!手札 || !フィールド || !リザーブ) {
      return false;
    }

    const リザーブ保持者 = 試合.コア管理.ゾーンを保持者に(リザーブ);
    const フィールドのシンボル = this.フィールドのシンボルを集計する(フィールド);

    for (const カード of 手札.カード一覧を取得()) {
      if (!this.カード種別ルール.スピリットか(カード)) {
        continue; // フェーズ1はスピリットの召喚のみ対応
      }

      if (温存する && this.後で出すほうが得か(試合, カード)) {
        continue; // 第2メインステップまで待つ
      }

      const 基本コスト = this.コストルール.コストを取得(カード);
      const コスト = this.軽減シンボルルール.軽減後のコストを計算(カード, 基本コスト, フィールドのシンボル);
      const 最低必要数 = this.消滅判定.最小必要コア数を取得(カード);
      const 必要合計 = コスト + 最低必要数;

      if (this.コア判定.通常コア数を取得(リザーブ保持者) < 必要合計) {
        continue; // このカードは支払えない、次の候補へ
      }

      const 成功 = 試合.召喚する(
        this.自分の識別子,
        カード,
        [{ 保持者: リザーブ保持者, 数: コスト }],
        [{ 保持者: リザーブ保持者, 数: 最低必要数 }]
      );
      if (成功) {
        return true;
      }
    }
    return false;
  }

  // 今出すと召喚時効果が不発になるが、待てば当たる見込みがあるか。
  // 「攻撃すれば自分のスピリットが疲労する」ように、条件は自分の行動で変えられることが多いため、
  // これから攻撃できる回復状態のスピリットがいる場合にかぎり待つ。
  private 後で出すほうが得か(試合: 試合, カード: カード): boolean {
    const 条件を満たす = 試合.効果実行器.トリガー効果の条件を満たすか(カード, '召喚時');
    if (条件を満たす !== false) {
      return false; // 条件を満たしている、または条件付きの召喚時効果を持たない
    }

    // 攻撃できる味方がいなければ盤面は変わらないので、待っても無駄
    const フィールド = 試合.ゾーン管理.フィールドを取得(試合.ゲーム, this.自分の識別子);
    if (!フィールド) {
      return false;
    }
    return フィールド.カード一覧を取得().some(候補 => this.回復状態のスピリットか(試合, 候補));
  }

  // リザーブの余剰コアで、回復状態のLvアップ可能なスピリットのLvを1段階上げる
  private 回復スピリットのレベルアップを試みる(試合: 試合): boolean {
    const フィールド = 試合.ゾーン管理.フィールドを取得(試合.ゲーム, this.自分の識別子);
    const リザーブ = 試合.ゾーン管理.リザーブを取得(試合.ゲーム, this.自分の識別子);
    if (!フィールド || !リザーブ) {
      return false;
    }

    const リザーブ保持者 = 試合.コア管理.ゾーンを保持者に(リザーブ);

    for (const カード of フィールド.カード一覧を取得()) {
      if (!this.回復状態のスピリットか(試合, カード)) {
        continue;
      }
      const 次のLv情報 = this.次のLv情報を取得(試合, カード);
      if (!次のLv情報) {
        continue;
      }
      const 現在のコア数 = this.コア判定.総コア数を取得(試合.コア管理.カードを保持者に(カード));
      const 不足数 = 次のLv情報.cost - 現在のコア数;
      if (不足数 <= 0) {
        continue;
      }
      if (this.コア判定.通常コア数を取得(リザーブ保持者) < 不足数) {
        continue; // リザーブだけでは足りない、次の候補へ
      }

      if (試合.コアを移動する(リザーブ, カード, 不足数)) {
        return true;
      }
    }
    return false;
  }

  // 疲労状態のLvアップ可能なスピリットのLvを1段階上げる。
  // まずリザーブから、足りなければ他の回復状態スピリット（供給元は回復状態に限る）の
  // 余剰コアから補う。供給元は1個残しまで引き剥がせる。必要数を全て賄えない場合は行わない。
  private 疲労スピリットのレベルアップを試みる(試合: 試合): boolean {
    const フィールド = 試合.ゾーン管理.フィールドを取得(試合.ゲーム, this.自分の識別子);
    const リザーブ = 試合.ゾーン管理.リザーブを取得(試合.ゲーム, this.自分の識別子);
    if (!フィールド || !リザーブ) {
      return false;
    }

    const リザーブ保持者 = 試合.コア管理.ゾーンを保持者に(リザーブ);

    for (const カード of フィールド.カード一覧を取得()) {
      if (!this.疲労状態のスピリットか(試合, カード)) {
        continue;
      }
      const 次のLv情報 = this.次のLv情報を取得(試合, カード);
      if (!次のLv情報) {
        continue;
      }
      const 現在のコア数 = this.コア判定.総コア数を取得(試合.コア管理.カードを保持者に(カード));
      const 不足数 = 次のLv情報.cost - 現在のコア数;
      if (不足数 <= 0) {
        continue;
      }

      const リザーブから使える数 = this.コア判定.通常コア数を取得(リザーブ保持者);

      const 提供元候補 = フィールド
        .カード一覧を取得()
        .filter(候補 => 候補 !== カード && this.回復状態のスピリットか(試合, 候補))
        .map(候補 => ({ カード: 候補, 提供可能数: this.引き剥がし可能なコア数を取得(試合, 候補) }))
        .filter(候補 => 候補.提供可能数 > 0);

      const 提供元合計 = 提供元候補.reduce((合計, 候補) => 合計 + 候補.提供可能数, 0);
      if (リザーブから使える数 + 提供元合計 < 不足数) {
        continue; // 賄いきれない、次の候補へ
      }

      let 残り不足 = 不足数;
      const リザーブからの移動数 = Math.min(残り不足, リザーブから使える数);
      if (リザーブからの移動数 > 0 && 試合.コアを移動する(リザーブ, カード, リザーブからの移動数)) {
        残り不足 -= リザーブからの移動数;
      }
      for (const 候補 of 提供元候補) {
        if (残り不足 <= 0) {
          break;
        }
        const 移動数 = Math.min(残り不足, 候補.提供可能数);
        if (移動数 > 0 && 試合.コアを移動する(候補.カード, カード, 移動数)) {
          残り不足 -= 移動数;
        }
      }
      return true;
    }
    return false;
  }

  // 供給元スピリットから引き剥がせる通常コアの上限（総コアが1個になるまで許可）
  private 引き剥がし可能なコア数を取得(試合: 試合, カード: カード): number {
    const 保持者 = 試合.コア管理.カードを保持者に(カード);
    const 総コア数 = this.コア判定.総コア数を取得(保持者);
    const 通常コア数 = this.コア判定.通常コア数を取得(保持者);
    return Math.max(0, Math.min(通常コア数, 総コア数 - 1));
  }

  private 次のLv情報を取得(試合: 試合, カード: カード): Lv情報 | null {
    const 現在のLv = 試合.Lv管理.現在のLvを取得(カード);
    const Lv一覧 = this.Lvルール.Lvを取得(カード);
    return Lv一覧.find(lv => lv.level === 現在のLv + 1) ?? null;
  }

  // アタックステップの開始時に一度だけ呼び、リーサルの有無をキャッシュする
  // （攻撃が進むにつれて自分の回復状態スピリットが減るため、都度再計算すると判定がぶれる）
  攻撃ステップを開始する(試合: 試合): void {
    this.攻撃ステップのリーサルキャッシュ = this.リーサルを判定する(
      試合,
      this.自分の識別子,
      this.相手の識別子
    );
  }

  // アタックステップで、次に攻撃させるスピリットを1体選ぶ（居なければnull＝これ以上攻撃しない）
  // リーサルが無い場合は1体を温存し、残りの回復状態スピリットで攻撃する。
  攻撃者を選ぶ(試合: 試合): カード | null {
    const フィールド = 試合.ゾーン管理.フィールドを取得(試合.ゲーム, this.自分の識別子);
    if (!フィールド) {
      return null;
    }
    const 候補 = フィールド.カード一覧を取得().filter(カード => this.回復状態のスピリットか(試合, カード));
    if (候補.length === 0) {
      return null;
    }
    if (!this.攻撃ステップのリーサルキャッシュ && 候補.length <= 1) {
      return null; // リーサルでなければ最後の1体は温存する
    }
    return 候補[0];
  }

  // 相手の攻撃に対して、ブロックするスピリットを選ぶ（居なければnull＝ブロックしない）
  // 相手（攻撃側）が自分に対してリーサルを持つ場合は、BP条件を無視して可能な限りブロックする。
  ブロッカーを選ぶ(試合: 試合, アタッカー: カード): カード | null {
    const フィールド = 試合.ゾーン管理.フィールドを取得(試合.ゲーム, this.自分の識別子);
    if (!フィールド) {
      return null;
    }
    // 『〜からブロックされない』のような制約があると、回復状態でもブロックできない。
    // 試合に聞かないと分からないため、ここで絞り込む。
    const 回復状態の候補 = フィールド
      .カード一覧を取得()
      .filter(カード => this.回復状態のスピリットか(試合, カード))
      .filter(カード => 試合.ブロックできるか(カード, アタッカー));

    const 相手がリーサルを持つ = this.リーサルを判定する(試合, this.相手の識別子, this.自分の識別子);
    if (相手がリーサルを持つ) {
      return 回復状態の候補[0] ?? null; // 通常のBP条件を無視し、可能な限りブロックする
    }

    const アタッカーBP = 試合.BP管理.現在のBPを取得(アタッカー);
    const 候補 = 回復状態の候補
      .filter(カード => 試合.BP管理.現在のBPを取得(カード) >= アタッカーBP)
      .sort((a, b) => 試合.BP管理.現在のBPを取得(a) - 試合.BP管理.現在のBPを取得(b));
    return 候補[0] ?? null;
  }

  // 効果の対象を選ぶ。
  // AIがこれに答えられないと、AI側の効果が選択待ちのまま試合全体が止まってしまうため、
  // どんな選択が来ても必ず有効な答えを返す（分からなければ最小限で済ませる）。
  効果対象を選ぶ(試合: 試合, 選択待ち: 効果選択の依頼): string[] {
    const { 候補, 最小, 最大 } = 選択待ち;
    if (候補.length === 0 || 最大 === 0) {
      return [];
    }

    // 相手のカードを選ぶ場面なら、脅威の大きいものから選ぶ
    const 自分のフィールド = 試合.ゾーン管理.フィールドを取得(試合.ゲーム, this.自分の識別子);
    const 自分のカード識別子 = new Set(
      (自分のフィールド?.カード一覧を取得() ?? []).map(c => c.識別子)
    );

    const 並び替え済み = [...候補].sort((a, b) => {
      const aは自分 = 自分のカード識別子.has(a.識別子);
      const bは自分 = 自分のカード識別子.has(b.識別子);
      // 相手のカードを優先して選ぶ（除去効果を想定）
      if (aは自分 !== bは自分) {
        return aは自分 ? 1 : -1;
      }
      // 同じ側なら、相手ならBPが高い順・自分ならBPが低い順
      const aのBP = 試合.BP管理.現在のBPを取得(a);
      const bのBP = 試合.BP管理.現在のBPを取得(b);
      return aは自分 ? aのBP - bのBP : bのBP - aのBP;
    });

    // 任意（最小0）の選択は見送らず、有効な範囲で最大まで取る。
    // 「〜できる」効果は基本的に得になるため。
    const 選ぶ数 = Math.min(最大, 並び替え済み.length);
    return 並び替え済み.slice(0, 選ぶ数).map(c => c.識別子);
  }

  // リーサル判定：
  // (攻撃側の回復状態スピリットのシンボル数合計 + 攻撃側の追加召喚可能数)
  //   >= (防御側のライフのコア数 + 防御側の回復状態スピリット数)
  private リーサルを判定する(試合: 試合, 攻撃側識別子: string, 防御側識別子: string): boolean {
    const 攻撃側フィールド = 試合.ゾーン管理.フィールドを取得(試合.ゲーム, 攻撃側識別子);
    const 防御側フィールド = 試合.ゾーン管理.フィールドを取得(試合.ゲーム, 防御側識別子);
    const 防御側ライフ = 試合.ゾーン管理.ライフを取得(試合.ゲーム, 防御側識別子);
    if (!攻撃側フィールド || !防御側フィールド || !防御側ライフ) {
      return false;
    }

    const 攻撃側シンボル数合計 = 攻撃側フィールド
      .カード一覧を取得()
      .filter(カード => this.回復状態のスピリットか(試合, カード))
      .reduce((合計, カード) => 合計 + this.シンボルルール.シンボル数を取得(カード), 0);

    const 追加召喚可能数 = this.追加召喚可能数を見積もる(試合, 攻撃側識別子);

    const 防御側ライフ保持者 = 試合.コア管理.ゾーンを保持者に(防御側ライフ);
    const 防御側ライフコア数 = this.コア判定.総コア数を取得(防御側ライフ保持者);

    const 防御側回復スピリット数 = 防御側フィールド
      .カード一覧を取得()
      .filter(カード => this.回復状態のスピリットか(試合, カード)).length;

    return 攻撃側シンボル数合計 + 追加召喚可能数 >= 防御側ライフコア数 + 防御側回復スピリット数;
  }

  // 手札とリザーブの現状から、このターンあと何体スピリットを追加召喚できそうかを見積もる
  // （フィールドのシンボルはその時点の値のまま固定し、逐次再計算はしない簡易な見積もり）
  private 追加召喚可能数を見積もる(試合: 試合, プレイヤー識別子: string): number {
    const 手札 = 試合.ゾーン管理.手札を取得(試合.ゲーム, プレイヤー識別子);
    const フィールド = 試合.ゾーン管理.フィールドを取得(試合.ゲーム, プレイヤー識別子);
    const リザーブ = 試合.ゾーン管理.リザーブを取得(試合.ゲーム, プレイヤー識別子);
    if (!手札 || !フィールド || !リザーブ) {
      return 0;
    }

    const リザーブ保持者 = 試合.コア管理.ゾーンを保持者に(リザーブ);
    let 残りコア = this.コア判定.通常コア数を取得(リザーブ保持者);
    const フィールドのシンボル = this.フィールドのシンボルを集計する(フィールド);

    const 必要合計一覧 = 手札
      .カード一覧を取得()
      .filter(カード => this.カード種別ルール.スピリットか(カード))
      .map(カード => {
        const 基本コスト = this.コストルール.コストを取得(カード);
        const コスト = this.軽減シンボルルール.軽減後のコストを計算(カード, 基本コスト, フィールドのシンボル);
        const 最低必要数 = this.消滅判定.最小必要コア数を取得(カード);
        return コスト + 最低必要数;
      })
      .sort((a, b) => a - b);

    let 数 = 0;
    for (const 必要合計 of 必要合計一覧) {
      if (残りコア < 必要合計) {
        break; // 昇順なので、これ以降も支払えない
      }
      残りコア -= 必要合計;
      数++;
    }
    return 数;
  }

  private フィールドのシンボルを集計する(フィールド: ゾーン): string[] {
    const フィールドのシンボル: string[] = [];
    for (const カード of フィールド.カード一覧を取得()) {
      for (const シンボル of this.シンボルルール.シンボルを取得(カード)) {
        フィールドのシンボル.push(シンボル.色);
      }
    }
    return フィールドのシンボル;
  }

  private 回復状態のスピリットか(試合: 試合, カード: カード): boolean {
    if (!this.カード種別ルール.スピリットか(カード)) {
      return false;
    }
    return 試合.カードの表示形式管理.現在の表示形式を取得(カード) === '回復';
  }

  private 疲労状態のスピリットか(試合: 試合, カード: カード): boolean {
    if (!this.カード種別ルール.スピリットか(カード)) {
      return false;
    }
    return 試合.カードの表示形式管理.現在の表示形式を取得(カード) === '疲労';
  }
}
