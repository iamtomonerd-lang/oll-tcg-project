import { カード } from '../../../データ/カード/カード.js';
import { ゾーン } from '../../../データ/ゾーン/ゾーン.js';
import { 試合 } from '../試合.js';
import { コア支払い元 } from '../判定/プレイコスト判定.js';
import { カード種別ルール } from '../カードの情報/カード種別.js';
import { コストルール } from '../カードの情報/コスト.js';
import { 軽減シンボルルール } from '../カードの情報/軽減シンボル.js';
import { シンボルルール } from '../カードの情報/シンボル.js';
import { Lvルール } from '../カードの情報/Lv.js';
import { 消滅判定 } from '../判定/消滅判定.js';
import { コア判定 } from '../判定/コア判定.js';
import { キーワードルール } from '../カードの情報/キーワード.js';

// 「いま自分に何ができるか」を全部並べる。
//
// これまでのAIは**スピリットの召喚しか知らなかった**。
// マジックもネクサスも起動効果も、選択肢として挙がっていなかったので、
// どれだけ賢く選ばせても手札の半分は使われないままだった。
// 強くする前に、まず手が届く範囲を広げる。
//
// ここは「挙げるだけ」で、どれが良いかは決めない（決めるのは 思考AI）。
// 挙げる側と選ぶ側を分けておくと、選び方だけを学習で差し替えられる。

export type 手 =
  | { 種類: '召喚'; カード: カード; コスト支払い元: コア支払い元[]; 初期コア: コア支払い元[]; 表示: string }
  | { 種類: '配置'; カード: カード; コスト支払い元: コア支払い元[]; 初期コア: コア支払い元[]; 表示: string }
  | { 種類: '使用'; カード: カード; コスト支払い元: コア支払い元[]; ソウルマジックで払う: boolean; 表示: string }
  | { 種類: 'Lvアップ'; カード: カード; 元: カード | ゾーン; 数: number; 表示: string }
  | { 種類: '起動効果'; 効果識別子: string; タイミング: 'メイン' | 'フラッシュ'; 表示: string }
  | { 種類: '終える'; 表示: string };

export class 打てる手を挙げる {
  private カード種別ルール = new カード種別ルール();
  private コストルール = new コストルール();
  private 軽減シンボルルール = new 軽減シンボルルール();
  private シンボルルール = new シンボルルール();
  private Lvルール = new Lvルール();
  private 消滅判定 = new 消滅判定();
  private コア判定 = new コア判定();
  private キーワードルール = new キーワードルール();

  // メインステップ／第2メインステップで打てる手。
  // 「終える」は常に入れる（何もしないのも1つの手であり、
  //  これが無いと「打てる手が尽きるまで打つ」しかできない）。
  メインで打てる手(試合インスタンス: 試合, 自分の識別子: string): 手[] {
    return [
      ...this.プレイできる手(試合インスタンス, 自分の識別子, 'メイン'),
      ...this.Lvアップできる手(試合インスタンス, 自分の識別子),
      ...this.起動効果の手(試合インスタンス, 自分の識別子, 'メイン'),
      { 種類: '終える', 表示: 'ステップを終える' },
    ];
  }

  // 割り込みの窓で打てる手。
  // ［フラッシュ］のマジックと、フラッシュの起動効果だけ。
  // 「終える」＝パスに当たる。
  フラッシュで打てる手(試合インスタンス: 試合, 自分の識別子: string): 手[] {
    return [
      ...this.プレイできる手(試合インスタンス, 自分の識別子, 'フラッシュ'),
      ...this.起動効果の手(試合インスタンス, 自分の識別子, 'フラッシュ'),
      { 種類: '終える', 表示: 'パスする' },
    ];
  }

  // 手札から出せるもの（スピリット・ネクサス・マジック）。
  //
  // タイミングが 'フラッシュ' のときは、［フラッシュ］の効果を持つマジックだけ。
  // 'メイン' のときはスピリット・ネクサスに加えて、
  // マジックも（［フラッシュ］しか持たないものを含めて）出せる。
  // ［フラッシュ］の効果はメインステップでも使えるため。
  private プレイできる手(
    試合インスタンス: 試合,
    自分の識別子: string,
    タイミング: 'メイン' | 'フラッシュ'
  ): 手[] {
    const ゲーム = 試合インスタンス.ゲーム;
    const 手札 = 試合インスタンス.ゾーン管理.手札を取得(ゲーム, 自分の識別子);
    const フィールド = 試合インスタンス.ゾーン管理.フィールドを取得(ゲーム, 自分の識別子);
    const リザーブ = 試合インスタンス.ゾーン管理.リザーブを取得(ゲーム, 自分の識別子);
    if (!手札 || !フィールド || !リザーブ) return [];

    const リザーブ保持者 = 試合インスタンス.コア管理.ゾーンを保持者に(リザーブ);
    const フィールドのシンボル = フィールド
      .カード一覧を取得()
      .flatMap(c => this.シンボルルール.シンボルを取得(c).map(x => x.色));

    const 手一覧: 手[] = [];

    for (const カード of 手札.カード一覧を取得()) {
      const マジックか = this.カード種別ルール.マジックか(カード);
      if (タイミング === 'フラッシュ' && !マジックか) {
        continue; // 割り込み中にスピリットやネクサスは出せない
      }
      if (マジックか && タイミング === 'フラッシュ' && !this.フラッシュで使えるか(カード)) {
        continue;
      }

      const 基本コスト = this.コストルール.コストを取得(カード);
      const コスト = this.軽減シンボルルール.軽減後のコストを計算(
        カード,
        基本コスト,
        フィールドのシンボル
      );

      if (マジックか) {
        // ふつうに払う
        if (this.コア判定.通常コア数を取得(リザーブ保持者) >= コスト) {
          手一覧.push({
            種類: '使用',
            カード,
            コスト支払い元: [{ 保持者: リザーブ保持者, 数: コスト }],
            ソウルマジックで払う: false,
            表示: `${カード.名称.表示名} を使う`,
          });
        }
        // 《ソウルマジック》で払う（コアを1個も減らさずに撃てるので、別の手として挙げる）
        if (this.ソウルマジックで撃てるか(試合インスタンス, 自分の識別子, カード, フィールドのシンボル)) {
          手一覧.push({
            種類: '使用',
            カード,
            コスト支払い元: [],
            ソウルマジックで払う: true,
            表示: `${カード.名称.表示名} を《ソウルマジック》で使う`,
          });
        }
        continue;
      }

      // スピリット・ネクサスは、コストに加えて Lv1 を保てる分のコアが要る。
      // ここを足さずに出すと、置いた瞬間に消滅する。
      const 最低必要数 = this.消滅判定.最小必要コア数を取得(カード);
      if (this.コア判定.通常コア数を取得(リザーブ保持者) < コスト + 最低必要数) {
        continue;
      }
      const 共通 = {
        カード,
        コスト支払い元: [{ 保持者: リザーブ保持者, 数: コスト }],
        初期コア: [{ 保持者: リザーブ保持者, 数: 最低必要数 }],
      };
      手一覧.push(
        this.カード種別ルール.スピリットか(カード)
          ? { 種類: '召喚', ...共通, 表示: `${カード.名称.表示名} を召喚` }
          : { 種類: '配置', ...共通, 表示: `${カード.名称.表示名} を配置` }
      );
    }

    return 手一覧;
  }

  // 場のスピリットをLv1段階上げる手。
  // 上げ先ごとに1つの手として挙げ、どれを上げるかは選ぶ側に任せる。
  // コアはリザーブからのみ（他のスピリットから引き剥がす手は、
  // 剥がした側が弱るぶん判断が難しいので、まずはリザーブだけに絞る）。
  private Lvアップできる手(試合インスタンス: 試合, 自分の識別子: string): 手[] {
    const ゲーム = 試合インスタンス.ゲーム;
    const フィールド = 試合インスタンス.ゾーン管理.フィールドを取得(ゲーム, 自分の識別子);
    const リザーブ = 試合インスタンス.ゾーン管理.リザーブを取得(ゲーム, 自分の識別子);
    if (!フィールド || !リザーブ) return [];

    const リザーブ保持者 = 試合インスタンス.コア管理.ゾーンを保持者に(リザーブ);
    const 使えるコア = this.コア判定.通常コア数を取得(リザーブ保持者);
    const 手一覧: 手[] = [];

    for (const カード of フィールド.カード一覧を取得()) {
      const 現在のLv = 試合インスタンス.Lv管理.現在のLvを取得(カード);
      const 次 = this.Lvルール.Lvを取得(カード).find(lv => lv.level === 現在のLv + 1);
      if (!次) continue;

      const 現在のコア数 = this.コア判定.総コア数を取得(
        試合インスタンス.コア管理.カードを保持者に(カード)
      );
      const 不足数 = 次.cost - 現在のコア数;
      if (不足数 <= 0 || 使えるコア < 不足数) continue;

      手一覧.push({
        種類: 'Lvアップ',
        カード,
        元: リザーブ,
        数: 不足数,
        表示: `${カード.名称.表示名} を Lv${次.level} へ`,
      });
    }
    return 手一覧;
  }

  private 起動効果の手(
    試合インスタンス: 試合,
    自分の識別子: string,
    タイミング: 'メイン' | 'フラッシュ'
  ): 手[] {
    return 試合インスタンス.効果実行器
      .発動できる起動効果を集める(自分の識別子, タイミング)
      .map(候補 => ({
        種類: '起動効果' as const,
        効果識別子: 候補.効果識別子,
        タイミング,
        表示: `${候補.発揮源.名称.表示名} の起動効果`,
      }));
  }

  private フラッシュで使えるか(カード: カード): boolean {
    const 効果一覧 = (カード.名称 as any).効果 ?? [];
    return 効果一覧.some((効果: any) => 効果.種別 === '使用' && 効果.タイミング === 'フラッシュ');
  }

  // 《ソウルマジック》で撃てるか（12-2-1-2-1）。
  // ・そのカードが《ソウルマジック》を持つ
  // ・自分の場にそのカードの色のシンボルがある
  // ・ソウルコアがリザーブか場にある（トラッシュに落ちていたら撃てない）
  private ソウルマジックで撃てるか(
    試合インスタンス: 試合,
    自分の識別子: string,
    カード: カード,
    フィールドのシンボル: string[]
  ): boolean {
    if (!this.キーワードルール.キーワードを持つ(カード, 'ソウルマジック')) {
      return false;
    }
    const 属性 = (カード.名称 as any).属性;
    if (属性 && !フィールドのシンボル.includes(属性)) {
      return false;
    }
    return this.ソウルコアの居場所(試合インスタンス, 自分の識別子) !== null;
  }

  // ソウルコアが今どこにあるか（リザーブか、自分の場のカードの上）。
  // 無ければ null。
  ソウルコアの居場所(試合インスタンス: 試合, 自分の識別子: string) {
    const ゲーム = 試合インスタンス.ゲーム;
    const リザーブ = 試合インスタンス.ゾーン管理.リザーブを取得(ゲーム, 自分の識別子);
    const フィールド = 試合インスタンス.ゾーン管理.フィールドを取得(ゲーム, 自分の識別子);
    if (リザーブ) {
      const 保持者 = 試合インスタンス.コア管理.ゾーンを保持者に(リザーブ);
      if (this.コア判定.ソウルコアあるか(保持者)) return 保持者;
    }
    for (const カード of フィールド?.カード一覧を取得() ?? []) {
      const 保持者 = 試合インスタンス.コア管理.カードを保持者に(カード);
      if (this.コア判定.ソウルコアあるか(保持者)) return 保持者;
    }
    return null;
  }
}
