import { カード } from '../../../データ/カード/カード.js';
import { 試合 } from '../試合.js';
import { 対戦相手 } from './対戦相手.js';
import { 対戦を進行する } from './対戦進行.js';

// AI同士を何百試合も戦わせて勝率を出す。
//
// 「強くなった」を口で言わずに数字で言うための道具。
// 学習（自己対戦で重みを調整する）も、結局はこれを何度も回すことになるので、
// 学習の土台でもある。
//
// 種を渡すので、同じ組み合わせなら**何度回しても同じ結果**になる。
// 落ちたときにその試合を作り直せるし、勝率が偶然で動くこともない。

export interface 腕試しの結果 {
  試合数: number;
  先の勝ち: number;
  後の勝ち: number;
  決着せず: number;
  先の勝率: number; // 決着した試合のうち、先が勝った割合
}

export type AIを作る = (自分の識別子: string, 相手の識別子: string, 種: number) => 対戦相手;

// 2つのAIを戦わせる。
//
// **先攻を入れ替えて半分ずつ戦わせる。** 先攻が有利なゲームなので、
// 入れ替えないと「強いAI」ではなく「先攻」を測ってしまう。
export function 腕試しする(
  先: AIを作る,
  後: AIを作る,
  デッキを作る: (接頭辞: string) => カード[],
  試合数 = 200,
  最初の種 = 1
): 腕試しの結果 {
  let 先の勝ち = 0;
  let 後の勝ち = 0;
  let 決着せず = 0;

  for (let i = 0; i < 試合数; i++) {
    const 種 = 最初の種 + i;
    // 前半は先が p1（先攻）、後半は入れ替える
    const 先が先攻か = i % 2 === 0;
    const 先の側 = 先が先攻か ? 'p1' : 'p2';
    const 後の側 = 先が先攻か ? 'p2' : 'p1';

    const 試合インスタンス = 試合を用意する(デッキを作る, 種);
    const AIマップ = new Map<string, 対戦相手>([
      [先の側, 先(先の側, 後の側, 種)],
      [後の側, 後(後の側, 先の側, 種)],
    ]);

    const 結果 = 対戦を進行する(試合インスタンス, AIマップ);
    const 勝者 = 結果?.勝者?.識別子 ?? null;
    if (勝者 === 先の側) 先の勝ち++;
    else if (勝者 === 後の側) 後の勝ち++;
    else 決着せず++;
  }

  const 決着数 = 先の勝ち + 後の勝ち;
  return {
    試合数,
    先の勝ち,
    後の勝ち,
    決着せず,
    先の勝率: 決着数 === 0 ? 0 : 先の勝ち / 決着数,
  };
}

export function 試合を用意する(デッキを作る: (接頭辞: string) => カード[], 種: number): 試合 {
  const 試合インスタンス = new 試合(種);
  試合インスタンス.プレイヤーを準備する('p1', 'プレイヤー1');
  試合インスタンス.プレイヤーを準備する('p2', 'プレイヤー2');
  試合インスタンス.ボイドを準備する();
  試合インスタンス.デッキを設定する('p1', デッキを作る('p1'));
  試合インスタンス.デッキを設定する('p2', デッキを作る('p2'));
  試合インスタンス.準備を行う('p1');
  試合インスタンス.準備を行う('p2');
  試合インスタンス.先攻を決める('p1');
  試合インスタンス.試合を開始する();
  return 試合インスタンス;
}
