import { test } from 'node:test';
import assert from 'node:assert/strict';

import { 盤面評価, 既定の重み, 勝ちの点 } from './盤面評価.js';
import { 試合を用意する } from './腕試し.js';
import { グンガタを作成 } from '../カードデータ/グンガタ.js';
import { カード } from '../../../データ/カード/カード.js';

// 盤面評価は「強さの正体」なので、向きを間違えると
// AIが自分の首を絞める手を最善だと信じ込む。向きだけは必ず固定する。

function デッキを作る(接頭辞: string): カード[] {
  const デッキ: カード[] = [];
  for (let i = 0; i < 40; i++) デッキ.push(グンガタを作成(`${接頭辞}-${i}`));
  return デッキ;
}

test('盤面評価は自分から見た有利さを返す', async t => {
  // 同じ形の盤面なら、どちらから見ても同じ点になること。
  //
  // 点そのものは0にならない。攻めを守りより重く見る重みにしてあるので
  // （相手のライフ -120 対 自分のライフ +100）、互角の盤面はマイナスに出る。
  // 手を比べるのに使うのは点の差だけなので、これは問題にならない。
  // 大事なのは「同じ形なのに片方だけ得に見える」ことが無いこと。
  await t.test('同じ形の盤面なら、どちらから見ても同じ点になる', () => {
    const 試合インスタンス = 試合を用意する(デッキを作る, 1);
    const 評価 = new 盤面評価();
    const p1 = 評価.評価する(試合インスタンス, 'p1', 'p2');
    const p2 = 評価.評価する(試合インスタンス, 'p2', 'p1');
    assert.equal(p1, p2, `同じ形なのに点が違う: p1=${p1} p2=${p2}`);
  });

  await t.test('相手のライフが減れば、自分の点は上がる', () => {
    const 試合インスタンス = 試合を用意する(デッキを作る, 1);
    const 評価 = new 盤面評価();
    const 前 = 評価.評価する(試合インスタンス, 'p1', 'p2');

    // 相手のライフから1個、リザーブへ移す（＝ライフを削ったのと同じ状態）
    const ライフ = 試合インスタンス.ゾーン管理.ライフを取得(試合インスタンス.ゲーム, 'p2')!;
    const リザーブ = 試合インスタンス.ゾーン管理.リザーブを取得(試合インスタンス.ゲーム, 'p2')!;
    試合インスタンス.コアを移動する(ライフ, リザーブ, 1);

    const 後 = 評価.評価する(試合インスタンス, 'p1', 'p2');
    assert.ok(後 > 前, `相手のライフが減ったのに点が上がらない: ${前} → ${後}`);
  });

  await t.test('自分のライフが減れば、自分の点は下がる', () => {
    const 試合インスタンス = 試合を用意する(デッキを作る, 1);
    const 評価 = new 盤面評価();
    const 前 = 評価.評価する(試合インスタンス, 'p1', 'p2');

    const ライフ = 試合インスタンス.ゾーン管理.ライフを取得(試合インスタンス.ゲーム, 'p1')!;
    const リザーブ = 試合インスタンス.ゾーン管理.リザーブを取得(試合インスタンス.ゲーム, 'p1')!;
    試合インスタンス.コアを移動する(ライフ, リザーブ, 1);

    const 後 = 評価.評価する(試合インスタンス, 'p1', 'p2');
    assert.ok(後 < 前, `自分のライフが減ったのに点が下がらない: ${前} → ${後}`);
  });

  // 「負けるが手札は多い」を良しとしないこと。
  // 勝ち負けの点が他の項目に埋もれると、AIは負ける手を選ぶ。
  await t.test('決着がついたら、他のどの項目より勝ち負けが優先される', () => {
    const 試合インスタンス = 試合を用意する(デッキを作る, 1);
    const 評価 = new 盤面評価();
    試合インスタンス.降参する('p2');
    assert.equal(試合インスタンス.試合終了か(), true, '前提：降参で試合が終わっていない');
    assert.equal(評価.評価する(試合インスタンス, 'p1', 'p2'), 勝ちの点);
    assert.equal(評価.評価する(試合インスタンス, 'p2', 'p1'), -勝ちの点);
  });

  await t.test('重みは外から差し替えられる（学習の結果を流し込む先）', () => {
    const 変えた = { ...既定の重み, 自分の手札枚数: 999 };
    const 評価 = new 盤面評価(変えた);
    assert.equal(評価.重みを取得().自分の手札枚数, 999);

    const 試合インスタンス = 試合を用意する(デッキを作る, 1);
    const 既定で = new 盤面評価().評価する(試合インスタンス, 'p1', 'p2');
    const 変えて = 評価.評価する(試合インスタンス, 'p1', 'p2');
    assert.notEqual(既定で, 変えて, '重みを変えたのに点が変わらない');
  });
});
