import { 効果選択の依頼 } from './練習用AI.js';
import { 手, 打てる手を挙げる } from './打てる手.js';
import { 盤面評価, 評価の重み, 既定の重み } from './盤面評価.js';
import { カード種別ルール } from '../カードの情報/カード種別.js';
import { シンボルルール } from '../カードの情報/シンボル.js';
import { Lvルール } from '../カードの情報/Lv.js';
import { 消滅判定 } from '../判定/消滅判定.js';
import { コア判定 } from '../判定/コア判定.js';
import { 乱数, 既定の乱数 } from '../乱数.js';

// 評価関数で手を選ぶAI。
//
// 練習用AI と同じ口（メソッド）を持たせてあるので、そのまま差し替えられる。
// 違いは1点だけ ——
//   練習用AI … 手札に並んでいる順に、出せるものから出す
//   思考AI  … 打てる手を全部挙げ、**盤面がいちばん良くなる手**を選ぶ
//
// 「良くなる」の中身は 盤面評価 の重みが決めていて、その重みは自己対戦で鍛えられる。
// つまり **このクラスは強さを持たない**。強さは重みの側にある。
// ここを混ぜると学習の反映先が2か所に散るので、判断の骨組みだけを置く。

// 強さ（0〜1）。
// 1 が「重みどおりに最善を選ぶ」、0 に近づくほど手をわざと散らす。
// あとでレート戦を入れるとき、レートからこの数値を作れば強さが連続的に動く。
export const 最強 = 1;

export interface 思考AIの設定 {
  重み?: 評価の重み;
  強さ?: number; // 0〜1。既定は最強
  乱数?: 乱数;
  // 盤面を複製して、手を実際に打って測るか。既定は測る。
  // 切ると見込みの足し引きで選ぶ（複製を入れる前の振る舞い）。
  // 強さの比較と、複製が本当に効いているかを確かめるために残してある。
  先読みする?: boolean;
}

export class 思考AI {
  private 評価: 盤面評価;
  private 手を挙げる = new 打てる手を挙げる();
  private カード種別ルール = new カード種別ルール();
  private シンボルルール = new シンボルルール();
  private Lvルール = new Lvルール();
  private 消滅判定 = new 消滅判定();
  private コア判定 = new コア判定();

  private 強さ: number;
  private 乱数: 乱数;
  private 先読みする: boolean;
  // 複製ごとに違う種を渡す（複製の中で引きが必要になったとき、
  // 毎回同じ引きになると偏った読みをするため）
  private 複製の種 = 1;
  private 攻撃ステップのリーサルキャッシュ = false;

  constructor(
    private 自分の識別子: string,
    private 相手の識別子: string,
    設定: 思考AIの設定 = {}
  ) {
    this.評価 = new 盤面評価(設定.重み ?? 既定の重み);
    this.強さ = 設定.強さ ?? 最強;
    this.乱数 = 設定.乱数 ?? 既定の乱数;
    this.先読みする = 設定.先読みする ?? true;
  }

  識別子を取得(): string {
    return this.自分の識別子;
  }

  重みを取得(): 評価の重み {
    return this.評価.重みを取得();
  }

  // === メインステップ ===
  //
  // 「打てる手を挙げて、いちばん良い1手を打つ」を、
  // 『終える』が選ばれるまで繰り返す。
  // 打つたびに盤面が変わる（コアが減る・シンボルが増える）ので、毎回挙げ直す。
  メイン1を行動する(試合インスタンス: 試合): void {
    this.メインを行動する(試合インスタンス);
  }

  メイン2を行動する(試合インスタンス: 試合): void {
    this.メインを行動する(試合インスタンス);
  }

  private メインを行動する(試合インスタンス: 試合): void {
    // 打ち切り線。手を打つたびに盤面が変わるので理屈の上では終わるが、
    // 「打っても盤面が変わらない手」が現れると回り続けるため上限を置く。
    for (let 回 = 0; 回 < 40; 回++) {
      if (試合インスタンス.試合終了か()) return;
      // 効果が対象選択で止まっていたら、ここで手を打っても通らない
      if (試合インスタンス.効果実行器.選択待ちか()) break;

      const 手一覧 = this.手を挙げる.メインで打てる手(試合インスタンス, this.自分の識別子);
      const 選んだ = this.いちばん良い手を選ぶ(試合インスタンス, 手一覧);
      if (!選んだ || 選んだ.種類 === '終える') break;
      if (!this.手を打つ(試合インスタンス, 選んだ)) break; // 打てなかった（想定外）ので止める
    }
    if (!試合インスタンス.試合終了か()) {
      試合インスタンス.ステップを終了する();
    }
  }

  // === 割り込みの窓 ===
  //
  // 練習用AIは常にパスしていた。［フラッシュ］のマジックも起動効果も、
  // 一度も撃たないまま試合が終わっていた。
  // 打つ手があるなら打つ／無ければパスする、を返す。
  フラッシュで打つ手を選ぶ(試合インスタンス: 試合): 手 | null {
    if (試合インスタンス.効果実行器.選択待ちか()) return null;
    const 手一覧 = this.手を挙げる.フラッシュで打てる手(試合インスタンス, this.自分の識別子);
    const 選んだ = this.いちばん良い手を選ぶ(試合インスタンス, 手一覧);
    if (!選んだ || 選んだ.種類 === '終える') return null;
    return 選んだ;
  }

  // 手を実際に打つ。打てたら true。
  手を打つ(試合インスタンス: 試合, 打つ手: 手): boolean {
    switch (打つ手.種類) {
      case '召喚':
        return 試合インスタンス.召喚する(
          this.自分の識別子,
          打つ手.カード,
          打つ手.コスト支払い元,
          打つ手.初期コア
        );
      case '配置':
        return 試合インスタンス.配置する(
          this.自分の識別子,
          打つ手.カード,
          打つ手.コスト支払い元,
          打つ手.初期コア
        );
      case '使用':
        return 試合インスタンス.使用する(
          this.自分の識別子,
          打つ手.カード,
          打つ手.コスト支払い元,
          0,
          // ［フラッシュ］しか持たないマジックはメインステップでも
          // ［フラッシュ］の効果で解決する
          this.メイン専用の効果を持つか(打つ手.カード) ? 'メイン' : 'フラッシュ',
          打つ手.ソウルマジックで払う
        );
      case 'Lvアップ':
        return 試合インスタンス.コアを移動する(打つ手.元, 打つ手.カード, 打つ手.数);
      case '起動効果': {
        const 進行 = 試合インスタンス.効果実行器.起動効果を発動する(
          this.自分の識別子,
          打つ手.効果識別子,
          打つ手.タイミング
        );
        return !進行.ログ.some(行 => 行.includes('発動できません'));
      }
      case '終える':
        return false;
    }
  }

  // 打てる手のうち、盤面がいちばん良くなるものを選ぶ。
  //
  // 強さが 1 未満なら、上位の手からゆるく選ぶ（弱くする）。
  // レート戦を入れるときは、レートから 強さ を作ればここが連続的に動く。
  private いちばん良い手を選ぶ(試合インスタンス: 試合, 手一覧: 手[]): 手 | null {
    if (手一覧.length === 0) return null;

    const 点付き = 手一覧
      .map(手 => ({ 手, 点: this.手の点を求める(試合インスタンス, 手) }))
      .sort((a, b) => b.点 - a.点);

    if (this.強さ >= 1) return 点付き[0].手;

    // 弱くするときは「最善を選ぶ確率」を 強さ そのものにする。
    //
    // はじめは「上から何番目までを候補にするか」で弱くしていたが、
    // 手が数個しかない場面では 強さ0.6 でも上位2手に絞られてしまい、
    // 最強とほとんど差が出なかった（実測で 77% → 75.5%）。
    // 確率にすると強さがそのまま勝率の傾きになり、
    // レートから強さを作ったときに素直に効く。
    if (this.乱数() < this.強さ) return 点付き[0].手;
    return 点付き[Math.floor(this.乱数() * 点付き.length)].手;
  }

  // その手の点を求める。
  //
  // 盤面を複製できるなら、**複製の上で実際に打って測る**。
  // 効果が何をしたかまで盤面に出るので、見込みの足し引きより正確。
  //
  // 複製できない場面（効果の答え待ちなど）では見込みに落とす。
  // ここで例外を投げると、AIが手を選べずに試合が止まってしまう。
  private 手の点を求める(試合インスタンス: 試合, 打つ手: 手): number {
    if (!this.先読みする) {
      return this.手の見込みを評価する(試合インスタンス, 打つ手);
    }
    const 実測 = this.複製に打って測る(試合インスタンス, 打つ手);
    return 実測 ?? this.手の見込みを評価する(試合インスタンス, 打つ手);
  }

  // 複製の上でその手を打ち、打ち終わった盤面を評価する。
  // 測れなければ null（呼び出し側が見込みに落とす）。
  private 複製に打って測る(試合インスタンス: 試合, 打つ手: 手): number | null {
    if (打つ手.種類 === '終える') {
      // 何もしない手は、いまの盤面そのもの
      return this.評価.評価する(試合インスタンス, this.自分の識別子, this.相手の識別子);
    }
    if (試合インスタンス.効果実行器.選択待ちか()) return null;

    let 複製: 試合;
    try {
      複製 = 試合インスタンス.複製する(this.複製の種++);
    } catch {
      return null; // 複製できない場面。見込みに落とす。
    }

    // 複製の中の同じカードに置き換える（複製は別物なので、本物のカードは通らない）
    const 複製の手 = this.手を複製へ移す(複製, 打つ手);
    if (!複製の手) return null;

    if (!this.手を打つ(複製, 複製の手)) return null;

    // 効果が対象選択で止まったら、自分で答えて最後まで解決する。
    // 答えないまま評価すると、効果が起きる前の盤面を見てしまう。
    this.複製の中の選択に答える(複製);

    // **破壊は2段階**。ここを忘れると、壊した相手が場に残ったまま評価される。
    //
    // 実際それで、AIがマジックを1枚も撃たなくなった（40回 → 0回）。
    // フレイムハリケーンで相手を壊しても、複製の盤面では待機状態のまま
    // 場に居座るので、AIには「手札とコアが減っただけの損な手」に見えていた。
    複製.効果実行器.キューを進める();
    複製.ルール処理を実行する();

    return this.評価.評価する(複製, this.自分の識別子, this.相手の識別子);
  }

  // 本物のカードを指している手を、複製の中の同じカードを指す手に作り直す。
  // ここを怠ると、複製の盤面に無いカードを召喚しようとして必ず失敗する。
  private 手を複製へ移す(複製: 試合, 打つ手: 手): 手 | null {
    const 同じカードを探す = (識別子: string) => {
      for (const プレイヤー of 複製.ゲーム.全プレイヤーを取得()) {
        for (const 領域 of 複製.ゾーン管理.プレイヤーの全領域を取得(複製.ゲーム, プレイヤー.識別子)) {
          const 見つけた = 領域.カードを取得(識別子);
          if (見つけた) return 見つけた;
        }
      }
      return null;
    };

    switch (打つ手.種類) {
      case '召喚':
      case '配置': {
        const カード = 同じカードを探す(打つ手.カード.識別子);
        if (!カード) return null;
        // 支払い元も複製側の保持者に取り直す
        const リザーブ = 複製.ゾーン管理.リザーブを取得(複製.ゲーム, this.自分の識別子);
        if (!リザーブ) return null;
        const 保持者 = 複製.コア管理.ゾーンを保持者に(リザーブ);
        return {
          ...打つ手,
          カード,
          コスト支払い元: 打つ手.コスト支払い元.map(元 => ({ ...元, 保持者 })),
          初期コア: 打つ手.初期コア.map(元 => ({ ...元, 保持者 })),
        };
      }
      case '使用': {
        const カード = 同じカードを探す(打つ手.カード.識別子);
        if (!カード) return null;
        const リザーブ = 複製.ゾーン管理.リザーブを取得(複製.ゲーム, this.自分の識別子);
        if (!リザーブ) return null;
        const 保持者 = 複製.コア管理.ゾーンを保持者に(リザーブ);
        return { ...打つ手, カード, コスト支払い元: 打つ手.コスト支払い元.map(元 => ({ ...元, 保持者 })) };
      }
      case 'Lvアップ': {
        const カード = 同じカードを探す(打つ手.カード.識別子);
        const リザーブ = 複製.ゾーン管理.リザーブを取得(複製.ゲーム, this.自分の識別子);
        if (!カード || !リザーブ) return null;
        return { ...打つ手, カード, 元: リザーブ };
      }
      case '起動効果':
        // 効果識別子は「カードの識別子＋番号」なので、複製でもそのまま通る
        return 打つ手;
      case '終える':
        return 打つ手;
    }
  }

  // 複製の中で止まっている選択に、自分で答えて解決しきる。
  private 複製の中の選択に答える(複製: 試合): void {
    for (let 回 = 0; 回 < 20 && 複製.効果実行器.選択待ちか(); 回++) {
      const 情報 = 複製.効果実行器.選択待ち情報を取得();
      if (!情報) return;
      // 相手が答える選択もある。相手の判断は読めないので、同じ選び方で埋める。
      複製.効果実行器.選択に答える(this.効果対象を選ぶ(複製, 情報));
    }
  }

  // === 手の見込み ===
  //
  // その手を打った後の盤面が、いま何点になるかの**見込み**。
  //
  // 本当は打ってみて測るのが正しいが、いまの土台には盤面を複製する仕組みが無く、
  // 打った手は戻せない。そこで、評価に使っている項目のうち
  // **確実に分かる分（シンボル・BP・コアの行き先・手札）だけを足し引き**する。
  //
  // 効果（召喚時に相手を壊すなど）はここでは読まない。そのぶんは
  // 「条件を満たしている効果を持つカード」に重みで下駄を履かせて表す。
  // 盤面を複製できるようになったら、ここは実測に置き換える。
  private 手の見込みを評価する(試合インスタンス: 試合, 打つ手: 手): number {
    const 現在 = this.評価.評価する(試合インスタンス, this.自分の識別子, this.相手の識別子);
    const w = this.評価.重みを取得();

    switch (打つ手.種類) {
      case '終える':
        return 現在; // 何もしないぶん、増えも減りもしない

      case '召喚':
      case '配置': {
        const カード = 打つ手.カード;
        const コスト = 打つ手.コスト支払い元.reduce((合計, 元) => 合計 + 元.数, 0);
        const 初期コア = 打つ手.初期コア.reduce((合計, 元) => 合計 + 元.数, 0);
        const スピリットか = this.カード種別ルール.スピリットか(カード);
        const BP = スピリットか ? this.Lv1のBPを求める(カード) : 0;

        return (
          現在 +
          this.シンボルルール.シンボル数を取得(カード) * w.自分のシンボル数 +
          BP * w.自分のBP合計 +
          (スピリットか ? 1 : 0) * w.自分の回復スピリット数 +
          -1 * w.自分の手札枚数 +
          // リザーブから コスト＋初期コア が出て、初期コアだけが場に乗り、コストはトラッシュへ
          -(コスト + 初期コア) * w.自分のリザーブのコア +
          初期コア * w.自分の場のコア +
          コスト * w.自分のトラッシュのコア +
          this.効果の下駄(試合インスタンス, カード, スピリットか ? '召喚時' : '配置時')
        );
      }

      case '使用': {
        const コスト = 打つ手.コスト支払い元.reduce((合計, 元) => 合計 + 元.数, 0);
        // 《ソウルマジック》はソウルコアを1個トラッシュへ送る。
        // 通常コアは減らないが、ソウルコアが使えなくなるぶんを引く。
        const ソウル分 = 打つ手.ソウルマジックで払う
          ? -w.自分のソウルコアが使えるか - 1 * w.自分のリザーブのコア + 1 * w.自分のトラッシュのコア
          : 0;
        return (
          現在 +
          -1 * w.自分の手札枚数 +
          -コスト * w.自分のリザーブのコア +
          コスト * w.自分のトラッシュのコア +
          ソウル分 +
          this.効果の下駄(試合インスタンス, 打つ手.カード, '使用') +
          // ［フラッシュ］しか持たないマジックは、取っておけば
          // 相手のアタックに合わせて撃てる。いま撃つぶんを割り引く。
          (this.メイン専用の効果を持つか(打つ手.カード) ? 0 : -w.フラッシュ専用をメインで撃つ割引)
        );
      }

      case 'Lvアップ': {
        // リザーブから場へコアが移る。Lvが上がるとBPも上がる。
        const 前のBP = 試合インスタンス.BP管理.現在のBPを取得(打つ手.カード);
        const 上がるBP = this.次のLvのBPを求める(試合インスタンス, 打つ手.カード) - 前のBP;
        return (
          現在 +
          -打つ手.数 * w.自分のリザーブのコア +
          打つ手.数 * w.自分の場のコア +
          Math.max(0, 上がるBP) * w.自分のBP合計
        );
      }

      case '起動効果':
        // 起動効果は中身が読めないので、「撃てるなら撃つ」に寄せる。
        // 〔ターン1回〕が多く、撃たずに終わると丸ごと損になるため。
        return 現在 + w.自分のシンボル数; // シンボル1つぶんの価値があるものとして扱う
    }
  }

  // 条件を満たしている効果を持つカードには下駄を履かせる。
  // 中身までは読まないので、「いま撃てば当たる」ことだけを見る。
  private 効果の下駄(試合インスタンス: 試合, カード: カード, トリガー: string): number {
    const w = this.評価.重みを取得();
    if (トリガー === '使用') {
      // マジックは撃てば必ず何かが起きる
      return w.マジックを撃つ値打ち;
    }
    const 満たす = 試合インスタンス.効果実行器.トリガー効果の条件を満たすか(カード, トリガー);
    if (満たす === undefined) return 0; // その手の効果を持たない
    return 満たす ? w.召喚時効果が当たる値打ち : 0; // 条件を満たさないなら、いま出しても不発
  }

  private Lv1のBPを求める(カード: カード): number {
    return this.Lvルール.Lvを取得(カード).find(lv => lv.level === 1)?.bp ?? 0;
  }

  private 次のLvのBPを求める(試合インスタンス: 試合, カード: カード): number {
    const 現在のLv = 試合インスタンス.Lv管理.現在のLvを取得(カード);
    const 次 = this.Lvルール.Lvを取得(カード).find(lv => lv.level === 現在のLv + 1);
    return 次?.bp ?? 試合インスタンス.BP管理.現在のBPを取得(カード);
  }

  private メイン専用の効果を持つか(カード: カード): boolean {
    const 効果一覧 = (カード.名称 as any).効果 ?? [];
    return 効果一覧.some((効果: any) => 効果.種別 === '使用' && 効果.タイミング !== 'フラッシュ');
  }

  // === アタックステップ ===

  攻撃ステップを開始する(試合インスタンス: 試合): void {
    this.攻撃ステップのリーサルキャッシュ = this.リーサルを判定する(
      試合インスタンス,
      this.自分の識別子,
      this.相手の識別子
    );
  }

  // 次に攻撃させるスピリットを選ぶ。
  //
  // 練習用AIは「リーサルでなければ1体を温存し、残りは先頭から」だった。
  // ここでは相手のブロッカーと見比べ、**取られるだけの攻撃をしない**。
  攻撃者を選ぶ(試合インスタンス: 試合): カード | null {
    const 自分の場 = 試合インスタンス.ゾーン管理.フィールドを取得(
      試合インスタンス.ゲーム,
      this.自分の識別子
    );
    if (!自分の場) return null;

    const 候補 = 自分の場
      .カード一覧を取得()
      .filter(カード => this.回復状態のスピリットか(試合インスタンス, カード));
    if (候補.length === 0) return null;

    // リーサルなら、取られようが構わず全部で殴る
    if (this.攻撃ステップのリーサルキャッシュ) return 候補[0];

    // 相手の回復スピリットのうち、いちばんBPが高いもの＝いちばん強いブロッカー
    const 相手の場 = 試合インスタンス.ゾーン管理.フィールドを取得(
      試合インスタンス.ゲーム,
      this.相手の識別子
    );
    const 相手のブロッカー最大BP = (相手の場?.カード一覧を取得() ?? [])
      .filter(カード => this.回復状態のスピリットか(試合インスタンス, カード))
      .reduce((最大, カード) => Math.max(最大, 試合インスタンス.BP管理.現在のBPを取得(カード)), 0);

    // 相手より高いBPで攻めれば、ブロックされても取られない。
    // BPが高い順に見て、取られない1体を選ぶ。
    const 安全な候補 = 候補
      .filter(カード => 試合インスタンス.BP管理.現在のBPを取得(カード) >= 相手のブロッカー最大BP)
      .sort((a, b) => 試合インスタンス.BP管理.現在のBPを取得(b) - 試合インスタンス.BP管理.現在のBPを取得(a));

    if (安全な候補.length > 0) {
      // 最後の1体は残す（ブロッカーが居なくなると次の番に一気に削られる）
      if (候補.length <= 1) return null;
      return 安全な候補[0];
    }

    // 取られずに殴れる者が居ない。相手にブロッカーが無ければ誰で殴っても通る。
    if (相手のブロッカー最大BP === 0 && 候補.length > 1) {
      return 候補[0];
    }
    return null;
  }

  // ブロックするスピリットを選ぶ。
  //
  // 相手がリーサルを持つなら何を犠牲にしても止める。
  // そうでなければ「相打ち以上になる中でいちばんBPが低い者」で受ける。
  ブロッカーを選ぶ(試合インスタンス: 試合, アタッカー: カード): カード | null {
    const 自分の場 = 試合インスタンス.ゾーン管理.フィールドを取得(
      試合インスタンス.ゲーム,
      this.自分の識別子
    );
    if (!自分の場) return null;

    const 候補 = 自分の場
      .カード一覧を取得()
      .filter(カード => this.回復状態のスピリットか(試合インスタンス, カード))
      .filter(カード => 試合インスタンス.ブロックできるか(カード, アタッカー));
    if (候補.length === 0) return null;

    if (this.リーサルを判定する(試合インスタンス, this.相手の識別子, this.自分の識別子)) {
      return 候補[0];
    }

    const アタッカーBP = 試合インスタンス.BP管理.現在のBPを取得(アタッカー);
    const 取られない = 候補
      .filter(カード => 試合インスタンス.BP管理.現在のBPを取得(カード) >= アタッカーBP)
      .sort((a, b) => 試合インスタンス.BP管理.現在のBPを取得(a) - 試合インスタンス.BP管理.現在のBPを取得(b));
    return 取られない[0] ?? null;
  }

  // === 効果の対象選び ===
  //
  // 練習用AIと同じ考え方（相手の強いものから壊す／自分は弱いものから差し出す）。
  // 答えないと効果が止まったままになるので、必ず有効な答えを返す。
  効果対象を選ぶ(試合インスタンス: 試合, 選択待ち: 効果選択の依頼): string[] {
    const { 候補, 最大, 選択肢 } = 選択待ち;

    if (選択肢 && 選択肢.length > 0) {
      const ソウルコアを残す = 選択肢.find(候補 => 候補.識別子 === '通常コアだけ置く');
      return [(ソウルコアを残す ?? 選択肢[0]).識別子];
    }
    if (候補.length === 0 || 最大 === 0) return [];

    const 自分の場 = 試合インスタンス.ゾーン管理.フィールドを取得(
      試合インスタンス.ゲーム,
      this.自分の識別子
    );
    const 自分のカード = new Set((自分の場?.カード一覧を取得() ?? []).map(c => c.識別子));

    const 並び = [...候補].sort((a, b) => {
      const aは自分 = 自分のカード.has(a.識別子);
      const bは自分 = 自分のカード.has(b.識別子);
      if (aは自分 !== bは自分) return aは自分 ? 1 : -1;
      const aのBP = 試合インスタンス.BP管理.現在のBPを取得(a);
      const bのBP = 試合インスタンス.BP管理.現在のBPを取得(b);
      return aは自分 ? aのBP - bのBP : bのBP - aのBP;
    });
    return 並び.slice(0, Math.min(最大, 並び.length)).map(c => c.識別子);
  }

  // === 見立て ===

  // このターン中に相手を倒しきれそうか。
  // 練習用AIと同じ式（回復スピリットのシンボル数 ＋ まだ出せる数 ≧ ライフ ＋ 相手のブロッカー数）。
  private リーサルを判定する(試合インスタンス: 試合, 攻撃側: string, 防御側: string): boolean {
    const ゲーム = 試合インスタンス.ゲーム;
    const 攻撃側の場 = 試合インスタンス.ゾーン管理.フィールドを取得(ゲーム, 攻撃側);
    const 防御側の場 = 試合インスタンス.ゾーン管理.フィールドを取得(ゲーム, 防御側);
    const 防御側ライフ = 試合インスタンス.ゾーン管理.ライフを取得(ゲーム, 防御側);
    if (!攻撃側の場 || !防御側の場 || !防御側ライフ) return false;

    const 打点 = 攻撃側の場
      .カード一覧を取得()
      .filter(カード => this.回復状態のスピリットか(試合インスタンス, カード))
      .reduce((合計, カード) => 合計 + this.シンボルルール.シンボル数を取得(カード), 0);

    const ライフ = this.コア判定.総コア数を取得(
      試合インスタンス.コア管理.ゾーンを保持者に(防御側ライフ)
    );
    const ブロッカー数 = 防御側の場
      .カード一覧を取得()
      .filter(カード => this.回復状態のスピリットか(試合インスタンス, カード)).length;

    return 打点 + this.あと何体出せるか(試合インスタンス, 攻撃側) >= ライフ + ブロッカー数;
  }

  private あと何体出せるか(試合インスタンス: 試合, 識別子: string): number {
    return this.手を挙げる
      .メインで打てる手(試合インスタンス, 識別子)
      .filter(手 => 手.種類 === '召喚').length;
  }

  private 回復状態のスピリットか(試合インスタンス: 試合, カード: カード): boolean {
    if (!this.カード種別ルール.スピリットか(カード)) return false;
    return 試合インスタンス.カードの表示形式管理.現在の表示形式を取得(カード) === '回復';
  }
}
