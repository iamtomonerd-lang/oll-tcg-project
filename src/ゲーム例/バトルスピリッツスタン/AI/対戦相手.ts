import { カード } from '../../../データ/カード/カード.js';
import { 試合 } from '../試合.js';
import { 効果選択の依頼 } from './練習用AI.js';
import { 手 } from './打てる手.js';

// AIが満たすべき口（メソッド）。
//
// 練習用AI と 思考AI の2つがこれを満たす。
// 進行させる側（対戦進行・ゲームAPI）はこの型だけを見るので、
// どちらを差し込んでも動く ——「弱いAI」「強いAI」を並べられるのはこのため。
//
// あとでレート戦を入れるときも、レートから作ったAIをここに流し込むだけで済む。
export interface 対戦相手 {
  識別子を取得(): string;
  メイン1を行動する(試合インスタンス: 試合): void;
  メイン2を行動する(試合インスタンス: 試合): void;
  攻撃ステップを開始する(試合インスタンス: 試合): void;
  攻撃者を選ぶ(試合インスタンス: 試合): カード | null;
  ブロッカーを選ぶ(試合インスタンス: 試合, アタッカー: カード): カード | null;
  効果対象を選ぶ(試合インスタンス: 試合, 選択待ち: 効果選択の依頼): string[];

  // 割り込みの窓で打つ手を選ぶ。null ならパス。
  //
  // 持っていなくてもよい（練習用AIは持たない＝常にパス）。
  // 進行させる側は「持っていなければパス」として扱うこと。
  フラッシュで打つ手を選ぶ?(試合インスタンス: 試合): 手 | null;
  手を打つ?(試合インスタンス: 試合, 打つ手: 手): boolean;
}
