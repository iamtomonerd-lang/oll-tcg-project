import { test } from 'node:test';
import assert from 'node:assert/strict';

import { 思考AI } from './思考AI.js';
import { 対戦相手 } from './対戦相手.js';
import { 対戦を進行する } from './対戦進行.js';
import { 試合を用意する } from './腕試し.js';
import { カード } from '../../../データ/カード/カード.js';
import { カード帳 } from '../カードデータ/カード帳.js';

// 自己対戦で**割り込みの窓が開くこと**を固定する。
//
// ここが開いていなかったあいだ、【起動：フラッシュ】も［フラッシュ］のマジックも
// 撃つ機会が無く、40試合で起動効果が0回という数字が出ていた。
// AIが撃たないのではなく、撃てる場面を作っていなかった。
//
// 数字だけ見ていると「AIがフラッシュを使わない」と読み違える。
// しかも学習は自己対戦で回すので、**フラッシュの使い方を一切学べない**。
// 測り方の穴がそのまま強さの穴になる。

const 風牙のカード = カード帳.filter(x => !/^紫/.test(x.カード名));

function デッキを作る(接頭辞: string): カード[] {
  const デッキ: カード[] = [];
  for (let i = 0; i < 40; i++) {
    デッキ.push(風牙のカード[i % 風牙のカード.length].作る(`${接頭辞}-${i}`));
  }
  return デッキ;
}

test('自己対戦でも割り込みの窓が開き、AIが起動効果を撃つ', () => {
  let 撃った = 0;
  let 尋ねられた = 0;

  const 作る = (自分: string, 相手: string): 対戦相手 => {
    const AI = new 思考AI(自分, 相手);
    const 元選ぶ = AI.フラッシュで打つ手を選ぶ.bind(AI);
    AI.フラッシュで打つ手を選ぶ = (試合インスタンス: any) => {
      尋ねられた++;
      const 手 = 元選ぶ(試合インスタンス);
      if (手?.種類 === '起動効果') 撃った++;
      return 手;
    };
    return AI;
  };

  for (let 種 = 1; 種 <= 20; 種++) {
    const 試合インスタンス = 試合を用意する(デッキを作る, 種);
    対戦を進行する(
      試合インスタンス,
      new Map<string, 対戦相手>([
        ['p1', 作る('p1', 'p2')],
        ['p2', 作る('p2', 'p1')],
      ])
    );
  }

  assert.ok(尋ねられた > 0, '割り込みの窓が一度も開いていない（窓を開ける側の不備）');
  assert.ok(
    撃った > 0,
    `窓は開いたが起動効果を一度も撃っていない（${尋ねられた}回尋ねて0回）`
  );
});
