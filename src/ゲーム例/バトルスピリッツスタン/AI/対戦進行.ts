// 対戦進行（AI同士、またはAI対応可能な進行ドライバー）
// 試合クラス自体には手を加えず、外側から 次の行動可能なステップまで進める／各行動 を呼び出して
// 1試合を最後まで進める。メインステップ／第2メインステップ／アタックステップの意思決定を、
// 現在のターンプレイヤーに対応する対戦相手へ委譲する。
export function 対戦を進行する(
  試合インスタンス: 試合,
  AIマップ: Map<string, 対戦相手>,
  最大反復回数 = 2000
): 勝利結果 | null {
  for (let 反復 = 0; 反復 < 最大反復回数; 反復++) {
    if (試合インスタンス.試合終了か()) {
      return 試合インスタンス.勝敗結果を取得();
    }
    if (!一手だけ進める(試合インスタンス, AIマップ)) {
      break;
    }
  }

  return 試合インスタンス.勝敗結果を取得();
}

// 進行を1つだけ進める（1ステップぶんの意思決定）。進めたら true。
//
// 先読みで「相手のターンを1つ通す」のに要る。
// 対戦を進行する はこれを繰り返しているだけ。
export function 一手だけ進める(
  試合インスタンス: 試合,
  AIマップ: Map<string, 対戦相手>
): boolean {
  if (試合インスタンス.試合終了か()) return false;

  // 効果が対象選択で止まっていたら、まずそれを解消する。
  // 放置すると以後すべての効果が解決されず、試合が進まなくなる。
  if (効果の選択待ちを解消する(試合インスタンス, AIマップ)) {
    return true;
  }

  const ステップ = 試合インスタンス.次の行動可能なステップまで進める();
  if (試合インスタンス.試合終了か()) return false;
  if (!ステップ) return false; // 現在のステップが特定できない（異常系）

  const ターンプレイヤー = 試合インスタンス.ゲーム.現在のプレイヤーを取得();
  if (!ターンプレイヤー) return false;
  const 現在のAI = AIマップ.get(ターンプレイヤー.識別子);
  if (!現在のAI) return false; // このプレイヤーにAIが割り当てられていない

  switch (ステップ) {
    case 'メインステップ':
      現在のAI.メイン1を行動する(試合インスタンス);
      return true;
    case '第2メインステップ':
      現在のAI.メイン2を行動する(試合インスタンス);
      return true;
    case 'アタックステップ':
      アタックステップを進行する(試合インスタンス, 現在のAI, AIマップ, ターンプレイヤー.識別子);
      return true;
    default:
      // ここに来るのは想定外（随意ステップはメイン/アタック/第2メインのみ）
      return false;
  }
}

function アタックステップを進行する(
  試合インスタンス: 試合,
  攻撃側AI: 対戦相手,
  AIマップ: Map<string, 対戦相手>,
  攻撃側識別子: string
): void {
  const 防御側識別子 = 試合インスタンス.ゲーム
    .全プレイヤーを取得()
    .find(p => p.識別子 !== 攻撃側識別子)?.識別子;
  const 防御側AI = 防御側識別子 ? AIマップ.get(防御側識別子) : undefined;

  攻撃側AI.攻撃ステップを開始する(試合インスタンス);

  for (let 攻撃回数 = 0; 攻撃回数 < 100; 攻撃回数++) {
    if (試合インスタンス.試合終了か()) {
      return;
    }

    const アタッカー = 攻撃側AI.攻撃者を選ぶ(試合インスタンス);
    if (!アタッカー) {
      break; // これ以上攻撃できるスピリットが無い
    }

    const 宣言成功 = 試合インスタンス.アタック宣言する(アタッカー);
    if (!宣言成功) {
      break; // 安全策（意思決定と実際の可否がずれた場合、無限ループを避ける）
    }

    // アタック後の割り込みの窓（8-1-2）
    割り込みの窓を回す(試合インスタンス, AIマップ, 攻撃側識別子, 防御側識別子);

    const ブロッカー = 防御側AI ? 防御側AI.ブロッカーを選ぶ(試合インスタンス, アタッカー) : null;
    let 宣言したブロッカー = null;
    if (ブロッカー) {
      // 試合経由で宣言する（『ブロックされない』の制約を通すため）
      const ブロック成功 = 試合インスタンス.ブロック宣言する(ブロッカー, アタッカー);
      宣言したブロッカー = ブロック成功 ? ブロッカー : null;
    }

    // ブロック後の割り込みの窓（8-1-4）。ブロックした場合にだけ開く。
    if (宣言したブロッカー) {
      割り込みの窓を回す(試合インスタンス, AIマップ, 攻撃側識別子, 防御側識別子);
    }

    試合インスタンス.バトルを解決する(アタッカー, 宣言したブロッカー);
    試合インスタンス.バトル管理.バトルを終了(アタッカー, 宣言したブロッカー);
  }

  if (!試合インスタンス.試合終了か()) {
    試合インスタンス.ステップを終了する();
  }
}

// 割り込みの窓を、双方が続けてパスするまで回す（8-1-2／8-1-4）。
//
// ここが無かったあいだ、自己対戦では**割り込みの窓が一度も開かなかった**。
// 【起動：フラッシュ】も［フラッシュ］のマジックも撃つ機会が無いので、
// 40試合で起動効果が0回という数字が出ていた。AIが撃たないのではなく、
// 撃てる場面を作っていなかった。学習もフラッシュを一切学べていなかった。
function 割り込みの窓を回す(
  試合インスタンス: 試合,
  AIマップ: Map<string, 対戦相手>,
  攻撃側識別子: string,
  防御側識別子: string | undefined
): void {
  if (!防御側識別子) return;
  const 管理 = new フラッシュタイミング管理(防御側識別子, 攻撃側識別子);

  // 打ち切り線。パス2回で閉じるので普通は数回で終わるが、
  // 撃ち続けられる効果があると回り続けるため上限を置く。
  for (let 回 = 0; 回 < 20 && !管理.終了か(); 回++) {
    // 効果が選択待ちなら先に解消する
    if (効果の選択待ちを解消する(試合インスタンス, AIマップ)) continue;

    const 権利者 = 管理.現在の権利者();
    const AI = AIマップ.get(権利者);
    const 打つ手 = AI?.フラッシュで打つ手を選ぶ?.(試合インスタンス) ?? null;

    if (打つ手 && AI?.手を打つ?.(試合インスタンス, 打つ手)) {
      管理.効果を使用した();
      continue;
    }
    管理.パスした();
  }

  // 撃った効果を解決しきる（撃ちっぱなしで解決を忘れると盤面に反映されない）
  効果の選択待ちを解消する(試合インスタンス, AIマップ);
  試合インスタンス.効果実行器.キューを進める();
  試合インスタンス.ルール処理を実行する();
}

// 選択待ちの効果があれば、その効果の持ち主のAIに答えさせる。
// 解消を試みたら true を返す（呼び出し側は進行をやり直す）。
export function 効果の選択待ちを解消する(
  試合インスタンス: 試合,
  AIマップ: Map<string, 対戦相手>
): boolean {
  const 情報 = 試合インスタンス.効果実行器.選択待ち情報を取得();
  if (!情報) {
    return false;
  }

  const AI = AIマップ.get(情報.所有者識別子);
  if (!AI) {
    return false; // 人間の判断待ち。呼び出し側が制御を返す。
  }

  const 選択 = AI.効果対象を選ぶ(試合インスタンス, 情報);
  試合インスタンス.効果実行器.選択に答える(選択);
  return true;
}

// 効果の発揮源が今どのプレイヤーの領域にあるか
export function 効果の持ち主を求める(
  試合インスタンス: 試合,
  カード識別子: string
): string | undefined {
  for (const プレイヤー of 試合インスタンス.ゲーム.全プレイヤーを取得()) {
    const 領域一覧 = 試合インスタンス.ゾーン管理.プレイヤーの全領域を取得(
      試合インスタンス.ゲーム,
      プレイヤー.識別子
    );
    for (const 領域 of 領域一覧) {
      if (領域.カードを取得(カード識別子)) {
        return プレイヤー.識別子;
      }
    }
  }
  return undefined;
}
