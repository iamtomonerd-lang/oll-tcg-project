import { 試合 } from '../試合.js';
import { 勝利結果 } from '../判定/勝利判定.js';
import { 練習用AI } from './練習用AI.js';

// 対戦進行（AI同士、またはAI対応可能な進行ドライバー）
// 試合クラス自体には手を加えず、外側から 次の行動可能なステップまで進める／各行動 を呼び出して
// 1試合を最後まで進める。メインステップ／第2メインステップ／アタックステップの意思決定を、
// 現在のターンプレイヤーに対応する練習用AIへ委譲する。
export function 対戦を進行する(
  試合インスタンス: 試合,
  AIマップ: Map<string, 練習用AI>,
  最大反復回数 = 2000
): 勝利結果 | null {
  for (let 反復 = 0; 反復 < 最大反復回数; 反復++) {
    if (試合インスタンス.試合終了か()) {
      return 試合インスタンス.勝敗結果を取得();
    }

    const ステップ = 試合インスタンス.次の行動可能なステップまで進める();
    if (試合インスタンス.試合終了か()) {
      return 試合インスタンス.勝敗結果を取得();
    }
    if (!ステップ) {
      break; // 現在のステップが特定できない（異常系）
    }

    const ターンプレイヤー = 試合インスタンス.ゲーム.現在のプレイヤーを取得();
    if (!ターンプレイヤー) {
      break;
    }
    const 現在のAI = AIマップ.get(ターンプレイヤー.識別子);
    if (!現在のAI) {
      break; // このプレイヤーにAIが割り当てられていない
    }

    switch (ステップ) {
      case 'メインステップ':
      case '第2メインステップ':
        現在のAI.メインステップを行動する(試合インスタンス);
        break;
      case 'アタックステップ':
        アタックステップを進行する(試合インスタンス, 現在のAI, AIマップ, ターンプレイヤー.識別子);
        break;
      default:
        // ここに来るのは想定外（随意ステップはメイン/アタック/第2メインのみ）
        return 試合インスタンス.勝敗結果を取得();
    }
  }

  return 試合インスタンス.勝敗結果を取得();
}

function アタックステップを進行する(
  試合インスタンス: 試合,
  攻撃側AI: 練習用AI,
  AIマップ: Map<string, 練習用AI>,
  攻撃側識別子: string
): void {
  const 防御側識別子 = 試合インスタンス.ゲーム
    .全プレイヤーを取得()
    .find(p => p.識別子 !== 攻撃側識別子)?.識別子;
  const 防御側AI = 防御側識別子 ? AIマップ.get(防御側識別子) : undefined;

  for (let 攻撃回数 = 0; 攻撃回数 < 100; 攻撃回数++) {
    if (試合インスタンス.試合終了か()) {
      return;
    }

    const アタッカー = 攻撃側AI.攻撃者を選ぶ(試合インスタンス);
    if (!アタッカー) {
      break; // これ以上攻撃できるスピリットが無い
    }

    const 宣言成功 = 試合インスタンス.バトル管理.アタック宣言(試合インスタンス.ゲーム, アタッカー);
    if (!宣言成功) {
      break; // 安全策（意思決定と実際の可否がずれた場合、無限ループを避ける）
    }

    // フラッシュタイミング（8-1-2／8-1-4）：発揮できるフラッシュ効果が無いため双方即パス扱いとする
    const ブロッカー = 防御側AI ? 防御側AI.ブロッカーを選ぶ(試合インスタンス, アタッカー) : null;
    let 宣言したブロッカー = null;
    if (ブロッカー) {
      const ブロック成功 = 試合インスタンス.バトル管理.ブロック宣言(試合インスタンス.ゲーム, ブロッカー);
      宣言したブロッカー = ブロック成功 ? ブロッカー : null;
    }

    試合インスタンス.バトルを解決する(アタッカー, 宣言したブロッカー);
    試合インスタンス.バトル管理.バトルを終了(アタッカー, 宣言したブロッカー);
  }

  if (!試合インスタンス.試合終了か()) {
    試合インスタンス.ステップを終了する();
  }
}
