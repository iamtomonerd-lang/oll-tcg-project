import { test } from 'node:test';
import assert from 'node:assert/strict';

import { 打てる手を挙げる } from './打てる手.js';
import { 試合を用意する } from './腕試し.js';
import { カード } from '../../../データ/カード/カード.js';
import { グンガタを作成 } from '../カードデータ/グンガタ.js';
import { フレイムハリケーンを作成 } from '../カードデータ/フレイムハリケーン.js';
import { 浮遊岩域を作成 } from '../カードデータ/浮遊岩域.js';

// これまでのAIはスピリットの召喚しか手として持っていなかった。
// マジックもネクサスも「選択肢に無い」ので、どれだけ賢く選ばせても撃たれない。
// ここで固定するのは「挙がっていること」そのもの。

function デッキを作る(接頭辞: string): カード[] {
  const デッキ: カード[] = [];
  for (let i = 0; i < 40; i++) デッキ.push(グンガタを作成(`${接頭辞}-${i}`));
  return デッキ;
}

// 手札を好きな中身に差し替える（引きに左右されずに確かめるため）
function 手札を入れ替える(試合インスタンス: any, 識別子: string, カード一覧: カード[]): void {
  const 手札 = 試合インスタンス.ゾーン管理.手札を取得(試合インスタンス.ゲーム, 識別子)!;
  for (const c of [...手札.カード一覧を取得()]) 手札.カードを削除(c.識別子);
  for (const c of カード一覧) 手札.カードを追加(c);
}

// リザーブに通常コアを好きなだけ用意する。
// ライフから移す形にすると、ライフの5個を超えたところで移動ごと失敗して
// 「コアを積んだつもりが積めていない」に気づけないので、直に数を置く
// （カードのテストでも同じやり方をしている）。
function リザーブにコアを積む(試合インスタンス: any, 識別子: string, 数: number): void {
  const リザーブ = 試合インスタンス.ゾーン管理.リザーブを取得(試合インスタンス.ゲーム, 識別子)!;
  試合インスタンス.コア管理.ゾーンを保持者に(リザーブ).コア数を設定(数);
}

test('打てる手には、召喚だけでなくネクサスとマジックも並ぶ', () => {
  const 試合インスタンス = 試合を用意する(デッキを作る, 1);
  手札を入れ替える(試合インスタンス, 'p1', [
    グンガタを作成('手-スピリット'),
    浮遊岩域を作成('手-ネクサス'),
    フレイムハリケーンを作成('手-マジック'),
  ]);
  リザーブにコアを積む(試合インスタンス, 'p1', 8);

  const 手一覧 = new 打てる手を挙げる().メインで打てる手(試合インスタンス, 'p1');
  const 種類 = new Set(手一覧.map(手 => 手.種類));

  assert.ok(種類.has('召喚'), 'スピリットの召喚が挙がっていない');
  assert.ok(種類.has('配置'), 'ネクサスの配置が挙がっていない');
  assert.ok(種類.has('使用'), 'マジックの使用が挙がっていない');
  // 何もしないのも1つの手。これが無いと「打てる手が尽きるまで打つ」しかできない。
  assert.ok(種類.has('終える'), '「終える」が挙がっていない');
});

test('コアが足りないカードは、打てる手に挙がらない', () => {
  const 試合インスタンス = 試合を用意する(デッキを作る, 1);
  手札を入れ替える(試合インスタンス, 'p1', [フレイムハリケーンを作成('手-マジック')]);
  // 開始直後のリザーブは乏しいので、そのまま。積まない。

  const 手一覧 = new 打てる手を挙げる().メインで打てる手(試合インスタンス, 'p1');
  assert.equal(
    手一覧.filter(手 => 手.種類 === '使用').length,
    0,
    'コアが足りないのに使用が挙がっている'
  );
  assert.equal(手一覧.length, 1, '「終える」だけになるはず');
});

// 割り込みの窓ではスピリットもネクサスも出せない（11-1／11-2）。
// ここが緩いと、AIがフラッシュ中に召喚しようとして進行が止まる。
test('割り込みの窓では、［フラッシュ］のマジックだけが挙がる', () => {
  const 試合インスタンス = 試合を用意する(デッキを作る, 1);
  手札を入れ替える(試合インスタンス, 'p1', [
    グンガタを作成('手-スピリット'),
    浮遊岩域を作成('手-ネクサス'),
    フレイムハリケーンを作成('手-マジック'),
  ]);
  リザーブにコアを積む(試合インスタンス, 'p1', 8);

  const 手一覧 = new 打てる手を挙げる().フラッシュで打てる手(試合インスタンス, 'p1');
  const 種類 = new Set(手一覧.map(手 => 手.種類));

  assert.ok(!種類.has('召喚'), '割り込み中にスピリットが挙がっている');
  assert.ok(!種類.has('配置'), '割り込み中にネクサスが挙がっている');
  assert.ok(種類.has('使用'), '［フラッシュ］のマジックが挙がっていない');
});

// フレイムハリケーンは［フラッシュ］しか持たないが、メインステップでも使える。
// （利用者の指摘：「フラッシュ効果はメインフェイズに使うことができます」）
test('［フラッシュ］しか持たないマジックも、メインステップの手に挙がる', () => {
  const 試合インスタンス = 試合を用意する(デッキを作る, 1);
  手札を入れ替える(試合インスタンス, 'p1', [フレイムハリケーンを作成('手-マジック')]);
  リザーブにコアを積む(試合インスタンス, 'p1', 8);

  const 手一覧 = new 打てる手を挙げる().メインで打てる手(試合インスタンス, 'p1');
  assert.ok(
    手一覧.some(手 => 手.種類 === '使用'),
    '［フラッシュ］のマジックがメインの手に挙がっていない'
  );
});
