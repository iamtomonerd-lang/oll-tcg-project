import { カード } from '../../../データ/カード/カード.js';

// カードの表示形式（公式ルールの名称）
// フィールドのカードは常にいずれか1つを持つ（排他）
// UI/UXの向きなどの表示データは持たず、状態の識別のみに用いる
export type カードの表示形式 = '回復' | '疲労' | '重疲労';

// 表示形式管理（ゲームエンジン層）
// カードの表示形式を読み書き・遷移させる。
// いつ疲労/重疲労になるか、どう回復するか等の遷移ルールは詳細定義が出てから追加する。
export class 表示形式管理 {
  // 現在の表示形式を取得（未設定時は回復を既定とする ※初期状態の正式定義は詳細待ち）
  現在の表示形式を取得(カード: カード): カードの表示形式 {
    const 値 = カード.状態を取得('表示形式');
    if (値 === '疲労' || 値 === '重疲労') {
      return 値;
    }
    return '回復';
  }

  表示形式を設定(カード: カード, 表示形式: カードの表示形式): void {
    カード.状態を設定('表示形式', 表示形式);
  }

  回復にする(カード: カード): void {
    this.表示形式を設定(カード, '回復');
  }

  疲労にする(カード: カード): void {
    this.表示形式を設定(カード, '疲労');
  }

  重疲労にする(カード: カード): void {
    this.表示形式を設定(カード, '重疲労');
  }

  回復か(カード: カード): boolean {
    return this.現在の表示形式を取得(カード) === '回復';
  }

  疲労か(カード: カード): boolean {
    return this.現在の表示形式を取得(カード) === '疲労';
  }

  重疲労か(カード: カード): boolean {
    return this.現在の表示形式を取得(カード) === '重疲労';
  }
}
