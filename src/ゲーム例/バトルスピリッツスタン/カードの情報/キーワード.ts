import { カード } from '../../../データ/カード/カード.js';

// キーワードルール（ルール層 ＝ 状態を返すだけ）
// 《継召》《ソウルマジック》のようにカード自身が持つキーワード能力を読み取る。
// 《真界放》はLv情報側に書かれるため、こちらではなく 真界放判定 が担当する。
export class キーワードルール {
  キーワードを取得(カード: カード): string[] {
    return (カード.名称 as any).キーワード ?? [];
  }

  キーワードを持つ(カード: カード, キーワード名: string): boolean {
    return this.キーワードを取得(カード).includes(キーワード名);
  }

  キーワード数を取得(カード: カード): number {
    return this.キーワードを取得(カード).length;
  }
}
