import { カード } from '../../../データ/カード/カード.js';

export class 軽減シンボルルール {
  軽減シンボルを取得(カード: カード): string[] {
    const 名称データ = カード.名称 as any;
    const 軽減シンボル = 名称データ.軽減シンボル ?? [];
    return Array.isArray(軽減シンボル) ? 軽減シンボル : [];
  }

  軽減後のコストを計算(
    カード: カード,
    オリジナルコスト: number,
    フィールドのシンボル: string[]
  ): number {
    const 軽減シンボル = this.軽減シンボルを取得(カード);

    if (軽減シンボル.length === 0) {
      return オリジナルコスト;
    }

    const 軽減可能な数 = this.軽減可能な数を計算(カード, フィールドのシンボル);
    const 軽減量 = Math.min(軽減可能な数, オリジナルコスト);
    return オリジナルコスト - 軽減量;
  }

  軽減シンボルは有効(カード: カード): boolean {
    const 軽減シンボル = this.軽減シンボルを取得(カード);
    return Array.isArray(軽減シンボル) && 軽減シンボル.length > 0;
  }

  // 軽減シンボルの各枠を、フィールドのシンボルから実際に1つずつ消費しながら満たせる数を数える。
  // 同じ色のシンボルが1個しかフィールドに無ければ、その色の軽減シンボルは1枠しか満たせない
  // （枚数を数えず存在の有無だけで判定すると、1個の存在で複数枠が満たされてしまう不具合になるため）。
  軽減可能な数を計算(
    カード: カード,
    フィールドのシンボル: string[]
  ): number {
    const 軽減シンボル = this.軽減シンボルを取得(カード);

    if (軽減シンボル.length === 0) {
      return 0;
    }

    // 色ごとの残り枚数を数える
    const 残数マップ = new Map<string, number>();
    for (const シンボル of フィールドのシンボル) {
      残数マップ.set(シンボル, (残数マップ.get(シンボル) ?? 0) + 1);
    }

    let 軽減可能な数 = 0;
    for (const シンボル of 軽減シンボル) {
      const 残数 = 残数マップ.get(シンボル) ?? 0;
      if (残数 > 0) {
        残数マップ.set(シンボル, 残数 - 1); // 消費する
        軽減可能な数++;
      }
    }

    return 軽減可能な数;
  }
}
