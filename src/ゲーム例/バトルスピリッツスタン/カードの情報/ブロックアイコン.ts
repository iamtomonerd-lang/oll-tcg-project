import { カード } from '../../../データ/カード/カード.js';

export class ブロックアイコンルール {
  ブロックアイコンを取得(カード: カード): string {
    const 名称データ = カード.名称 as any;
    return 名称データ.ブロックアイコン ?? '';
  }

  ブロックアイコンは有効(カード: カード): boolean {
    const ブロックアイコン = this.ブロックアイコンを取得(カード);
    return ブロックアイコン !== null && ブロックアイコン !== undefined && ブロックアイコン.length > 0;
  }

  ブロックアイコンが同じ(カード1: カード, カード2: カード): boolean {
    return this.ブロックアイコンを取得(カード1) === this.ブロックアイコンを取得(カード2);
  }
}
