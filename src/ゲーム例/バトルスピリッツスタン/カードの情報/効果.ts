import { カード } from '../../../データ/カード/カード.js';
import { 効果定義 } from '../../../効果解釈/効果定義.js';

// 効果ルール（ルール層 ＝ 状態を返すだけ）
// カードデータに書かれた効果定義を読み取る。
// 効果は1枚が複数持つことがあるため配列で扱い、添字が効果の識別に使われる。
export class 効果ルール {
  効果を取得(カード: カード): 効果定義[] {
    return (カード.名称 as any).効果 ?? [];
  }

  効果数を取得(カード: カード): number {
    return this.効果を取得(カード).length;
  }

  // キューの重複判定に使う、カード内で一意な効果識別子
  効果識別子を作る(カード: カード, 添字: number): string {
    return `${カード.識別子}#${添字}`;
  }

  // 効果識別子から効果定義を引き当てる
  識別子で取得(カード: カード, 効果識別子: string): 効果定義 | undefined {
    const 効果一覧 = this.効果を取得(カード);
    for (let 添字 = 0; 添字 < 効果一覧.length; 添字++) {
      if (this.効果識別子を作る(カード, 添字) === 効果識別子) {
        return 効果一覧[添字];
      }
    }
    return undefined;
  }
}
