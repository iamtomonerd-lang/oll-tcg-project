// 置換型効果の定義
// 何らかの事象が発生する場合、それを実行せず別の事象を実行する効果（9-1-8-1）。
// 「かわりに○○する」「変更する」と表記されている能力が該当する（9-1-8-1-1）。
// ※効果の具体的な処理内容は効果システム側（未実装）の担当。
export interface 置換型効果 {
  識別子: string;
}

// 置換型効果判定（ルール層 ＝ 状態を返すだけ）
export class 置換型効果判定 {
  // 指定した事象が置換の適用対象になり得るか
  // 既にその事象が置換済みなら、再度置換することはできない（9-1-8-1-2）
  適用可能か(事象識別子: string, 既に置換済みの事象一覧: ReadonlySet<string>): boolean {
    return !既に置換済みの事象一覧.has(事象識別子);
  }
}
