// 効果の強制度（テキストの表記による効果の性質。9-1-2）
// - する              ：必ず発揮し、可能な限り処理する
// - できる            ：発揮しないことを選べる（任意）
// - しなければならない：必ず発揮する（する／できるより優先）
// - できない          ：発揮を禁止する（最優先）
export type 効果の強制度 = 'する' | 'できる' | 'しなければならない' | 'できない';

// 効果の分類（原則。9-1-3）
// - 常在型効果：継続して発揮する効果
// - 誘発型効果：特定の条件（「〜時」など）で誘発して発揮する効果
// - 起動型効果：プレイヤーが起動して発揮する効果
// - 宣言型効果：宣言によって発揮する効果
// - 置換型効果：ある処理を別の処理に置き換える効果
// ※各分類の詳細は後述の定義で扱う。
export type 効果の分類 =
  | '常在型効果'
  | '誘発型効果'
  | '起動型効果'
  | '宣言型効果'
  | '置換型効果';

// 効果判定（ルール層 ＝ 状態を返すだけ）
export class 効果判定 {
  // 優先順位（数が大きいほど優先）：できない ＞ しなければならない ＞ する ＝ できる（9-1-2-2）
  優先度(強制度: 効果の強制度): number {
    const 表: Record<効果の強制度, number> = {
      できない: 3,
      しなければならない: 2,
      する: 1,
      できる: 1,
    };
    return 表[強制度];
  }

  // 同時に発揮した強制度のうち、優先される強制度を返す（9-1-2-1）
  // 例：「できない」が含まれれば「できない」が優先される
  優先される強制度(強制度一覧: 効果の強制度[]): 効果の強制度 | undefined {
    if (強制度一覧.length === 0) {
      return undefined;
    }
    return 強制度一覧.reduce((最優先, 現在) =>
      this.優先度(現在) > this.優先度(最優先) ? 現在 : 最優先
    );
  }

  // 必ず発揮するか（する・しなければならない）
  必須か(強制度: 効果の強制度): boolean {
    return 強制度 === 'する' || 強制度 === 'しなければならない';
  }

  // 発揮しないことを選べるか（できる）
  任意か(強制度: 効果の強制度): boolean {
    return 強制度 === 'できる';
  }

  // 発揮が禁止されているか（できない）
  禁止か(強制度: 効果の強制度): boolean {
    return 強制度 === 'できない';
  }
}
