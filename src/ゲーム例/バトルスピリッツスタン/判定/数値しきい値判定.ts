// 数値しきい値判定（ルール層 ＝ 状態を返すだけ）
// 「～以上になった時」「～以下になった時」（13-1）の発揮条件を判定する。
// BP・コスト・ライフなど、数値全般のしきい値誘発に共通して使える。
export class 数値しきい値判定 {
  // 「～以上になった時」（13-1-1）
  // 値そのものが増加し、その結果 基準値 以上になったら発揮する。
  // すでに基準値以上であっても、値が増加した結果なお基準値以上であれば発揮する。
  // 一方、基準値（しきい値）自体が変化した結果満たすようになっても発揮しない
  // （＝呼び出し側は値そのものが変化したときのみこのメソッドを呼ぶこと。基準値だけが
  //   変化した場合は 変化前の値 と 変化後の値 が同じになるため、増加とみなされず false になる）。
  以上になった時に発揮するか(変化前の値: number, 変化後の値: number, 基準値: number): boolean {
    if (変化後の値 <= 変化前の値) {
      return false; // 増加していない
    }
    return 変化後の値 >= 基準値;
  }

  // 「～以下になった時」（13-1-2）
  // 値そのものが減少し、その結果 基準値 以下になったら発揮する。
  // すでに基準値以下であっても、値が減少した結果なお基準値以下であれば発揮する。
  // 基準値自体が変化した結果満たすようになっても発揮しない（以上になった時と同様の理由）。
  以下になった時に発揮するか(変化前の値: number, 変化後の値: number, 基準値: number): boolean {
    if (変化後の値 >= 変化前の値) {
      return false; // 減少していない
    }
    return 変化後の値 <= 基準値;
  }
}
