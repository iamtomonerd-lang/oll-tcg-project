// 制限効果（12-3）
// いずれも、対象となる「効果」の識別は同名カードの同じ効果テキスト単位で行う。
// 別名のカードが同じ効果テキストを持っていても、同じ効果としては扱わない
// （12-3-1-3／12-3-2-2／12-3-3-3）ため、呼び出し側は 効果識別子 にカード名由来の
// 識別子を含めて一意化すること（カードのインスタンスIDではなく、名前＋効果テキスト単位）。
export type 制限効果種別 = 'ターン1回' | '重複不可' | '重複不可・ターン1回';

// 〔ターン1回〕の発揮記録。カードのインスタンスごとに独立して管理する
// （12-3-1-2：同名カードが複数あっても、それぞれが1回ずつ発揮できる）。
export interface ターン1回記録 {
  カード識別子: string;
  効果識別子: string;
  ターン数: number;
}

// 制限効果判定（ルール層 ＝ 状態を返すだけ）
//
// 〔重複不可〕（12-3-2）について：
//   同じタイミング（同一事象）で、同名カードが持つ同じ効果は1回しか発揮できない、という制限は、
//   誘発型効果判定.事象に対して誘発済みか（9-1-5-4の重複排除）と全く同じ仕組みで表現できる。
//   効果識別子 をカード名＋効果テキスト単位（カードのインスタンスIDではない）で統一しさえすれば、
//   誘発型効果管理.誘発する の重複排除がそのまま〔重複不可〕を満たす。専用の新しい仕組みは不要。
export class 制限効果判定 {
  // 〔ターン1回〕：このカード（インスタンス）・この効果が、指定ターンで既に発揮済みか（12-3-1-1／12-3-1-2）
  ターン1回は発揮済みか(
    記録一覧: ターン1回記録[],
    カード識別子: string,
    効果識別子: string,
    ターン数: number
  ): boolean {
    return 記録一覧.some(
      記録 => 記録.カード識別子 === カード識別子 && 記録.効果識別子 === 効果識別子 && 記録.ターン数 === ターン数
    );
  }

  // 〔重複不可・ターン1回〕：ターン1回の制限と重複不可の制限、両方を満たしたときのみ発揮できる（12-3-3-1）。
  // 重複していないか は、誘発型効果判定.事象に対して誘発済みか の否定を呼び出し側から渡す。
  重複不可ターン1回は発揮可能か(ターン1回は未発揮か: boolean, 重複していないか: boolean): boolean {
    return ターン1回は未発揮か && 重複していないか;
  }
}
