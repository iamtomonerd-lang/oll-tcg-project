import { カード } from '../../../データ/カード/カード.js';

// 誘発型効果の定義
// - 発揮領域：この効果を持つカードが発揮できる領域（例：フィールド）
// ※効果の具体的な処理内容は効果システム側（未実装）の担当。ここは判定のみ。
export interface 誘発型効果 {
  発揮領域: string[];
}

// 誘発予約：条件となる事象が発生し、誘発した効果1つ分の記録
export interface 誘発予約 {
  予約識別子: string;
  効果識別子: string;
  発揮源: カード;
  所有者識別子: string;
  事象キー: string; // 同一事象での重複誘発をまとめるためのキー（9-1-5-4）
}

// 誘発型効果判定（ルール層 ＝ 状態を返すだけ）
export class 誘発型効果判定 {
  // 発揮源が今いる領域で、この効果が発揮できるか（9-1-5-5：場を離れたら発揮不可）
  発揮可能か(効果: 誘発型効果, 現在の領域: string): boolean {
    return 効果.発揮領域.includes(現在の領域);
  }

  // 同一事象（事象キー）に対して同じ効果が既に誘発済みかどうか（9-1-5-4）
  // 例：スピリット2体を同時に召喚しても「召喚された時」は1回しか誘発しない
  事象に対して誘発済みか(既存の予約一覧: 誘発予約[], 効果識別子: string, 事象キー: string): boolean {
    return 既存の予約一覧.some(
      予約 => 予約.効果識別子 === 効果識別子 && 予約.事象キー === 事象キー
    );
  }
}
