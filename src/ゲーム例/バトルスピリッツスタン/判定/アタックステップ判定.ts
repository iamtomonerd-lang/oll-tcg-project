// アタックステップで選択可能な行動
// アタックの詳細（バトル）は後述の定義で実装する。
export type アタックステップ行動 =
  | 'スピリットでアタック'
  | 'アタックステップの終了';

// アタックステップ判定（ルール層 ＝ 状態を返すだけ）
export class アタックステップ判定 {
  // アタックステップで選択可能な行動の一覧
  選択可能な行動(): アタックステップ行動[] {
    return ['スピリットでアタック', 'アタックステップの終了'];
  }

  // ターンプレイヤーは他の処理の解決中でなければ行動できる。
  // 解決中かどうかは効果システム側の状態のため、呼び出し側から受け取る。
  行動可能か(解決中: boolean): boolean {
    return !解決中;
  }
}
