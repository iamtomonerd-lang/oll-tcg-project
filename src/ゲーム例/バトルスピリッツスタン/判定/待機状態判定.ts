// 待機状態判定（ルール層 ＝ 状態を返すだけ）
export class 待機状態判定 {
  // 待機状態になったスピリットやネクサスが、ある効果を発揮できるかを判定する（10-2-2-4）。
  // 待機状態でなければ制限なし。待機状態であれば、
  //  - 待機状態になる前から発揮している常在型効果（効果を発揮できない効果を受けていなければ）
  //  - 待機状態そのもので発揮する効果（『破壊時』「フィールドを離れるとき」等）
  // 以外は発揮できない。
  発揮できる効果か(
    待機状態か: boolean,
    待機前から発揮している常在型効果か: boolean,
    待機理由に紐づく発揮か: boolean
  ): boolean {
    if (!待機状態か) {
      return true;
    }
    return 待機前から発揮している常在型効果か || 待機理由に紐づく発揮か;
  }
}
