import { カード } from '../../../データ/カード/カード.js';

// 破壊の原因（12-2-1-12／12-2-1-12-1）
// 『相手による破壊時』は、相手の効果、または相手のスピリットとのBP比べで破壊されたときに発揮する。
export type 破壊原因 =
  | { 由来: '自分の効果'; 効果識別子: string }
  | { 由来: '相手の効果'; 効果識別子: string }
  | { 由来: 'BP比べ'; 相手のカード: カード };

// 破壊原因判定（ルール層 ＝ 状態を返すだけ）
export class 破壊原因判定 {
  // 『相手による破壊時』（12-2-1-12-1）：相手の効果、または相手のスピリットとのBP比べで破壊されたか
  相手による破壊か(原因: 破壊原因 | undefined): boolean {
    if (!原因) {
      return false;
    }
    return 原因.由来 === '相手の効果' || 原因.由来 === 'BP比べ';
  }
}
