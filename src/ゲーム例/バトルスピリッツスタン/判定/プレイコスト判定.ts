import { コア保持者 } from './コア保持者.js';
import { コア判定 } from './コア判定.js';

// コアの支払い元（プレイヤーが選んだ、フィールドまたはリザーブの保持者と、そこから出す数）
//
// ソウルコア数 は「数 のうち何個をソウルコアで払うか」。
// 省略すると「通常コアを優先し、足りなければソウルコアで埋める」という自動の払い方になる。
// 省略しなければ、通常コアが足りていてもソウルコアを狙って払える。
// ソウルコアを狙って払えないと、トラッシュにソウルコアを置けず、
// キュペルLv2の「トラッシュの{ソウルコア}をそれに置く」を試す手立てが無かった。
export interface コア支払い元 {
  保持者: コア保持者;
  数: number;
  ソウルコア数?: number;
}

// プレイコスト判定（ルール層 ＝ 状態を返すだけ）
// 召喚（11-1）・配置（11-2）・使用（11-3）に共通するコスト支払いの検証を行う。
export class プレイコスト判定 {
  private コア判定: コア判定;

  constructor() {
    this.コア判定 = new コア判定();
  }

  // 支払い元一覧の合計がコストとちょうど一致するか。
  // 召喚・配置・使用コストは過剰に支払うことができない（11-1-1-5／11-2-1-5／11-3-1-5）ため、ちょうどのみ有効。
  支払い総数はちょうどか(支払い元一覧: コア支払い元[], コスト: number): boolean {
    const 合計 = 支払い元一覧.reduce((合計, 元) => 合計 + 元.数, 0);
    return 合計 === コスト;
  }

  // カードに置く最低必要数（最低LvのLvコスト）以上を満たしているか。
  // こちらは「以上」でよく、過剰に置くことは禁止されない（11-1-1-6／11-2-1-6）。
  初期配置数は十分か(支払い元一覧: コア支払い元[], 最低必要数: number): boolean {
    const 合計 = 支払い元一覧.reduce((合計, 元) => 合計 + 元.数, 0);
    return 合計 >= 最低必要数;
  }

  // 各支払い元が、指定された数のコア（通常＋ソウルコアを含む）を実際に持っているか。
  // ソウルコア数 を名指ししているときは、その内訳が本当に払えるかまで見る。
  // ソウルコアは1個しか無いので、名指しできるのは各支払い元につき1個まで。
  各支払い元に十分なコアがあるか(支払い元一覧: コア支払い元[]): boolean {
    return 支払い元一覧.every(元 => {
      if (元.保持者.コア数を取得() < 元.数) {
        return false;
      }
      if (元.ソウルコア数 === undefined) {
        return true;
      }
      if (元.ソウルコア数 < 0 || 元.ソウルコア数 > 1 || 元.ソウルコア数 > 元.数) {
        return false;
      }
      if (元.ソウルコア数 > 0 && !元.保持者.ソウルコアあるか()) {
        return false;
      }
      // 残りは通常コアで賄えるか
      return this.コア判定.通常コア数を取得(元.保持者) >= 元.数 - 元.ソウルコア数;
    });
  }
}
