import { カード } from '../../../データ/カード/カード.js';

// 選ぶ数の指定（「～を指定する」「～までを」等。9-3-2-1）
// までを＝true の場合は「～までを」表記＝0から数まで自由に選べる。
// までを＝false の場合は、可能な限りその数になるまで選ぶ必要がある（義務）。
export interface 選択数指定 {
  数: number;
  までを: boolean;
}

// 選択が及ぶ範囲（最小・最大）
export interface 選択数範囲 {
  最小: number;
  最大: number;
}

// 対象選択判定（ルール層 ＝ 状態を返すだけ）
export class 対象選択判定 {
  // 指定と候補数（実際に選べる対象の数）から、有効な選択数の範囲を求める（9-3-2-1）
  有効な選択数の範囲(指定: 選択数指定, 候補数: number): 選択数範囲 {
    const 上限 = Math.min(指定.数, 候補数);
    if (指定.までを) {
      return { 最小: 0, 最大: 上限 };
    }
    return { 最小: 上限, 最大: 上限 };
  }

  // 実際に選んだ数が有効な範囲内か
  選択数は有効か(指定: 選択数指定, 候補数: number, 選んだ数: number): boolean {
    const 範囲 = this.有効な選択数の範囲(指定, 候補数);
    return 選んだ数 >= 範囲.最小 && 選んだ数 <= 範囲.最大;
  }

  // 非公開領域からの選択で、選ぶための条件にカードの情報を必要とする場合、
  // 条件を満たすカードがあっても選ばないことを選べる（9-3-2-2）
  選択を強制されないか(領域は非公開か: boolean, 選択条件がカード情報を要求するか: boolean): boolean {
    return 領域は非公開か && 選択条件がカード情報を要求するか;
  }

  // テキスト中に選択の指示が無い場合のデフォルト対象（9-3-2-3）
  // カードに対する効果なら発生源のカード、プレイヤーに対する効果ならその効果のプレイヤーを指す。
  デフォルト対象カード(発生源: カード): カード {
    return 発生源;
  }

  デフォルト対象プレイヤー(効果のプレイヤー識別子: string): string {
    return 効果のプレイヤー識別子;
  }
}
