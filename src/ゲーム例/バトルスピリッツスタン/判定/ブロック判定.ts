import { カード } from '../../../データ/カード/カード.js';
import { カード種別ルール } from '../カードの情報/カード種別.js';
import { 表示形式判定 } from './表示形式判定.js';

export class ブロック判定 {
  private カード種別ルール: カード種別ルール;
  private 表示形式判定: 表示形式判定;

  constructor() {
    this.カード種別ルール = new カード種別ルール();
    this.表示形式判定 = new 表示形式判定();
  }

  // ブロックできるのは回復状態のスピリット（8-1-3-1）
  ブロック可能か(カード: カード): boolean {
    return this.カード種別ルール.スピリットか(カード) && this.表示形式判定.回復か(カード);
  }
}
