import { test } from 'node:test';
import assert from 'node:assert/strict';

import { ゲームエンジン } from '../../../ゲームエンジン.js';
import { プレイヤー } from '../../../データ/プレイヤー/プレイヤー.js';
import { ターン判定 } from './ターン判定.js';
import { ステップ順 } from '../ターン/ステップ.js';

function 準備() {
  const ゲーム = new ゲームエンジン();
  const p1 = new プレイヤー('p1', 'プレイヤー1');
  const p2 = new プレイヤー('p2', 'プレイヤー2');
  ゲーム.プレイヤーを追加(p1);
  ゲーム.プレイヤーを追加(p2);
  return { ゲーム, p1, p2 };
}

test('先攻の第1ターンか：先攻の1ターン目（他プレイヤーが誰もターンを行っていない）ならtrue', () => {
  const { ゲーム, p1 } = 準備();
  p1.数値を設定('ターン数', 1);
  assert.equal(new ターン判定().先攻の第1ターンか(ゲーム), true);
});

test('先攻の第1ターンか：後攻が1ターン目を行っている（先攻は既にターンを終えている）場合はfalse', () => {
  const { ゲーム, p1, p2 } = 準備();
  p1.数値を設定('ターン数', 1);
  p2.数値を設定('ターン数', 1);
  assert.equal(new ターン判定().先攻の第1ターンか(ゲーム), false);
});

test('先攻の第1ターンか：2ターン目以降はfalse', () => {
  const { ゲーム, p1 } = 準備();
  p1.数値を設定('ターン数', 2);
  assert.equal(new ターン判定().先攻の第1ターンか(ゲーム), false);
});

test('ステップをスキップするか：先攻第1ターンにスキップ指定のあるステップは、先攻第1ターンだけスキップする', () => {
  const { ゲーム, p1 } = 準備();
  const 判定 = new ターン判定();
  const コアステップ = ステップ順.find(s => s.名前 === 'コアステップ')!;

  p1.数値を設定('ターン数', 1);
  assert.equal(判定.ステップをスキップするか(ゲーム, コアステップ), true);

  p1.数値を設定('ターン数', 2);
  assert.equal(判定.ステップをスキップするか(ゲーム, コアステップ), false);
});

test('ステップをスキップするか：スキップ指定の無いステップは先攻第1ターンでもスキップしない', () => {
  const { ゲーム, p1 } = 準備();
  p1.数値を設定('ターン数', 1);
  const メインステップ = ステップ順.find(s => s.名前 === 'メインステップ')!;
  assert.equal(new ターン判定().ステップをスキップするか(ゲーム, メインステップ), false);
});
