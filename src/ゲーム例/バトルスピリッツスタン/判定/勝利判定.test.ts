import { test } from 'node:test';
import assert from 'node:assert/strict';

import { ゲームエンジン } from '../../../ゲームエンジン.js';
import { ゾーン } from '../../../データ/ゾーン/ゾーン.js';
import { プレイヤー } from '../../../データ/プレイヤー/プレイヤー.js';
import { バトルスピリッツ勝利判定 } from './勝利判定.js';

function 準備() {
  const ゲーム = new ゲームエンジン();
  const p1 = new プレイヤー('p1', 'プレイヤー1');
  const p2 = new プレイヤー('p2', 'プレイヤー2');
  ゲーム.プレイヤーを追加(p1);
  ゲーム.プレイヤーを追加(p2);

  const p1ライフ = new ゾーン('p1-ライフ', { 識別子: 'ライフ', 表示名: 'ライフ' });
  const p2ライフ = new ゾーン('p2-ライフ', { 識別子: 'ライフ', 表示名: 'ライフ' });
  const p1デッキ = new ゾーン('p1-デッキエリア', { 識別子: 'デッキエリア', 表示名: 'デッキ' });
  const p2デッキ = new ゾーン('p2-デッキエリア', { 識別子: 'デッキエリア', 表示名: 'デッキ' });
  ゲーム.ゾーンを追加(p1ライフ);
  ゲーム.ゾーンを追加(p2ライフ);
  ゲーム.ゾーンを追加(p1デッキ);
  ゲーム.ゾーンを追加(p2デッキ);

  p1ライフ.状態を設定('コア数', 5);
  p2ライフ.状態を設定('コア数', 5);

  const デッキゾーン識別子マップ = new Map([
    ['p1', 'p1-デッキエリア'],
    ['p2', 'p2-デッキエリア'],
  ]);
  const ライフゾーン識別子マップ = new Map([
    ['p1', 'p1-ライフ'],
    ['p2', 'p2-ライフ'],
  ]);

  return { ゲーム, p1, p2, p1ライフ, p2ライフ, p1デッキ, デッキゾーン識別子マップ, ライフゾーン識別子マップ };
}

test('両者のライフが残っていれば試合は続行中と判定される', () => {
  const { ゲーム, デッキゾーン識別子マップ, ライフゾーン識別子マップ } = 準備();
  const 結果 = new バトルスピリッツ勝利判定().勝利判定(ゲーム, デッキゾーン識別子マップ, ライフゾーン識別子マップ);
  assert.equal(結果.勝利, false);
});

test('ライフのコアが0になったプレイヤーが敗者になる（10-2-1-1）', () => {
  const { ゲーム, p1ライフ, デッキゾーン識別子マップ, ライフゾーン識別子マップ } = 準備();
  p1ライフ.状態を設定('コア数', 0);

  const 結果 = new バトルスピリッツ勝利判定().勝利判定(ゲーム, デッキゾーン識別子マップ, ライフゾーン識別子マップ);

  assert.equal(結果.勝利, true);
  assert.equal(結果.敗者?.識別子, 'p1');
  assert.equal(結果.勝者?.識別子, 'p2');
});

test('スタートステップに自分のデッキが0枚なら敗北する（10-2-1-2）', () => {
  const { ゲーム, デッキゾーン識別子マップ, ライフゾーン識別子マップ } = 準備();
  ゲーム.現在のフェーズを設定({ 名前: 'スタートステップ', 順序: 1 });

  const 結果 = new バトルスピリッツ勝利判定().勝利判定(ゲーム, デッキゾーン識別子マップ, ライフゾーン識別子マップ);

  assert.equal(結果.勝利, true);
  // 両者ともデッキ0枚のため、先に判定されるプレイヤー（登録順＝p1）が敗者になる
  assert.equal(結果.敗者?.識別子, 'p1');
});

test('スタートステップ以外でデッキが0枚でも敗北判定にはならない', () => {
  const { ゲーム, デッキゾーン識別子マップ, ライフゾーン識別子マップ } = 準備();
  ゲーム.現在のフェーズを設定({ 名前: 'メインステップ', 順序: 5 });

  const 結果 = new バトルスピリッツ勝利判定().勝利判定(ゲーム, デッキゾーン識別子マップ, ライフゾーン識別子マップ);

  assert.equal(結果.勝利, false);
});
