import { コア保持者 } from './コア保持者.js';

// コア判定（ルール層 ＝ 状態を返すだけ、遷移はしない）
export class コア判定 {
  // 総コア数（ソウルコア含む）
  総コア数を取得(保持者: コア保持者): number {
    return 保持者.コア数を取得();
  }

  // 通常コア数（総数 − ソウルコア）
  通常コア数を取得(保持者: コア保持者): number {
    const 総数 = 保持者.コア数を取得();
    return 総数 - (保持者.ソウルコアあるか() ? 1 : 0);
  }

  ソウルコアあるか(保持者: コア保持者): boolean {
    return 保持者.ソウルコアあるか();
  }

  // 必要数のコアを支払えるか（総数で判定。ソウルコアも通常コアと同様にコストに使える）
  支払い可能か(保持者: コア保持者, 必要数: number): boolean {
    return 保持者.コア数を取得() >= 必要数;
  }

  // 5-7-3：ソウルコアを移動先に置けるか
  // 制限付き配置先（ライフ／ボイド）へは、効果がソウルコアを対象とする場合のみ置ける
  ソウルコアを置けるか(先: コア保持者, 効果がソウルコアを対象とする: boolean): boolean {
    if (!先.制限付き配置先か()) {
      return true;
    }
    return 効果がソウルコアを対象とする;
  }
}
