import { カード } from '../../../データ/カード/カード.js';
import { カード種別ルール } from '../カードの情報/カード種別.js';

// 破壊判定（ルール層 ＝ 状態を返すだけ）
export class 破壊判定 {
  private カード種別ルール: カード種別ルール;

  constructor() {
    this.カード種別ルール = new カード種別ルール();
  }

  // 破壊の対象になるのはスピリットとネクサスのみ
  破壊対象か(カード: カード): boolean {
    return this.カード種別ルール.スピリットか(カード) || this.カード種別ルール.ネクサスか(カード);
  }
}
