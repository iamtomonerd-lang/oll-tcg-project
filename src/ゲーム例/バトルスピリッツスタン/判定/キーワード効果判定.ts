// キーワード効果（12-1）
// テキスト上で黒地に白文字で書かれた効果（【激突】など。12-1-1）。
// 【○○：△△】の場合、○○がキーワード効果名、△△は対象内容や指定数などの
// 効果内条件を変更する部分（12-1-2）。
export interface キーワード効果 {
  名前: string; // 【○○】部分
  パラメータ?: string; // 【○○：△△】の△△部分
}

// キーワード効果判定（ルール層 ＝ 状態を返すだけ）
// 1体のスピリットや1つのネクサスは、同じキーワード効果を複数個持てる（12-1-3）ため、
// カードは キーワード効果[] として保持し、重複を除去しない。
export class キーワード効果判定 {
  パラメータ付きか(効果: キーワード効果): boolean {
    return 効果.パラメータ !== undefined;
  }

  // 同じ名前のキーワード効果を何個持っているか（12-1-3：複数所持の判定に使う）
  同名の効果数(効果一覧: キーワード効果[], 名前: string): number {
    return 効果一覧.filter(効果 => 効果.名前 === 名前).length;
  }
}
