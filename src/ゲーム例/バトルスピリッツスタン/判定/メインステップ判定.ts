// メインステップで選択可能な行動
// 各行動の詳細（召喚・配置・使用・起動など）は後述の定義で実装する。コアの移動は実装済み。
export type メインステップ行動 =
  | 'スピリットの召喚'
  | 'ネクサスの配置'
  | 'マジックの使用'
  | 'コアの移動'
  | 'メイン効果の起動'
  | 'メインステップの終了';

// メインステップ判定（ルール層 ＝ 状態を返すだけ）
export class メインステップ判定 {
  // メインステップで選択可能な行動の一覧
  選択可能な行動(): メインステップ行動[] {
    return [
      'スピリットの召喚',
      'ネクサスの配置',
      'マジックの使用',
      'コアの移動',
      'メイン効果の起動',
      'メインステップの終了',
    ];
  }

  // ターンプレイヤーは他の処理の解決中でなければ行動できる。
  // 解決中かどうかは効果システム側の状態のため、呼び出し側から受け取る。
  行動可能か(解決中: boolean): boolean {
    return !解決中;
  }
}
