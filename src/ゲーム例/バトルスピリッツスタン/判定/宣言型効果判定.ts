// 宣言型効果が発揮できるタイミング（[メイン]／[フラッシュ]。9-1-7-1）
export type 宣言タイミング = 'メイン' | 'フラッシュ';

// 宣言型効果の定義
// 手札にあるカードに書かれた効果で、指定されたタイミングに宣言することで発揮する。
// ※効果の具体的な処理内容は効果システム側（未実装）の担当。
export interface 宣言型効果 {
  タイミング: 宣言タイミング;
}

// 宣言できる状況
// - 自分のメインステップ：自分のメインステップで発揮を宣言した場合
// - フラッシュタイミング：フラッシュタイミングで発揮を宣言した場合
export type 宣言状況 = '自分のメインステップ' | 'フラッシュタイミング';

// 宣言型効果判定（ルール層 ＝ 状態を返すだけ）
export class 宣言型効果判定 {
  // この効果を、現在の状況で宣言できるか
  // [メイン]・[フラッシュ]どちらも自分のメインステップで宣言できる（9-1-7-1-1／9-1-7-1-2）
  // フラッシュタイミングでは[フラッシュ]のみ宣言できる（9-1-7-1-2）
  宣言可能か(効果: 宣言型効果, 現在の状況: 宣言状況): boolean {
    if (現在の状況 === '自分のメインステップ') {
      return true;
    }
    return 効果.タイミング === 'フラッシュ';
  }

  // 現在の状況で宣言可能な効果の一覧を返す
  // カードが[メイン]と[フラッシュ]の両方を持ち、メインステップで宣言する場合は
  // 両方が候補として返るため、呼び出し側（効果システム／プレイヤー）がその中から
  // 発揮する1つを選ぶ（9-1-7-1-3）。
  宣言可能な効果一覧(効果一覧: 宣言型効果[], 現在の状況: 宣言状況): 宣言型効果[] {
    return 効果一覧.filter(効果 => this.宣言可能か(効果, 現在の状況));
  }
}
