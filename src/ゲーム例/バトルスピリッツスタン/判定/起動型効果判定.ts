// 起動型効果が発揮できるタイミング（【起動：メイン】【起動：フラッシュ】。9-1-6-1）
export type 起動タイミング = 'メイン' | 'フラッシュ';

// 起動型効果の定義
// タイミングが省略されている場合、特に【起動】の表記が無く、宣言することで発揮できる（9-1-6-3）。
// ※「▶」より前（コスト）・後（効果）の具体的な処理内容は効果システム側（未実装）の担当。
export interface 起動型効果 {
  タイミング?: 起動タイミング;
}

// 起動型効果判定（ルール層 ＝ 状態を返すだけ）
export class 起動型効果判定 {
  // 現在のタイミングでこの起動型効果を起動できるか
  // タイミング表記が無ければ、いつでも宣言することで発揮できる（9-1-6-3）
  起動可能なタイミングか(効果: 起動型効果, 現在のタイミング: 起動タイミング): boolean {
    if (!効果.タイミング) {
      return true;
    }
    return 効果.タイミング === 現在のタイミング;
  }
}
