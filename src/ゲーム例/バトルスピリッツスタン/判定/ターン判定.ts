import { ゲームエンジン } from '../../../ゲームエンジン.js';

// ターン判定（ルール層 ＝ 状態を返すだけ）
// ターン数は各プレイヤーの 数値('ターン数') に記録される（ターン管理が加算する）。
export class ターン判定 {
  // 先攻の第1ターンか
  // ＝ ターンプレイヤーが自分の1ターン目 かつ 他の全プレイヤーがまだ1ターンも行っていない
  //   （＝ゲームの最初のターン。先攻が最初に行うため、この条件は先攻の第1ターンだけを指す）
  先攻の第1ターンか(ゲーム: ゲームエンジン): boolean {
    const ターンプレイヤー = ゲーム.現在のプレイヤーを取得();
    if (!ターンプレイヤー) {
      return false;
    }
    if (ターンプレイヤー.数値を取得('ターン数') !== 1) {
      return false;
    }
    return ゲーム
      .全プレイヤーを取得()
      .filter(p => p.識別子 !== ターンプレイヤー.識別子)
      .every(p => p.数値を取得('ターン数') === 0);
  }
}
