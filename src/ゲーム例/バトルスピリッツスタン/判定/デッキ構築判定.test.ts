import { test } from 'node:test';
import assert from 'node:assert/strict';

import {
  デッキ構築判定,
  デッキの枚数,
  同名の上限,
  構築,
} from './デッキ構築判定.js';
import { カード帳, 番号で引く } from '../カードデータ/カード帳.js';
import { グンガタを作成 } from '../カードデータ/グンガタ.js';
import { ハーリアを作成 } from '../カードデータ/ハーリア.js';

const 判定 = () => new デッキ構築判定();

// 実在するカードナンバーを、必要な種類だけ取り出す
const 番号一覧 = カード帳.map(項 => 項.カードナンバー);

// ちょうど40枚・同名3枚以下の、正しい構築を組む
function 正しい構築を作る(): 構築 {
  const 出来上がり: 構築 = {};
  let 残り = デッキの枚数;
  for (const 番号 of 番号一覧) {
    if (残り === 0) break;
    const 入れる = Math.min(同名の上限, 残り);
    出来上がり[番号] = 入れる;
    残り -= 入れる;
  }
  return 出来上がり;
}

test('デッキ構築判定：ちょうど40枚・同名3枚まで', async t => {
  await t.test('カードの種類が足りていることの確認', () => {
    // 同名3枚までで40枚を組むには、少なくとも14種類が要る
    assert.ok(
      番号一覧.length >= Math.ceil(デッキの枚数 / 同名の上限),
      `実装済みが${番号一覧.length}種類。40枚を組むには足りている必要がある`
    );
  });

  await t.test('正しい構築は組める', () => {
    const 結果 = 判定().検証する(正しい構築を作る());
    assert.deepEqual(結果.問題, []);
    assert.equal(結果.合計, デッキの枚数);
    assert.equal(結果.組めるか, true);
  });

  await t.test('39枚では足りないと言う', () => {
    const 構築 = 正しい構築を作る();
    const 最初 = Object.keys(構築)[0];
    構築[最初] -= 1;

    const 結果 = 判定().検証する(構築);
    assert.equal(結果.組めるか, false);
    assert.equal(結果.合計, 39);
    assert.equal(結果.問題[0].種別, '合計が足りない');
    assert.match(結果.問題[0].説明, /あと1枚/);
  });

  await t.test('41枚では多いと言う', () => {
    const 構築 = 正しい構築を作る();
    // まだ3枚に達していないカードを1枚足す
    const 余地のある番号 = 番号一覧.find(番号 => (構築[番号] ?? 0) < 同名の上限)!;
    構築[余地のある番号] = (構築[余地のある番号] ?? 0) + 1;

    const 結果 = 判定().検証する(構築);
    assert.equal(結果.組めるか, false);
    assert.equal(結果.合計, 41);
    assert.equal(結果.問題[0].種別, '合計が多すぎる');
    assert.match(結果.問題[0].説明, /1枚多い/);
  });

  await t.test('同名4枚は弾く', () => {
    const 構築: 構築 = { [番号一覧[0]]: 4 };
    const 結果 = 判定().検証する(構築);

    const 同名の問題 = 結果.問題.find(問 => 問.種別 === '同名が多すぎる');
    assert.ok(同名の問題, '同名の問題が報告される');
    assert.equal(同名の問題!.枚数, 4);
    assert.match(同名の問題!.説明, /3枚まで/);
  });

  await t.test('同名ちょうど3枚は通る', () => {
    const 結果 = 判定().検証する({ [番号一覧[0]]: 3 });
    assert.equal(
      結果.問題.some(問 => 問.種別 === '同名が多すぎる'),
      false
    );
  });

  await t.test('知らないカードナンバーは弾く', () => {
    const 結果 = 判定().検証する({ 'そんなカードはない-999': 3 });
    const 問題 = 結果.問題.find(問 => 問.種別 === '知らないカード');
    assert.ok(問題);
    assert.equal(問題!.カードナンバー, 'そんなカードはない-999');
  });

  await t.test('枚数が整数でなければ弾く', () => {
    const 結果 = 判定().検証する({ [番号一覧[0]]: 1.5 as number });
    assert.ok(結果.問題.some(問 => 問.種別 === '枚数が不正'));
  });

  await t.test('空の構築は「40枚足りない」と言う', () => {
    const 結果 = 判定().検証する({});
    assert.equal(結果.合計, 0);
    assert.match(結果.問題[0].説明, /あと40枚/);
  });
});

// 同名はカードナンバーではなくカード名で数える。
// 別番号で同じ名前が出たときに、番号で数えると4枚以上入ってしまう。
test('デッキ構築判定：同名はカード名で数える', () => {
  const 集計 = 判定().カード名ごとに数える({ [番号一覧[0]]: 2, [番号一覧[1]]: 1 });
  const 名1 = 番号で引く(番号一覧[0])!.カード名;
  const 名2 = 番号で引く(番号一覧[1])!.カード名;

  assert.equal(集計.get(名1), 2);
  assert.equal(集計.get(名2), 1);
});

test('デッキ構築判定：あと何枚足せるか', async t => {
  await t.test('空なら3枚まで足せる', () => {
    assert.equal(判定().あと何枚足せるか({}, 番号一覧[0]), 3);
  });

  await t.test('すでに3枚あれば足せない', () => {
    assert.equal(判定().あと何枚足せるか({ [番号一覧[0]]: 3 }, 番号一覧[0]), 0);
  });

  await t.test('デッキが39枚なら、同名に余裕があっても1枚だけ', () => {
    const 構築 = 正しい構築を作る();
    const 最初 = Object.keys(構築)[0];
    構築[最初] -= 1; // 39枚
    const 余地のある番号 = 番号一覧.find(番号 => (構築[番号] ?? 0) < 同名の上限)!;

    assert.equal(判定().あと何枚足せるか(構築, 余地のある番号), 1, '全体の残り枠で頭打ちになる');
  });

  await t.test('40枚ちょうどならもう足せない', () => {
    const 構築 = 正しい構築を作る();
    const 余地のある番号 = 番号一覧.find(番号 => (構築[番号] ?? 0) < 同名の上限);
    if (余地のある番号) assert.equal(判定().あと何枚足せるか(構築, 余地のある番号), 0);
  });

  await t.test('知らないカードは0', () => {
    assert.equal(判定().あと何枚足せるか({}, 'そんなカードはない-999'), 0);
  });
});

test('デッキ構築判定：出来上がったデッキの列を見る', async t => {
  // 同名3枚までで40枚を組む
  function 正しいデッキを作る() {
    const デッキ = [];
    const 作り手 = カード帳.map(項 => 項.作る);
    for (let i = 0; i < デッキの枚数; i++) {
      デッキ.push(作り手[Math.floor(i / 同名の上限)](`d-${i}`));
    }
    return デッキ;
  }

  await t.test('ちょうど40枚・同名3枚までなら通る', () => {
    const デッキ = 正しいデッキを作る();
    assert.equal(デッキ.length, 40);
    assert.equal(判定().構築が有効か(デッキ), true);
  });

  await t.test('39枚だと通らない', () => {
    const デッキ = 正しいデッキを作る().slice(0, 39);
    assert.equal(判定().枚数が有効か(デッキ), false);
    assert.equal(判定().構築が有効か(デッキ), false);
  });

  await t.test('41枚だと通らない（多い側も弾く）', () => {
    const デッキ = 正しいデッキを作る();
    デッキ.push(ハーリアを作成('あまり'));
    assert.equal(判定().枚数が有効か(デッキ), false);
  });

  await t.test('同名が4枚あると通らない', () => {
    const デッキ = 正しいデッキを作る();
    // 40枚を保ったまま、先頭のカードと同名を4枚目として混ぜる
    デッキ[39] = グンガタを作成('4枚目');
    デッキ[38] = グンガタを作成('3枚目');
    デッキ[37] = グンガタを作成('2枚目');
    デッキ[36] = グンガタを作成('1枚目');
    // 元々の先頭3枚もグン＝ガタなので合計7枚になる
    assert.equal(判定().枚数が有効か(デッキ), true, '枚数は40のまま');
    assert.equal(判定().同名の数が有効か(デッキ), false);
    assert.equal(判定().構築が有効か(デッキ), false);
  });
});
