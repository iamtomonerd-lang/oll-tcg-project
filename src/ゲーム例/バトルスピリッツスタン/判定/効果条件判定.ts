// 対象の選択ができる領域（9-2-2）
export type 対象選択領域 = 'フィールド' | '手札' | 'トラッシュ';

// 対象の選択の定義
// 「～を指定する。」（必須）／「～を指定できる。」（任意）でフィールド・手札・トラッシュの
// カードを選択する場合を指す（9-2-2）。
export interface 対象選択 {
  領域: 対象選択領域[];
  必須: boolean; // true＝指定する（必須）、false＝指定できる（任意）
}

// 効果条件判定（ルール層 ＝ 状態を返すだけ）
export class 効果条件判定 {
  // 対象の選択がこの領域を含むか
  選択可能な領域か(対象選択: 対象選択, 領域: 対象選択領域): boolean {
    return 対象選択.領域.includes(領域);
  }

  // 対象の選択が必須か（「指定する」）
  選択必須か(対象選択: 対象選択): boolean {
    return 対象選択.必須;
  }

  // 効果が発揮できるか
  // 9-2-1：条件を満たさない限り発揮しない
  // 9-2-3：条件を満たしていても「できない」効果による制限があれば発揮しない（制限が優先）
  発揮できるか(条件を満たしているか: boolean, できない効果による制限があるか: boolean): boolean {
    if (できない効果による制限があるか) {
      return false;
    }
    return 条件を満たしているか;
  }
}
