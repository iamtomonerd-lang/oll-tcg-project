// デッキ構築判定（ルール層 ＝ 状態を返すだけ）
//
// バトルスピリッツのデッキの決まり：
//   ・ちょうど40枚（多くても少なくても組めない）
//   ・同じカード名は3枚まで
//
// 「同名」はカード名で数える。カードナンバーではない。
// 別の番号で同じ名前のカードが出たとき、番号で数えると4枚以上入ってしまう。
//
// ソウルコアはデッキの40枚には含まれない（コアであってカードではない）ので扱わない。
//
// 数え方が2通りあるのは、聞かれ方が2通りあるため。
//   構築（カードナンバー→枚数）… デッキ構築の画面が組み立て中に聞く
//   カード[]                   … 出来上がったデッキが規則を満たすか聞く

import { カード } from '../../../データ/カード/カード.js';
import { カード名ルール } from '../カードの情報/カード名.js';
import { 番号からカード名を引く, 番号は実在するか } from '../カードデータ/カード帳.js';

export const デッキの枚数 = 40;
export const 同名の上限 = 3;

// デッキの中身。カードナンバー → 枚数。
export type 構築 = Record<string, number>;

export type 問題の種別 =
  | '知らないカード'
  | '枚数が不正'
  | '同名が多すぎる'
  | '合計が足りない'
  | '合計が多すぎる';

export interface 構築の問題 {
  種別: 問題の種別;
  // 画面にそのまま出せる文言
  説明: string;
  カードナンバー?: string;
  カード名?: string;
  枚数?: number;
}

export interface 検証結果 {
  組めるか: boolean;
  合計: number;
  問題: 構築の問題[];
}

export class デッキ構築判定 {
  private カード名ルール = new カード名ルール();

  readonly 必要枚数 = デッキの枚数;
  readonly 同名の上限 = 同名の上限;

  // === 構築（カードナンバー→枚数）を見る ===

  合計枚数を数える(構築: 構築): number {
    let 合計 = 0;
    for (const 枚数 of Object.values(構築)) {
      if (Number.isInteger(枚数) && 枚数 > 0) 合計 += 枚数;
    }
    return 合計;
  }

  // カード名ごとの枚数。同名が複数の番号にまたがっていてもまとめて数える。
  カード名ごとに数える(構築: 構築): Map<string, number> {
    const 集計 = new Map<string, number>();
    for (const [カードナンバー, 枚数] of Object.entries(構築)) {
      if (!Number.isInteger(枚数) || 枚数 <= 0) continue;
      const カード名 = 番号からカード名を引く(カードナンバー);
      if (カード名 === undefined) continue;
      集計.set(カード名, (集計.get(カード名) ?? 0) + 枚数);
    }
    return 集計;
  }

  検証する(構築: 構築): 検証結果 {
    const 問題: 構築の問題[] = [];

    for (const [カードナンバー, 枚数] of Object.entries(構築)) {
      if (!番号は実在するか(カードナンバー)) {
        問題.push({
          種別: '知らないカード',
          説明: `「${カードナンバー}」は実装されていないカードです`,
          カードナンバー,
        });
        continue;
      }
      if (!Number.isInteger(枚数) || 枚数 < 0) {
        問題.push({
          種別: '枚数が不正',
          説明: `「${カードナンバー}」の枚数が正しくありません`,
          カードナンバー,
        });
      }
    }

    for (const [カード名, 枚数] of this.カード名ごとに数える(構築)) {
      if (枚数 > 同名の上限) {
        問題.push({
          種別: '同名が多すぎる',
          説明: `「${カード名}」が${枚数}枚あります（同じ名前は${同名の上限}枚まで）`,
          カード名,
          枚数,
        });
      }
    }

    const 合計 = this.合計枚数を数える(構築);
    if (合計 < デッキの枚数) {
      問題.push({
        種別: '合計が足りない',
        説明: `あと${デッキの枚数 - 合計}枚（デッキはちょうど${デッキの枚数}枚）`,
      });
    } else if (合計 > デッキの枚数) {
      問題.push({
        種別: '合計が多すぎる',
        説明: `${合計 - デッキの枚数}枚多いです（デッキはちょうど${デッキの枚数}枚）`,
      });
    }

    return { 組めるか: 問題.length === 0, 合計, 問題 };
  }

  // そのカードをあと何枚足せるか。画面の「＋」を止めるのに使う。
  // 同名の上限と、デッキ全体の残り枠の小さいほうで決まる。
  あと何枚足せるか(構築: 構築, カードナンバー: string): number {
    if (!番号は実在するか(カードナンバー)) return 0;
    const カード名 = 番号からカード名を引く(カードナンバー)!;
    const 同名の残り = 同名の上限 - (this.カード名ごとに数える(構築).get(カード名) ?? 0);
    const 全体の残り = デッキの枚数 - this.合計枚数を数える(構築);
    return Math.max(0, Math.min(同名の残り, 全体の残り));
  }

  // === 出来上がったデッキ（カードの列）を見る ===

  // ちょうど40枚か
  枚数が有効か(デッキ: カード[]): boolean {
    return デッキ.length === デッキの枚数;
  }

  // 同じカード名が3枚を超えていないか
  同名の数が有効か(デッキ: カード[]): boolean {
    const 集計 = new Map<string, number>();
    for (const 札 of デッキ) {
      const 名 = this.カード名ルール.カード名を取得(札);
      集計.set(名, (集計.get(名) ?? 0) + 1);
    }
    for (const 枚数 of 集計.values()) {
      if (枚数 > 同名の上限) return false;
    }
    return true;
  }

  // デッキ構築全体が規則を満たすか
  構築が有効か(デッキ: カード[]): boolean {
    return this.枚数が有効か(デッキ) && this.同名の数が有効か(デッキ);
  }
}
