import { カード } from '../../../データ/カード/カード.js';

// デッキ構築判定（ルール層 ＝ 状態を返すだけ）
// ゲーム準備：各プレイヤーは開始前にデッキを用意する。デッキは40枚以上で構築する。
// 今後の構築ルール（同名上限・使用可能カード制限など）もここに集約していく。
export class デッキ構築判定 {
  readonly 最小枚数 = 40;

  // 枚数が構築条件（40枚以上）を満たすか
  枚数が有効か(デッキ: カード[]): boolean {
    return デッキ.length >= this.最小枚数;
  }

  // デッキ構築全体が有効か（現時点では枚数のみ）
  構築が有効か(デッキ: カード[]): boolean {
    return this.枚数が有効か(デッキ);
  }
}
