import { カード } from '../../../データ/カード/カード.js';

// バトル判定（ルール層 ＝ 状態を返すだけ）
// アタック中／ブロック中／バトル中の状態を照会する。
// これらの状態はバトル管理が付与・解除する。
export class バトル判定 {
  アタック中か(カード: カード): boolean {
    return カード.状態を取得('アタック中') === true;
  }

  ブロック中か(カード: カード): boolean {
    return カード.状態を取得('ブロック中') === true;
  }

  // バトル中か（アタック中またはブロック中のスピリットは「バトル中」）
  バトル中か(カード: カード): boolean {
    return this.アタック中か(カード) || this.ブロック中か(カード);
  }
}
