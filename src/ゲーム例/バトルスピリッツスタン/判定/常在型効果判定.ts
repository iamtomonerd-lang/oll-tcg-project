import { カード } from '../../../データ/カード/カード.js';

// 常在型効果の定義
// - 発揮領域：この効果が発揮され得る領域（カードの状態が置かれている場所）の一覧
// - 条件    ：追加の発揮条件（省略時は領域にあるだけで発揮）
// ※効果の具体的な処理内容は効果システム側（未実装）の担当。ここは発揮しているかどうかの判定のみ。
export interface 常在型効果 {
  発揮領域: string[];
  条件?: (カード: カード) => boolean;
}

// 常在型効果判定（ルール層 ＝ 状態を返すだけ）
export class 常在型効果判定 {
  // 常在型効果が今、発揮しているか
  // 9-1-4-2: 効果を発揮する領域にある間、常に発揮する
  // 9-1-4-3: 条件がある場合は、領域にあり かつ 条件を満たす間のみ発揮する
  // 9-1-4-4: 誘発・発揮待ちの順番を待たず、領域に出た時点から即座に発揮する
  //          （＝解決キューを介さないため、この判定を都度呼び出すだけで足りる）
  発揮しているか(効果: 常在型効果, 現在の領域: string, カード: カード): boolean {
    if (!効果.発揮領域.includes(現在の領域)) {
      return false;
    }
    if (効果.条件 && !効果.条件(カード)) {
      return false;
    }
    return true;
  }
}
