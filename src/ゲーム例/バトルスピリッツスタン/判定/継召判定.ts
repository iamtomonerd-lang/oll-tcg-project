import { カード } from '../../../データ/カード/カード.js';
import { シンボルルール } from '../カードの情報/シンボル.js';
import { 軽減シンボルルール } from '../カードの情報/軽減シンボル.js';

// 継召判定（ルール層 ＝ 状態を返すだけ）
// 《継召》：トラッシュにあるEXシンボルを持つカードをゲームから除外して、除外したカード1枚につき、
// 召喚・配置・使用するカードの軽減シンボル1つを満たすことができる共通効果（12-2-1-3-1）。
export class 継召判定 {
  private シンボルルール: シンボルルール;
  private 軽減シンボルルール: 軽減シンボルルール;

  constructor() {
    this.シンボルルール = new シンボルルール();
    this.軽減シンボルルール = new 軽減シンボルルール();
  }

  // このカードは継召で除外できるか（EXシンボルを持つか）
  除外できるか(カード: カード): boolean {
    return this.シンボルルール.EXシンボルを持つ(カード);
  }

  // 継召とフィールドのシンボルによる軽減は、同じ軽減シンボルの枠を分け合う（12-2-1-3-2：
  // フィールドのシンボルで軽減をする前に継召を発揮して満たすことができる、という順序関係のため）。
  // 残り枠 ＝ 軽減シンボルの総数 − フィールドのシンボルで既に満たした数。
  残り枠を取得(対象カード: カード, フィールドのシンボル: string[]): number {
    const 軽減シンボル数 = this.軽減シンボルルール.軽減シンボルを取得(対象カード).length;
    const フィールドで満たした数 = this.軽減シンボルルール.軽減可能な数を計算(対象カード, フィールドのシンボル);
    return Math.max(0, 軽減シンボル数 - フィールドで満たした数);
  }

  // 除外できる最大枚数：残り枠（軽減シンボルの総数からフィールドで満たした分を除いた数）を
  // 超えて除外することはできない（12-2-1-3-2-1）
  除外できる最大枚数(対象カード: カード, 除外候補一覧: カード[], フィールドのシンボル: string[]): number {
    const 残り枠 = this.残り枠を取得(対象カード, フィールドのシンボル);
    const EXシンボルを持つ候補数 = 除外候補一覧.filter(候補 => this.除外できるか(候補)).length;
    return Math.min(残り枠, EXシンボルを持つ候補数);
  }

  // 指定した除外するカード一覧が、除外可能な範囲内か（12-2-1-3-2-1）
  除外は有効か(対象カード: カード, 除外するカード一覧: カード[], フィールドのシンボル: string[]): boolean {
    if (!除外するカード一覧.every(カード => this.除外できるか(カード))) {
      return false;
    }
    const 残り枠 = this.残り枠を取得(対象カード, フィールドのシンボル);
    return 除外するカード一覧.length <= 残り枠;
  }
}
