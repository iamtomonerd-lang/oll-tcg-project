import { test } from 'node:test';
import assert from 'node:assert/strict';

import { グンガタを作成 } from '../カードデータ/グンガタ.js';
import { 表示形式判定 } from './表示形式判定.js';

test('現在の表示形式を取得：未設定のカードは既定で回復を返す', () => {
  const カード = グンガタを作成('test-1');
  assert.equal(new 表示形式判定().現在の表示形式を取得(カード), '回復');
});

test('回復か／疲労か／重疲労か：状態を正しく判定する', () => {
  const 判定 = new 表示形式判定();
  const カード = グンガタを作成('test-2');

  assert.equal(判定.回復か(カード), true);
  カード.状態を設定('表示形式', '疲労');
  assert.equal(判定.疲労か(カード), true);
  assert.equal(判定.回復か(カード), false);
  カード.状態を設定('表示形式', '重疲労');
  assert.equal(判定.重疲労か(カード), true);
});

test('回復できるか：回復状態でなければ回復できる、回復状態なら回復できない', () => {
  const 判定 = new 表示形式判定();
  const カード = グンガタを作成('test-3');
  assert.equal(判定.回復できるか(カード), false);
  カード.状態を設定('表示形式', '疲労');
  assert.equal(判定.回復できるか(カード), true);
});

test('回復後の表示形式：重疲労→疲労、疲労→回復、回復→回復', () => {
  const 判定 = new 表示形式判定();
  const カード = グンガタを作成('test-4');

  assert.equal(判定.回復後の表示形式(カード), '回復');
  カード.状態を設定('表示形式', '疲労');
  assert.equal(判定.回復後の表示形式(カード), '回復');
  カード.状態を設定('表示形式', '重疲労');
  assert.equal(判定.回復後の表示形式(カード), '疲労');
});

test('疲労できるか：回復状態のときのみ疲労できる', () => {
  const 判定 = new 表示形式判定();
  const カード = グンガタを作成('test-5');
  assert.equal(判定.疲労できるか(カード), true);
  カード.状態を設定('表示形式', '疲労');
  assert.equal(判定.疲労できるか(カード), false);
  カード.状態を設定('表示形式', '重疲労');
  assert.equal(判定.疲労できるか(カード), false);
});

test('重疲労できるか：既に重疲労でなければ、回復・疲労のどちらからでもできる', () => {
  const 判定 = new 表示形式判定();
  const カード = グンガタを作成('test-6');
  assert.equal(判定.重疲労できるか(カード), true);
  カード.状態を設定('表示形式', '疲労');
  assert.equal(判定.重疲労できるか(カード), true);
  カード.状態を設定('表示形式', '重疲労');
  assert.equal(判定.重疲労できるか(カード), false);
});
