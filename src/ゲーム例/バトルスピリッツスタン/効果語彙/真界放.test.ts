import assert from 'node:assert';
import { 試合 } from '../試合.js';
import { カード } from '../../../データ/カード/カード.js';
import { 真界放判定 } from '../判定/真界放判定.js';
import { グライファーを作成 } from '../カードデータ/グライファー.js';
import { グンガタを作成 } from '../カードデータ/グンガタ.js';

// 《真界放》の2つの規則を分けて押さえる。
//
//   12-2-1-1-2 … Lv2コストのコアを置かなくても、ソウルコア1個でLv2になる（Lvへの到達）
//   12-2-1-1-3 … 《真界放》を持つカードがLv2のとき、真界放状態になる（状態の判定）
//
// この2つは別物で、混同すると次の取り違えが起きる。
//   ・「ソウルコアが無いとLv2でも真界放状態でない」… 誤り。状態はLv2かどうかだけで決まる
//   ・「真界放を持てば常に真界放状態」          … 誤り。Lv1なら状態ではない
//
// さらに、真界放状態は自分自身の条件判定だけでなく、
// 他のカードを対象にとる絞り込み（カードフィルタの 真界放）でも使われる。
// 「真界放していない相手のスピリット」を対象にとる効果が出たときに壊れていないよう、
// ここで両方向（true / false）を固定しておく。

// グライファー：Lv1 コスト1／Lv2 コスト3・真界放
// グン＝ガタ  ：Lv1 コスト1／Lv2 コスト3・真界放を持たない（対照用）

function 試合を準備する(): 試合 {
  const 試合インスタンス = new 試合();
  試合インスタンス.プレイヤーを準備する('p1', 'プレイヤー1');
  試合インスタンス.プレイヤーを準備する('p2', 'プレイヤー2');
  試合インスタンス.ボイドを準備する();
  試合インスタンス.デッキを設定する(
    'p1',
    Array.from({ length: 10 }, (_, i) => グンガタを作成(`p1-deck-${i + 1}`))
  );
  試合インスタンス.デッキを設定する(
    'p2',
    Array.from({ length: 10 }, (_, i) => グンガタを作成(`p2-deck-${i + 1}`))
  );
  試合インスタンス.準備を行う('p1');
  試合インスタンス.準備を行う('p2');
  試合インスタンス.先攻を決める('p1');
  試合インスタンス.試合を開始する();
  return 試合インスタンス;
}

// コアを載せ、コア移動と同じ経路でLvを同期させる
function 場に置く(
  試合インスタンス: 試合,
  持ち主: string,
  対象: カード,
  コア数: number,
  ソウルコア = false
): カード {
  試合インスタンス.ゾーン管理.フィールドを取得(試合インスタンス.ゲーム, 持ち主)!.カードを追加(対象);
  const 保持者 = 試合インスタンス.コア管理.カードを保持者に(対象);
  保持者.コア数を設定(コア数);
  保持者.ソウルコアを設定(ソウルコア);
  試合インスタンス.Lv管理.Lvを更新(対象, 保持者.コア数を取得(), 保持者.ソウルコアあるか());
  return 対象;
}

const 真界放状態か = (試合インスタンス: 試合, 対象: カード): boolean =>
  new 真界放判定().真界放状態か(対象, 試合インスタンス.Lv管理.現在のLvを取得(対象));

test('《真界放》12-2-1-1-2：ソウルコア1個でLv2に到達できる', async t => {
  await t.test('真界放を持つなら、Lv2コストに届かなくてもソウルコア1個でLv2', () => {
    const 試合インスタンス = 試合を準備する();
    // グライファーのLv2コストは3。コアは1個しかないが、それがソウルコアならLv2。
    const 対象 = 場に置く(試合インスタンス, 'p1', グライファーを作成('真界放持ち'), 1, true);

    assert.equal(試合インスタンス.Lv管理.現在のLvを取得(対象), 2);
  });

  await t.test('真界放を持たないカードは、ソウルコア1個ではLv2にならない', () => {
    const 試合インスタンス = 試合を準備する();
    // グン＝ガタもLv2コストは3だが、真界放を持たないのでコア数で判定される
    const 対象 = 場に置く(試合インスタンス, 'p1', グンガタを作成('真界放なし'), 1, true);

    assert.equal(試合インスタンス.Lv管理.現在のLvを取得(対象), 1);
  });
});

test('《真界放》12-2-1-1-3：真界放状態はLv2かどうかだけで決まる', async t => {
  await t.test('ソウルコア1個でLv2になった場合、真界放状態', () => {
    const 試合インスタンス = 試合を準備する();
    const 対象 = 場に置く(試合インスタンス, 'p1', グライファーを作成('対象'), 1, true);

    assert.equal(真界放状態か(試合インスタンス, 対象), true);
  });

  // ここが取り違えやすい。ソウルコアはLv2へ到達する手段の1つにすぎず、
  // 通常コアだけでLv2にしたカードも等しく真界放状態になる。
  await t.test('通常コアだけでLv2になった場合も、同じく真界放状態', () => {
    const 試合インスタンス = 試合を準備する();
    const 対象 = 場に置く(試合インスタンス, 'p1', グライファーを作成('対象'), 3, false);

    assert.equal(試合インスタンス.Lv管理.現在のLvを取得(対象), 2);
    assert.equal(真界放状態か(試合インスタンス, 対象), true, 'ソウルコアの有無は状態に関わらない');
  });

  await t.test('Lv1なら、真界放を持っていても真界放状態ではない', () => {
    const 試合インスタンス = 試合を準備する();
    const 対象 = 場に置く(試合インスタンス, 'p1', グライファーを作成('対象'), 1, false);

    assert.equal(試合インスタンス.Lv管理.現在のLvを取得(対象), 1);
    assert.equal(真界放状態か(試合インスタンス, 対象), false);
  });

  await t.test('真界放を持たないカードは、Lv2でも真界放状態にならない', () => {
    const 試合インスタンス = 試合を準備する();
    const 対象 = 場に置く(試合インスタンス, 'p1', グンガタを作成('真界放なし'), 3, false);

    assert.equal(試合インスタンス.Lv管理.現在のLvを取得(対象), 2);
    assert.equal(真界放状態か(試合インスタンス, 対象), false);
  });

  await t.test('コアが減ってLv1に落ちたら、真界放状態も解ける', () => {
    const 試合インスタンス = 試合を準備する();
    const 対象 = 場に置く(試合インスタンス, 'p1', グライファーを作成('対象'), 3, false);
    assert.equal(真界放状態か(試合インスタンス, 対象), true);

    // 相手の効果でコアを剥がされた場面
    const 保持者 = 試合インスタンス.コア管理.カードを保持者に(対象);
    保持者.コア数を設定(1);
    試合インスタンス.Lv管理.Lvを更新(対象, 1, false);

    assert.equal(試合インスタンス.Lv管理.現在のLvを取得(対象), 1);
    assert.equal(真界放状態か(試合インスタンス, 対象), false, '状態は取り残されない');
  });
});

// === 他のカードを対象にとるときの絞り込み ===

// 「真界放している／していない 相手のスピリット1体を破壊する」だけを持つ検証用カード
function 破壊カードを作る(識別子: string, 真界放フィルタ: boolean): カード {
  return new カード(識別子, {
    識別子,
    表示名: 識別子,
    カード名: 識別子,
    カードナンバー: 'TEST-真界放',
    カード種別: 'スピリット',
    レアリティ: 'C',
    コスト: 1,
    系統: ['試験'],
    ブロックアイコン: 'A',
    属性: ['赤'],
    Lv: [{ level: 1, cost: 1, bp: 1000 }],
    効果: [
      {
        Lv: [1],
        トリガー: 'アタック時',
        処理: [
          { 選択: { 場: '相手', 種別: 'スピリット', 真界放: 真界放フィルタ, 数: 1 } },
          { 破壊: '選択' },
        ],
      },
    ],
  } as any);
}

// 相手の場に「真界放している」と「していない」を1体ずつ置いて撃たせ、
// どちらが選ばれたかを見る。
function 撃って破壊されたものを返す(真界放フィルタ: boolean): string[] {
  const 試合インスタンス = 試合を準備する();
  場に置く(試合インスタンス, 'p2', グライファーを作成('真界放している'), 1, true);
  場に置く(試合インスタンス, 'p2', グライファーを作成('真界放していない'), 1, false);

  const 主 = 破壊カードを作る('主', 真界放フィルタ);
  試合インスタンス.ゾーン管理.フィールドを取得(試合インスタンス.ゲーム, 'p1')!.カードを追加(主);
  試合インスタンス.効果実行器.事象を通知する('アタック時', 主);
  試合インスタンス.効果実行器.キューを進める();

  return 試合インスタンス.ゾーン管理
    .フィールドを取得(試合インスタンス.ゲーム, 'p2')!
    .カード一覧を取得()
    .filter(c => 試合インスタンス.待機状態管理.待機状態か(c))
    .map(c => c.識別子);
}

test('《真界放》他のカードを対象にとるときも真界放を判定する', async t => {
  await t.test('真界放:true は、真界放しているスピリットだけを対象にとる', () => {
    assert.deepEqual(撃って破壊されたものを返す(true), ['真界放している']);
  });

  // 「真界放していない相手のスピリット」を対象にとる効果のための経路。
  // ここが素通りすると、真界放しているスピリットまで巻き込んで破壊してしまう。
  await t.test('真界放:false は、真界放していないスピリットだけを対象にとる', () => {
    assert.deepEqual(撃って破壊されたものを返す(false), ['真界放していない']);
  });
});
