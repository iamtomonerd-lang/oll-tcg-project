// 期限付き効果（このバトル中／このターン中）と〔ターン1回〕、
// および【起動】効果の発動導線を確認する。

function 検証カードを作る(識別子: string, 効果?: 効果定義[]): カード {
  return new カード(識別子, {
    識別子,
    表示名: 識別子,
    カード名: 識別子,
    カードナンバー: 'TEST-000',
    カード種別: 'スピリット',
    レアリティ: 'C',
    コスト: 1,
    系統: ['風牙'],
    ブロックアイコン: 'A',
    属性: ['赤'],
    軽減シンボル: [],
    シンボル: [],
    Lv: [
      { level: 1, cost: 1, bp: 3000 },
      { level: 2, cost: 3, bp: 5000 },
    ],
    効果,
  } as any);
}

function 試合を準備する(): 試合 {
  const 試合インスタンス = new 試合();
  試合インスタンス.プレイヤーを準備する('p1', 'プレイヤー1');
  試合インスタンス.プレイヤーを準備する('p2', 'プレイヤー2');
  試合インスタンス.ボイドを準備する();
  試合インスタンス.デッキを設定する(
    'p1',
    Array.from({ length: 15 }, (_, i) => 検証カードを作る(`p1-deck-${i + 1}`))
  );
  試合インスタンス.デッキを設定する(
    'p2',
    Array.from({ length: 15 }, (_, i) => グンガタを作成(`p2-deck-${i + 1}`))
  );
  試合インスタンス.準備を行う('p1');
  試合インスタンス.準備を行う('p2');
  試合インスタンス.先攻を決める('p1');
  試合インスタンス.試合を開始する();
  return 試合インスタンス;
}

function 場に出す(試合インスタンス: 試合, プレイヤー識別子: string, 対象: カード, BP = 3000): カード {
  試合インスタンス.ゾーン管理
    .フィールドを取得(試合インスタンス.ゲーム, プレイヤー識別子)!
    .カードを追加(対象);
  試合インスタンス.BP管理.BPを設定(対象, BP);
  return 対象;
}

// === このバトル中 ===

test('このバトル中：バトルが終わるとBPが元に戻る', () => {
  const 試合インスタンス = 試合を準備する();

  const アタッカー = 場に出す(
    試合インスタンス,
    'p1',
    検証カードを作る('アタッカー', [
      {
        トリガー: 'アタック時',
        処理: [{ BP変更: { 対象: '自身', 値: 3000, 期間: 'このバトル中' } }],
      },
    ])
  );

  試合インスタンス.アタック宣言する(アタッカー);
  assert.equal(試合インスタンス.BP管理.現在のBPを取得(アタッカー), 6000, 'アタック時にBPが上がる');
  assert.equal(試合インスタンス.一時効果管理.記録数を取得('このバトル中'), 1);

  // ブロックされずにバトルが解決される
  試合インスタンス.バトルを解決する(アタッカー, null);

  assert.equal(試合インスタンス.BP管理.現在のBPを取得(アタッカー), 3000, 'バトル終了で元に戻る');
  assert.equal(試合インスタンス.一時効果管理.記録数を取得('このバトル中'), 0, '記録も消える');
});

// === このターン中 ===

test('このターン中：ターンが終わるとBPが元に戻る', () => {
  const 試合インスタンス = 試合を準備する();

  const 対象 = 場に出す(試合インスタンス, 'p1', 検証カードを作る('対象'));
  const 起点 = 場に出す(
    試合インスタンス,
    'p1',
    検証カードを作る('起点', [
      {
        トリガー: 'アタック時',
        処理: [{ BP変更: { 対象: '自身', 値: 2000, 期間: 'このターン中' } }],
      },
    ])
  );

  試合インスタンス.アタック宣言する(起点);
  assert.equal(試合インスタンス.BP管理.現在のBPを取得(起点), 5000);

  // バトルを終えても「このターン中」はまだ戻らない
  試合インスタンス.バトルを解決する(起点, null);
  assert.equal(
    試合インスタンス.BP管理.現在のBPを取得(起点),
    5000,
    'バトル終了では「このターン中」は戻らない'
  );

  // ターンを終わらせる
  let 安全カウンタ = 0;
  while (試合インスタンス.ゲーム.現在のプレイヤーを取得()?.識別子 === 'p1' && 安全カウンタ++ < 10) {
    試合インスタンス.ステップを終了する();
  }

  assert.equal(試合インスタンス.BP管理.現在のBPを取得(起点), 3000, 'ターン終了で元に戻る');
  assert.equal(試合インスタンス.BP管理.現在のBPを取得(対象), 3000);
});

