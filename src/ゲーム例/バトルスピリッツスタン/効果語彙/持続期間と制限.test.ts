// === 起動効果 ===

const 起動効果: 効果定義 = {
  種別: '起動',
  タイミング: 'フラッシュ',
  状態: 'アタック中',
  制限: 'ターン1回',
  コスト: [{ 疲労: '自身' }],
  処理: [{ BP変更: { 対象: '自身', 値: 3000, 期間: 'このバトル中' } }],
};

test('起動効果：条件を満たすときだけ候補に出る', async t => {
  await t.test('持続状態を満たさなければ候補に出ない', () => {
    const 試合インスタンス = 試合を準備する();
    場に出す(試合インスタンス, 'p1', 検証カードを作る('起動持ち', [起動効果]));

    const 候補 = 試合インスタンス.効果実行器.発動できる起動効果を集める('p1');
    assert.equal(候補.length, 0, 'アタック中でないので撃てない');
  });

  await t.test('持続状態を満たせば候補に出る', () => {
    const 試合インスタンス = 試合を準備する();
    const カード1 = 場に出す(試合インスタンス, 'p1', 検証カードを作る('起動持ち', [起動効果]));
    カード1.状態を設定('アタック中', true);

    const 候補 = 試合インスタンス.効果実行器.発動できる起動効果を集める('p1');
    assert.equal(候補.length, 1);
    assert.equal(候補[0].発揮源.識別子, '起動持ち');
    assert.equal(候補[0].タイミング, 'フラッシュ');
  });

  await t.test('タイミングで絞り込める', () => {
    const 試合インスタンス = 試合を準備する();
    const カード1 = 場に出す(試合インスタンス, 'p1', 検証カードを作る('起動持ち', [起動効果]));
    カード1.状態を設定('アタック中', true);

    assert.equal(
      試合インスタンス.効果実行器.発動できる起動効果を集める('p1', 'フラッシュ').length,
      1
    );
    assert.equal(試合インスタンス.効果実行器.発動できる起動効果を集める('p1', 'メイン').length, 0);
  });

  await t.test('相手の起動効果は自分の候補に出ない', () => {
    const 試合インスタンス = 試合を準備する();
    const カード1 = 場に出す(試合インスタンス, 'p2', 検証カードを作る('相手の起動持ち', [起動効果]));
    カード1.状態を設定('アタック中', true);

    assert.equal(試合インスタンス.効果実行器.発動できる起動効果を集める('p1').length, 0);
    assert.equal(試合インスタンス.効果実行器.発動できる起動効果を集める('p2').length, 1);
  });
});

test('起動効果：発動するとコストを払って効果が走る', () => {
  const 試合インスタンス = 試合を準備する();
  const カード1 = 場に出す(試合インスタンス, 'p1', 検証カードを作る('起動持ち', [起動効果]));
  カード1.状態を設定('アタック中', true);

  const 候補 = 試合インスタンス.効果実行器.発動できる起動効果を集める('p1');
  const 結果 = 試合インスタンス.効果実行器.起動効果を発動する('p1', 候補[0].効果識別子);

  assert.equal(結果.状態, 'アイドル');
  assert.equal(
    試合インスタンス.カードの表示形式管理.現在の表示形式を取得(カード1),
    '疲労',
    'コストとして疲労している'
  );
  assert.equal(試合インスタンス.BP管理.現在のBPを取得(カード1), 6000, '効果でBPが上がっている');
});

test('起動効果：同じターンに2度は撃てない', () => {
  const 試合インスタンス = 試合を準備する();
  const カード1 = 場に出す(試合インスタンス, 'p1', 検証カードを作る('起動持ち', [起動効果]));
  カード1.状態を設定('アタック中', true);

  const 候補 = 試合インスタンス.効果実行器.発動できる起動効果を集める('p1');
  試合インスタンス.効果実行器.起動効果を発動する('p1', 候補[0].効果識別子);

  // 撃った後は候補から消える
  assert.equal(
    試合インスタンス.効果実行器.発動できる起動効果を集める('p1').length,
    0,
    'ターン1回を使い切ったので候補から外れる'
  );

  // 直接指定しても撃てない
  const 再発動 = 試合インスタンス.効果実行器.起動効果を発動する('p1', 候補[0].効果識別子);
  assert.equal(再発動.状態, 'アイドル');
  assert.ok(
    再発動.ログ.some(行 => 行.includes('発動できません')),
    '撃てない理由が返る'
  );
});

