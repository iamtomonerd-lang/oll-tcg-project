import { カード } from '../../../データ/カード/カード.js';
import { ゾーン } from '../../../データ/ゾーン/ゾーン.js';
import type { 試合 } from '../試合.js';
import {
  アクション結果,
  ゲーム接続,
  実行文脈,
  対象を解決,
  決定依頼,
} from '../../../効果解釈/ゲーム接続.js';
import {
  カードフィルタ,
  コア位置,
  処理ステップ,
  決定者,
  発動条件,
  期間,
} from '../../../効果解釈/効果定義.js';
import { カード種別ルール } from '../カードの情報/カード種別.js';
import { 属性ルール } from '../カードの情報/属性.js';
import { 系統ルール } from '../カードの情報/系統.js';
import { コストルール } from '../カードの情報/コスト.js';
import { カード名ルール } from '../カードの情報/カード名.js';
