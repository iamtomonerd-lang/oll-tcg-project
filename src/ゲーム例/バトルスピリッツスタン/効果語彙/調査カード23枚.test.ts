interface スピリット指定 {
  カード名?: string;
  系統?: string[];
  属性?: string[];
  キーワード?: string[];
  種別?: string;
  真界放?: boolean;
  コスト?: number;
}

// フィルタの各項目を狙って検証できるよう、属性を自由に指定できるカードを作る
function 検証カードを作る(識別子: string, 指定: スピリット指定 = {}): カード {
  return new カード(識別子, {
    識別子,
    表示名: 指定.カード名 ?? '検証スピリット',
    カード名: 指定.カード名 ?? '検証スピリット',
    カードナンバー: 'TEST-000',
    カード種別: 指定.種別 ?? 'スピリット',
    レアリティ: 'C',
    コスト: 指定.コスト ?? 3,
    系統: 指定.系統 ?? ['風牙'],
    ブロックアイコン: 'A',
    属性: 指定.属性 ?? ['赤'],
    軽減シンボル: ['赤'],
    シンボル: [{ 色: '赤' }],
    Lv: [
      { level: 1, cost: 1, bp: 3000 },
      { level: 2, cost: 3, bp: 5000, 真界放: 指定.真界放 === true ? true : undefined },
    ],
    キーワード: 指定.キーワード,
  } as any);
}

function 試合を準備する(): 試合 {
  const 試合インスタンス = new 試合();
  試合インスタンス.プレイヤーを準備する('p1', 'プレイヤー1');
  試合インスタンス.プレイヤーを準備する('p2', 'プレイヤー2');
  試合インスタンス.ボイドを準備する();
  試合インスタンス.デッキを設定する(
    'p1',
    Array.from({ length: 12 }, (_, i) => 検証カードを作る(`p1-deck-${i + 1}`))
  );
  試合インスタンス.デッキを設定する(
    'p2',
    Array.from({ length: 12 }, (_, i) => グンガタを作成(`p2-deck-${i + 1}`))
  );
  試合インスタンス.準備を行う('p1');
  試合インスタンス.準備を行う('p2');
  試合インスタンス.先攻を決める('p1');
  return 試合インスタンス;
}

function 環境を作る() {
  const 試合インスタンス = 試合を準備する();
  const インタプリタ = new 効果インタプリタ(new バトスピ接続(試合インスタンス));
  return { 試合: 試合インスタンス, インタプリタ };
}

function 場に出す(試合インスタンス: 試合, プレイヤー識別子: string, カード: カード, BP?: number): カード {
  const フィールド = 試合インスタンス.ゾーン管理.フィールドを取得(試合インスタンス.ゲーム, プレイヤー識別子)!;
  フィールド.カードを追加(カード);
  // 場のカードには必ずコアが乗っている。乗せずに置くと、ルール処理の消滅判定に
  // 引っかかって即トラッシュ行きになる（実戦では起こらない状態）。
  // Lv1を保てる最小限だけ乗せる。Lvを変えたいテストは、このあとで自分で乗せ直す。
  試合インスタンス.コア管理
    .カードを保持者に(カード)
    .コア数を設定(new 消滅判定().最小必要コア数を取得(カード));
  if (BP !== undefined) {
    試合インスタンス.BP管理.BPを設定(カード, BP);
  }
  return カード;
}

function トラッシュに入れる(試合インスタンス: 試合, プレイヤー識別子: string, カード: カード): カード {
  const トラッシュ = 試合インスタンス.ゾーン管理.トラッシュを取得(試合インスタンス.ゲーム, プレイヤー識別子)!;
  トラッシュ.カードを追加(カード);
  return カード;
}

function ゾーンにコアを置く(試合インスタンス: 試合, 領域: ゾーン, 個数: number): void {
  const 保持者 = 試合インスタンス.コア管理.ゾーンを保持者に(領域);
  保持者.コア数を設定(保持者.コア数を取得() + 個数);
}

// 選択が来たら常に最大数を選んで、完了か失敗まで進める
function 最後まで実行する(
  インタプリタ: 効果インタプリタ,
  効果: 効果定義,
  自身: カード,
  プレイヤー識別子: string
): 実行結果 {
  let 結果 = インタプリタ.実行(効果, 自身, プレイヤー識別子);
  let 安全カウンタ = 0;
  while (結果.状態 === '選択待ち' && 安全カウンタ++ < 10) {
    const 選ぶ = 結果.候補.slice(0, 結果.最大).map(c => c.識別子);
    結果 = インタプリタ.再開(結果.中断状態, 選ぶ);
  }
  return 結果;
}

