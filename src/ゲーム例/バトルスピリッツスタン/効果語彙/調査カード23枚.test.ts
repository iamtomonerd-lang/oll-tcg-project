test('調査した21枚（効果を持つカード）がすべて実行できる', async t => {
  for (const { 番号, 効果 } of 全効果) {
    await t.test(`カード${番号} が未知の語彙なしで最後まで走る`, () => {
      const { 試合: 試合インスタンス, インタプリタ } = 環境を作る();

      // どの効果でも何らかの対象が見つかるよう、盤面を厚めに用意する
      const 味方 = 場に出す(試合インスタンス, 'p1', 検証カードを作る('味方1'), 4000);
      試合インスタンス.カードの表示形式管理.疲労する(味方);
      味方.状態を設定('アタック中', true);

      場に出す(試合インスタンス, 'p1', 検証カードを作る('味方2', { キーワード: ['継召'] }), 3000);
      場に出す(試合インスタンス, 'p2', グンガタを作成('相手1'), 3000);
      場に出す(
        試合インスタンス,
        'p2',
        検証カードを作る('相手ネクサス', { 種別: 'ネクサス' }),
        0
      );

      トラッシュに入れる(試合インスタンス, 'p1', 検証カードを作る('墓地1', { コスト: 2 }));
      const トラッシュ = 試合インスタンス.ゾーン管理.トラッシュを取得(試合インスタンス.ゲーム, 'p1')!;
      ゾーンにコアを置く(試合インスタンス, トラッシュ, 5);
      // ソウルコアを名指しする効果（カード6）のために1個だけ置いておく
      試合インスタンス.コア管理.ゾーンを保持者に(トラッシュ).ソウルコアを設定(true);

      const 自身 = 場に出す(試合インスタンス, 'p1', 検証カードを作る('自身', { 真界放: true }), 5000);
      試合インスタンス.Lv管理.Lvを上げる(自身, 2);
      自身.状態を設定('アタック中', true);

      const 結果 = 最後まで実行する(インタプリタ, 効果, 自身, 'p1');

      assert.equal(結果.状態, '完了', `カード${番号} が完了しなかった`);
      if (結果.状態 !== '完了') return;

      assert.equal(結果.発動した, true, `カード${番号} が発動しなかった`);

      // 語彙の抜け（未実装）だけでなく、実際に処理が空振りしていないことも見る。
      // 対象が揃った盤面を用意しているので、失敗を示すログが出ていれば語彙の不備。
      const 問題のあるログ = 結果.ログ.filter(
        行 =>
          行.includes('未知のアクション') ||
          行.includes('できませんでした') ||
          行.includes('動かせませんでした') ||
          行.includes('定まりません') ||
          行.includes('対象がいません') ||
          行.includes('対象がありません')
      );
      assert.deepEqual(問題のあるログ, [], `カード${番号} の処理が空振りしている`);

      assert.ok(結果.ログ.length > 0, `カード${番号} が何も記録していない`);
    });
  }
});

