// 効果実行器
//
// ゲームの出来事（召喚した・アタックした等）と、効果インタプリタをつなぐ層。
//   1. 事象が起きたら、条件に合う効果を既存の 誘発型効果管理 のキューへ積む
//   2. キューを順に取り出し、インタプリタで実行する
//   3. 対象選択が要るところで止まり、答えを受け取ったら続きから再開する
//
// 誘発の順序・重複排除・発揮源が場を離れた場合の除去は 誘発型効果管理 が既に持っているため、
// ここではそれを使うだけで、同じ仕組みを作り直さない。

import { カード } from '../../../データ/カード/カード.js';
import type { 試合 } from '../試合.js';
import { カードフィルタ, 効果定義 } from '../../../効果解釈/効果定義.js';
import { 効果インタプリタ, 中断状態 } from '../../../効果解釈/インタプリタ.js';
import { バトスピ接続 } from './バトスピ接続.js';
import { 効果ルール } from '../カードの情報/効果.js';

// 発揮を待っている選択
export interface 選択待ち情報 {
  発揮源: カード;
  // 誰が答えるべきか。使用中のマジックはどの領域にも属さない（11-3-1-6）ため、
  // 発揮源の位置から持ち主を引くことはできない。ここで明示的に持つ。
  所有者識別子: string;
  効果識別子: string;
  候補: カード[];
  最小: number;
  最大: number;
  任意: boolean;
  // カードを選ぶのではない判断（「置くコアは相手が選ぶ」など）のとき、
  // 候補は空で、こちらに選択肢が入る。答えは選択肢の識別子で返す。
  選択肢?: { 識別子: string; 表示: string }[];
  問い?: string;
  // 「好きな順で」の並べ替えを聞いているか。
  // 画面は、選ぶ／選ばないではなく順番を決める場面だと分かるよう出し分ける。
  順番を決める?: boolean;
}

// 今このプレイヤーが撃てる【起動】効果
export interface 起動効果候補 {
  発揮源: カード;
  効果識別子: string;
  タイミング?: string;
  制限?: string;
}

export type 進行結果 =
  | { 状態: 'アイドル'; ログ: string[] }
  | ({ 状態: '選択待ち'; ログ: string[] } & 選択待ち情報);

export class 効果実行器 {
  private 試合: 試合;
  private インタプリタ: 効果インタプリタ;
  private 効果ルール = new 効果ルール();

  // 中断中の効果（答え待ち）。
  // 効果の持ち主と「答える人」は別なので（相手が決める判断があるため）両方持つ。
  private 中断中: {
    中断状態: 中断状態;
    情報: 選択待ち情報;
    効果の持ち主識別子: string;
  } | null = null;
  // 事象ごとに変わる重複排除キー
  private 事象連番 = 0;
  // 解決が終わったらトラッシュへ置く、使用中のマジック
  private 片付け待ち: { カード: カード; 持ち主識別子: string }[] = [];

  private 接続: バトスピ接続;

  constructor(試合インスタンス: 試合) {
    this.試合 = 試合インスタンス;
    this.接続 = new バトスピ接続(試合インスタンス);
    this.インタプリタ = new 効果インタプリタ(this.接続);
  }

  // カードの語彙（フィルタ・条件の意味づけ）。効果の外から判定したい場所のために公開する。
  接続を取得(): バトスピ接続 {
    return this.接続;
  }

  // このカードの指定トリガーの効果が、今の盤面で発動条件を満たすか。
  // 条件を持たない（＝いつでも発動する）場合と、そもそも該当する効果が無い場合を
  // 区別できるよう、判定できないときは undefined を返す。
  //
  // 「今出しても不発だが、後で出せば当たる」をAIが判断するために使う。
  トリガー効果の条件を満たすか(カード: カード, トリガー: string): boolean | undefined {
    const 効果一覧 = this.効果ルール.効果を取得(カード);
    const 該当 = 効果一覧.filter(
      効果 => 効果.トリガー === トリガー && (効果.種別 === undefined || 効果.種別 === '誘発')
    );
    if (該当.length === 0) {
      return undefined; // このトリガーの効果を持たない
    }
    const 条件付き = 該当.filter(効果 => 効果.条件 !== undefined);
    if (条件付き.length === 0) {
      return undefined; // 条件がないので満たす／満たさないの判断が要らない
    }

    const 所有者識別子 = this.カードの所有者を求める(カード);
    if (!所有者識別子) {
      return undefined;
    }
    const 文脈 = {
      自身: カード,
      プレイヤー識別子: 所有者識別子,
      スコープ: [],
      選択済み: [],
      残り: [],
      変数: new Map<string, number>(),
      直前成功: false,
      決定: new Map<string, string>(),
      ログ: [],
    };
    return 条件付き.some(効果 => this.接続.条件を評価(効果.条件!, 文脈));
  }

  // === 事象の通知 ===

  // 出来事を知らせ、誘発する効果をキューへ積む。積んだ件数を返す。
  //
  // 発揮源     … そのカードの効果だけを見る（召喚時・アタック時など、起きた本人が誘発源）
  // 所有者限定 … そのプレイヤーの場のカードだけを見る。
  //              『自分が相手のスピリットを破壊した時』のように「自分が」と書かれた効果は、
  //              その事象を起こした側のカードしか誘発しないため必要になる。
  // どちらも指定しなければ両プレイヤーの場を見る。
  事象を通知する(事象名: string, 発揮源?: カード, 所有者限定?: string): number {
    const 事象キー = `${事象名}-${++this.事象連番}`;
    const 対象カード一覧 = 発揮源
      ? [発揮源]
      : this.フィールドの全カードを取得(所有者限定);

    let 積んだ件数 = 0;
    for (const カード of 対象カード一覧) {
      const 所有者識別子 = this.カードの所有者を求める(カード);
      if (!所有者識別子) {
        continue;
      }
      const 効果一覧 = this.効果ルール.効果を取得(カード);
      for (let 添字 = 0; 添字 < 効果一覧.length; 添字++) {
        if (!this.この事象で誘発するか(効果一覧[添字], 事象名, カード, 添字)) {
          continue;
        }
        const 効果識別子 = this.効果ルール.効果識別子を作る(カード, 添字);
        const 予約 = this.試合.誘発型効果管理.誘発する(
          効果識別子,
          カード,
          所有者識別子,
          事象キー,
          this.中断中 !== null // 解決中なら先頭へ割り込む（9-1-5-9）
        );
        if (予約) {
          積んだ件数++;
        }
      }
    }
    return 積んだ件数;
  }

  // 誘発の対象になる効果か
  private この事象で誘発するか(
    効果: 効果定義,
    事象名: string,
    カード: カード,
    添字: number
  ): boolean {
    if (効果.トリガー !== 事象名) {
      return false;
    }
    // 起動・使用・常在は「事象で自動的に誘発する」ものではない
    if (効果.種別 !== undefined && 効果.種別 !== '誘発') {
      return false;
    }
    // ［Lv1-2］のようなLv制限
    if (効果.Lv !== undefined) {
      const 現在のLv = this.試合.Lv管理.現在のLvを取得(カード);
      if (!効果.Lv.includes(現在のLv)) {
        return false;
      }
    }
    // 『アタック中』のような持続状態の要求
    if (効果.状態 !== undefined && カード.状態を取得(効果.状態) !== true) {
      return false;
    }
    // 〔ターン1回〕（12-3-1）。記録は既存の 制限効果管理 が持っている。
    if (効果.制限 === 'ターン1回') {
      const 効果識別子 = this.効果ルール.効果識別子を作る(カード, 添字);
      if (
        !this.試合.制限効果管理.ターン1回は発揮可能か(
          カード.識別子,
          効果識別子,
          this.通算ターン数を取得()
        )
      ) {
        return false;
      }
    }
    return true;
  }

  // 〔ターン1回〕は自分のターンだけの制限ではないため、
  // プレイヤーごとのターン数ではなく、試合を通した通算のターン番号で数える。
  private 通算ターン数を取得(): number {
    return this.試合.ゲーム
      .全プレイヤーを取得()
      .reduce((合計, プレイヤー) => 合計 + プレイヤー.数値を取得('ターン数'), 0);
  }

  // === キューの処理 ===

  // キューを順に解決する。選択が必要になったらそこで止まる。
  キューを進める(): 進行結果 {
    const ログ: string[] = [];

    if (this.中断中) {
      return { 状態: '選択待ち', ログ, ...this.中断中.情報 };
    }

    // 発揮源が場を離れた予約は取り除く（9-1-5-5）
    this.発揮できない予約を掃除する();

    let 安全カウンタ = 0;
    while (!this.試合.誘発型効果管理.空か() && 安全カウンタ++ < 100) {
      const 予約 = this.試合.誘発型効果管理.次を取り出す();
      if (!予約) {
        break;
      }

      const 効果 = this.効果ルール.識別子で取得(予約.発揮源, 予約.効果識別子);
      if (!効果) {
        continue;
      }

      // 発揮が始まった時点で〔ターン1回〕を消費したものとして記録する。
      // 途中で選択待ちになっても二重に誘発させないため、実行の前に記録する。
      if (効果.制限 === 'ターン1回') {
        this.試合.制限効果管理.ターン1回を記録する(
          予約.発揮源.識別子,
          予約.効果識別子,
          this.通算ターン数を取得()
        );
      }

      const 結果 = this.インタプリタ.実行(効果, 予約.発揮源, 予約.所有者識別子);

      if (結果.状態 === '選択待ち') {
        this.中断中 = {
          中断状態: 結果.中断状態,
          情報: this.選択待ち情報を作る(結果, 予約.発揮源, 予約.所有者識別子, 予約.効果識別子),
          効果の持ち主識別子: 予約.所有者識別子,
        };
        return { 状態: '選択待ち', ログ, ...this.中断中.情報 };
      }

      ログ.push(...(結果.状態 === '完了' ? 結果.ログ : [結果.理由]));
      this.発揮できない予約を掃除する();
    }

    // すべて解決し終えたので、使い終わったマジックをトラッシュへ置く
    this.使用済みマジックを片付ける();

    return { 状態: 'アイドル', ログ };
  }

  // 選択の答えを受け取り、続きを解決してからキューを進める
  選択に答える(選択されたカード識別子: string[]): 進行結果 {
    if (!this.中断中) {
      return { 状態: 'アイドル', ログ: ['選択待ちの効果はありません'] };
    }

    const 中断 = this.中断中;
    this.中断中 = null;

    const 結果 = this.インタプリタ.再開(中断.中断状態, 選択されたカード識別子);

    if (結果.状態 === '選択待ち') {
      // 1つの効果に選択が複数あるカードのため、続けて止まることがある。
      // 誰が答えるかは判断ごとに変わりうるので、毎回 結果 から決め直す。
      this.中断中 = {
        中断状態: 結果.中断状態,
        情報: this.選択待ち情報を作る(
          結果,
          中断.情報.発揮源,
          中断.効果の持ち主識別子,
          中断.情報.効果識別子
        ),
        効果の持ち主識別子: 中断.効果の持ち主識別子,
      };
      return { 状態: '選択待ち', ログ: [], ...this.中断中.情報 };
    }

    const これまでのログ = 結果.状態 === '完了' ? 結果.ログ : [結果.理由];
    const 続き = this.キューを進める();
    return { ...続き, ログ: [...これまでのログ, ...続き.ログ] };
  }

  // 中断した結果から選択待ち情報を組み立てる。
  //
  // 大事なのは 所有者識別子（＝誰が答えるか）。
  // 効果の持ち主が答えるのが普通だが、「（置くコアは相手が選ぶ）」のように
  // 相手が決める判断もある。そのときは持ち主を相手に振り替える。
  private 選択待ち情報を作る(
    結果: { 候補: カード[]; 最小: number; 最大: number; 任意: boolean } & {
      決定者: '自分' | '相手';
      選択肢?: { 識別子: string; 表示: string }[];
      問い?: string;
      並べ替え先?: string;
    },
    発揮源: カード,
    効果の持ち主識別子: string,
    効果識別子: string
  ): 選択待ち情報 {
    const 答える人 =
      結果.決定者 === '相手' ? this.相手識別子(効果の持ち主識別子) : 効果の持ち主識別子;

    return {
      発揮源,
      所有者識別子: 答える人,
      効果識別子,
      候補: 結果.候補,
      最小: 結果.最小,
      最大: 結果.最大,
      任意: 結果.任意,
      選択肢: 結果.選択肢,
      問い: 結果.問い,
      順番を決める: 結果.並べ替え先 !== undefined,
    };
  }

  private 相手識別子(識別子: string): string {
    const 相手 = this.試合.ゲーム.全プレイヤーを取得().find(p => p.識別子 !== 識別子);
    return 相手 ? 相手.識別子 : 識別子;
  }

  // === 起動効果 ===

  // 今このプレイヤーが撃てる【起動】効果を集める。
  // 誘発と違って自動では発揮しないので、撃つかどうかはプレイヤーが決める。
  発動できる起動効果を集める(プレイヤー識別子: string, タイミング?: string): 起動効果候補[] {
    if (this.中断中) {
      return []; // 解決の途中では新たに撃たせない
    }

    const 候補: 起動効果候補[] = [];
    for (const カード of this.フィールドの全カードを取得(プレイヤー識別子)) {
      const 効果一覧 = this.効果ルール.効果を取得(カード);
      for (let 添字 = 0; 添字 < 効果一覧.length; 添字++) {
        const 効果 = 効果一覧[添字];
        if (効果.種別 !== '起動') {
          continue;
        }
        if (タイミング !== undefined && 効果.タイミング !== タイミング) {
          continue;
        }
        if (!this.発動条件を満たすか(効果, カード, 添字, プレイヤー識別子)) {
          continue;
        }
        候補.push({
          発揮源: カード,
          効果識別子: this.効果ルール.効果識別子を作る(カード, 添字),
          タイミング: 効果.タイミング,
          制限: 効果.制限,
        });
      }
    }
    return 候補;
  }

  // 起動効果を撃つ。撃てない指定なら失敗を返す。
  起動効果を発動する(プレイヤー識別子: string, 効果識別子: string): 進行結果 {
    if (this.中断中) {
      return { 状態: '選択待ち', ログ: [], ...this.中断中.情報 };
    }

    const 候補 = this.発動できる起動効果を集める(プレイヤー識別子).find(
      c => c.効果識別子 === 効果識別子
    );
    if (!候補) {
      return { 状態: 'アイドル', ログ: ['その効果は今発動できません'] };
    }

    const 効果 = this.効果ルール.識別子で取得(候補.発揮源, 効果識別子);
    if (!効果) {
      return { 状態: 'アイドル', ログ: ['効果が見つかりません'] };
    }

    const 結果 = this.インタプリタ.実行(効果, 候補.発揮源, プレイヤー識別子);

    // 誘発と同じく、発揮を始めた時点で〔ターン1回〕を消費する。
    // ただしコストを払えずに何も起きなかったときは発揮していないので消費しない。
    // 払えないコストの効果は そもそも コストが払えるか で候補から外れるが、
    // ここを通ると1ターンぶんの権利だけが消えてしまうため、二重に守る。
    const 発揮を始めた = !(結果.状態 === '完了' && !結果.発動した);
    if (効果.制限 === 'ターン1回' && 発揮を始めた) {
      this.試合.制限効果管理.ターン1回を記録する(
        候補.発揮源.識別子,
        効果識別子,
        this.通算ターン数を取得()
      );
    }

    if (結果.状態 === '選択待ち') {
      this.中断中 = {
        中断状態: 結果.中断状態,
        情報: this.選択待ち情報を作る(結果, 候補.発揮源, プレイヤー識別子, 効果識別子),
        効果の持ち主識別子: プレイヤー識別子,
      };
      return { 状態: '選択待ち', ログ: [], ...this.中断中.情報 };
    }

    const ログ = 結果.状態 === '完了' ? 結果.ログ : [結果.理由];
    const 続き = this.キューを進める();
    return { ...続き, ログ: [...ログ, ...続き.ログ] };
  }

  // === 使用効果（マジック） ===

  // マジックの効果を発揮させる。
  // マジックは使用中どの領域にも属さず、解決し終えてからトラッシュへ置く（11-3-1-6）。
  // 途中で対象選択に入って中断することがあるため、片付けは解決が終わってから行う。
  //
  // ［メイン］と［フラッシュ］の両方を持つマジックは、1枚で2つの撃ち方があり、
  // 使うときにどちらかを選ぶ。タイミングを渡すと、その撃ち方だけを発揮する。
  // 片方しか持たないマジックは、タイミングを渡さなくても今までどおり発揮する。
  使用効果を発動する(
    カード: カード,
    プレイヤー識別子: string,
    タイミング?: string
  ): 進行結果 {
    const すべての使用効果 = this.効果ルール.効果を取得(カード).filter(効果 => 効果.種別 === '使用');
    const 絞った =
      タイミング === undefined
        ? すべての使用効果
        : すべての使用効果.filter(効果 => 効果.タイミング === タイミング);
    // 指定された撃ち方を持たないカードは、持っている撃ち方をそのまま発揮する
    const 効果一覧 = 絞った.length > 0 ? 絞った : すべての使用効果;

    this.片付け待ち.push({ カード, 持ち主識別子: プレイヤー識別子 });

    const ログ: string[] = [];
    for (const 効果 of 効果一覧) {
      const 結果 = this.インタプリタ.実行(効果, カード, プレイヤー識別子);
      if (結果.状態 === '選択待ち') {
        this.中断中 = {
          中断状態: 結果.中断状態,
          情報: this.選択待ち情報を作る(結果, カード, プレイヤー識別子, 'マジック使用'),
          効果の持ち主識別子: プレイヤー識別子,
        };
        return { 状態: '選択待ち', ログ, ...this.中断中.情報 };
      }
      ログ.push(...(結果.状態 === '完了' ? 結果.ログ : [結果.理由]));
    }

    const 続き = this.キューを進める();
    return { ...続き, ログ: [...ログ, ...続き.ログ] };
  }

  // 使い終わったマジックをトラッシュへ置く。解決がすべて終わってから呼ぶ。
  private 使用済みマジックを片付ける(): void {
    for (const { カード, 持ち主識別子 } of this.片付け待ち) {
      this.試合.使用管理.効果発揮を終える(カード);
      const トラッシュ = this.試合.ゾーン管理.トラッシュを取得(this.試合.ゲーム, 持ち主識別子);
      if (トラッシュ) {
        トラッシュ.カードを追加(カード);
      }
    }
    this.片付け待ち = [];
  }

  // 起動効果が今の状況で撃てるか（Lv・持続状態・ターン1回・コストが払えるか）
  private 発動条件を満たすか(
    効果: 効果定義,
    カード: カード,
    添字: number,
    プレイヤー識別子: string
  ): boolean {
    // 待機状態のカード（破壊・消滅が決まってトラッシュを待っている）は効果を撃てない
    if (this.試合.待機状態管理.待機状態か(カード)) {
      return false;
    }
    if (!this.コストが払えるか(効果, カード, プレイヤー識別子)) {
      return false;
    }
    if (効果.Lv !== undefined) {
      const 現在のLv = this.試合.Lv管理.現在のLvを取得(カード);
      if (!効果.Lv.includes(現在のLv)) {
        return false;
      }
    }
    if (効果.状態 !== undefined && カード.状態を取得(効果.状態) !== true) {
      return false;
    }
    // 『自分のアタックステップ』… 撃てるステップの制限。
    // 誘発効果と違って起動効果は事象で積まれないので、トリガー欄は
    // 「この場面でだけ撃てる」という条件としてここで見る。
    if (
      効果.トリガー === '自分のアタックステップ' &&
      !this.自分のアタックステップか(プレイヤー識別子)
    ) {
      return false;
    }
    if (効果.制限 === 'ターン1回') {
      const 効果識別子 = this.効果ルール.効果識別子を作る(カード, 添字);
      if (
        !this.試合.制限効果管理.ターン1回は発揮可能か(
          カード.識別子,
          効果識別子,
          this.通算ターン数を取得()
        )
      ) {
        return false;
      }
    }
    return true;
  }

  // 今が「撃とうとしている側のアタックステップ」か。
  // 「自分の」なので、相手のアタックステップ中には撃てない。
  private 自分のアタックステップか(プレイヤー識別子: string): boolean {
    if (this.試合.現在のステップ() !== 'アタックステップ') {
      return false;
    }
    return this.試合.ゲーム.現在のプレイヤーを取得()?.識別子 === プレイヤー識別子;
  }

  // 払えないコストの効果は、そもそも選ばせない。
  //
  // 「このカードを疲労させる」は既に疲労していたら払えないし、
  // 「このカードを破壊する」は既に待機状態なら払えない。
  // 「手札の風牙1枚を破棄する」は、手札に風牙が無ければ払えない。
  // 払えない効果を候補に出し続けると、選んでも何も起きない手が延々と残ってしまう。
  private コストが払えるか(効果: 効果定義, カード: カード, プレイヤー識別子: string): boolean {
    for (const ステップ of 効果.コスト ?? []) {
      if ('疲労' in ステップ && ステップ.疲労 === '自身') {
        if (this.試合.カードの表示形式管理.現在の表示形式を取得(カード) !== '回復') {
          return false;
        }
      }
      if ('破壊' in ステップ && ステップ.破壊 === '自身') {
        if (this.試合.待機状態管理.待機状態か(カード)) {
          return false;
        }
      }
      if ('選択' in ステップ && !this.選択コストの当てがあるか(ステップ.選択, カード, プレイヤー識別子)) {
        return false;
      }
    }
    return true;
  }

  // 「自分の手札の系統：「風牙」を持つカード1枚を破棄する▶」のように、
  // 選んでから払うコストに、選べるカードが盤面にあるか。
  //
  // 見るのは盤面に当てられる絞り込みだけ。'スコープ'（直前にめくった中から）は
  // 実行してみないと中身が決まらないので、ここでは判断せず通す。
  // 必要数が数値で書かれていないもの、「N枚まで」「指定できる」も、
  // 0枚でも成立しうるので通す。
  private 選択コストの当てがあるか(
    指定: カードフィルタ & { 数?: unknown; まで?: boolean; 任意?: boolean },
    カード: カード,
    プレイヤー識別子: string
  ): boolean {
    if (指定.元 === 'スコープ' || 指定.まで === true || 指定.任意 === true) {
      return true;
    }
    const 必要数 = typeof 指定.数 === 'number' ? 指定.数 : undefined;
    if (必要数 === undefined || 必要数 <= 0) {
      return true;
    }
    return this.接続.絞り込みで集める(指定, カード, プレイヤー識別子).length >= 必要数;
  }

  // 今、選択の答えを待っているか
  選択待ちか(): boolean {
    return this.中断中 !== null;
  }

  選択待ち情報を取得(): 選択待ち情報 | null {
    return this.中断中 ? this.中断中.情報 : null;
  }

  // === 内部 ===

  private 発揮できない予約を掃除する(): void {
    this.試合.誘発型効果管理.発揮できない予約を取り除く(予約 => {
      const フィールド = this.試合.ゾーン管理.フィールドを取得(
        this.試合.ゲーム,
        予約.所有者識別子
      );
      return フィールド ? フィールド.カードを取得(予約.発揮源.識別子) !== undefined : false;
    });
  }

  private フィールドの全カードを取得(所有者限定?: string): カード[] {
    const 全カード: カード[] = [];
    for (const プレイヤー of this.試合.ゲーム.全プレイヤーを取得()) {
      if (所有者限定 !== undefined && プレイヤー.識別子 !== 所有者限定) {
        continue;
      }
      const フィールド = this.試合.ゾーン管理.フィールドを取得(this.試合.ゲーム, プレイヤー.識別子);
      if (フィールド) {
        全カード.push(...フィールド.カード一覧を取得());
      }
    }
    return 全カード;
  }

  private カードの所有者を求める(カード: カード): string | undefined {
    for (const プレイヤー of this.試合.ゲーム.全プレイヤーを取得()) {
      const 領域一覧 = this.試合.ゾーン管理.プレイヤーの全領域を取得(
        this.試合.ゲーム,
        プレイヤー.識別子
      );
      for (const 領域 of 領域一覧) {
        if (領域.カードを取得(カード.識別子)) {
          return プレイヤー.識別子;
        }
      }
    }
    return undefined;
  }
}
