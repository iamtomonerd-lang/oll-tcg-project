// ゲームの出来事が効果を誘発させるところまで、実際の経路で通っているかを確かめる。
// インタプリタ単体ではなく、試合の各操作から発火することが確認したいこと。

interface カード指定 {
  種別?: string;
  効果?: 効果定義[];
  コスト?: number;
}

function 検証カードを作る(識別子: string, 指定: カード指定 = {}): カード {
  return new カード(識別子, {
    識別子,
    表示名: 識別子,
    カード名: 識別子,
    カードナンバー: 'TEST-000',
    カード種別: 指定.種別 ?? 'スピリット',
    レアリティ: 'C',
    コスト: 指定.コスト ?? 1,
    系統: ['風牙'],
    ブロックアイコン: 'A',
    属性: ['赤'],
    軽減シンボル: [],
    シンボル: [],
    Lv: [
      { level: 1, cost: 1, bp: 3000 },
      { level: 2, cost: 3, bp: 5000 },
    ],
    効果: 指定.効果,
  } as any);
}

function 試合を準備する(): 試合 {
  const 試合インスタンス = new 試合();
  試合インスタンス.プレイヤーを準備する('p1', 'プレイヤー1');
  試合インスタンス.プレイヤーを準備する('p2', 'プレイヤー2');
  試合インスタンス.ボイドを準備する();
  試合インスタンス.デッキを設定する(
    'p1',
    Array.from({ length: 15 }, (_, i) => 検証カードを作る(`p1-deck-${i + 1}`))
  );
  試合インスタンス.デッキを設定する(
    'p2',
    Array.from({ length: 15 }, (_, i) => グンガタを作成(`p2-deck-${i + 1}`))
  );
  試合インスタンス.準備を行う('p1');
  試合インスタンス.準備を行う('p2');
  試合インスタンス.先攻を決める('p1');
  試合インスタンス.試合を開始する();
  return 試合インスタンス;
}

function 場に出す(試合インスタンス: 試合, プレイヤー識別子: string, 対象: カード, BP?: number): カード {
  試合インスタンス.ゾーン管理
    .フィールドを取得(試合インスタンス.ゲーム, プレイヤー識別子)!
    .カードを追加(対象);
  // 場のカードには必ずコアが乗っている。乗せずに置くと、ルール処理の消滅判定に
  // 引っかかって即トラッシュ行きになる（実戦では起こらない状態）。
  // Lv1を保てる最小限だけ乗せる。Lvを変えたいテストは、このあとで自分で乗せ直す。
    試合インスタンス.コア管理
      .カードを保持者に(対象)
      .コア数を設定(new 消滅判定().最小必要コア数を取得(対象));
  if (BP !== undefined) {
    試合インスタンス.BP管理.BPを設定(対象, BP);
  }
  return 対象;
}

// 召喚・配置は支払いがちょうどの額でないと通らないので、必要額を計算してから渡す
function 場に出す手続き(
  試合インスタンス: 試合,
  プレイヤー識別子: string,
  対象: カード,
  操作: '召喚' | '配置'
): boolean {
  const 手札 = 試合インスタンス.ゾーン管理.手札を取得(試合インスタンス.ゲーム, プレイヤー識別子)!;
  const フィールド = 試合インスタンス.ゾーン管理.フィールドを取得(試合インスタンス.ゲーム, プレイヤー識別子)!;
  const リザーブ = 試合インスタンス.ゾーン管理.リザーブを取得(試合インスタンス.ゲーム, プレイヤー識別子)!;

  手札.カードを追加(対象);
  const リザーブ保持者 = 試合インスタンス.コア管理.ゾーンを保持者に(リザーブ);
  リザーブ保持者.コア数を設定(リザーブ保持者.コア数を取得() + 10);

  const フィールドのシンボル = フィールド
    .カード一覧を取得()
    .flatMap(c => new シンボルルール().シンボルを取得(c).map(x => x.色));
  const 基本コスト = new コストルール().コストを取得(対象);
  const 支払額 = new 軽減シンボルルール().軽減後のコストを計算(対象, 基本コスト, フィールドのシンボル);
  const 最低必要数 = new 消滅判定().最小必要コア数を取得(対象);

  const 支払い = [{ 保持者: リザーブ保持者, 数: 支払額 }];
  const 初期配置 = [{ 保持者: リザーブ保持者, 数: 最低必要数 }];

  return 操作 === '召喚'
    ? 試合インスタンス.召喚する(プレイヤー識別子, 対象, 支払い, 初期配置)
    : 試合インスタンス.配置する(プレイヤー識別子, 対象, 支払い, 初期配置);
}

// === 配置時 ===

test('配置時：試合.配置する でネクサスの効果が誘発する', () => {
  const 試合インスタンス = 試合を準備する();

  const ネクサス = 検証カードを作る('配置ネクサス', {
    種別: 'ネクサス',
    効果: [{ トリガー: '配置時', 処理: [{ ドロー: 1 }] }],
  });

  const 手札枚数の前 = 試合インスタンス.ゾーン管理
    .手札を取得(試合インスタンス.ゲーム, 'p1')!
    .カード枚数を取得();

  const 成功 = 場に出す手続き(試合インスタンス, 'p1', ネクサス, '配置');
  assert.equal(成功, true, '配置が成立する');

  const 手札枚数の後 = 試合インスタンス.ゾーン管理
    .手札を取得(試合インスタンス.ゲーム, 'p1')!
    .カード枚数を取得();

  // 手札にネクサスを足して場に出した分（±0）＋ドロー1枚
  assert.equal(手札枚数の後, 手札枚数の前 + 1, '配置時効果でドローしている');
});

// === アタック時 ===

test('アタック時：試合.アタック宣言する で効果が誘発する', async t => {
  await t.test('宣言が通れば誘発する', () => {
    const 試合インスタンス = 試合を準備する();

    const アタッカー = 場に出す(
      試合インスタンス,
      'p1',
      検証カードを作る('アタッカー', {
        効果: [{ トリガー: 'アタック時', 処理: [{ ドロー: 1 }] }],
      }),
      3000
    );

    const 前 = 試合インスタンス.ゾーン管理.手札を取得(試合インスタンス.ゲーム, 'p1')!.カード枚数を取得();

    const 成功 = 試合インスタンス.アタック宣言する(アタッカー);
    assert.equal(成功, true, 'アタック宣言が通る');

    const 後 = 試合インスタンス.ゾーン管理.手札を取得(試合インスタンス.ゲーム, 'p1')!.カード枚数を取得();
    assert.equal(後, 前 + 1, 'アタック時効果でドローしている');
  });

  await t.test('宣言が通らなければ誘発しない', () => {
    const 試合インスタンス = 試合を準備する();

    const アタッカー = 場に出す(
      試合インスタンス,
      'p1',
      検証カードを作る('アタッカー', {
        効果: [{ トリガー: 'アタック時', 処理: [{ ドロー: 1 }] }],
      }),
      3000
    );
    // 疲労状態ではアタック宣言できない
    試合インスタンス.カードの表示形式管理.疲労する(アタッカー);

    const 前 = 試合インスタンス.ゾーン管理.手札を取得(試合インスタンス.ゲーム, 'p1')!.カード枚数を取得();

    const 成功 = 試合インスタンス.アタック宣言する(アタッカー);
    assert.equal(成功, false, '疲労状態では宣言できない');

    const 後 = 試合インスタンス.ゾーン管理.手札を取得(試合インスタンス.ゲーム, 'p1')!.カード枚数を取得();
    assert.equal(後, 前, '宣言が通らなければ効果も誘発しない');
  });
});

// === 自分のエンドステップ ===

test('自分のエンドステップ：ステップ進行で誘発し、ターンプレイヤー側だけが対象になる', () => {
  const 試合インスタンス = 試合を準備する();

  // ドローで観測すると、ターンが移った先のドローステップと区別できない。
  // BPはターン進行では動かないので、自分のBPを上げる効果を目印にする。
  const 自分のBPを上げる: 効果定義 = {
    トリガー: '自分のエンドステップ',
    処理: [{ BP変更: { 対象: '自身', 値: 1000 } }],
  };

  const 自分のカード = 場に出す(
    試合インスタンス,
    'p1',
    検証カードを作る('自分エンド', { 効果: [自分のBPを上げる] }),
    3000
  );
  const 相手のカード = 場に出す(
    試合インスタンス,
    'p2',
    検証カードを作る('相手エンド', { 効果: [自分のBPを上げる] }),
    3000
  );

  // p1のターンをエンドステップまで進める（随意ステップを順に終了していく）
  let 安全カウンタ = 0;
  while (試合インスタンス.ゲーム.現在のプレイヤーを取得()?.識別子 === 'p1' && 安全カウンタ++ < 10) {
    試合インスタンス.ステップを終了する();
  }

  assert.equal(
    試合インスタンス.BP管理.現在のBPを取得(自分のカード),
    4000,
    'ターンプレイヤー側の『自分のエンドステップ』は誘発する'
  );
  assert.equal(
    試合インスタンス.BP管理.現在のBPを取得(相手のカード),
    3000,
    '相手側の『自分のエンドステップ』は誘発しない'
  );
});

// === 自分が相手のスピリットを破壊した時 ===

test('破壊時：自分が相手のスピリットを破壊すると誘発する', async t => {
  // 相手スピリットを破壊する効果と、破壊した時に誘発する効果を別カードに持たせる
  const 破壊する効果: 効果定義 = {
    トリガー: '召喚時',
    処理: [{ 選択: { 場: '相手', 種別: 'スピリット', 数: 1 } }, { 破壊: '選択' }],
  };
  const 破壊に反応する効果: 効果定義 = {
    トリガー: '自分が相手のスピリットを破壊した時',
    処理: [{ ドロー: 1 }],
  };

  await t.test('相手のスピリットを破壊すると反応する', () => {
    const 試合インスタンス = 試合を準備する();

    場に出す(試合インスタンス, 'p1', 検証カードを作る('反応役', { 効果: [破壊に反応する効果] }), 3000);
    場に出す(試合インスタンス, 'p2', グンガタを作成('相手1'), 3000);

    const 前 = 試合インスタンス.ゾーン管理.手札を取得(試合インスタンス.ゲーム, 'p1')!.カード枚数を取得();

    const 破壊役 = 検証カードを作る('破壊役', { 効果: [破壊する効果] });
    const 成功 = 場に出す手続き(試合インスタンス, 'p1', 破壊役, '召喚');
    assert.equal(成功, true, '召喚が成立する');

    const 後 = 試合インスタンス.ゾーン管理.手札を取得(試合インスタンス.ゲーム, 'p1')!.カード枚数を取得();
    // 破壊役を手札に足して場に出した分（±0）＋反応のドロー1枚
    assert.equal(後, 前 + 1, '破壊に反応してドローしている');
  });

  await t.test('相手側のカードは「自分が」に該当しないので反応しない', () => {
    const 試合インスタンス = 試合を準備する();

    // 反応する効果を相手側に置く
    場に出す(試合インスタンス, 'p2', 検証カードを作る('相手の反応役', { 効果: [破壊に反応する効果] }), 3000);
    場に出す(試合インスタンス, 'p2', グンガタを作成('相手1'), 3000);

    const 前 = 試合インスタンス.ゾーン管理.手札を取得(試合インスタンス.ゲーム, 'p2')!.カード枚数を取得();

    const 破壊役 = 検証カードを作る('破壊役', { 効果: [破壊する効果] });
    場に出す手続き(試合インスタンス, 'p1', 破壊役, '召喚');

    const 後 = 試合インスタンス.ゾーン管理.手札を取得(試合インスタンス.ゲーム, 'p2')!.カード枚数を取得();
    assert.equal(後, 前, '破壊したのは相手なので誘発しない');
  });

  await t.test('自分のスピリットを破壊しても反応しない', () => {
    const 試合インスタンス = 試合を準備する();

    場に出す(試合インスタンス, 'p1', 検証カードを作る('反応役', { 効果: [破壊に反応する効果] }), 3000);
    場に出す(試合インスタンス, 'p1', 検証カードを作る('自分の犠牲', {}), 3000);

    const 前 = 試合インスタンス.ゾーン管理.手札を取得(試合インスタンス.ゲーム, 'p1')!.カード枚数を取得();

    // 自分の場のスピリットを破壊する効果
    const 自壊効果: 効果定義 = {
      トリガー: '召喚時',
      処理: [
        { 選択: { 場: '自分', 種別: 'スピリット', カード名以外: '反応役', 数: 1 } },
        { 破壊: '選択' },
      ],
    };
    const 破壊役 = 検証カードを作る('破壊役', { 効果: [自壊効果] });
    場に出す手続き(試合インスタンス, 'p1', 破壊役, '召喚');

    const 後 = 試合インスタンス.ゾーン管理.手札を取得(試合インスタンス.ゲーム, 'p1')!.カード枚数を取得();
    assert.equal(後, 前, '相手のスピリットではないので誘発しない');
  });
});
