import { ゾーン } from '../../../データ/ゾーン/ゾーン.js';
import { 公開範囲 } from './公開範囲.js';

// ライフ
// 中身  ：コア（このコア数がライフ値になる。0でゲームに敗北）
// 可視性：全員公開
// 所持  ：各プレイヤーが1つずつ
// コアは universal ゾーンを触らずに 状態Map で数として持つ（ソウルコアは位置フラグ）
export class ライフ {
  readonly 識別子キー = 'ライフ';
  readonly 表示名 = 'ライフ';
  readonly 公開範囲: 公開範囲 = '全員公開';

  生成(プレイヤー識別子: string, 初期コア数: number = 0): ゾーン {
    const 領域 = new ゾーン(
      `${プレイヤー識別子}-ライフ`,
      { 識別子: this.識別子キー, 表示名: this.表示名, 説明: 'ライフを表すコアを置く。コア数がライフ値。全員に公開' }
    );
    領域.状態を設定('公開範囲', this.公開範囲);
    領域.状態を設定('所有者', プレイヤー識別子);
    領域.状態を設定('コア数', 初期コア数);
    領域.状態を設定('ソウルコア', false);
    return 領域;
  }
}
