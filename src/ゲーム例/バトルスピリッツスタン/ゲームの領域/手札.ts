import { ゾーン } from '../../../データ/ゾーン/ゾーン.js';
import { 公開範囲 } from './公開範囲.js';

// 手札
// 中身  ：カード
// 可視性：所有者のみ（相手には見えない）
// 所持  ：各プレイヤーが1つずつ
export class 手札 {
  readonly 識別子キー = '手札';
  readonly 表示名 = '手札';
  readonly 公開範囲: 公開範囲 = '所有者のみ';

  生成(プレイヤー識別子: string): ゾーン {
    const 領域 = new ゾーン(
      `${プレイヤー識別子}-手札`,
      { 識別子: this.識別子キー, 表示名: this.表示名, 説明: '所有プレイヤーのみが中身を見られる' }
    );
    領域.状態を設定('公開範囲', this.公開範囲);
    領域.状態を設定('所有者', プレイヤー識別子);
    return 領域;
  }
}
