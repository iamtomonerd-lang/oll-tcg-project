import { ゾーン } from '../../../データ/ゾーン/ゾーン.js';
import { 公開範囲 } from './公開範囲.js';

// フィールド
// 中身  ：カード（スピリット・ネクサス）。コアはこのカードの上に乗る
// 可視性：全員公開
// 所持  ：各プレイヤーが1つずつ
// フィールドのコアは各カードが 数値('コア数') で持つため、領域自体はコア数を持たない
export class フィールド {
  readonly 識別子キー = 'フィールド';
  readonly 表示名 = 'フィールド';
  readonly 公開範囲: 公開範囲 = '全員公開';

  生成(プレイヤー識別子: string): ゾーン {
    const 領域 = new ゾーン(
      `${プレイヤー識別子}-フィールド`,
      { 識別子: this.識別子キー, 表示名: this.表示名, 説明: 'スピリット・ネクサスが配置される。全員に公開' }
    );
    領域.状態を設定('公開範囲', this.公開範囲);
    領域.状態を設定('所有者', プレイヤー識別子);
    return 領域;
  }
}
