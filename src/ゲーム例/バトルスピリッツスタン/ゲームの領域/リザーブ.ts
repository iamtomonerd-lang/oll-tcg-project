import { ゾーン } from '../../../データ/ゾーン/ゾーン.js';
import { 公開範囲 } from './公開範囲.js';

// リザーブ
// 中身  ：コア
// 可視性：全員公開
// 所持  ：各プレイヤーが1つずつ
// コアは universal ゾーンを触らずに 状態Map で数として持つ（ソウルコアは位置フラグ）
export class リザーブ {
  readonly 識別子キー = 'リザーブ';
  readonly 表示名 = 'リザーブ';
  readonly 公開範囲: 公開範囲 = '全員公開';

  生成(プレイヤー識別子: string): ゾーン {
    const 領域 = new ゾーン(
      `${プレイヤー識別子}-リザーブ`,
      { 識別子: this.識別子キー, 表示名: this.表示名, 説明: '使用可能なコアを置く。全員に公開' }
    );
    領域.状態を設定('公開範囲', this.公開範囲);
    領域.状態を設定('所有者', プレイヤー識別子);
    領域.状態を設定('コア数', 0);
    領域.状態を設定('ソウルコア', false);
    return 領域;
  }
}
