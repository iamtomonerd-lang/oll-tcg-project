import { ゾーン } from '../../../データ/ゾーン/ゾーン.js';
import { 公開範囲 } from './公開範囲.js';

// 除外エリア
// 中身  ：カード
// 可視性：全員公開
// 所持  ：各プレイヤーが1つずつ
export class 除外エリア {
  readonly 識別子キー = '除外エリア';
  readonly 表示名 = '除外エリア';
  readonly 公開範囲: 公開範囲 = '全員公開';

  生成(プレイヤー識別子: string): ゾーン {
    const 領域 = new ゾーン(
      `${プレイヤー識別子}-除外エリア`,
      { 識別子: this.識別子キー, 表示名: this.表示名, 説明: 'ゲームから除外されたカードを置く。全員に公開' }
    );
    領域.状態を設定('公開範囲', this.公開範囲);
    領域.状態を設定('所有者', プレイヤー識別子);
    return 領域;
  }
}
