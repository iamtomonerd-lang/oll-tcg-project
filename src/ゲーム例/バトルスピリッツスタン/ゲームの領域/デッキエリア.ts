import { ゾーン } from '../../../データ/ゾーン/ゾーン.js';
import { 公開範囲 } from './公開範囲.js';

// デッキエリア
// 中身  ：カード
// 可視性：非公開（所有者本人も並び順を見られない・裏向きシャッフル済み）
// 所持  ：各プレイヤーが1つずつ
export class デッキエリア {
  readonly 識別子キー = 'デッキエリア';
  readonly 表示名 = 'デッキエリア';
  readonly 公開範囲: 公開範囲 = '非公開';

  生成(プレイヤー識別子: string): ゾーン {
    const 領域 = new ゾーン(
      `${プレイヤー識別子}-デッキエリア`,
      { 識別子: this.識別子キー, 表示名: this.表示名, 説明: '裏向きのカードの山。誰も中身を見られない' }
    );
    領域.状態を設定('公開範囲', this.公開範囲);
    領域.状態を設定('所有者', プレイヤー識別子);
    return 領域;
  }
}
