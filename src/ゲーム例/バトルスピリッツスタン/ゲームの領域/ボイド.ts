import { ゾーン } from '../../../データ/ゾーン/ゾーン.js';
import { 公開範囲 } from './公開範囲.js';

// ボイド
// 中身    ：コア（ゲーム外のコア置き場）
// 可視性  ：全員公開
// 所持    ：共通（ゲームに1つ。プレイヤーごとではない）
// 位置づけ：ゲーム外。ルール5-7-3により、ソウルコアは「ソウルコアを対象とする効果」でなければここに置かれない
// コアは universal ゾーンを触らずに 状態Map で数として持つ（ソウルコアは位置フラグ）
export class ボイド {
  readonly 識別子キー = 'ボイド';
  readonly 表示名 = 'ボイド';
  readonly 公開範囲: 公開範囲 = '全員公開';

  // 共通領域のため、識別子はプレイヤー接頭辞を付けず 'ボイド' 単体
  生成(): ゾーン {
    const 領域 = new ゾーン(
      this.識別子キー,
      { 識別子: this.識別子キー, 表示名: this.表示名, 説明: 'ゲーム外のコア置き場。両プレイヤー共通で1つ。全員に公開' }
    );
    領域.状態を設定('公開範囲', this.公開範囲);
    領域.状態を設定('共通', true);
    領域.状態を設定('コア数', 0);
    領域.状態を設定('ソウルコア', false);
    return 領域;
  }
}
