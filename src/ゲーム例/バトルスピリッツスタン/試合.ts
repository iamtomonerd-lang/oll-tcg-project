// 試合（バトルスピリッツ・スタンのゲーム進行の統括層）
// ・universal な ゲームエンジン と 効果エンジン を1つずつ所有する（シンプルTCGと同じ所有パターン）。
// ・状態を持つ管理（誘発型効果管理／置換型効果管理／制限効果管理）は、ここで1つだけ生成して
//   共有する。他のどの管理クラスも内部でこれらを new しないこと（キューやSetが分裂してしまうため）。
// ・フラッシュタイミング管理は1回のバトルごとに使い切りの状態機械のため、match全体で共有する
//   フィールドとしては持たず、バトルごとに フラッシュタイミングを開始する で都度生成する。
