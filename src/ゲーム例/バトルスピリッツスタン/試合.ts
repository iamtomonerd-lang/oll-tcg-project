// 試合（バトルスピリッツ・スタンのゲーム進行の統括層）
// ・universal な ゲームエンジン と 効果エンジン を1つずつ所有する（シンプルTCGと同じ所有パターン）。
// ・状態を持つ管理（誘発型効果管理／置換型効果管理／制限効果管理）は、ここで1つだけ生成して
//   共有する。他のどの管理クラスも内部でこれらを new しないこと（キューやSetが分裂してしまうため）。
// ・フラッシュタイミング管理は1回のバトルごとに使い切りの状態機械のため、match全体で共有する
//   フィールドとしては持たず、バトルごとに フラッシュタイミングを開始する で都度生成する。
export class 試合 {
  readonly ゲーム: ゲームエンジン;
  readonly 効果エンジン: 効果エンジン;

  // 状態を持つ管理（項目3：単一インスタンスをここで共有する）
  readonly 誘発型効果管理: 誘発型効果管理;
  readonly 置換型効果管理: 置換型効果管理;
  readonly 制限効果管理: 制限効果管理;

  // 状態を持たない各種管理（カード／ゾーンを都度受け取って操作する）
  readonly ゾーン管理: ゾーン管理;
  readonly 準備管理: 準備管理;
  readonly デッキ管理: デッキ管理;
  readonly ターン管理: ターン管理;
  readonly ターン判定: ターン判定;
  readonly バトル管理: バトル管理;
  readonly 召喚管理: 召喚管理;
  readonly 配置管理: 配置管理;
  readonly 使用管理: 使用管理;
  readonly 破壊管理: 破壊管理;
  readonly 破棄管理: 破棄管理;
  readonly 継召管理: 継召管理;
  readonly ソウルマジック管理: ソウルマジック管理;
  readonly コア管理: コア管理;
  readonly Lv管理: Lv管理;
  readonly BP管理: BP管理;
  readonly カードの表示形式管理: カードの表示形式管理;
  readonly 待機状態管理: 待機状態管理;
  readonly プレイコスト管理: プレイコスト管理;

  private スタートステップ管理: スタートステップ管理;
  private コアステップ管理: コアステップ管理;
  private ドローステップ管理: ドローステップ管理;
  private リフレッシュステップ管理: リフレッシュステップ管理;
  private エンドステップ管理: エンドステップ管理;

  private 勝敗結果: 勝利結果 | null = null;

  constructor() {
    this.ゲーム = new ゲームエンジン();
    this.効果エンジン = new 効果エンジン();

    this.誘発型効果管理 = new 誘発型効果管理();
    this.置換型効果管理 = new 置換型効果管理();
    this.制限効果管理 = new 制限効果管理();

    this.ゾーン管理 = new ゾーン管理();
    this.準備管理 = new 準備管理();
    this.デッキ管理 = new デッキ管理();
    this.ターン管理 = new ターン管理();
    this.ターン判定 = new ターン判定();
    this.バトル管理 = new バトル管理();
    this.召喚管理 = new 召喚管理();
    this.配置管理 = new 配置管理();
    this.使用管理 = new 使用管理();
    this.破壊管理 = new 破壊管理();
    this.破棄管理 = new 破棄管理();
    this.継召管理 = new 継召管理();
    this.ソウルマジック管理 = new ソウルマジック管理();
    this.コア管理 = new コア管理();
    this.Lv管理 = new Lv管理();
    this.BP管理 = new BP管理();
    this.カードの表示形式管理 = new カードの表示形式管理();
    this.待機状態管理 = new 待機状態管理();
    this.プレイコスト管理 = new プレイコスト管理();

    this.スタートステップ管理 = new スタートステップ管理();
    this.コアステップ管理 = new コアステップ管理();
    this.ドローステップ管理 = new ドローステップ管理();
    this.リフレッシュステップ管理 = new リフレッシュステップ管理();
    this.エンドステップ管理 = new エンドステップ管理();
  }

  // === 準備（ゲーム開始前） ===

  // プレイヤーを追加し、7領域を生成する（ボイドは共通のため別途 ボイドを準備する で1度だけ用意する）
  プレイヤーを準備する(識別子: string, 名前: string): プレイヤー {
    const プレイヤー個体 = new プレイヤー(識別子, 名前);
    this.ゲーム.プレイヤーを追加(プレイヤー個体);
    this.ゾーン管理.プレイヤーの領域を生成(this.ゲーム, 識別子);
    return プレイヤー個体;
  }

  // 共通のボイドを用意する（両プレイヤーを準備した後に1度だけ呼ぶ）
  ボイドを準備する(): void {
    this.ゾーン管理.ボイドを生成(this.ゲーム);
  }

  // 構築済みデッキをそのままデッキエリアへ設定する
  デッキを設定する(プレイヤー識別子: string, デッキ: カード[]): boolean {
    const デッキエリア = this.ゾーン管理.デッキエリアを取得(this.ゲーム, プレイヤー識別子);
    if (!デッキエリア) {
      return false;
    }
    for (const カード of デッキ) {
      デッキエリア.カードを追加(カード);
    }
    return true;
  }

  // シャッフル・初期コア配置・初期ドローを行う（先攻/後攻の決定、引き直しの有無は別のメソッドで行う）
  準備を行う(プレイヤー識別子: string): void {
    this.準備管理.デッキをシャッフルする(this.ゲーム, プレイヤー識別子);
    this.準備管理.初期コアを配置(this.ゲーム, プレイヤー識別子);
    this.準備管理.初期ドロー(this.ゲーム, プレイヤー識別子);
  }

  先攻決定権を抽選する(): string | undefined {
    return this.準備管理.先攻決定権を抽選する(this.ゲーム);
  }

  先攻を決める(プレイヤー識別子: string): boolean {
    return this.準備管理.先攻を設定する(this.ゲーム, プレイヤー識別子);
  }

  手札を引き直す(プレイヤー識別子: string): boolean {
    return this.準備管理.手札を引き直す(this.ゲーム, プレイヤー識別子);
  }

  // 先攻のターンから試合を開始する（先攻を決める の後に呼ぶ）
  試合を開始する(): void {
    this.ゲーム.ゲームを開始();
    this.ターン管理.ターンを開始する(this.ゲーム);
  }

  // === ターン進行 ===

  試合終了か(): boolean {
    return this.勝敗結果?.勝利 === true;
  }

  勝敗結果を取得(): 勝利結果 | null {
    return this.勝敗結果;
  }

  現在のステップ(): ステップ名 | undefined {
    return this.ターン管理.現在のステップを取得(this.ゲーム);
  }

  // ターン起因処理ステップを自動で実行しながら、次に行動が必要な随意ステップまで進める
  // （先攻第1ターンのスキップ、ターン交代も含めて自動で処理する）。既に随意ステップならそこで停止する。
  // 試合が終了した場合はその時点で停止する。
  次の行動可能なステップまで進める(): ステップ名 | undefined {
    if (this.試合終了か()) {
      return this.現在のステップ();
    }

    // 8ステップ×プレイヤー数を大きく超える回数で打ち切り、無限ループを防ぐ
    for (let 安全カウンタ = 0; 安全カウンタ < 100; 安全カウンタ++) {
      const 現在の名前 = this.現在のステップ();
      const 現在の情報 = ステップ順.find(s => s.名前 === 現在の名前);
      if (!現在の情報) {
        break;
      }

      if (this.ターン判定.ステップをスキップするか(this.ゲーム, 現在の情報)) {
        this.ターン管理.次のステップへ(this.ゲーム);
        continue;
      }

      if (現在の情報.種別 !== 'ターン起因処理') {
        return 現在の名前; // 随意ステップ：制御を呼び出し側へ返す
      }

      this.ターン起因処理を実行する(現在の情報.名前);
      if (this.試合終了か()) {
        return this.現在のステップ();
      }

      this.ターン管理.次のステップへ(this.ゲーム);
    }

    return this.現在のステップ();
  }

  private ターン起因処理を実行する(ステップ名: ステップ名): void {
    switch (ステップ名) {
      case 'スタートステップ': {
        const 結果 = this.スタートステップ管理.ターン起因処理(this.ゲーム);
        if (結果) {
          this.勝敗結果 = 結果;
        }
        break;
      }
      case 'コアステップ':
        this.コアステップ管理.ターン起因処理(this.ゲーム);
        break;
      case 'ドローステップ':
        this.ドローステップ管理.ターン起因処理(this.ゲーム);
        break;
      case 'リフレッシュステップ':
        this.リフレッシュステップ管理.ターン起因処理(this.ゲーム);
        break;
      case 'エンドステップ':
        this.エンドステップ管理.ターン起因処理(this.ゲーム);
        break;
      default:
        break; // メイン/アタック/第2メインは随意ステップのためここには来ない
    }
  }

  // 現在の随意ステップを終了し、次の行動可能なステップまで自動で進める
  // （「メインステップの終了」「アタックステップの終了」の宣言に対応）。
  ステップを終了する(): ステップ名 | undefined {
    if (this.試合終了か()) {
      return this.現在のステップ();
    }
    this.ターン管理.次のステップへ(this.ゲーム);
    return this.次の行動可能なステップまで進める();
  }

  // === 効果の解決 ===

  // 誘発型効果管理のキューから先頭を1件取り出し、効果エンジンで実行する。
  // 発揮源がまだ発揮できる状態かどうかの判定（9-1-5-5等）は、効果自身の 実行可能判定 に委ねる。
  // キューが空なら null を返す。
  async 誘発予約を1件解決する(): Promise<効果結果 | null> {
    const 予約 = this.誘発型効果管理.次を取り出す();
    if (!予約) {
      return null;
    }
    return this.効果エンジン.効果を実行(予約.効果識別子, {
      発動源: 予約.発揮源,
      ゲーム: this.ゲーム,
      追加データ: { 事象キー: 予約.事象キー, 所有者識別子: 予約.所有者識別子 },
    });
  }

  // キューが空になるまで誘発型効果を解決し続ける
  async 誘発予約をすべて解決する(): Promise<効果結果[]> {
    const 結果一覧: 効果結果[] = [];
    while (!this.誘発型効果管理.空か()) {
      const 結果 = await this.誘発予約を1件解決する();
      if (結果) {
        結果一覧.push(結果);
      }
    }
    return 結果一覧;
  }

  // === バトル ===

  // バトルのフラッシュタイミングを開始する（防御側から。8-1-2／8-1-4）。
  // 1回のバトルごとに使い切りの状態機械のため、都度新しく生成して返す。
  フラッシュタイミングを開始する(防御側識別子: string, 攻撃側識別子: string): フラッシュタイミング管理 {
    return new フラッシュタイミング管理(防御側識別子, 攻撃側識別子);
  }
}
