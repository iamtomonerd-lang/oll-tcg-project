  readonly ソウルマジック管理: ソウルマジック管理;
  readonly コア管理: コア管理;
  readonly Lv管理: Lv管理;
  readonly BP管理: BP管理;
  readonly カードの表示形式管理: カードの表示形式管理;
  readonly 待機状態管理: 待機状態管理;
  readonly プレイコスト管理: プレイコスト管理;

