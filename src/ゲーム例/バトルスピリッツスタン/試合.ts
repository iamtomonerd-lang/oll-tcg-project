  readonly ゲーム: ゲームエンジン;
  readonly 効果エンジン: 効果エンジン;
  // カードの効果はデータで書かれ、この実行器がインタプリタで解釈する
  readonly 効果実行器: 効果実行器;
  // 「このバトル中」「このターン中」の期限付き効果を戻すための記録
  readonly 一時効果管理: 一時効果管理;
  // ずっと働いている効果（BPの補正・「〜されない」）の問い合わせ先
  readonly 常在効果管理: 常在効果管理;
  // 「このターンに〜していたなら」を答えるための、ターン内の出来事の記録
  readonly ターン履歴管理: ターン履歴管理;

  // 状態を持つ管理（項目3：単一インスタンスをここで共有する）
  readonly 誘発型効果管理: 誘発型効果管理;
  readonly 置換型効果管理: 置換型効果管理;
  readonly 制限効果管理: 制限効果管理;

  // 状態を持たない各種管理（カード／ゾーンを都度受け取って操作する）
  readonly ゾーン管理: ゾーン管理;
  readonly 準備管理: 準備管理;
  readonly デッキ管理: デッキ管理;
  readonly ターン管理: ターン管理;
  readonly ターン判定: ターン判定;
