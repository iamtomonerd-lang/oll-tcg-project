import { ゲームエンジン } from '../../../ゲームエンジン.js';
import { ステップ名, ステップ情報, ステップ順 } from '../ターン/ステップ.js';

// ターン管理（ゲームエンジン層）
// ターンプレイヤーが8ステップをこの順に実行する。
// エンドステップの次は、ターンプレイヤーを交代して次のターンのスタートステップへ進む。
export class ターン管理 {
  // ターンを開始する（最初のステップ＝スタートステップに設定）
  ターンを開始する(ゲーム: ゲームエンジン): void {
    this.ステップを設定(ゲーム, ステップ順[0]);
  }

  // 現在のステップ名を取得
  現在のステップを取得(ゲーム: ゲームエンジン): ステップ名 | undefined {
    const 名前 = ゲーム.現在のフェーズを取得()?.名前;
    return this.ステップ名か(名前) ? 名前 : undefined;
  }

  // 次のステップへ進む。
  // エンドステップの次はターンプレイヤーを交代し、次のターンのスタートステップへ。
  // 戻り値：ターンが交代した（新しいターンに入った）場合 true
  次のステップへ(ゲーム: ゲームエンジン): boolean {
    const 現在 = this.現在のステップを取得(ゲーム);
    const 現在の順序 = ステップ順.findIndex(s => s.名前 === 現在);

    // 最後（エンドステップ）または不明なら、ターン交代して先頭へ
    if (現在の順序 < 0 || 現在の順序 >= ステップ順.length - 1) {
      ゲーム.次のプレイヤーに切り替え();
      this.ステップを設定(ゲーム, ステップ順[0]);
      return true;
    }

    this.ステップを設定(ゲーム, ステップ順[現在の順序 + 1]);
    return false;
  }

  private ステップを設定(ゲーム: ゲームエンジン, ステップ: ステップ情報): void {
    ゲーム.現在のフェーズを設定({ 名前: ステップ.名前, 順序: ステップ.順序 });
  }

  private ステップ名か(名前: string | undefined): 名前 is ステップ名 {
    return ステップ順.some(s => s.名前 === 名前);
  }
}
