// 対象指定（ゲームエンジン層 ＝ 遷移する者）
// 解決の際、指示があった段階で対象（カードやプレイヤー等）を選択し確定する（9-3-2）。
// 一度確定した対象は、後で対象が指定する条件から外れても再選択・変更されない
// （指定する() は最初の1回のみ有効。以後の呼び出しは無視される）。
export class 対象指定<T> {
  private 確定済み: T[] | null = null;

  // 対象を確定する。既に確定済みなら何もしない（再指定の禁止）。
  指定する(対象: T[]): void {
    if (this.確定済み !== null) {
      return;
    }
    this.確定済み = [...対象];
  }

  確定済みか(): boolean {
    return this.確定済み !== null;
  }

  取得(): T[] {
    return this.確定済み ? [...this.確定済み] : [];
  }
}
