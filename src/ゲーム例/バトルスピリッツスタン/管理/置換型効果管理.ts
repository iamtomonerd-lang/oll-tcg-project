import { 置換型効果判定, 置換型効果 } from '../判定/置換型効果判定.js';

// 置換型効果管理（ゲームエンジン層 ＝ 遷移する者）
// 事象ごとに「既に置換されたか」を記録し、多重置換を防ぐ（9-1-8-1-2）。
// ※置換候補の中からどれを解決するかはターンプレイヤーが決める（9-1-8-1-3）。
//   実際の選択（プレイヤーの意思決定）は呼び出し側（効果システム／UI）が行い、
//   ここでは選ばれた1つを適用し、事象を置換済みとして記録するのみを担う。
export class 置換型効果管理 {
  private 置換型効果判定: 置換型効果判定;
  private 置換済み事象: Set<string> = new Set();

  // 状態を写し取る（先読みで盤面を複製するため）
  状態を写す(元: 置換型効果管理): void {
    this.置換済み事象 = new Set(元.置換済み事象);
  }

  constructor() {
    this.置換型効果判定 = new 置換型効果判定();
  }

  // 指定した事象がまだ置換されていないか
  適用可能か(事象識別子: string): boolean {
    return this.置換型効果判定.適用可能か(事象識別子, this.置換済み事象);
  }

  // 複数の置換型効果がある場合の候補一覧を返す（9-1-8-1-3：どれを解決するかはターンプレイヤーが決める）
  // 既に置換済みの事象には候補を提示しない（9-1-8-1-2）。
  適用候補を取得(事象識別子: string, 候補一覧: 置換型効果[]): 置換型効果[] {
    if (!this.適用可能か(事象識別子)) {
      return [];
    }
    return [...候補一覧];
  }

  // ターンプレイヤーが選んだ置換型効果を適用する。
  // 適用後、その事象は置換済みとして記録され、以後この事象を再度置換することはできない（9-1-8-1-2）。
  置換を適用する(事象識別子: string, 選ばれた効果: 置換型効果): boolean {
    if (!this.適用可能か(事象識別子)) {
      return false;
    }
    this.置換済み事象.add(事象識別子);
    return true;
  }
}
