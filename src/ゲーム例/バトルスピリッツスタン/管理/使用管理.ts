import { ゲームエンジン } from '../../../ゲームエンジン.js';
import { カード } from '../../../データ/カード/カード.js';
import { カード種別ルール } from '../カードの情報/カード種別.js';
import { コストルール } from '../カードの情報/コスト.js';
import { 軽減シンボルルール } from '../カードの情報/軽減シンボル.js';
import { シンボルルール } from '../カードの情報/シンボル.js';
import { コア支払い元 } from '../判定/プレイコスト判定.js';
import { ゾーン管理 } from './ゾーン管理.js';
import { コア管理 } from './コア管理.js';
import { プレイコスト管理 } from './プレイコスト管理.js';

// 使用管理（ゲームエンジン層 ＝ 遷移する者）
// マジックカードを使用する（11-3）。
//  11-3-1-1 使用するカードを提示する（手札にあることを確認）
//  11-3-1-2 使用するカードのコストを確認する
//  11-3-1-3／11-2-1-4／11-3-1-4-1 軽減するコストを確認する。《継召》（12-2-1-3）で満たした
//    軽減シンボルの数は、呼び出し側が 継召による軽減数 として渡す（継召管理.発揮する の戻り値）
//  11-3-1-5 使用コストの数だけ、プレイヤーが選んだフィールド／リザーブのコアをトラッシュへ移動する（過剰不可）
//  11-3-1-6 使用された効果発揮中のマジックは、どの領域にも属していないものとする
//           （手札から取り出すのみで、フィールド等どこにも置かない。'効果発揮中' フラグで表す）
export class 使用管理 {
  private カード種別ルール: カード種別ルール;
  private コストルール: コストルール;
  private 軽減シンボルルール: 軽減シンボルルール;
  private シンボルルール: シンボルルール;
  private ゾーン管理: ゾーン管理;
  private コア管理: コア管理;
  private プレイコスト管理: プレイコスト管理;

  constructor() {
    this.カード種別ルール = new カード種別ルール();
    this.コストルール = new コストルール();
    this.軽減シンボルルール = new 軽減シンボルルール();
    this.シンボルルール = new シンボルルール();
    this.ゾーン管理 = new ゾーン管理();
    this.コア管理 = new コア管理();
    this.プレイコスト管理 = new プレイコスト管理();
  }

  使用する(
    ゲーム: ゲームエンジン,
    プレイヤー識別子: string,
    カード: カード,
    コスト支払い元一覧: コア支払い元[],
    継召による軽減数: number = 0
  ): boolean {
    if (!this.カード種別ルール.マジックか(カード)) {
      return false;
    }

    const 手札 = this.ゾーン管理.手札を取得(ゲーム, プレイヤー識別子);
    const トラッシュ = this.ゾーン管理.トラッシュを取得(ゲーム, プレイヤー識別子);
    if (!手札 || !トラッシュ) {
      return false;
    }
    if (!手札.カードを取得(カード.識別子)) {
      return false; // 11-3-1-1：使用するカードが手札に無い
    }

    // 11-3-1-2：コストを確認する
    const 基本コスト = this.コストルール.コストを取得(カード);
    // 11-3-1-3／4／4-1：軽減するコストを確認する
    const フィールドのシンボル = this.フィールドのシンボルを取得(ゲーム, プレイヤー識別子);
    const フィールド軽減後コスト = this.軽減シンボルルール.軽減後のコストを計算(カード, 基本コスト, フィールドのシンボル);
    // 継召で満たした分をさらに軽減する
    const 使用コスト = Math.max(0, フィールド軽減後コスト - 継召による軽減数);

    // 11-3-1-5：使用コストを支払う（トラッシュへ、ちょうどの数のみ）
    const トラッシュ保持者 = this.コア管理.ゾーンを保持者に(トラッシュ);
    if (!this.プレイコスト管理.コストを支払う(コスト支払い元一覧, トラッシュ保持者, 使用コスト)) {
      return false;
    }

    // 11-3-1-6：手札から取り出し、どの領域にも属さない状態にする（効果発揮中フラグ）
    手札.カードを削除(カード.識別子);
    カード.状態を設定('効果発揮中', true);

    return true;
  }

  // 使用中のマジックか（どの領域にも属していない状態か）
  効果発揮中か(カード: カード): boolean {
    return カード.状態を取得('効果発揮中') === true;
  }

  // 効果発揮中の状態を解除する（効果解決後、後述の規定に従いトラッシュ等へ置く処理は呼び出し側が行う）
  効果発揮を終える(カード: カード): void {
    カード.状態をクリア('効果発揮中');
  }

  private フィールドのシンボルを取得(ゲーム: ゲームエンジン, プレイヤー識別子: string): string[] {
    const フィールド = this.ゾーン管理.フィールドを取得(ゲーム, プレイヤー識別子);
    if (!フィールド) {
      return [];
    }
    const 色一覧: string[] = [];
    for (const カード of フィールド.カード一覧を取得()) {
      for (const シンボル of this.シンボルルール.シンボルを取得(カード)) {
        色一覧.push(シンボル.色);
      }
    }
    return 色一覧;
  }
}
