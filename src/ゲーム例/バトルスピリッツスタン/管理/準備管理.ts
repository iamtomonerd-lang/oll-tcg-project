import { ゲームエンジン } from '../../../ゲームエンジン.js';
import { ゾーン管理 } from './ゾーン管理.js';
import { コア管理 } from './コア管理.js';

// 準備管理（ゲームエンジン層）：ゲーム開始前の準備を行う。
// 各プレイヤーはボイドからコアを、ライフに5個、リザーブに通常3個＋ソウルコア1個（計4個）を置く。
// ※ボイドはゲーム外の無尽蔵のコア源として扱い、配置先へ直接置く（ボイドの数は減らさない）。
//   共通ボイドは単一のソウルコアフラグしか持たないため、各プレイヤーのソウルコアは
//   ボイドから移さず、リザーブへ直接置く。
export class 準備管理 {
  private ゾーン管理: ゾーン管理;
  private コア管理: コア管理;

  readonly ライフの初期コア数 = 5;
  readonly リザーブの初期通常コア数 = 3;

  constructor() {
    this.ゾーン管理 = new ゾーン管理();
    this.コア管理 = new コア管理();
  }

  // プレイヤーの初期コアを配置する
  // ライフ：通常コア5個、リザーブ：通常コア3個＋ソウルコア1個（総数4）
  初期コアを配置(ゲーム: ゲームエンジン, プレイヤー識別子: string): boolean {
    const ライフ = this.ゾーン管理.ライフを取得(ゲーム, プレイヤー識別子);
    const リザーブ = this.ゾーン管理.リザーブを取得(ゲーム, プレイヤー識別子);
    if (!ライフ || !リザーブ) {
      return false;
    }

    const ライフ保持者 = this.コア管理.ゾーンを保持者に(ライフ);
    const リザーブ保持者 = this.コア管理.ゾーンを保持者に(リザーブ);

    // ライフ：通常コア5個
    ライフ保持者.コア数を設定(this.ライフの初期コア数);

    // リザーブ：通常コア3個＋ソウルコア1個（総数はソウルコアを含めて4）
    リザーブ保持者.コア数を設定(this.リザーブの初期通常コア数 + 1);
    リザーブ保持者.ソウルコアを設定(true);

    return true;
  }
}
