import { ゲームエンジン } from '../../../ゲームエンジン.js';
import { ゾーン管理 } from './ゾーン管理.js';
import { コア管理 } from './コア管理.js';
import { 乱数, 既定の乱数 } from '../乱数.js';
import { デッキ管理 } from './デッキ管理.js';

// 準備管理（ゲームエンジン層）：ゲーム開始前の準備を行う。
// - 初期コア配置：ライフに5個、リザーブに通常3個＋ソウルコア1個（計4個）
// - 初期ドロー：各プレイヤーが4枚ドロー
// - 先攻後攻：決定権をランダム抽選し、先攻を最初のターンプレイヤーに設定
// - 手札の引き直し（マリガン）：手札をデッキに戻す→シャッフル→再度4枚ドロー
// ※先攻/後攻の選択、引き直しの有無 は呼び出し側（ゲーム進行）が決め、その結果を引数で渡す。
// ※ボイドはゲーム外の無尽蔵のコア源として扱い、配置先へ直接置く（ボイドの数は減らさない）。
//   共通ボイドは単一のソウルコアフラグしか持たないため、各プレイヤーのソウルコアは
//   ボイドから移さず、リザーブへ直接置く。
export class 準備管理 {
  private ゾーン管理: ゾーン管理;
  private コア管理: コア管理;
  private デッキ管理: デッキ管理;

  readonly ライフの初期コア数 = 5;
  readonly リザーブの初期通常コア数 = 3;
  readonly 初期手札枚数 = 4;

  // シャッフルに使う乱数を持ち回す。渡さなければ Math.random。
  constructor(使う乱数: 乱数 = 既定の乱数) {
    this.ゾーン管理 = new ゾーン管理();
    this.コア管理 = new コア管理();
    this.デッキ管理 = new デッキ管理(使う乱数);
  }

  // プレイヤーの初期コアを配置する
  // ライフ：通常コア5個、リザーブ：通常コア3個＋ソウルコア1個（総数4）
  初期コアを配置(ゲーム: ゲームエンジン, プレイヤー識別子: string): boolean {
    const ライフ = this.ゾーン管理.ライフを取得(ゲーム, プレイヤー識別子);
    const リザーブ = this.ゾーン管理.リザーブを取得(ゲーム, プレイヤー識別子);
    if (!ライフ || !リザーブ) {
      return false;
    }

    const ライフ保持者 = this.コア管理.ゾーンを保持者に(ライフ);
    const リザーブ保持者 = this.コア管理.ゾーンを保持者に(リザーブ);

    // ライフ：通常コア5個
    ライフ保持者.コア数を設定(this.ライフの初期コア数);

    // リザーブ：通常コア3個＋ソウルコア1個（総数はソウルコアを含めて4）
    リザーブ保持者.コア数を設定(this.リザーブの初期通常コア数 + 1);
    リザーブ保持者.ソウルコアを設定(true);

    return true;
  }

  // デッキをシャッフルする
  デッキをシャッフルする(ゲーム: ゲームエンジン, プレイヤー識別子: string): boolean {
    return this.デッキ管理.シャッフルする(ゲーム, プレイヤー識別子);
  }

  // 初期ドロー（4枚）。実際に引いた枚数を返す。
  初期ドロー(ゲーム: ゲームエンジン, プレイヤー識別子: string): number {
    return this.デッキ管理.ドローする(ゲーム, プレイヤー識別子, this.初期手札枚数);
  }

  // 先攻・後攻の決定権を持つプレイヤーをランダムに抽選する
  先攻決定権を抽選する(ゲーム: ゲームエンジン): string | undefined {
    const 全員 = ゲーム.全プレイヤーを取得();
    if (全員.length === 0) {
      return undefined;
    }
    const 添字 = Math.floor(Math.random() * 全員.length);
    return 全員[添字].識別子;
  }

  // 先攻プレイヤーを最初のターンプレイヤーに設定する
  // universalを編集せず、現在のプレイヤーが先攻になるまで切り替える（2人なら最大1回）
  先攻を設定する(ゲーム: ゲームエンジン, 先攻プレイヤー識別子: string): boolean {
    const 全員 = ゲーム.全プレイヤーを取得();
    if (!全員.some(p => p.識別子 === 先攻プレイヤー識別子)) {
      return false;
    }
    let 安全カウンタ = 全員.length;
    while (
      ゲーム.現在のプレイヤーを取得()?.識別子 !== 先攻プレイヤー識別子 &&
      安全カウンタ-- > 0
    ) {
      ゲーム.次のプレイヤーに切り替え();
    }
    return ゲーム.現在のプレイヤーを取得()?.識別子 === 先攻プレイヤー識別子;
  }

  // 手札の引き直し（マリガン）：手札をデッキに戻す→シャッフル（自分＋相手の2回）→再度4枚ドロー
  // 引き直すかどうかの判断は呼び出し側が行い、引き直す場合のみ本メソッドを呼ぶ。
  手札を引き直す(ゲーム: ゲームエンジン, プレイヤー識別子: string): boolean {
    if (!this.デッキ管理.手札をデッキに戻す(ゲーム, プレイヤー識別子)) {
      return false;
    }
    // 自分がシャッフルし、続けて相手がシャッフルする（手続き上の2回）
    this.デッキ管理.シャッフルする(ゲーム, プレイヤー識別子);
    this.デッキ管理.シャッフルする(ゲーム, プレイヤー識別子);
    // 上から再度4枚ドロー
    this.デッキ管理.ドローする(ゲーム, プレイヤー識別子, this.初期手札枚数);
    return true;
  }
}
