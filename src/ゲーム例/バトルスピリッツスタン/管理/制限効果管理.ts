import { 制限効果判定, ターン1回記録 } from '../判定/制限効果判定.js';

// 制限効果管理（ゲームエンジン層 ＝ 遷移する者）
// 〔ターン1回〕（12-3-1）の発揮記録を管理する。カードのインスタンスごとに独立して記録するため、
// 同名カードが複数あっても、それぞれが1回ずつ発揮できる（12-3-1-2）。
// 〔重複不可〕は誘発型効果管理の重複排除（9-1-5-4）で表現するため、ここでは扱わない
// （判定/制限効果判定.ts のコメントを参照）。
export class 制限効果管理 {
  private 制限効果判定: 制限効果判定;
  private 記録: ターン1回記録[] = [];

  constructor() {
    this.制限効果判定 = new 制限効果判定();
  }

  // このカード・この効果が、指定ターンでまだ発揮していないか
  ターン1回は発揮可能か(カード識別子: string, 効果識別子: string, 現在のターン数: number): boolean {
    return !this.制限効果判定.ターン1回は発揮済みか(this.記録, カード識別子, 効果識別子, 現在のターン数);
  }

  // 発揮したことを記録する（発揮可能な場合のみ記録する）
  ターン1回を記録する(カード識別子: string, 効果識別子: string, 現在のターン数: number): boolean {
    if (!this.ターン1回は発揮可能か(カード識別子, 効果識別子, 現在のターン数)) {
      return false;
    }
    this.記録.push({ カード識別子, 効果識別子, ターン数: 現在のターン数 });
    return true;
  }
}
