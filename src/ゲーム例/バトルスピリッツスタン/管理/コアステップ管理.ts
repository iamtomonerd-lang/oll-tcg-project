import { ゲームエンジン } from '../../../ゲームエンジン.js';
import { ゾーン管理 } from './ゾーン管理.js';
import { コア管理 } from './コア管理.js';

// コアステップ管理（ゲームエンジン層）
// コアステップのターン起因処理：ターンプレイヤーがボイドからコア1個をリザーブに置く。
// 先攻の第1ターンにはこのステップが存在しない（スキップ）が、その判定は
// ステップ定義の「先攻第1ターンにスキップ」フラグ＋ターン判定.ステップをスキップするか に集約している。
// ※『コアステップ』の誘発条件の効果の発揮、および解決待ち効果の解決は
//   効果システム側（未実装）の担当。
export class コアステップ管理 {
  private ゾーン管理: ゾーン管理;
  private コア管理: コア管理;

  readonly 配置コア数 = 1;

  constructor() {
    this.ゾーン管理 = new ゾーン管理();
    this.コア管理 = new コア管理();
  }

  // ターン起因処理：ターンプレイヤーがボイドからコア1個をリザーブに置く
  ターン起因処理(ゲーム: ゲームエンジン): boolean {
    const ターンプレイヤー = ゲーム.現在のプレイヤーを取得();
    if (!ターンプレイヤー) {
      return false;
    }
    const リザーブ = this.ゾーン管理.リザーブを取得(ゲーム, ターンプレイヤー.識別子);
    if (!リザーブ) {
      return false;
    }
    const リザーブ保持者 = this.コア管理.ゾーンを保持者に(リザーブ);
    this.コア管理.ボイドからコアを置く(リザーブ保持者, this.配置コア数);
    return true;
  }
}
