import { test } from 'node:test';
import assert from 'node:assert/strict';

import { ゲームエンジン } from '../../../ゲームエンジン.js';
import { グンガタを作成 } from '../カードデータ/グンガタ.js';
import { ゾーン管理 } from './ゾーン管理.js';
import { 待機状態管理 } from './待機状態管理.js';
import { Lv管理 } from './Lv管理.js';

test('待機状態にする：理由と移動先を記録し、初めて待機状態になった時点のLvをスナップショットする（10-2-2-3）', () => {
  const 管理 = new 待機状態管理();
  const カード = グンガタを作成('test-1');
  new Lv管理().Lvを更新(カード, 3); // Lv2にしておく

  管理.待機状態にする(カード, '破壊', 'トラッシュ');

  assert.equal(管理.待機状態か(カード), true);
  assert.equal(管理.待機理由を取得(カード), '破壊');
  assert.equal(管理.移動先を取得(カード), 'トラッシュ');
  assert.equal(管理.待機時Lvを取得(カード), 2);
});

test('待機状態にする：帰還後にLvが変わっても、待機時Lvは最初に待機状態化した時点のまま', () => {
  const 管理 = new 待機状態管理();
  const Lv管理個体 = new Lv管理();
  const カード = グンガタを作成('test-2');
  Lv管理個体.Lvを更新(カード, 1);

  管理.待機状態にする(カード, '消滅');
  assert.equal(管理.待機時Lvを取得(カード), 1);

  Lv管理個体.Lvを更新(カード, 3); // 待機状態化した後にLvが変わっても
  管理.待機状態にする(カード, '消滅'); // 既に待機状態なので「初めて」には当たらない

  assert.equal(管理.待機時Lvを取得(カード), 1);
});

test('別の待機状態に変化する：異なる理由になら変化できる。移動先の指定が無ければ元のまま', () => {
  const 管理 = new 待機状態管理();
  const カード = グンガタを作成('test-3');
  管理.待機状態にする(カード, '帰還', '手札');

  const 成功 = 管理.別の待機状態に変化する(カード, '消滅');

  assert.equal(成功, true);
  assert.equal(管理.待機理由を取得(カード), '消滅');
  assert.equal(管理.移動先を取得(カード), '手札', '移動先の指定が無ければ元の移動先を保持する（10-2-2-7）');
});

test('別の待機状態に変化する：同じ理由への変化は起こらない（10-2-2-6-1）', () => {
  const 管理 = new 待機状態管理();
  const カード = グンガタを作成('test-4');
  管理.待機状態にする(カード, '破壊');

  const 成功 = 管理.別の待機状態に変化する(カード, '破壊');

  assert.equal(成功, false);
});

test('待機状態へ遷移：消滅条件を満たさなければ何もしない', () => {
  const 管理 = new 待機状態管理();
  const カード = グンガタを作成('test-5');
  assert.equal(管理.待機状態へ遷移(カード, 5), false);
  assert.equal(管理.待機状態か(カード), false);
});

test('待機状態へ遷移：消滅条件を満たせば理由=消滅で待機状態にする', () => {
  const 管理 = new 待機状態管理();
  const カード = グンガタを作成('test-6');
  const 成功 = 管理.待機状態へ遷移(カード, 0);
  assert.equal(成功, true);
  assert.equal(管理.待機理由を取得(カード), '消滅');
});

test('待機状態へ遷移：既に帰還で待機状態中なら、消滅へ変化する（同じ理由の再遷移にはしない）', () => {
  const 管理 = new 待機状態管理();
  const カード = グンガタを作成('test-7');
  管理.待機状態にする(カード, '帰還', '手札');

  const 成功 = 管理.待機状態へ遷移(カード, 0);

  assert.equal(成功, true);
  assert.equal(管理.待機理由を取得(カード), '消滅');
  assert.equal(管理.移動先を取得(カード), '手札', '帰還中の消滅は、新たな移動効果が無ければ元の移動先を保持する（10-2-2-7）');
});

test('消滅原因を記録する／取得：記録した消滅原因をそのまま読み取れる', () => {
  const 管理 = new 待機状態管理();
  const カード = グンガタを作成('test-8');
  管理.消滅原因を記録する(カード, { 種別: '効果によるコア変化', 効果識別子: 'x' });
  assert.deepEqual(管理.消滅原因を取得(カード), { 種別: '効果によるコア変化', 効果識別子: 'x' });
});

test('待機状態から復帰：待機状態に関する状態をすべてクリアする', () => {
  const 管理 = new 待機状態管理();
  const カード = グンガタを作成('test-9');
  管理.待機状態にする(カード, '破壊');
  管理.消滅原因を記録する(カード, { 種別: '自分の行動によるコスト変化', プレイヤー識別子: 'p1' });

  管理.待機状態から復帰(カード);

  assert.equal(管理.待機状態か(カード), false);
  assert.equal(管理.待機理由を取得(カード), undefined);
  assert.equal(管理.移動先を取得(カード), undefined);
  assert.equal(管理.消滅原因を取得(カード), undefined);
});

test('解決する：待機状態でなければ何もしない', () => {
  const 管理 = new 待機状態管理();
  const ゾーン管理個体 = new ゾーン管理();
  const ゲーム = new ゲームエンジン();
  ゾーン管理個体.プレイヤーの領域を生成(ゲーム, 'p1');
  const カード = グンガタを作成('test-10');

  assert.equal(管理.解決する(ゲーム, 'p1', カード), false);
});

test('解決する：帰還（移動先=デッキエリア）なら、フィールドからデッキエリアへ移し、コアはリザーブへ戻す', () => {
  const 管理 = new 待機状態管理();
  const ゾーン管理個体 = new ゾーン管理();
  const ゲーム = new ゲームエンジン();
  ゾーン管理個体.プレイヤーの領域を生成(ゲーム, 'p1');

  const フィールド = ゾーン管理個体.フィールドを取得(ゲーム, 'p1')!;
  const デッキエリア = ゾーン管理個体.デッキエリアを取得(ゲーム, 'p1')!;
  const リザーブ = ゾーン管理個体.リザーブを取得(ゲーム, 'p1')!;

  const カード = グンガタを作成('test-11');
  カード.数値を設定('コア数', 2);
  フィールド.カードを追加(カード);
  管理.待機状態にする(カード, '帰還', 'デッキエリア');

  const 成功 = 管理.解決する(ゲーム, 'p1', カード);

  assert.equal(成功, true);
  assert.equal(フィールド.カードを取得(カード.識別子), undefined);
  assert.ok(デッキエリア.カードを取得(カード.識別子));
  assert.equal(カード.数値を取得('コア数'), 0);
  assert.equal(リザーブ.状態を取得('コア数'), 2);
  assert.equal(管理.待機状態か(カード), false, '解決後は待機状態から復帰する');
});
