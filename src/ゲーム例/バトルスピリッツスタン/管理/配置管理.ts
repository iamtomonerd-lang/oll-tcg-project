import { ゲームエンジン } from '../../../ゲームエンジン.js';
import { カード } from '../../../データ/カード/カード.js';
import { カード種別ルール } from '../カードの情報/カード種別.js';
import { コストルール } from '../カードの情報/コスト.js';
import { 軽減シンボルルール } from '../カードの情報/軽減シンボル.js';
import { シンボルルール } from '../カードの情報/シンボル.js';
import { 消滅判定 } from '../判定/消滅判定.js';
import { コア支払い元, プレイコスト判定 } from '../判定/プレイコスト判定.js';
import { ゾーン管理 } from './ゾーン管理.js';
import { コア管理 } from './コア管理.js';
import { プレイコスト管理 } from './プレイコスト管理.js';
import { Lv管理 } from './Lv管理.js';

// 配置管理（ゲームエンジン層 ＝ 遷移する者）
// ネクサスカードを配置する（11-2）。手順は召喚（11-1）とほぼ同じで、対象がネクサスである点のみ異なる。
//  11-2-1-1 配置するカードを提示する（手札にあることを確認）
//  11-2-1-2 配置するカードのコストを確認する
//  11-2-1-3／11-2-1-4／11-2-1-4-1 軽減するコストを確認する（《継召》は12-2-1-3で後述、
//    満たす軽減シンボルは呼び出し側が 継召提供シンボル として渡す）
//  11-2-1-5 配置コストの数だけ、プレイヤーが選んだフィールド／リザーブのコアをトラッシュへ移動する（過剰不可）
//  11-2-1-6 カードをフィールドに置き、最低LvのLvコスト以上のコアをカードに置く
export class 配置管理 {
  private カード種別ルール: カード種別ルール;
  private コストルール: コストルール;
  private 軽減シンボルルール: 軽減シンボルルール;
  private シンボルルール: シンボルルール;
  private 消滅判定: 消滅判定;
  private ゾーン管理: ゾーン管理;
  private コア管理: コア管理;
  private プレイコスト管理: プレイコスト管理;
  private プレイコスト判定: プレイコスト判定;
  private Lv管理: Lv管理;

  constructor() {
    this.カード種別ルール = new カード種別ルール();
    this.コストルール = new コストルール();
    this.軽減シンボルルール = new 軽減シンボルルール();
    this.シンボルルール = new シンボルルール();
    this.消滅判定 = new 消滅判定();
    this.ゾーン管理 = new ゾーン管理();
    this.コア管理 = new コア管理();
    this.プレイコスト管理 = new プレイコスト管理();
    this.プレイコスト判定 = new プレイコスト判定();
    this.Lv管理 = new Lv管理();
  }

  配置する(
    ゲーム: ゲームエンジン,
    プレイヤー識別子: string,
    カード: カード,
    コスト支払い元一覧: コア支払い元[],
    初期コア配置元一覧: コア支払い元[],
    継召提供シンボル: string[] = []
  ): boolean {
    if (!this.カード種別ルール.ネクサスか(カード)) {
      return false;
    }

    const 手札 = this.ゾーン管理.手札を取得(ゲーム, プレイヤー識別子);
    const フィールド = this.ゾーン管理.フィールドを取得(ゲーム, プレイヤー識別子);
    const リザーブ = this.ゾーン管理.リザーブを取得(ゲーム, プレイヤー識別子);
    const トラッシュ = this.ゾーン管理.トラッシュを取得(ゲーム, プレイヤー識別子);
    if (!手札 || !フィールド || !リザーブ || !トラッシュ) {
      return false;
    }
    if (!手札.カードを取得(カード.識別子)) {
      return false; // 11-2-1-1：配置するカードが手札に無い
    }

    // 11-2-1-2：コストを確認する
    const 基本コスト = this.コストルール.コストを取得(カード);
    // 11-2-1-3／4／4-1：軽減するコストを確認する（継召が満たす軽減シンボルも加味）
    const フィールドのシンボル = this.フィールドのシンボルを取得(ゲーム, プレイヤー識別子);
    const 配置コスト = this.軽減シンボルルール.軽減後のコストを計算(
      カード,
      基本コスト,
      [...フィールドのシンボル, ...継召提供シンボル]
    );

    // 11-2-1-6 後半の実行可能性を先に検証しておく
    const 最低必要数 = this.消滅判定.最小必要コア数を取得(カード);
    if (
      !this.プレイコスト判定.初期配置数は十分か(初期コア配置元一覧, 最低必要数) ||
      !this.プレイコスト判定.各支払い元に十分なコアがあるか(初期コア配置元一覧)
    ) {
      return false;
    }

    // 11-2-1-5：配置コストを支払う（トラッシュへ、ちょうどの数のみ）
    const トラッシュ保持者 = this.コア管理.ゾーンを保持者に(トラッシュ);
    if (!this.プレイコスト管理.コストを支払う(コスト支払い元一覧, トラッシュ保持者, 配置コスト)) {
      return false;
    }

    // 11-2-1-6 前半：カードをフィールドに置く
    const 取り出したカード = 手札.カードを削除(カード.識別子);
    if (取り出したカード) {
      フィールド.カードを追加(取り出したカード);
    }

    // 11-2-1-6 後半：最低LvのLvコスト以上のコアをカードに置く（検証済みなので必ず成功する）
    const カード保持者 = this.コア管理.カードを保持者に(カード);
    this.プレイコスト管理.初期コアを配置する(初期コア配置元一覧, カード保持者, 最低必要数);

    // 置いたコア数に応じてLvを更新する
    this.Lv管理.Lvを更新(カード, カード保持者.コア数を取得(), カード保持者.ソウルコアあるか());

    return true;
  }

  private フィールドのシンボルを取得(ゲーム: ゲームエンジン, プレイヤー識別子: string): string[] {
    const フィールド = this.ゾーン管理.フィールドを取得(ゲーム, プレイヤー識別子);
    if (!フィールド) {
      return [];
    }
    const 色一覧: string[] = [];
    for (const カード of フィールド.カード一覧を取得()) {
      for (const シンボル of this.シンボルルール.シンボルを取得(カード)) {
        色一覧.push(シンボル.色);
      }
    }
    return 色一覧;
  }
}
