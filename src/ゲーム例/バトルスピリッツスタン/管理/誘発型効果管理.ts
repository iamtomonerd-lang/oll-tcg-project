import { カード } from '../../../データ/カード/カード.js';
import { 誘発型効果判定, 誘発予約 } from '../判定/誘発型効果判定.js';

// 誘発型効果管理（ゲームエンジン層 ＝ 遷移する者）
// 条件となる事象が発生した際の誘発予約をキューとして管理する。
// ※誘発条件の判定・効果の具体的な処理内容は効果システム側（未実装）の担当。
//   ここは「誘発した」という事実をキューに積み、順序と重複を管理するのみ。
export class 誘発型効果管理 {
  private 誘発型効果判定: 誘発型効果判定;
  private キュー: 誘発予約[] = [];
  private 次の予約番号 = 1;

  constructor() {
    this.誘発型効果判定 = new 誘発型効果判定();
  }

  // 誘発する：キューに予約を積む。
  // 事象キーが既存の予約と重複する場合は何もしない（9-1-5-4：同時発生でも1回だけ誘発）。
  // 解決中（他の効果を解決している最中）に誘発した場合は、キューの先頭に挿入して優先する（9-1-5-9）。
  誘発する(
    効果識別子: string,
    発揮源: カード,
    所有者識別子: string,
    事象キー: string,
    解決中: boolean = false
  ): 誘発予約 | null {
    if (this.誘発型効果判定.事象に対して誘発済みか(this.キュー, 効果識別子, 事象キー)) {
      return null; // 同一事象で既に誘発済み（9-1-5-4）
    }

    const 予約: 誘発予約 = {
      予約識別子: `誘発-${this.次の予約番号++}`,
      効果識別子,
      発揮源,
      所有者識別子,
      事象キー,
    };

    if (解決中) {
      this.キュー.unshift(予約); // 新たな誘発を優先（9-1-5-9）
    } else {
      this.キュー.push(予約);
    }
    return 予約;
  }

  // 現在キューにある予約の一覧（読み取り専用）
  キューを取得(): 誘発予約[] {
    return [...this.キュー];
  }

  空か(): boolean {
    return this.キュー.length === 0;
  }

  // 同時に誘発した予約を、指定した順序に一括で並び替える（9-1-5-7：自分のみ複数／9-1-5-8：自分と相手が混在）
  // どちらの場合も、並べる主体（自分のみなら自分、混在ならターンプレイヤー）が
  // 好きな順番を選べるため、選ばれた順序（予約識別子の配列）をそのまま適用する。
  // ※9-4-1のように「1つ選んで解決→また選ぶ」を繰り返す場合は、
  //   これで一括固定するのではなく 指定した予約を取り出す を都度呼ぶ方が適切。
  順序を指定する(新しい順序: string[]): boolean {
    if (新しい順序.length !== this.キュー.length) {
      return false;
    }
    const 現在の識別子集合 = new Set(this.キュー.map(p => p.予約識別子));
    if (!新しい順序.every(id => 現在の識別子集合.has(id))) {
      return false;
    }
    const 予約マップ = new Map(this.キュー.map(p => [p.予約識別子, p]));
    this.キューを置換(新しい順序.map(id => 予約マップ.get(id)!));
    return true;
  }

  // 先頭の予約を1つ取り出して解決する（呼び出し側が発揮可能かを確認してから効果を処理する）
  次を取り出す(): 誘発予約 | undefined {
    return this.キューから取り出す();
  }

  // 同時に発揮タイミングを満たした効果の中から、指定した1件を選んで取り出す（9-4-1）。
  // 9-4-1は一括で全順序を固定するのではなく「1つ選んで解決→また選ぶ」を繰り返す手順のため、
  // 順序を指定する（一括並び替え）とは別に、キューのどこにある予約でも個別に取り出せるようにする。
  // これにより、解決の合間に新たな誘発（誘発するの解決中=trueで先頭挿入）が割り込んでも、
  // 次に選ぶ対象にそのまま反映される（9-4-1-1）。
  指定した予約を取り出す(予約識別子: string): 誘発予約 | undefined {
    const 添字 = this.キュー.findIndex(p => p.予約識別子 === 予約識別子);
    if (添字 < 0) {
      return undefined;
    }
    return this.キュー.splice(添字, 1)[0];
  }

  // 発揮できなくなった予約（発揮源がフィールドを離れた等）をキューから取り除く。
  // 9-1-5-5／9-4-1-2：発揮できるタイミングに発揮源が実際にいなければ、その効果は発揮できない。
  // 判定自体（今どの領域にいるか等）はゾーンを扱う呼び出し側に委ね、ここでは述語関数を受け取る。
  発揮できない予約を取り除く(発揮可能か: (予約: 誘発予約) => boolean): 誘発予約[] {
    const 残す: 誘発予約[] = [];
    const 取り除いた: 誘発予約[] = [];
    for (const 予約 of this.キュー) {
      if (発揮可能か(予約)) {
        残す.push(予約);
      } else {
        取り除いた.push(予約);
      }
    }
    this.キューを置換(残す);
    return 取り除いた;
  }

  private キューから取り出す(): 誘発予約 | undefined {
    return this.キュー.shift();
  }

  private キューを置換(新しいキュー: 誘発予約[]): void {
    this.キュー = 新しいキュー;
  }
}
