import { ゲームエンジン } from '../../../ゲームエンジン.js';
import { カード } from '../../../データ/カード/カード.js';
import { ゾーン } from '../../../データ/ゾーン/ゾーン.js';
import { 破棄判定 } from '../判定/破棄判定.js';
import { ゾーン管理 } from './ゾーン管理.js';

// 破棄管理（ゲームエンジン層 ＝ 遷移する者）
// 破棄 = 手札またはデッキから、そのカードの持ち主のトラッシュへカードを置くこと。
export class 破棄管理 {
  private 破棄判定: 破棄判定;
  private ゾーン管理: ゾーン管理;

  constructor() {
    this.破棄判定 = new 破棄判定();
    this.ゾーン管理 = new ゾーン管理();
  }

  // 手札またはデッキから、持ち主のトラッシュへカードを置く
  破棄する(ゲーム: ゲームエンジン, 持ち主識別子: string, カード: カード): boolean {
    const トラッシュ = this.ゾーン管理.トラッシュを取得(ゲーム, 持ち主識別子);
    if (!トラッシュ) {
      return false;
    }

    const 元領域 = this.破棄元を探す(ゲーム, 持ち主識別子, カード);
    if (!元領域) {
      return false; // 手札にもデッキにも無い
    }

    const 取り出したカード = 元領域.カードを削除(カード.識別子);
    if (!取り出したカード) {
      return false;
    }
    トラッシュ.カードを追加(取り出したカード);
    return true;
  }

  // 持ち主の手札・デッキのうち、対象カードがあり かつ 破棄可能な領域 を返す
  private 破棄元を探す(ゲーム: ゲームエンジン, 持ち主識別子: string, カード: カード): ゾーン | undefined {
    const 候補 = [
      this.ゾーン管理.手札を取得(ゲーム, 持ち主識別子),
      this.ゾーン管理.デッキエリアを取得(ゲーム, 持ち主識別子),
    ];
    for (const 領域 of 候補) {
      if (領域 && this.破棄判定.破棄可能な領域か(領域) && 領域.カードを取得(カード.識別子)) {
        return 領域;
      }
    }
    return undefined;
  }
}
