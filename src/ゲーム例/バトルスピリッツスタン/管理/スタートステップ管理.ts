import { ゲームエンジン } from '../../../ゲームエンジン.js';
import { ゾーン管理 } from './ゾーン管理.js';
import { 勝利結果 } from '../判定/勝利判定.js';

// スタートステップ管理（ゲームエンジン層）
// スタートステップのターン起因処理：ターンプレイヤーのデッキが0枚なら勝敗判定を行う。
// ※『スタートステップ』の誘発条件の効果の発揮、および解決待ち効果の解決は
//   効果システム側（未実装）の担当。ここではターン起因処理のみを行う。
export class スタートステップ管理 {
  private ゾーン管理: ゾーン管理;

  constructor() {
    this.ゾーン管理 = new ゾーン管理();
  }

  // ターン起因処理：ターンプレイヤーのデッキが0枚なら勝敗判定を行う。
  // また、前のターンで召喚されたカードの「召喚時」フラグをクリアする。
  ターン起因処理(ゲーム: ゲームエンジン): 勝利結果 | null {
    const ターンプレイヤー = ゲーム.現在のプレイヤーを取得();
    if (!ターンプレイヤー) {
      return null;
    }

    // このターンプレイヤーのターン数が2以上なら、前のターンの「召喚時」フラグをクリアする
    // （1ターン目なら、前のターンがないため何もしない）
    if (ターンプレイヤー.数値を取得('ターン数') >= 2) {
      this.前のターンの召喚フラグをクリア(ゲーム, ターンプレイヤー.識別子);
    }

    const デッキ = this.ゾーン管理.デッキエリアを取得(ゲーム, ターンプレイヤー.識別子);
    if (!デッキ) {
      return null;
    }

    if (デッキ.カード枚数を取得() > 0) {
      return null; // デッキが残っている
    }

    // デッキ0枚 → ターンプレイヤーの敗北（デッキ切れ）
    const 相手 = ゲーム.全プレイヤーを取得().find(p => p.識別子 !== ターンプレイヤー.識別子) ?? null;
    return {
      勝利: true,
      勝者: 相手,
      敗者: ターンプレイヤー,
      理由: `${ターンプレイヤー.名前} のデッキが0枚になりました`,
    };
  }

  private 前のターンの召喚フラグをクリア(ゲーム: ゲームエンジン, プレイヤー識別子: string): void {
    const フィールド = this.ゾーン管理.フィールドを取得(ゲーム, プレイヤー識別子);
    if (!フィールド) {
      return;
    }
    for (const カード of フィールド.カード一覧を取得()) {
      カード.状態をクリア('召喚時');
    }
  }
}
