import { カード } from '../../../データ/カード/カード.js';
import { カードフィルタ, 効果定義, 期間, 処理ステップ } from '../../../効果解釈/効果定義.js';
import type { 試合 } from '../試合.js';
import { 効果ルール } from '../カードの情報/効果.js';

// 常在効果管理
//
// 常在効果（種別:'常在'）は「発揮する」ものではなく「ずっと働いている」ものなので、
// 誘発のキューに積んでも扱えない。ここは問い合わせ式にしてある。
//   ・BPの補正 → BP管理が現在のBPを求めるたびに、ここへ「補正はいくら？」と聞く
//   ・ルールの書き換え → ブロックやライフ減少のルールが「この制約は働いている？」と聞く
//
// 状態を持って先に計算しておくと、コアが動いてLvが変わった瞬間に食い違う。
// そのため、聞かれたときに毎回その場で判定する。
//
// マジックのように「このターン中」だけ働く制約は盤面から読み取れないので、
// そちらは登録して期限で捨てる方式にする。

// 登録された（期限付きの）制約
interface 登録済み制約 {
  名: string;
  // 制約を受けるカード。プレイヤー全体にかかる制約（ライフなど）では undefined。
  対象: カード | undefined;
  // 制約の持ち主。「自分のライフは減らない」の "自分"。
  所有者識別子: string;
  相手: カードフィルタ | undefined;
  期限: 期間;
}

// 制約が働いているかを問うときの状況
export interface 制約の問い {
  // 制約を受けている側（「このスピリットはブロックされない」のこのスピリット）
  対象?: カード;
  // 制約を働かせる相手（「コスト4以下の相手のスピリットからは」のその相手）
  相手?: カード;
  // プレイヤーにかかる制約を問うとき（「自分のライフは減らない」）
  プレイヤー識別子?: string;
}

export class 常在効果管理 {
  private 試合: 試合;
  private 効果ルール = new 効果ルール();
  private 登録済み: 登録済み制約[] = [];
  // BPの条件を持つ常在効果を判定する途中で、またBPを聞かれる可能性があるための番人
  private 判定中 = false;

  // 状態を写し取る（先読みで盤面を複製するため）。
  // 登録済みの制約は対象のカードを指しているので、複製したカードに差し替える。
  // 対象が undefined の制約（プレイヤー全体にかかるもの）はそのまま写す。
  状態を写す(元: 常在効果管理, カードを解決: (識別子: string) => カード | undefined): void {
    this.登録済み = 元.登録済み
      .map(制約 => {
        if (制約.対象 === undefined) return { ...制約 };
        const 差し替えた対象 = カードを解決(制約.対象.識別子);
        return 差し替えた対象 ? { ...制約, 対象: 差し替えた対象 } : null;
      })
      .filter((制約): 制約 is 登録済み制約 => 制約 !== null);
    this.判定中 = false;
  }

  constructor(試合インスタンス: 試合) {
    this.試合 = 試合インスタンス;
  }

  // === BPの補正 ===

  // このカードに働いている常在効果によるBPの増減を合計する
  BP補正を取得(対象: カード): number {
    if (this.判定中) {
      return 0; // 入れ子の問い合わせでは補正なしとして答え、無限の行き来を防ぐ
    }
    this.判定中 = true;
    try {
      let 合計 = 0;
      for (const { カード: 発揮源, 効果, 所有者識別子 } of this.働いている常在効果を集める()) {
        合計 += this.この効果によるBP補正(効果, 発揮源, 所有者識別子, 対象);
      }
      return 合計;
    } finally {
      this.判定中 = false;
    }
  }

  // 常在効果1つが、聞かれたカードのBPをいくら動かすか。
  //
  // 常在効果には2つの形がある。
  //   ・「このスピリットをBP+2000する」        … 発揮源自身だけ（ゲン_ボーなど）
  //   ・「〜を持つ自分のスピリットすべてを…」  … 条件に合う別のカードも含む（浮遊岩域など）
  //
  // 後者は、絞り込みの 選択 ステップと BP変更（対象:'選択'）の組で書かれる。
  // 常在効果は「発揮する」ものではないので選択は実行されず、
  // 代わりにここで「聞かれたカードがその絞り込みに合うか」を判定する。
  private この効果によるBP補正(
    効果: 効果定義,
    発揮源: カード,
    所有者識別子: string,
    対象: カード
  ): number {
    // 直前の 選択 ステップが、BP変更の 対象:'選択' の絞り込みになる
    let 直前の絞り込み: カードフィルタ | undefined;
    let 合計 = 0;

    for (const ステップ of 効果.処理) {
      if ('選択' in ステップ) {
        直前の絞り込み = ステップ.選択;
        continue;
      }
      if (!('BP変更' in ステップ)) {
        continue;
      }
      const 値 = typeof ステップ.BP変更.値 === 'number' ? ステップ.BP変更.値 : 0;

      if (ステップ.BP変更.対象 === '自身') {
        if (発揮源.識別子 === 対象.識別子) {
          合計 += 値;
        }
        continue;
      }
      if (ステップ.BP変更.対象 === '選択' && 直前の絞り込み) {
        if (this.絞り込みに合うか(直前の絞り込み, 発揮源, 所有者識別子, 対象)) {
          合計 += 値;
        }
      }
    }
    return 合計;
  }

  // 絞り込みに合うカードを集めて、その中に居るかで判定する。
  // 「自分の」「相手の」は効果の持ち主から見た向きなので、持ち主を基準に集める。
  private 絞り込みに合うか(
    絞り込み: カードフィルタ,
    発揮源: カード,
    所有者識別子: string,
    対象: カード
  ): boolean {
    return this.試合
      .接続を取得()
      .絞り込みで集める(絞り込み, 発揮源, 所有者識別子)
      .some(カード => カード.識別子 === 対象.識別子);
  }

  // === ルールを書き換える制約 ===

  // 期限付きの制約を登録する（マジックなどが「このターン中」働かせるもの）
  制約を登録する(登録: 登録済み制約): void {
    this.登録済み.push(登録);
  }

  期限切れを解除する(期限: 期間): void {
    this.登録済み = this.登録済み.filter(制約 => 制約.期限 !== 期限);
  }

  登録数を取得(): number {
    return this.登録済み.length;
  }

  // その制約が今この状況で働いているか
  制約が働いているか(名: string, 問い: 制約の問い): boolean {
    if (this.登録された制約が働いているか(名, 問い)) {
      return true;
    }
    return this.常在効果の制約が働いているか(名, 問い);
  }

  private 登録された制約が働いているか(名: string, 問い: 制約の問い): boolean {
    return this.登録済み.some(制約 => {
      if (制約.名 !== 名) {
        return false;
      }
      if (制約.対象 && 制約.対象.識別子 !== 問い.対象?.識別子) {
        return false;
      }
      if (!制約.対象 && 問い.プレイヤー識別子 !== undefined) {
        // プレイヤーにかかる制約：持ち主が一致していなければ働かない
        if (制約.所有者識別子 !== 問い.プレイヤー識別子) {
          return false;
        }
      }
      return this.相手の条件に合うか(制約.相手, 制約.所有者識別子, 問い.相手);
    });
  }

  private 常在効果の制約が働いているか(名: string, 問い: 制約の問い): boolean {
    for (const { カード: 発揮源, 効果, 所有者識別子 } of this.働いている常在効果を集める()) {
      for (const ステップ of 効果.処理) {
        if (!('制約' in ステップ) || ステップ.制約.名 !== 名) {
          continue;
        }
        // 対象は今のところ「このカード自身」だけ
        const 対象参照 = ステップ.制約.対象 ?? '自身';
        if (対象参照 === '自身' && 発揮源.識別子 !== 問い.対象?.識別子) {
          continue;
        }
        if (this.相手の条件に合うか(ステップ.制約.相手, 所有者識別子, 問い.相手)) {
          return true;
        }
      }
    }
    return false;
  }

  // 「コスト4以下の相手のスピリットからは」の判定。
  // 相手の条件が書かれていなければ、誰が相手でも働く。
  private 相手の条件に合うか(
    相手条件: カードフィルタ | undefined,
    所有者識別子: string,
    相手?: カード
  ): boolean {
    if (!相手条件) {
      return true;
    }
    if (!相手) {
      return false;
    }
    return this.試合.接続を取得().カードが条件に合うか(相手, 相手条件, 所有者識別子);
  }

  // === 働いている常在効果を集める ===

  // 場のカードのうち、今この瞬間に常在効果が働いているものを列挙する。
  // Lv・持続状態（アタック中）・発動条件のすべてを満たしているものだけを返す。
  private 働いている常在効果を集める(): {
    カード: カード;
    効果: 効果定義;
    所有者識別子: string;
  }[] {
    const 結果: { カード: カード; 効果: 効果定義; 所有者識別子: string }[] = [];

    for (const プレイヤー of this.試合.ゲーム.全プレイヤーを取得()) {
      const フィールド = this.試合.ゾーン管理.フィールドを取得(this.試合.ゲーム, プレイヤー.識別子);
      if (!フィールド) {
        continue;
      }
      for (const カード of フィールド.カード一覧を取得()) {
        for (const 効果 of this.効果ルール.効果を取得(カード)) {
          if (効果.種別 !== '常在') {
            continue;
          }
          if (!this.今働いているか(効果, カード, プレイヤー.識別子)) {
            continue;
          }
          結果.push({ カード, 効果, 所有者識別子: プレイヤー.識別子 });
        }
      }
    }
    return 結果;
  }

  private 今働いているか(効果: 効果定義, カード: カード, 所有者識別子: string): boolean {
    if (効果.Lv !== undefined) {
      if (!効果.Lv.includes(this.試合.Lv管理.現在のLvを取得(カード))) {
        return false;
      }
    }
    if (効果.状態 !== undefined && カード.状態を取得(効果.状態) !== true) {
      return false;
    }
    // 『自分のアタックステップ』… その場面のあいだだけ働く。
    // 起動効果と同じ扱い（トリガー欄を「この場面でだけ」という条件として読む）。
    if (効果.トリガー === '自分のアタックステップ' && !this.自分のアタックステップか(所有者識別子)) {
      return false;
    }
    if (効果.条件 !== undefined) {
      if (!this.試合.接続を取得().条件を満たすか(効果.条件, カード, 所有者識別子)) {
        return false;
      }
    }
    return true;
  }

  private 自分のアタックステップか(所有者識別子: string): boolean {
    if (this.試合.現在のステップ() !== 'アタックステップ') {
      return false;
    }
    return this.試合.ゲーム.現在のプレイヤーを取得()?.識別子 === 所有者識別子;
  }

  // 常在効果が宣言している制約のうち、期限付きのものを登録する。
  // 使用（マジック）や誘発の処理としてこのステップが実行されたときに呼ばれる。
  ステップから登録する(
    ステップ: 処理ステップ,
    対象: カード[],
    所有者識別子: string
  ): boolean {
    if (!('制約' in ステップ)) {
      return false;
    }
    const 指定 = ステップ.制約;
    // 対象が指定されていない制約はプレイヤーにかかるものとして扱う
    const 対象一覧: (カード | undefined)[] = 対象.length > 0 ? 対象 : [undefined];
    for (const 対象カード of 対象一覧) {
      this.制約を登録する({
        名: 指定.名,
        対象: 対象カード,
        所有者識別子,
        相手: 指定.相手,
        期限: 指定.期間 ?? '永続',
      });
    }
    return true;
  }
}
