import { ゲームエンジン } from '../../../ゲームエンジン.js';
import { ゾーン管理 } from './ゾーン管理.js';

// デッキ管理（ゲームエンジン層）：デッキ／手札のカード操作
// - デッキのシャッフル
// - デッキの上から手札へドロー（デッキの上＝カード群の先頭[0]）
// - 手札をすべてデッキへ戻す
export class デッキ管理 {
  private ゾーン管理: ゾーン管理;

  constructor() {
    this.ゾーン管理 = new ゾーン管理();
  }

  // デッキをシャッフルする（フィッシャーイェーツ、その場で並べ替え）
  シャッフルする(ゲーム: ゲームエンジン, プレイヤー識別子: string): boolean {
    const デッキ = this.ゾーン管理.デッキエリアを取得(ゲーム, プレイヤー識別子);
    if (!デッキ) {
      return false;
    }
    const 配列 = デッキ.カード群;
    for (let i = 配列.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [配列[i], 配列[j]] = [配列[j], 配列[i]];
    }
    return true;
  }

  // デッキの上から手札へ 枚数 枚ドローする。実際に引いた枚数を返す。
  ドローする(ゲーム: ゲームエンジン, プレイヤー識別子: string, 枚数: number): number {
    const デッキ = this.ゾーン管理.デッキエリアを取得(ゲーム, プレイヤー識別子);
    const 手札 = this.ゾーン管理.手札を取得(ゲーム, プレイヤー識別子);
    if (!デッキ || !手札) {
      return 0;
    }

    let 引いた枚数 = 0;
    for (let i = 0; i < 枚数; i++) {
      const 上のカード = デッキ.カード群[0]; // デッキの上＝先頭
      if (!上のカード) {
        break; // デッキ切れ
      }
      デッキ.カードを削除(上のカード.識別子);
      手札.カードを追加(上のカード);
      引いた枚数++;
    }
    return 引いた枚数;
  }

  // 手札をすべてデッキに戻す
  手札をデッキに戻す(ゲーム: ゲームエンジン, プレイヤー識別子: string): boolean {
    const 手札 = this.ゾーン管理.手札を取得(ゲーム, プレイヤー識別子);
    const デッキ = this.ゾーン管理.デッキエリアを取得(ゲーム, プレイヤー識別子);
    if (!手札 || !デッキ) {
      return false;
    }
    for (const カード of 手札.カード一覧を取得()) {
      手札.カードを削除(カード.識別子);
      デッキ.カードを追加(カード);
    }
    return true;
  }
}
