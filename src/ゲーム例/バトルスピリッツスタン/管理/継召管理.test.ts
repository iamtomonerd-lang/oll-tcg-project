import { test } from 'node:test';
import assert from 'node:assert/strict';

import { カード } from '../../../データ/カード/カード.js';
import { ゾーン } from '../../../データ/ゾーン/ゾーン.js';
import { グンガタを作成 } from '../カードデータ/グンガタ.js';
import { 継召判定 } from '../判定/継召判定.js';
import { 継召管理 } from './継召管理.js';

function EXシンボルカードを作る(識別子: string): カード {
  return new カード(識別子, {
    識別子,
    表示名: 'テストEXカード',
    シンボル: [{ 色: '赤', タイプ: 'EX' }],
  } as any);
}

// === 継召判定（12-2-1-3） ===

test('除外できるか：EXシンボルを持つカードのみ継召で除外できる', () => {
  const 判定 = new 継召判定();
  assert.equal(判定.除外できるか(EXシンボルカードを作る('ex-1')), true);
  assert.equal(判定.除外できるか(グンガタを作成('normal-1')), false, 'グン＝ガタはEXシンボルを持たない');
});

test('残り枠を取得：軽減シンボルの総数から、フィールドのシンボルで既に満たした数を引く（12-2-1-3-2）', () => {
  const 判定 = new 継召判定();
  const 対象 = グンガタを作成('target-1'); // 軽減シンボル赤×3

  assert.equal(判定.残り枠を取得(対象, []), 3, 'フィールドが空なら3枠すべて残っている');
  assert.equal(判定.残り枠を取得(対象, ['赤']), 2, 'フィールドの赤1個で1枠が満たされる');
  assert.equal(判定.残り枠を取得(対象, ['赤', '赤', '赤', '赤']), 0, '枠を超えては減らない');
});

test('除外できる最大枚数：残り枠とEXシンボルを持つ候補数の小さい方', () => {
  const 判定 = new 継召判定();
  const 対象 = グンガタを作成('target-2');
  const 候補 = [EXシンボルカードを作る('ex-2'), EXシンボルカードを作る('ex-3'), グンガタを作成('normal-2')];

  // 残り枠3、EX候補は2枚（グン＝ガタはEXを持たないため候補から除外）
  assert.equal(判定.除外できる最大枚数(対象, 候補, []), 2);
  // フィールドのシンボルで2枠既に満たされていれば、残り枠1が上限になる
  assert.equal(判定.除外できる最大枚数(対象, 候補, ['赤', '赤']), 1);
});

test('除外は有効か：EXシンボルを持たないカードが1枚でも含まれれば無効', () => {
  const 判定 = new 継召判定();
  const 対象 = グンガタを作成('target-3');
  const 除外一覧 = [EXシンボルカードを作る('ex-4'), グンガタを作成('normal-3')];
  assert.equal(判定.除外は有効か(対象, 除外一覧, []), false);
});

test('除外は有効か：残り枠を超える枚数を指定すれば無効（12-2-1-3-2-1）', () => {
  const 判定 = new 継召判定();
  const 対象 = グンガタを作成('target-4');
  const 除外一覧 = [EXシンボルカードを作る('ex-5'), EXシンボルカードを作る('ex-6'), EXシンボルカードを作る('ex-7'), EXシンボルカードを作る('ex-8')];
  assert.equal(判定.除外は有効か(対象, 除外一覧, []), false, '残り枠3を超える4枚は無効');
});

test('除外は有効か：残り枠の範囲内でEXシンボルを持つカードのみなら有効', () => {
  const 判定 = new 継召判定();
  const 対象 = グンガタを作成('target-5');
  const 除外一覧 = [EXシンボルカードを作る('ex-9'), EXシンボルカードを作る('ex-10')];
  assert.equal(判定.除外は有効か(対象, 除外一覧, []), true);
});

// === 継召管理 ===

test('発揮する：有効な除外指定なら、トラッシュから除外エリアへカードを移し、満たした数を返す', () => {
  const トラッシュ = new ゾーン('p1-トラッシュ', { 識別子: 'トラッシュ', 表示名: 'トラッシュ' });
  const 除外エリア = new ゾーン('p1-除外エリア', { 識別子: '除外エリア', 表示名: '除外エリア' });
  const 対象 = グンガタを作成('target-6');
  const ex1 = EXシンボルカードを作る('ex-11');
  const ex2 = EXシンボルカードを作る('ex-12');
  トラッシュ.カードを追加(ex1);
  トラッシュ.カードを追加(ex2);

  const 満たした数 = new 継召管理().発揮する(トラッシュ, 除外エリア, 対象, [ex1, ex2], []);

  assert.equal(満たした数, 2);
  assert.equal(トラッシュ.カードを取得(ex1.識別子), undefined);
  assert.equal(トラッシュ.カードを取得(ex2.識別子), undefined);
  assert.ok(除外エリア.カードを取得(ex1.識別子));
  assert.ok(除外エリア.カードを取得(ex2.識別子));
});

test('発揮する：12-2-1-3-2-1に反する指定（残り枠超過）なら何も動かさず0を返す', () => {
  const トラッシュ = new ゾーン('p1-トラッシュ', { 識別子: 'トラッシュ', 表示名: 'トラッシュ' });
  const 除外エリア = new ゾーン('p1-除外エリア', { 識別子: '除外エリア', 表示名: '除外エリア' });
  const 対象 = グンガタを作成('target-7');
  const 除外候補 = [
    EXシンボルカードを作る('ex-13'),
    EXシンボルカードを作る('ex-14'),
    EXシンボルカードを作る('ex-15'),
    EXシンボルカードを作る('ex-16'),
  ];
  for (const カード of 除外候補) {
    トラッシュ.カードを追加(カード);
  }

  const 満たした数 = new 継召管理().発揮する(トラッシュ, 除外エリア, 対象, 除外候補, []);

  assert.equal(満たした数, 0);
  assert.equal(除外エリア.カード枚数を取得(), 0);
  assert.equal(トラッシュ.カード枚数を取得(), 4, 'トラッシュの中身は変化しない');
});

test('発揮する：指定したカードがトラッシュに実在しなければ、そのカードだけスキップする', () => {
  const トラッシュ = new ゾーン('p1-トラッシュ', { 識別子: 'トラッシュ', 表示名: 'トラッシュ' });
  const 除外エリア = new ゾーン('p1-除外エリア', { 識別子: '除外エリア', 表示名: '除外エリア' });
  const 対象 = グンガタを作成('target-8');
  const トラッシュにあるカード = EXシンボルカードを作る('ex-17');
  const トラッシュに無いカード = EXシンボルカードを作る('ex-18');
  トラッシュ.カードを追加(トラッシュにあるカード);

  const 満たした数 = new 継召管理().発揮する(
    トラッシュ,
    除外エリア,
    対象,
    [トラッシュにあるカード, トラッシュに無いカード],
    []
  );

  assert.equal(満たした数, 1);
  assert.ok(除外エリア.カードを取得(トラッシュにあるカード.識別子));
  assert.equal(除外エリア.カードを取得(トラッシュに無いカード.識別子), undefined);
});
