import { ゲームエンジン } from '../../../ゲームエンジン.js';
import { ゾーン } from '../../../データ/ゾーン/ゾーン.js';
import { 公開範囲 } from '../ゲームの領域/公開範囲.js';
import { デッキエリア } from '../ゲームの領域/デッキエリア.js';
import { 手札 } from '../ゲームの領域/手札.js';
import { トラッシュ } from '../ゲームの領域/トラッシュ.js';
import { フィールド } from '../ゲームの領域/フィールド.js';
import { リザーブ } from '../ゲームの領域/リザーブ.js';
import { ライフ } from '../ゲームの領域/ライフ.js';
import { 除外エリア } from '../ゲームの領域/除外エリア.js';

// ゾーン管理（ゲームエンジン層）
// - 各プレイヤーの7領域を生成してゲームエンジンに登録する
// - プレイヤー×種別で領域を取得する
// - 可視性（公開範囲）に基づき、あるプレイヤーが中身を見られるかを判定する
export class ゾーン管理 {
  private デッキエリア = new デッキエリア();
  private 手札 = new 手札();
  private トラッシュ = new トラッシュ();
  private フィールド = new フィールド();
  private リザーブ = new リザーブ();
  private ライフ = new ライフ();
  private 除外エリア = new 除外エリア();

  // プレイヤー1人分の7領域を生成し、ゲームエンジンに登録する
  プレイヤーの領域を生成(ゲーム: ゲームエンジン, プレイヤー識別子: string, 初期ライフ: number = 0): void {
    const 領域一覧 = [
      this.デッキエリア.生成(プレイヤー識別子),
      this.手札.生成(プレイヤー識別子),
      this.トラッシュ.生成(プレイヤー識別子),
      this.フィールド.生成(プレイヤー識別子),
      this.リザーブ.生成(プレイヤー識別子),
      this.ライフ.生成(プレイヤー識別子, 初期ライフ),
      this.除外エリア.生成(プレイヤー識別子),
    ];
    for (const 領域 of 領域一覧) {
      ゲーム.ゾーンを追加(領域);
    }
  }

  // プレイヤーの特定種別の領域を取得（識別子は `${プレイヤー識別子}-${種別キー}`）
  領域を取得(ゲーム: ゲームエンジン, プレイヤー識別子: string, 種別キー: string): ゾーン | undefined {
    return ゲーム.ゾーンを取得(`${プレイヤー識別子}-${種別キー}`);
  }

  // 種別ごとの取得ヘルパー（種別キーの打ち間違いを防ぐ）
  デッキエリアを取得(ゲーム: ゲームエンジン, プレイヤー識別子: string): ゾーン | undefined {
    return this.領域を取得(ゲーム, プレイヤー識別子, this.デッキエリア.識別子キー);
  }

  手札を取得(ゲーム: ゲームエンジン, プレイヤー識別子: string): ゾーン | undefined {
    return this.領域を取得(ゲーム, プレイヤー識別子, this.手札.識別子キー);
  }

  トラッシュを取得(ゲーム: ゲームエンジン, プレイヤー識別子: string): ゾーン | undefined {
    return this.領域を取得(ゲーム, プレイヤー識別子, this.トラッシュ.識別子キー);
  }

  フィールドを取得(ゲーム: ゲームエンジン, プレイヤー識別子: string): ゾーン | undefined {
    return this.領域を取得(ゲーム, プレイヤー識別子, this.フィールド.識別子キー);
  }

  リザーブを取得(ゲーム: ゲームエンジン, プレイヤー識別子: string): ゾーン | undefined {
    return this.領域を取得(ゲーム, プレイヤー識別子, this.リザーブ.識別子キー);
  }

  ライフを取得(ゲーム: ゲームエンジン, プレイヤー識別子: string): ゾーン | undefined {
    return this.領域を取得(ゲーム, プレイヤー識別子, this.ライフ.識別子キー);
  }

  除外エリアを取得(ゲーム: ゲームエンジン, プレイヤー識別子: string): ゾーン | undefined {
    return this.領域を取得(ゲーム, プレイヤー識別子, this.除外エリア.識別子キー);
  }

  // プレイヤーが所持する全領域を取得
  プレイヤーの全領域を取得(ゲーム: ゲームエンジン, プレイヤー識別子: string): ゾーン[] {
    return ゲーム.全ゾーンを取得().filter(領域 => 領域.状態を取得('所有者') === プレイヤー識別子);
  }

  // 領域の公開範囲を取得
  公開範囲を取得(領域: ゾーン): 公開範囲 | undefined {
    return 領域.状態を取得('公開範囲');
  }

  // 指定プレイヤーがこの領域の中身を見られるか
  中身が見えるか(領域: ゾーン, 見るプレイヤー識別子: string): boolean {
    const 範囲 = this.公開範囲を取得(領域);
    if (範囲 === '全員公開') {
      return true;
    }
    if (範囲 === '所有者のみ') {
      return 領域.状態を取得('所有者') === 見るプレイヤー識別子;
    }
    // 非公開・未設定は誰にも見えない
    return false;
  }
}
