import { コア保持者 } from '../判定/コア保持者.js';
import { コア支払い元, プレイコスト判定 } from '../判定/プレイコスト判定.js';
import { コア判定 } from '../判定/コア判定.js';
import { コア管理 } from './コア管理.js';

// プレイコスト管理（ゲームエンジン層 ＝ 遷移する者）
// 召喚（11-1）・配置（11-2）・使用（11-3）に共通するコスト支払いを実行する。
export class プレイコスト管理 {
  private プレイコスト判定: プレイコスト判定;
  private コア判定: コア判定;
  private コア管理: コア管理;

  constructor() {
    this.プレイコスト判定 = new プレイコスト判定();
    this.コア判定 = new コア判定();
    this.コア管理 = new コア管理();
  }

  // コストをちょうど支払う（過剰不可）。支払ったコアはトラッシュへ移動する。
  // 「召喚コストを支払う」「配置コストを支払う」「使用コストを支払う」に対応（11-1-1-5／11-2-1-5／11-3-1-5）。
  コストを支払う(支払い元一覧: コア支払い元[], トラッシュ: コア保持者, コスト: number): boolean {
    if (!this.プレイコスト判定.支払い総数はちょうどか(支払い元一覧, コスト)) {
      return false;
    }
    if (!this.プレイコスト判定.各支払い元に十分なコアがあるか(支払い元一覧)) {
      return false;
    }
    for (const 支払い元 of 支払い元一覧) {
      this.この支払い元から移す(支払い元, トラッシュ);
    }
    return true;
  }

  // 最低必要数以上のコアを対象（カード）に置く（過剰は許容）。
  // 「最低LvのLvコスト以上のコアを...カードに置く」に対応（11-1-1-6／11-2-1-6）。
  初期コアを配置する(支払い元一覧: コア支払い元[], 対象: コア保持者, 最低必要数: number): boolean {
    if (!this.プレイコスト判定.初期配置数は十分か(支払い元一覧, 最低必要数)) {
      return false;
    }
    if (!this.プレイコスト判定.各支払い元に十分なコアがあるか(支払い元一覧)) {
      return false;
    }
    for (const 支払い元 of 支払い元一覧) {
      this.この支払い元から移す(支払い元, 対象);
    }
    return true;
  }

  // 支払い元1つぶんのコアを移す。
  //
  // ソウルコア数 を名指ししていれば、その内訳で払う（通常コアが足りていても
  // 狙ってソウルコアを出せる）。名指しが無ければ従来どおり
  // 「通常コアを優先し、足りないぶんだけソウルコアで埋める」。
  private この支払い元から移す(支払い元: コア支払い元, 先: コア保持者): void {
    const { 保持者, 数 } = 支払い元;
    if (数 <= 0) {
      return;
    }

    const 通常コア数 = this.コア判定.通常コア数を取得(保持者);
    const 出すソウルコア数 =
      支払い元.ソウルコア数 ?? Math.max(0, 数 - 通常コア数);

    for (let i = 0; i < 出すソウルコア数; i++) {
      this.コア管理.ソウルコアを移動(保持者, 先, true);
    }
    const 出す通常コア数 = 数 - 出すソウルコア数;
    if (出す通常コア数 > 0) {
      this.コア管理.通常コアを移動(保持者, 先, 出す通常コア数);
    }
  }
}
