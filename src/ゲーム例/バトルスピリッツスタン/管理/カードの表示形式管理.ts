import { カード } from '../../../データ/カード/カード.js';
import { カードの表示形式, 表示形式判定 } from '../判定/表示形式判定.js';

// カードの表示形式管理（ゲームエンジン層）
// 表示形式の遷移（状態変更）を行う。
// 読み取り・判定（回復か/疲労か/重疲労か 等）は表示形式判定に委譲する。
// いつ疲労/重疲労になるか、どう回復するか等の遷移ルールは詳細定義が出てから追加する。
export class カードの表示形式管理 {
  private 表示形式判定: 表示形式判定;

  constructor() {
    this.表示形式判定 = new 表示形式判定();
  }

  // 現在の表示形式を取得（判定に委譲）
  現在の表示形式を取得(カード: カード): カードの表示形式 {
    return this.表示形式判定.現在の表示形式を取得(カード);
  }

  表示形式を設定(カード: カード, 表示形式: カードの表示形式): void {
    カード.状態を設定('表示形式', 表示形式);
  }

  回復にする(カード: カード): void {
    this.表示形式を設定(カード, '回復');
  }

  疲労にする(カード: カード): void {
    this.表示形式を設定(カード, '疲労');
  }

  重疲労にする(カード: カード): void {
    this.表示形式を設定(カード, '重疲労');
  }

  // 回復する：疲労を1段階戻す（重疲労→疲労、疲労→回復）
  // 戻せた場合は true を返す。重疲労→疲労も「回復した」に含まれる。
  // 戻り値 true は「回復したとき」の誘発型効果の発火契機（呼び出し側が効果処理を行う）。
  回復する(カード: カード): boolean {
    if (!this.表示形式判定.回復できるか(カード)) {
      return false; // 既に回復状態
    }
    this.表示形式を設定(カード, this.表示形式判定.回復後の表示形式(カード));
    return true;
  }

  // 疲労する：回復状態を疲労状態にする（回復→疲労）
  // 実際に疲労させた場合は true を返す（回復状態でなければ何もしない）
  疲労する(カード: カード): boolean {
    if (!this.表示形式判定.疲労できるか(カード)) {
      return false; // 回復状態でない（既に疲労／重疲労）
    }
    this.疲労にする(カード);
    return true;
  }
}
