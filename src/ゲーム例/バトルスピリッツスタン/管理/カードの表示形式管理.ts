import { カード } from '../../../データ/カード/カード.js';
import { カードの表示形式, 表示形式判定 } from '../判定/表示形式判定.js';

// カードの表示形式管理（ゲームエンジン層）
// 表示形式の遷移（状態変更）を行う。
// 読み取り・判定（回復か/疲労か/重疲労か 等）は表示形式判定に委譲する。
// いつ疲労/重疲労になるか、どう回復するか等の遷移ルールは詳細定義が出てから追加する。
export class カードの表示形式管理 {
  private 表示形式判定: 表示形式判定;

  constructor() {
    this.表示形式判定 = new 表示形式判定();
  }

  // 現在の表示形式を取得（判定に委譲）
  現在の表示形式を取得(カード: カード): カードの表示形式 {
    return this.表示形式判定.現在の表示形式を取得(カード);
  }

  表示形式を設定(カード: カード, 表示形式: カードの表示形式): void {
    カード.状態を設定('表示形式', 表示形式);
  }

  回復にする(カード: カード): void {
    this.表示形式を設定(カード, '回復');
  }

  疲労にする(カード: カード): void {
    this.表示形式を設定(カード, '疲労');
  }

  重疲労にする(カード: カード): void {
    this.表示形式を設定(カード, '重疲労');
  }
}
