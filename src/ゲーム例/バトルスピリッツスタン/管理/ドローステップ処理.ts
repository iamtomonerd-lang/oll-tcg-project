import { ゲームエンジン } from '../../../ゲームエンジン.js';
import { デッキ管理 } from './デッキ管理.js';

// ドローステップ処理（ゲームエンジン層）
// ドローステップのターン起因処理：ターンプレイヤーが自分のデッキから1枚ドローする。
// ※『ドローステップ』の誘発条件の効果の発揮、および解決待ち効果の解決は
//   効果システム側（未実装）の担当。
export class ドローステップ処理 {
  private デッキ管理: デッキ管理;

  readonly ドロー枚数 = 1;

  constructor() {
    this.デッキ管理 = new デッキ管理();
  }

  // ターン起因処理：ターンプレイヤーが自分のデッキから1枚ドローする
  ターン起因処理(ゲーム: ゲームエンジン): boolean {
    const ターンプレイヤー = ゲーム.現在のプレイヤーを取得();
    if (!ターンプレイヤー) {
      return false;
    }
    const 引いた枚数 = this.デッキ管理.ドローする(ゲーム, ターンプレイヤー.識別子, this.ドロー枚数);
    return 引いた枚数 === this.ドロー枚数;
  }
}
