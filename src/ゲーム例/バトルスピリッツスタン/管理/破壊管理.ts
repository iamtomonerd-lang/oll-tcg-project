import { ゲームエンジン } from '../../../ゲームエンジン.js';
import { カード } from '../../../データ/カード/カード.js';
import { 破壊判定 } from '../判定/破壊判定.js';
import { 待機状態管理 } from './待機状態管理.js';
import { ゾーン管理 } from './ゾーン管理.js';
import { コア管理 } from './コア管理.js';

// 破壊管理（ゲームエンジン層 ＝ 遷移する者）
// 破壊 = スピリット/ネクサスが効果やBP比べで破壊され、待機状態を経てトラッシュへ置かれること。
// 消滅とは別（原因が異なる）。「破壊されたとき」効果の発火のため2段階に分ける。
//   第1段階 破壊する    ：待機状態にする（理由=破壊）
//   （この間に「破壊されたとき」効果を処理する）
//   第2段階 トラッシュへ置く：カードをトラッシュへ、コアをリザーブへ戻す
export class 破壊管理 {
  private 破壊判定: 破壊判定;
  private 待機状態管理: 待機状態管理;
  private ゾーン管理: ゾーン管理;
  private コア管理: コア管理;

  constructor() {
    this.破壊判定 = new 破壊判定();
    this.待機状態管理 = new 待機状態管理();
    this.ゾーン管理 = new ゾーン管理();
    this.コア管理 = new コア管理();
  }

  // 第1段階：破壊する（待機状態にする。理由=破壊）
  // この後に「破壊されたとき」効果を処理し、その後 第2段階でトラッシュへ置く。
  破壊する(カード: カード): boolean {
    if (!this.破壊判定.破壊対象か(カード)) {
      return false;
    }
    this.待機状態管理.待機状態にする(カード, '破壊');
    return true;
  }

  // 第2段階：待機状態のカードをフィールドからトラッシュへ置く
  // カードはトラッシュへ、コア（ソウルコア含む）はリザーブへ戻す。
  // 破壊・消滅どちらの待機状態でも共通で使える離場処理。
  トラッシュへ置く(ゲーム: ゲームエンジン, プレイヤー識別子: string, カード: カード): boolean {
    if (!this.待機状態管理.待機状態か(カード)) {
      return false;
    }
    const フィールド = this.ゾーン管理.フィールドを取得(ゲーム, プレイヤー識別子);
    const トラッシュ = this.ゾーン管理.トラッシュを取得(ゲーム, プレイヤー識別子);
    const リザーブ = this.ゾーン管理.リザーブを取得(ゲーム, プレイヤー識別子);
    if (!フィールド || !トラッシュ || !リザーブ) {
      return false;
    }
    // このフィールドに対象カードが無ければ何もしない（部分的な変更を避けるため先に確認）
    if (!フィールド.カードを取得(カード.識別子)) {
      return false;
    }

    // コアをリザーブへ戻す（リザーブは制限付き配置先ではないのでソウルコアも移せる）
    const カード保持者 = this.コア管理.カードを保持者に(カード);
    const リザーブ保持者 = this.コア管理.ゾーンを保持者に(リザーブ);
    this.コア管理.全コアを移動(カード保持者, リザーブ保持者);

    // カードをフィールド→トラッシュへ
    const 取り出したカード = フィールド.カードを削除(カード.識別子);
    if (取り出したカード) {
      トラッシュ.カードを追加(取り出したカード);
    }

    // 待機状態を解除
    this.待機状態管理.待機状態から復帰(カード);
    return true;
  }
}
