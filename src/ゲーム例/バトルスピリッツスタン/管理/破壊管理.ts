import { ゲームエンジン } from '../../../ゲームエンジン.js';
import { カード } from '../../../データ/カード/カード.js';
import { 破壊判定 } from '../判定/破壊判定.js';
import { 待機状態管理 } from './待機状態管理.js';

// 破壊の原因（12-2-1-12／12-2-1-12-1）
// 『相手による破壊時』は、相手の効果、または相手のスピリットとのBP比べで破壊されたときに発揮する。
export type 破壊原因 =
  | { 由来: '自分の効果'; 効果識別子: string }
  | { 由来: '相手の効果'; 効果識別子: string }
  | { 由来: 'BP比べ'; 相手のカード: カード };

// 破壊管理（ゲームエンジン層 ＝ 遷移する者）
// 破壊 = スピリット/ネクサスが効果やBP比べで破壊され、待機状態を経てトラッシュへ置かれること。
// 消滅とは別（原因が異なる）。「破壊されたとき」効果の発火のため2段階に分ける。
//   第1段階 破壊する    ：待機状態にする（理由=破壊、移動先=トラッシュ）
//   （この間に「破壊されたとき」効果を処理する）
//   第2段階 トラッシュへ置く：待機状態管理.解決する に委譲（カードをトラッシュへ、コアをリザーブへ戻す）
export class 破壊管理 {
  private 破壊判定: 破壊判定;
  private 待機状態管理: 待機状態管理;

  constructor() {
    this.破壊判定 = new 破壊判定();
    this.待機状態管理 = new 待機状態管理();
  }

  // 第1段階：破壊する（待機状態にする。理由=破壊）
  // この後に「破壊されたとき」効果を処理し、その後 第2段階でトラッシュへ置く。
  // 原因を渡すと『相手による破壊時』（12-2-1-12-1）等の判定に使う帰属情報として記録する。
  破壊する(カード: カード, 原因?: 破壊原因): boolean {
    if (!this.破壊判定.破壊対象か(カード)) {
      return false;
    }
    this.待機状態管理.待機状態にする(カード, '破壊', 'トラッシュ');
    if (原因) {
      カード.状態を設定('破壊原因', 原因);
    }
    return true;
  }

  破壊原因を取得(カード: カード): 破壊原因 | undefined {
    return カード.状態を取得('破壊原因');
  }

  // 『相手による破壊時』（12-2-1-12-1）：相手の効果、または相手のスピリットとのBP比べで破壊されたか
  相手による破壊か(カード: カード): boolean {
    const 原因 = this.破壊原因を取得(カード);
    if (!原因) {
      return false;
    }
    return 原因.由来 === '相手の効果' || 原因.由来 === 'BP比べ';
  }

  // 第2段階：待機状態のカードをフィールドからトラッシュへ置く（待機状態の解決。10-2-2-5）
  // カードはトラッシュへ、コア（ソウルコア含む）はリザーブへ戻す。
  // 破壊・消滅どちらの待機状態でも共通で使える離場処理。
  トラッシュへ置く(ゲーム: ゲームエンジン, プレイヤー識別子: string, カード: カード): boolean {
    const 成功 = this.待機状態管理.解決する(ゲーム, プレイヤー識別子, カード);
    if (成功) {
      カード.状態をクリア('破壊原因');
    }
    return 成功;
  }
}
