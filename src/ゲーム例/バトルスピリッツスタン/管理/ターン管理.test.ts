import { test } from 'node:test';
import assert from 'node:assert/strict';

import { ゲームエンジン } from '../../../ゲームエンジン.js';
import { プレイヤー } from '../../../データ/プレイヤー/プレイヤー.js';
import { ターン管理 } from './ターン管理.js';

function 準備() {
  const ゲーム = new ゲームエンジン();
  const p1 = new プレイヤー('p1', 'プレイヤー1');
  const p2 = new プレイヤー('p2', 'プレイヤー2');
  ゲーム.プレイヤーを追加(p1);
  ゲーム.プレイヤーを追加(p2);
  return { ゲーム, p1, p2 };
}

test('ターンを開始する：最初のステップ（スタートステップ）に設定し、現在のプレイヤーのターン数を1増やす', () => {
  const { ゲーム, p1 } = 準備();
  new ターン管理().ターンを開始する(ゲーム);

  assert.equal(new ターン管理().現在のステップを取得(ゲーム), 'スタートステップ');
  assert.equal(p1.数値を取得('ターン数'), 1);
});

test('次のステップへ：ステップ順どおりに1つずつ進み、ターン交代はしない', () => {
  const { ゲーム } = 準備();
  const 管理 = new ターン管理();
  管理.ターンを開始する(ゲーム);

  const ターン交代した = 管理.次のステップへ(ゲーム);

  assert.equal(ターン交代した, false);
  assert.equal(管理.現在のステップを取得(ゲーム), 'コアステップ');
});

test('次のステップへ：エンドステップの次は、ターンプレイヤーを交代して次のターンのスタートステップへ進む', () => {
  const { ゲーム, p1, p2 } = 準備();
  const 管理 = new ターン管理();
  管理.ターンを開始する(ゲーム); // p1のターン開始（スタートステップ）

  // エンドステップまで進める（スタート→コア→ドロー→リフレッシュ→メイン→アタック→第2メイン→エンド の7回分）
  for (let i = 0; i < 7; i++) {
    管理.次のステップへ(ゲーム);
  }
  assert.equal(管理.現在のステップを取得(ゲーム), 'エンドステップ');
  assert.equal(ゲーム.現在のプレイヤーを取得()?.識別子, 'p1');

  const ターン交代した = 管理.次のステップへ(ゲーム);

  assert.equal(ターン交代した, true);
  assert.equal(管理.現在のステップを取得(ゲーム), 'スタートステップ');
  assert.equal(ゲーム.現在のプレイヤーを取得()?.識別子, 'p2', 'ターンプレイヤーが交代する');
  assert.equal(p2.数値を取得('ターン数'), 1, '新しいターンプレイヤーのターン数が増える');
  assert.equal(p1.数値を取得('ターン数'), 1, '交代前のプレイヤーのターン数はそのまま');
});
