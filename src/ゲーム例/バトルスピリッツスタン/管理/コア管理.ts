import { ゾーン } from '../../../データ/ゾーン/ゾーン.js';
import { カード } from '../../../データ/カード/カード.js';
import { コア保持者, ゾーンコア保持者, カードコア保持者 } from '../判定/コア保持者.js';
import { コア判定 } from '../判定/コア判定.js';

// コア管理（ゲームエンジン層 ＝ 遷移する者）
// 移動前にコア判定へ在庫・5-7-3を問い合わせてから実行する。
// ダメージ・コスト支払いなどの高レベル操作は、移動先の仕様が固まってから
// この移動プリミティブの上に追加していく。
export class コア管理 {
  private コア判定: コア判定;

  constructor() {
    this.コア判定 = new コア判定();
  }

  // ゾーン／カードを保持者として扱うためのラッパ
  ゾーンを保持者に(ゾーン: ゾーン): コア保持者 {
    return new ゾーンコア保持者(ゾーン);
  }

  カードを保持者に(カード: カード): コア保持者 {
    return new カードコア保持者(カード);
  }

  // 通常コアを 元→先 に 数 個移動する（ソウルコアは動かさない）
  通常コアを移動(元: コア保持者, 先: コア保持者, 数: number): boolean {
    if (数 <= 0) {
      return false;
    }
    if (this.コア判定.通常コア数を取得(元) < 数) {
      return false; // 通常コアが足りない
    }
    元.コア数を設定(元.コア数を取得() - 数);
    先.コア数を設定(先.コア数を取得() + 数);
    return true;
  }

  // ソウルコアを 元→先 に移動する
  // 5-7-3：先が制限付き配置先（ライフ／ボイド）なら、効果がソウルコアを対象とする場合のみ可
  ソウルコアを移動(元: コア保持者, 先: コア保持者, 効果がソウルコアを対象とする: boolean = false): boolean {
    if (!元.ソウルコアあるか()) {
      return false; // 元にソウルコアが無い
    }
    if (!this.コア判定.ソウルコアを置けるか(先, 効果がソウルコアを対象とする)) {
      return false; // 5-7-3で不可
    }
    // ソウルコアも1個のコアとして総数を増減し、位置フラグを移す
    元.コア数を設定(元.コア数を取得() - 1);
    元.ソウルコアを設定(false);
    先.コア数を設定(先.コア数を取得() + 1);
    先.ソウルコアを設定(true);
    return true;
  }

  // 元の全コア（通常＋ソウル）を先へ移動する
  // 破壊・消滅でスピリット/ネクサスが場を離れる際、コアをリザーブへ戻す用途など
  全コアを移動(元: コア保持者, 先: コア保持者, 効果がソウルコアを対象とする: boolean = false): void {
    const 通常数 = this.コア判定.通常コア数を取得(元);
    if (通常数 > 0) {
      this.通常コアを移動(元, 先, 通常数);
    }
    if (元.ソウルコアあるか()) {
      this.ソウルコアを移動(元, 先, 効果がソウルコアを対象とする);
    }
  }

  // ボイドからコアを 数 個、指定の保持者に置く
  // ボイドはゲーム外の無尽蔵のコア源として扱うため、ボイドは減らさず配置先を増やす。
  ボイドからコアを置く(先: コア保持者, 数: number): void {
    if (数 <= 0) {
      return;
    }
    先.コア数を設定(先.コア数を取得() + 数);
  }

  // ソウルコアと通常コアの場所を交換する（メインステップのコア移動）
  // ソウル側のソウルコアと、通常側の通常コア1個を入れ替える。
  // 両保持者の総数は変わらず、ソウルコアの位置だけが入れ替わる。
  ソウルコアと通常コアを交換(ソウル側: コア保持者, 通常側: コア保持者): boolean {
    if (!ソウル側.ソウルコアあるか()) {
      return false; // ソウル側にソウルコアが無い
    }
    if (this.コア判定.通常コア数を取得(通常側) < 1) {
      return false; // 通常側に通常コアが無い
    }
    // 通常側が制限付き配置先（ライフ／ボイド）だとソウルコアを置けない（5-7-3）
    if (通常側.制限付き配置先か()) {
      return false;
    }
    // ソウルコアを ソウル側→通常側、通常コア1個を 通常側→ソウル側 へ
    this.ソウルコアを移動(ソウル側, 通常側);
    this.通常コアを移動(通常側, ソウル側, 1);
    return true;
  }
}
