test('BP比べ：BPが低い側のスピリットが破壊されトラッシュへ置かれる（8-1-6-1）', () => {
  const { ゲーム, ゾーン管理 } = 試合環境を準備();
  const p1フィールド = ゾーン管理.フィールドを取得(ゲーム, 'p1')!;
  const p2フィールド = ゾーン管理.フィールドを取得(ゲーム, 'p2')!;
  const p1トラッシュ = ゾーン管理.トラッシュを取得(ゲーム, 'p1')!;

  const アタッカー = グンガタを作成('bp-1'); // Lv1 BP5000
  const ブロッカー = グンガタを作成('bp-2');
  p1フィールド.カードを追加(アタッカー);
  p2フィールド.カードを追加(ブロッカー);

  // ブロッカーを強化してアタッカーより高いBPにする
  ブロッカー.数値を設定('BP', 9000);

  new バトル管理().BP比べ(ゲーム, アタッカー, ブロッカー);

  assert.equal(p1フィールド.カードを取得(アタッカー.識別子), undefined, 'BPが低かったアタッカーが場を離れる');
  assert.ok(p1トラッシュ.カードを取得(アタッカー.識別子), 'アタッカーはトラッシュへ置かれる');
  assert.ok(p2フィールド.カードを取得(ブロッカー.識別子), 'BPが高かったブロッカーは場に残る');
});

