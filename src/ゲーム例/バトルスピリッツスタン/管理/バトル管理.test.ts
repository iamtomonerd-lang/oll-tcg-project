test('バトルを解決：ブロックされていなければ、アタッカーのシンボル数だけ防御側のライフを減らす', () => {
  const { ゲーム, ゾーン管理 } = 試合環境を準備(5);
  const アタッカー = グンガタを作成('dmg-1'); // シンボル2個（通常+EX）

  const 管理 = new バトル管理();
  管理.バトルを解決(ゲーム, アタッカー, null);

  const p2ライフ = ゾーン管理.ライフを取得(ゲーム, 'p2')!;
  const p2リザーブ = ゾーン管理.リザーブを取得(ゲーム, 'p2')!;
  assert.equal(p2ライフ.状態を取得('コア数'), 3);
  assert.equal(p2リザーブ.状態を取得('コア数'), 2, '減った分のライフのコアはリザーブへ移る');
});

