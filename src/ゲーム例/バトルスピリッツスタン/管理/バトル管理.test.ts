test('召喚直後アタック可能：サマニング・シックネスが無いため常にtrue', () => {
  assert.equal(new アタック判定().召喚直後アタック可能(), true);
  assert.equal(new アタック管理().召喚直後アタック可能(), true);
});

test('アタック管理：アタック禁止の付与／解除で アタック可能か の結果が変わる', () => {
  const 管理 = new アタック管理();
  const カード = グンガタを作成('atk-2');
  assert.equal(管理.アタック可能か(カード), true);

  管理.アタック禁止を付与(カード);
  assert.equal(管理.アタック禁止か(カード), true);
  assert.equal(管理.アタック可能か(カード), false);

  管理.アタック禁止を解除(カード);
  assert.equal(管理.アタック可能か(カード), true);
});

