import { ゲームエンジン } from '../../../ゲームエンジン.js';
import { カード } from '../../../データ/カード/カード.js';
import { 消滅判定 } from '../判定/消滅判定.js';
import { Lv管理 } from './Lv管理.js';
import { ゾーン管理 } from './ゾーン管理.js';
import { コア管理 } from './コア管理.js';

// 待機状態になった原因（10-2-2-1：破壊された／手札やデッキに戻った／消滅した）
export type 待機理由 = '破壊' | '消滅' | '帰還';

// 待機状態が解決したときの移動先（10-2-2-5：破壊・消滅はトラッシュ、帰還は手札かデッキ）
export type 待機移動先 = 'トラッシュ' | '手札' | 'デッキエリア';

// 消滅の原因の帰属情報（10-2-2-8／9／10：効果によるコア変化・コスト変化・自分の行動による
// コスト変化のいずれかが引き金でLv1コスト未満となり消滅した場合、消滅の原因をそれとみなす）
export type 消滅原因 =
  | { 種別: '効果によるコア変化'; 効果識別子: string }
  | { 種別: '効果によるコスト変化'; 効果識別子: string }
  | { 種別: '自分の行動によるコスト変化'; プレイヤー識別子: string };

export class 待機状態管理 {
  private 消滅判定: 消滅判定;
  private Lv管理: Lv管理;
  private ゾーン管理: ゾーン管理;
  private コア管理: コア管理;

  constructor() {
    this.消滅判定 = new 消滅判定();
    this.Lv管理 = new Lv管理();
    this.ゾーン管理 = new ゾーン管理();
    this.コア管理 = new コア管理();
  }

  // 理由（と、帰還の場合は移動先）を指定して待機状態にする。
  // 破壊・消滅の移動先は既定でトラッシュ。帰還の場合は手札かデッキエリアを指定する。
  // 初めて待機状態になった時点のLvをスナップショットする（10-2-2-3）。
  待機状態にする(カード: カード, 理由: 待機理由, 移動先: 待機移動先 = 'トラッシュ'): void {
    const 初回 = !this.待機状態か(カード);
    カード.状態を設定('待機状態', true);
    カード.状態を設定('待機理由', 理由);
    カード.状態を設定('待機移動先', 移動先);
    if (初回) {
      カード.数値を設定('待機時Lv', this.Lv管理.現在のLvを取得(カード));
    }
  }

  // 待機状態のまま、別の理由に変化する（10-2-2-6）。
  // 同じ理由への変化は起こらない（10-2-2-6-1：待機状態から同じ待機状態にはならない）。
  // 移動先は、新たな移動先が明示された場合のみ上書きする。指定が無ければ元の移動先を保持するため、
  // 帰還の待機中に消滅しても、新たな移動効果を受けない限り手札／デッキへ戻る（10-2-2-7）。
  // 前の待機状態で誘発する効果は解決できなくなる（10-2-2-6-2）が、その誘発予約の無効化は
  // 呼び出し側（誘発型効果管理.発揮できない予約を取り除く 等）が担う。
  別の待機状態に変化する(カード: カード, 新しい理由: 待機理由, 新しい移動先?: 待機移動先): boolean {
    const 現在の理由 = this.待機理由を取得(カード);
    if (現在の理由 === 新しい理由) {
      return false; // 10-2-2-6-1
    }
    カード.状態を設定('待機理由', 新しい理由);
    if (新しい移動先) {
      カード.状態を設定('待機移動先', 新しい移動先);
    }
    return true;
  }

  // 消滅判定に引っかかったら待機状態にする（理由=消滅）。
  // 既に別の理由（帰還など）で待機状態中であれば、別の待機状態に変化する を使う（10-2-2-6）。
  待機状態へ遷移(カード: カード, 現在のコア数: number): boolean {
    if (!this.消滅判定.消滅判定(カード, 現在のコア数)) {
      return false;
    }
    if (this.待機状態か(カード)) {
      this.別の待機状態に変化する(カード, '消滅');
    } else {
      this.待機状態にする(カード, '消滅');
    }
    return true;
  }

  待機状態か(カード: カード): boolean {
    return カード.状態を取得('待機状態') === true;
  }

  待機理由を取得(カード: カード): 待機理由 | undefined {
    const 理由 = カード.状態を取得('待機理由');
    return 理由 === '破壊' || 理由 === '消滅' || 理由 === '帰還' ? 理由 : undefined;
  }

  移動先を取得(カード: カード): 待機移動先 | undefined {
    const 移動先 = カード.状態を取得('待機移動先');
    return 移動先 === 'トラッシュ' || 移動先 === '手札' || 移動先 === 'デッキエリア' ? 移動先 : undefined;
  }

  // 待機状態になる直前のLv（10-2-2-3：消滅の待機状態の解決に用いる）
  待機時Lvを取得(カード: カード): number {
    return カード.数値を取得('待機時Lv');
  }

  // 消滅の原因を記録する（10-2-2-8／9／10）。後の効果条件判定のための帰属情報。
  消滅原因を記録する(カード: カード, 原因: 消滅原因): void {
    カード.状態を設定('消滅原因', 原因);
  }

  消滅原因を取得(カード: カード): 消滅原因 | undefined {
    return カード.状態を取得('消滅原因');
  }

  待機状態から復帰(カード: カード): void {
    カード.状態をクリア('待機状態');
    カード.状態をクリア('待機理由');
    カード.状態をクリア('待機移動先');
    カード.数値を設定('待機時Lv', 0);
    カード.状態をクリア('消滅原因');
  }

  // 待機状態を解決し、カードとコアを最終的な場所へ移動する（10-2-2-5）。
  // 移動先（トラッシュ／手札／デッキエリア）は 移動先を取得 が示す場所。コアはすべてリザーブへ置く。
  // 呼び出し前に「破壊時」「消滅時」等、待機状態で誘発する効果を解決しておくこと。
  解決する(ゲーム: ゲームエンジン, プレイヤー識別子: string, カード: カード): boolean {
    if (!this.待機状態か(カード)) {
      return false;
    }
    const フィールド = this.ゾーン管理.フィールドを取得(ゲーム, プレイヤー識別子);
    if (!フィールド || !フィールド.カードを取得(カード.識別子)) {
      return false;
    }

    const 移動先種別 = this.移動先を取得(カード) ?? 'トラッシュ';
    const 移動先ゾーン =
      移動先種別 === 'トラッシュ'
        ? this.ゾーン管理.トラッシュを取得(ゲーム, プレイヤー識別子)
        : 移動先種別 === '手札'
        ? this.ゾーン管理.手札を取得(ゲーム, プレイヤー識別子)
        : this.ゾーン管理.デッキエリアを取得(ゲーム, プレイヤー識別子);
    const リザーブ = this.ゾーン管理.リザーブを取得(ゲーム, プレイヤー識別子);
    if (!移動先ゾーン || !リザーブ) {
      return false;
    }

    // コアをリザーブへ戻す（リザーブは制限付き配置先ではないのでソウルコアも移せる）
    const カード保持者 = this.コア管理.カードを保持者に(カード);
    const リザーブ保持者 = this.コア管理.ゾーンを保持者に(リザーブ);
    this.コア管理.全コアを移動(カード保持者, リザーブ保持者);

    // カードをフィールド→移動先へ
    const 取り出したカード = フィールド.カードを削除(カード.識別子);
    if (取り出したカード) {
      移動先ゾーン.カードを追加(取り出したカード);
    }

    this.待機状態から復帰(カード);
    return true;
  }
}
