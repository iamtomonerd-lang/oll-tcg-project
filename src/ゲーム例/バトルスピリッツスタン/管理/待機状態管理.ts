import { カード } from '../../../データ/カード/カード.js';
import { 消滅判定 } from '../判定/消滅判定.js';

// 待機状態になった原因
// 「破壊されたとき」「消滅したとき」の効果を区別するために持つ
export type 待機理由 = '破壊' | '消滅';

export class 待機状態管理 {
  private 消滅判定: 消滅判定;

  constructor() {
    this.消滅判定 = new 消滅判定();
  }

  // 理由を指定して待機状態にする。
  // 9-3-3：フィールドからの領域移動を発揮タイミングとする誘発型効果（「フィールドを離れた時」等）は、
  //        実際にトラッシュ等へ置かれた瞬間ではなく、この待機状態になった時点で発揮する。
  //        （＝破壊管理・消滅の2段階処理のうち、この第1段階＝待機状態化のタイミングで誘発させる）
  待機状態にする(カード: カード, 理由: 待機理由): void {
    カード.状態を設定('待機状態', true);
    カード.状態を設定('待機理由', 理由);
  }

  // 消滅判定に引っかかったら待機状態にする（理由=消滅）
  待機状態へ遷移(カード: カード, 現在のコア数: number): boolean {
    if (this.消滅判定.消滅判定(カード, 現在のコア数)) {
      this.待機状態にする(カード, '消滅');
      return true;
    }
    return false;
  }

  待機状態か(カード: カード): boolean {
    return カード.状態を取得('待機状態') === true;
  }

  待機理由を取得(カード: カード): 待機理由 | undefined {
    const 理由 = カード.状態を取得('待機理由');
    return 理由 === '破壊' || 理由 === '消滅' ? 理由 : undefined;
  }

  待機状態から復帰(カード: カード): void {
    カード.状態をクリア('待機状態');
    カード.状態をクリア('待機理由');
  }
}
