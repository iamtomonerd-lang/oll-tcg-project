// ターン履歴管理（ゲームエンジン層 ＝ 遷移する者）
//
// 「このターンに自分のライフが減っていたなら」「このターンに相手のスピリットが消滅していたなら」
// のように、"今の盤面" では答えられない条件のための記録。
// 盤面を見ても分からないのは、起きたあとに元へ戻ってしまう出来事だから。
//
// 記録はプレイヤーごとに持つ。「自分の」「相手の」はどちらの立場から見るかで変わるため、
// 出来事の名前には主体を含めず、誰について起きたかを識別子で分けて持つ。
//   例：「ライフが減った」を p1 に記録 → p1 から見れば『自分のライフが減った』
//                                      p2 から見れば『相手のライフが減った』
export class ターン履歴管理 {
  // 出来事の名前 → 起きた対象プレイヤーの集合
  private 記録 = new Map<string, Set<string>>();

  記録する(出来事: string, プレイヤー識別子: string): void {
    const 集合 = this.記録.get(出来事) ?? new Set<string>();
    集合.add(プレイヤー識別子);
    this.記録.set(出来事, 集合);
  }

  起きたか(出来事: string, プレイヤー識別子: string): boolean {
    return this.記録.get(出来事)?.has(プレイヤー識別子) === true;
  }

  // 誰についてでも起きたか
  誰かに起きたか(出来事: string): boolean {
    return (this.記録.get(出来事)?.size ?? 0) > 0;
  }

  // ターンが変わったら忘れる
  ターンを切り替える(): void {
    this.記録.clear();
  }

  // 検証用：記録されている出来事の数
  記録数を取得(): number {
    let 合計 = 0;
    for (const 集合 of this.記録.values()) {
      合計 += 集合.size;
    }
    return 合計;
  }
}
