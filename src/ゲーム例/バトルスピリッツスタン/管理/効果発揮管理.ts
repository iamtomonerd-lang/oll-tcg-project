// 効果発揮の段階（9-3-1）
export type 効果発揮段階 = '条件確認' | '宣言' | '発揮' | '解決';

export interface 効果発揮結果 {
  成功: boolean;
  到達段階: 効果発揮段階;
}

// 効果発揮管理（ゲームエンジン層 ＝ 遷移する者）
// 効果を発揮する場合は、以下の手順で行う（9-3-1）。
//  1. 条件確認：発揮するための条件がある場合、満たしていない限り発揮できない（9-3-1-1）
//  2. 宣言    ：発揮する効果を宣言する。手札で発揮できる効果は、カードを公開して宣言する（9-3-1-2）
//  3. 発揮    ：実際に効果を発揮する（9-3-1-3）
//  4. 解決    ：効果の解決を行う（9-3-1-4）
// 9-3-4：この発揮と解決は、それ以前に解決済みの常在型効果や、有効な誘発型効果を前提として行う
//        （＝呼び出し時点までのゲーム状態が既に確定していることを前提とする。呼び出し順序を保証するのは呼び出し側）。
// ※条件・宣言・発揮・解決それぞれの具体的な処理内容は効果システム側（未実装）の担当。
//   ここは手順（順序とゲート）のみを保証する。
export class 効果発揮管理 {
  効果を発揮する(
    条件を満たしているか: () => boolean,
    宣言する: () => void,
    発揮する: () => void,
    解決する: () => void
  ): 効果発揮結果 {
    if (!条件を満たしているか()) {
      return { 成功: false, 到達段階: '条件確認' };
    }
    宣言する();
    発揮する();
    解決する();
    return { 成功: true, 到達段階: '解決' };
  }
}
