import { ゲームエンジン } from '../../../ゲームエンジン.js';
import { カード } from '../../../データ/カード/カード.js';
import { アタック管理 } from './アタック管理.js';
import { ブロック管理 } from './ブロック管理.js';
import { カードの表示形式管理 } from './カードの表示形式管理.js';
import { ゾーン管理 } from './ゾーン管理.js';
import { コア管理 } from './コア管理.js';
import { コア判定 } from '../判定/コア判定.js';
import { シンボルルール } from '../カードの情報/シンボル.js';
import { BP管理 } from './BP管理.js';
import { 破壊管理 } from './破壊管理.js';

// バトル管理（ゲームエンジン層）
// アタック宣言・ブロック宣言の機構的な処理を行う。
//  8-1-1-1 アタック宣言：ターンプレイヤーの回復状態のスピリット1体を疲労させて宣言
//  8-1-3-1 ブロック宣言：アタックされているプレイヤーの回復状態のスピリット1体を疲労させて宣言
// ※「アタック中/時/した時」「ブロック中/時/した時」効果、フラッシュ効果、バトルの解決(8-1-5)は
//   効果システム／後述の担当。ここでは疲労と「アタック中/ブロック中」状態の付与・照会のみを扱う。
export class バトル管理 {
  private アタック管理: アタック管理;
  private ブロック管理: ブロック管理;
  private カードの表示形式管理: カードの表示形式管理;
  private ゾーン管理: ゾーン管理;
  private コア管理: コア管理;
  private コア判定: コア判定;
  private シンボルルール: シンボルルール;
  private BP管理: BP管理;
  private 破壊管理: 破壊管理;

  constructor() {
    this.アタック管理 = new アタック管理();
    this.ブロック管理 = new ブロック管理();
    this.カードの表示形式管理 = new カードの表示形式管理();
    this.ゾーン管理 = new ゾーン管理();
    this.コア管理 = new コア管理();
    this.コア判定 = new コア判定();
    this.シンボルルール = new シンボルルール();
    this.BP管理 = new BP管理();
    this.破壊管理 = new 破壊管理();
  }

  // アタック宣言：ターンプレイヤーのフィールドの回復状態のスピリット1体を疲労させてアタックを宣言する
  アタック宣言(ゲーム: ゲームエンジン, アタッカー: カード): boolean {
    const ターンプレイヤー = ゲーム.現在のプレイヤーを取得();
    if (!ターンプレイヤー) {
      return false;
    }
    const フィールド = this.ゾーン管理.フィールドを取得(ゲーム, ターンプレイヤー.識別子);
    if (!フィールド || !フィールド.カードを取得(アタッカー.識別子)) {
      return false; // ターンプレイヤーのフィールドにいない
    }
    if (!this.アタック管理.アタック可能か(アタッカー)) {
      return false; // 回復状態のスピリットでない、またはアタック禁止
    }
    // 疲労させ、アタック中状態を付与
    this.カードの表示形式管理.疲労する(アタッカー);
    アタッカー.状態を設定('アタック中', true);

    return true;
  }

  // このカードがブロックの基本条件を満たすか（回復状態のスピリットで、ブロック禁止でない）。
  // 『〜からブロックされない』のようにアタッカーとの関係で決まる制約は、
  // アタッカーを知らないこの層では判定できないため 試合 側で見る。
  ブロック可能か(ブロッカー: カード): boolean {
    return this.ブロック管理.ブロック可能か(ブロッカー);
  }

  // ブロック宣言：アタックされているプレイヤーのフィールドの回復状態のスピリット1体を疲労させてブロックを宣言する
  ブロック宣言(ゲーム: ゲームエンジン, ブロッカー: カード): boolean {
    const ターンプレイヤー = ゲーム.現在のプレイヤーを取得();
    if (!ターンプレイヤー) {
      return false;
    }
    const 防御プレイヤー = ゲーム
      .全プレイヤーを取得()
      .find(p => p.識別子 !== ターンプレイヤー.識別子);
    if (!防御プレイヤー) {
      return false;
    }
    const フィールド = this.ゾーン管理.フィールドを取得(ゲーム, 防御プレイヤー.識別子);
    if (!フィールド || !フィールド.カードを取得(ブロッカー.識別子)) {
      return false; // 防御プレイヤーのフィールドにいない
    }
    if (!this.ブロック管理.ブロック可能か(ブロッカー)) {
      return false; // 回復状態のスピリットでない、またはブロック禁止
    }
    // まず疲労させ、ブロックを宣言する
    this.カードの表示形式管理.疲労する(ブロッカー);
    ブロッカー.状態を設定('ブロック中', true);
    return true;
  }

  // バトル終了時にアタック中／ブロック中の状態を解除する
  バトル状態をクリア(アタッカー: カード, ブロッカー: カード | null = null): void {
    アタッカー.状態をクリア('アタック中');
    if (ブロッカー) {
      ブロッカー.状態をクリア('ブロック中');
    }
  }

  // バトル終了（8-1-7）
  //  8-1-7-1 バトル終了時の効果 → 効果システム（シーム）
  //  8-1-7-2 「アタック中」「ブロック中」「バトル中」効果はここで無効になる（状態を解除）
  //  8-1-7-3 ターンプレイヤーに次の行動機会 → アタックステップの進行に戻る（フロー側）
  バトルを終了(アタッカー: カード, ブロッカー: カード | null = null): void {
    this.バトル状態をクリア(アタッカー, ブロッカー);
  }

  // バトルの解決（8-1-5-1）
  // ブロックされていればBP比べへ、されていなければアタックされているプレイヤーの
  // ライフをアタッカーのシンボル数だけ減らす。
  //
  // 破壊時通知 … BP比べでスピリットが破壊されたとき、トラッシュへ置く前に呼ばれる（8-1-6-2）。
  //              第2引数は「破壊した側」のプレイヤー識別子。
  //              『自分が相手のスピリットを破壊した時』を知らせるのに要る。
  // 『破壊時』効果を挟むための窓。効果システムを知らないこの層は、呼ぶだけで中身は関知しない。
  // ライフ減少の可否 … 『ライフは〜のアタックでは減らない』のような制約を見る窓。
  //                   渡されなければ常に減る。
  バトルを解決(
    ゲーム: ゲームエンジン,
    アタッカー: カード,
    ブロッカー: カード | null,
    破壊時通知?: (破壊されたカード: カード, 破壊した側識別子?: string) => void,
    ライフ減少の可否?: (防御プレイヤー識別子: string, アタッカー: カード) => boolean
  ): void {
    if (ブロッカー) {
      // ブロックされていた → BP比べ（8-1-5-2）
      this.BP比べ(ゲーム, アタッカー, ブロッカー, 破壊時通知);
      return;
    }
    // ブロックされていない → ライフダメージ
    if (ライフ減少の可否) {
      const 防御プレイヤー = this.防御プレイヤーを取得(ゲーム);
      if (防御プレイヤー && !ライフ減少の可否(防御プレイヤー.識別子, アタッカー)) {
        return; // 効果によりライフが減らない
      }
    }
    this.ライフダメージを与える(ゲーム, アタッカー);
  }

  // アタックされているプレイヤーのライフをアタッカーのシンボル数だけ減らす。
  // 減った分のライフのコアは【トラッシュ】へ置く。実際に減った数を返す。
  //
  // ここをリザーブへ移していたため、トラッシュにコアがまったく貯まらなかった。
  // 「自分のトラッシュのコアを置く」効果（キュペル・飛赫レンシス・最奥：風牙岩・
  // ブレイククロー）が、実戦では一度も働かない状態になっていた。
  // 選ぶ画面までは出るのに何も起きない、という形で表に出る。
  ライフダメージを与える(ゲーム: ゲームエンジン, アタッカー: カード): number {
    const 防御プレイヤー = this.防御プレイヤーを取得(ゲーム);
    if (!防御プレイヤー) {
      return 0;
    }
    const ライフ = this.ゾーン管理.ライフを取得(ゲーム, 防御プレイヤー.識別子);
    const トラッシュ = this.ゾーン管理.トラッシュを取得(ゲーム, 防御プレイヤー.識別子);
    if (!ライフ || !トラッシュ) {
      return 0;
    }
    const ライフ保持者 = this.コア管理.ゾーンを保持者に(ライフ);
    const トラッシュ保持者 = this.コア管理.ゾーンを保持者に(トラッシュ);

    const シンボル数 = this.シンボルルール.シンボル数を取得(アタッカー);
    // ライフに残っているコアが足りなければある分だけ減らす
    const 減少数 = Math.min(シンボル数, this.コア判定.通常コア数を取得(ライフ保持者));
    if (減少数 > 0) {
      this.コア管理.通常コアを移動(ライフ保持者, トラッシュ保持者, 減少数);
      if (this.ライフ減少の記録) {
        this.ライフ減少の記録(防御プレイヤー.識別子);
      }
    }
    return 減少数;
  }

  // ライフが減ったことを記録する先。『このターンに自分のライフが減っていたなら』のため。
  // 記録の置き場所を知らずに済むよう、通知先だけを受け取る。
  private ライフ減少の記録: ((減ったプレイヤー識別子: string) => void) | undefined;

  ライフ減少の記録先を設定(記録: (減ったプレイヤー識別子: string) => void): void {
    this.ライフ減少の記録 = 記録;
  }

  // BP比べ（8-1-5-2）：スピリット同士のバトルの結果を判定する。
  // すでにアタッカーかブロッカーがフィールドからいなくなっていたら何もしない（8-1-5-2-1）。
  // ※実際のBP比較（勝敗・破壊）は後述で実装する。
  BP比べ(
    ゲーム: ゲームエンジン,
    アタッカー: カード,
    ブロッカー: カード,
    破壊時通知?: (破壊されたカード: カード, 破壊した側識別子?: string) => void
  ): boolean {
    if (!this.フィールドにいるか(ゲーム, アタッカー) || !this.フィールドにいるか(ゲーム, ブロッカー)) {
      return false; // どちらかが場を離れていたら何もしない（8-1-5-2-1）
    }
    const ターンプレイヤー = ゲーム.現在のプレイヤーを取得();
    const 防御プレイヤー = this.防御プレイヤーを取得(ゲーム);
    if (!ターンプレイヤー || !防御プレイヤー) {
      return false;
    }

    const アタッカーBP = this.BP管理.現在のBPを取得(アタッカー);
    const ブロッカーBP = this.BP管理.現在のBPを取得(ブロッカー);

    // BPが低かったスピリットが破壊される。BPが同じなら両方破壊（8-1-6-1）。
    // 破壊原因はBP比べ（相手のスピリットとの比較）＝『相手による破壊時』の対象（12-2-1-12-1）。
    if (アタッカーBP < ブロッカーBP) {
      this.スピリットを破壊(ゲーム, アタッカー, ターンプレイヤー.識別子, ブロッカー, 破壊時通知);
    } else if (ブロッカーBP < アタッカーBP) {
      this.スピリットを破壊(ゲーム, ブロッカー, 防御プレイヤー.識別子, アタッカー, 破壊時通知);
    } else {
      this.スピリットを破壊(ゲーム, アタッカー, ターンプレイヤー.識別子, ブロッカー, 破壊時通知);
      this.スピリットを破壊(ゲーム, ブロッカー, 防御プレイヤー.識別子, アタッカー, 破壊時通知);
    }
    return true;
  }

  // スピリットを破壊する（8-1-6）：待機状態化 →（破壊したとき効果=シーム）→ トラッシュへ
  private スピリットを破壊(
    ゲーム: ゲームエンジン,
    スピリット: カード,
    所有者識別子: string,
    相手のカード: カード,
    破壊時通知?: (破壊されたカード: カード, 破壊した側識別子?: string) => void
  ): void {
    this.破壊管理.破壊する(スピリット, { 由来: 'BP比べ', 相手のカード }); // 待機状態化（理由=破壊）
    // 8-1-6-2: BP比べでスピリットを破壊したときに発揮する効果。
    // まだフィールドにいるこの瞬間に『破壊時』を解決させる。
    //
    // 破壊した側は、倒された側の持ち主ではないほう。
    // 『自分が相手のスピリットを破壊した時』はこの人の場のカードだけが誘発する。
    if (破壊時通知) {
      const 破壊した側 = ゲーム
        .全プレイヤーを取得()
        .find(p => p.識別子 !== 所有者識別子);
      破壊時通知(スピリット, 破壊した側?.識別子);
    }
    this.破壊管理.トラッシュへ置く(ゲーム, 所有者識別子, スピリット); // トラッシュへ、コアはリザーブへ
  }

  // 対戦相手（アタックされているプレイヤー＝ターンプレイヤーでない方）
  private 防御プレイヤーを取得(ゲーム: ゲームエンジン) {
    const ターンプレイヤー = ゲーム.現在のプレイヤーを取得();
    if (!ターンプレイヤー) {
      return undefined;
    }
    return ゲーム.全プレイヤーを取得().find(p => p.識別子 !== ターンプレイヤー.識別子);
  }

  // カードがいずれかのフィールドにいるか
  private フィールドにいるか(ゲーム: ゲームエンジン, カード: カード): boolean {
    return ゲーム.全プレイヤーを取得().some(プレイヤー => {
      const フィールド = this.ゾーン管理.フィールドを取得(ゲーム, プレイヤー.識別子);
      return フィールド?.カードを取得(カード.識別子) !== undefined;
    });
  }
}
