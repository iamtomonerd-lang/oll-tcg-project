// 起動を試みた結果
// コスト解決＝「▶」より前の行動（コスト）を完全に解決できたか。
// 効果解決＝「▶」の後の効果を発揮できたか（コストが解決できた場合のみ試みる）。
export interface 起動結果<T> {
  コスト解決: boolean;
  効果結果?: T;
}

// 起動型効果管理（ゲームエンジン層 ＝ 遷移する者）
// 起動型効果は「▶」より前のコストを完全に解決してから「▶」後の効果を発揮する（9-1-6-2）。
// コストの解決自体は独立しており、後の効果が解決できなくてもコストの解決自体は成立する（9-1-6-4）。
// ※コストの支払い方法・効果の具体的な処理内容は効果システム側（未実装）の担当。
//   ここは「コストを解決してから効果を発揮する」という手順のみを保証する。
export class 起動型効果管理 {
  起動する<T>(コストを支払う: () => boolean, 効果を発揮する: () => T): 起動結果<T> {
    const コスト解決 = コストを支払う();
    if (!コスト解決) {
      return { コスト解決: false };
    }
    // コストが解決できた場合のみ、後の効果を発揮する。
    // 効果が解決できるかどうかに関わらず、コストの解決自体はすでに成立している（9-1-6-4）。
    const 効果結果 = 効果を発揮する();
    return { コスト解決: true, 効果結果 };
  }
}
