import { カード } from '../../../データ/カード/カード.js';
import { BP管理 } from './BP管理.js';

// 一時効果管理（ゲームエンジン層 ＝ 遷移する者）
// 「このバトル中」「このターン中」のように期限付きで数値を変える効果を記録し、
// 期限が来たら元に戻す（7-9-1-1：「このターン中」を期限とする効果はエンドステップで無効になる）。
//
// 期限なし（永続）の変更はここでは扱わない。戻す必要がないため記録しない。
export type 効果期限 = 'このバトル中' | 'このターン中';

interface BP変更記録 {
  カード: カード;
  量: number;
  期限: 効果期限;
}

export class 一時効果管理 {
  private BP管理: BP管理;
  private 記録一覧: BP変更記録[] = [];

  // 状態を写し取る（先読みで盤面を複製するため）。
  // 記録はカードそのものを指しているので、複製したカードに差し替える。
  // ここを写し忘れると「このターン中」のBP補正が複製で消える。
  状態を写す(元: 一時効果管理, カードを解決: (識別子: string) => カード | undefined): void {
    this.記録一覧 = 元.記録一覧
      .map(記録 => {
        const 差し替えたカード = カードを解決(記録.カード.識別子);
        return 差し替えたカード ? { ...記録, カード: 差し替えたカード } : null;
      })
      .filter((記録): 記録 is BP変更記録 => 記録 !== null);
  }

  constructor(BP管理個体?: BP管理) {
    this.BP管理 = BP管理個体 ?? new BP管理();
  }

  // 期限付きのBP変更を記録する。実際にBPを動かすのは呼び出し側。
  BP変更を記録する(カード: カード, 量: number, 期限: 効果期限): void {
    if (量 === 0) {
      return;
    }
    this.記録一覧.push({ カード, 量, 期限 });
  }

  // 指定した期限の記録をすべて元に戻す。戻した件数を返す。
  期限切れを解除する(期限: 効果期限): number {
    const 対象 = this.記録一覧.filter(記録 => 記録.期限 === 期限);
    for (const 記録 of 対象) {
      // 加えた分をそのまま引いて元に戻す
      this.BP管理.効果によるBPを変更(記録.カード, -記録.量);
    }
    this.記録一覧 = this.記録一覧.filter(記録 => 記録.期限 !== 期限);
    return 対象.length;
  }

  // 今どれだけの期限付き変更を抱えているか（検証用）
  記録数を取得(期限?: 効果期限): number {
    if (期限 === undefined) {
      return this.記録一覧.length;
    }
    return this.記録一覧.filter(記録 => 記録.期限 === 期限).length;
  }
}
