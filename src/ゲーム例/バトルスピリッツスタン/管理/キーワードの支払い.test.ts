// 《継召》と《ソウルマジック》は、判定も管理も前からあったのに
// 呼び出す者が誰もいなかった（継召管理.発揮する の呼び出し箇所は0件だった）。
// そのため実戦では一度も働かず、「軽減できない」「発動しない」という形で表に出た。
//
// ここでは 試合 の入り口（継召を発揮する／使用する）を本物の経路として通し、
// 盤面に見える結果（リザーブが減った数・トラッシュの中身・場に出たか）で確かめる。

function 試合を準備する(): 試合 {
  const 試合インスタンス = new 試合(1);
  試合インスタンス.プレイヤーを準備する('p1', 'プレイヤー1');
  試合インスタンス.プレイヤーを準備する('p2', 'プレイヤー2');
  試合インスタンス.ボイドを準備する();
  試合インスタンス.デッキを設定する(
    'p1',
    Array.from({ length: 10 }, (_, i) => グンガタを作成(`p1-deck-${i + 1}`))
  );
  試合インスタンス.デッキを設定する(
    'p2',
    Array.from({ length: 10 }, (_, i) => グンガタを作成(`p2-deck-${i + 1}`))
  );
  試合インスタンス.準備を行う('p1');
  試合インスタンス.準備を行う('p2');
  試合インスタンス.先攻を決める('p1');
  試合インスタンス.試合を開始する();
  return 試合インスタンス;
}

const リザーブ保持者 = (m: 試合) =>
  m.コア管理.ゾーンを保持者に(m.ゾーン管理.リザーブを取得(m.ゲーム, 'p1')!);
const トラッシュ保持者 = (m: 試合) =>
  m.コア管理.ゾーンを保持者に(m.ゾーン管理.トラッシュを取得(m.ゲーム, 'p1')!);

function リザーブにコアを置く(m: 試合, 数: number): void {
  リザーブ保持者(m).コア数を設定(数);
}

function 手札に加える(m: 試合, カード一覧: カード[]): void {
  const 手札 = m.ゾーン管理.手札を取得(m.ゲーム, 'p1')!;
  for (const c of カード一覧) 手札.カードを追加(c);
}

function トラッシュに積む(m: 試合, カード一覧: カード[]): void {
  const トラッシュ = m.ゾーン管理.トラッシュを取得(m.ゲーム, 'p1')!;
  for (const c of カード一覧) トラッシュ.カードを追加(c);
}

const 場のカード名 = (m: 試合): string[] =>
  m.ゾーン管理
    .フィールドを取得(m.ゲーム, 'p1')!
    .カード一覧を取得()
    .map(c => c.名称.表示名);

const 除外エリアの識別子 = (m: 試合): string[] =>
  m.ゾーン管理
    .除外エリアを取得(m.ゲーム, 'p1')!
    .カード一覧を取得()
    .map(c => c.識別子);

// === 《継召》（12-2-1-3） ===

test('《継召》：トラッシュのEXシンボルを除外した数だけコストが軽くなる', () => {
  const m = 試合を準備する();
  const セルタリウス = セルタリウスを作成('自身'); // コスト6／軽減シンボル 赤赤赤
  手札に加える(m, [セルタリウス]);
  // グン＝ガタはEXシンボルを持つ（＝継召の燃料になる）
  トラッシュに積む(m, [グンガタを作成('燃料1'), グンガタを作成('燃料2')]);
  リザーブにコアを置く(m, 10);

  const 軽減数 = m.継召を発揮する('p1', セルタリウス, [
    m.ゾーン管理.トラッシュを取得(m.ゲーム, 'p1')!.カードを取得('燃料1')!,
    m.ゾーン管理.トラッシュを取得(m.ゲーム, 'p1')!.カードを取得('燃料2')!,
  ]);

  assert.equal(軽減数, 2, '2枚食べたので軽減シンボルを2つ満たす');
  assert.deepEqual(除外エリアの識別子(m).sort(), ['燃料1', '燃料2'], '食べたカードは除外エリアへ');
  assert.equal(
    m.ゾーン管理.トラッシュを取得(m.ゲーム, 'p1')!.カード枚数を取得(),
    0,
    'トラッシュからは消えている'
  );

  // 場にシンボルが無いので軽減はこの2つだけ。コスト6 − 2 ＝ 4、初期コア1で計5個減る。
  const 前 = リザーブ保持者(m).コア数を取得();
  const 成功 = m.召喚する(
    'p1',
    セルタリウス,
    [{ 保持者: リザーブ保持者(m), 数: 4 }],
    [{ 保持者: リザーブ保持者(m), 数: 1 }],
    軽減数
  );

  assert.equal(成功, true);
  assert.ok(場のカード名(m).includes('セルタリウス'), '場に出ている');
  assert.equal(リザーブ保持者(m).コア数を取得(), 前 - 5, 'コスト4＋初期コア1だけ減る');
  assert.equal(トラッシュ保持者(m).コア数を取得(), 4, '払った4個はトラッシュへ行く');
});

test('《継召》：EXシンボルを持たないカードは食べられない', () => {
  const m = 試合を準備する();
  const セルタリウス = セルタリウスを作成('自身');
  手札に加える(m, [セルタリウス]);
  // セルタリウス自身のシンボルは通常なので燃料にならない
  トラッシュに積む(m, [セルタリウスを作成('通常シンボル')]);

  const 軽減数 = m.継召を発揮する('p1', セルタリウス, [
    m.ゾーン管理.トラッシュを取得(m.ゲーム, 'p1')!.カードを取得('通常シンボル')!,
  ]);

  assert.equal(軽減数, 0);
  assert.deepEqual(除外エリアの識別子(m), [], '除外されない');
  assert.equal(
    m.ゾーン管理.トラッシュを取得(m.ゲーム, 'p1')!.カード枚数を取得(),
    1,
    'トラッシュに残っている'
  );
});

// 《継召》は「ルールブックに書かれている効果」であって、全カードが持つ性質ではない。
// カード側のキーワードを見ていなかったため、実機ではどのカードでもトラッシュの
// EXシンボルを食べられてしまっていた。
test('《継召》：キーワードを持たないカードでは発揮できない', () => {
  const m = 試合を準備する();
  const グンガタ = グンガタを作成('自身'); // 軽減シンボル赤×3を持つが《継召》は無い
  手札に加える(m, [グンガタ]);
  トラッシュに積む(m, [グンガタを作成('燃料1')]);
  リザーブにコアを置く(m, 10);
  const トラッシュ = m.ゾーン管理.トラッシュを取得(m.ゲーム, 'p1')!;

  const 軽減数 = m.継召を発揮する('p1', グンガタ, [トラッシュ.カードを取得('燃料1')!]);

  assert.equal(軽減数, 0);
  assert.deepEqual(除外エリアの識別子(m), [], '除外エリアへ動かない');
  assert.equal(トラッシュ.カード枚数を取得(), 1, 'トラッシュのカードは残ったまま');
});

test('《継召》：軽減シンボルの数を超えては食べられない（12-2-1-3-2-1）', () => {
  const m = 試合を準備する();
  const セルタリウス = セルタリウスを作成('自身'); // 軽減シンボルは3つ
  手札に加える(m, [セルタリウス]);
  トラッシュに積む(m, [
    グンガタを作成('燃料1'),
    グンガタを作成('燃料2'),
    グンガタを作成('燃料3'),
    グンガタを作成('燃料4'),
  ]);
  const トラッシュ = m.ゾーン管理.トラッシュを取得(m.ゲーム, 'p1')!;

  const 軽減数 = m.継召を発揮する(
    'p1',
    セルタリウス,
    ['燃料1', '燃料2', '燃料3', '燃料4'].map(id => トラッシュ.カードを取得(id)!)
  );

  assert.equal(軽減数, 0, '枠を超えた指定はまるごと無効（1枚も除外されない）');
  assert.equal(トラッシュ.カード枚数を取得(), 4, 'トラッシュは減らない');
});

// === 《ソウルマジック》（12-2-1-2-1） ===

test('《ソウルマジック》：自分の該当色シンボルがあれば、ソウルコアだけで使える', () => {
  const m = 試合を準備する();
  const マジック = フレイムハリケーンを作成('嵐'); // コスト6／《ソウルマジック：赤》
  手札に加える(m, [マジック]);
  // 場に赤のシンボルを1つ用意する（グン＝ガタは赤）
  m.ゾーン管理.フィールドを取得(m.ゲーム, 'p1')!.カードを追加(グンガタを作成('場の赤'));
  リザーブにコアを置く(m, 3);
  リザーブ保持者(m).ソウルコアを設定(true);

  const 前のコア数 = リザーブ保持者(m).コア数を取得();
  const 成功 = m.使用する(
    'p1',
    マジック,
    [{ 保持者: リザーブ保持者(m), 数: 1, ソウルコア数: 1 }],
    0,
    'フラッシュ',
    true // 《ソウルマジック》で払う
  );

  assert.equal(成功, true, 'コスト6を払わずに使えている');
  assert.equal(リザーブ保持者(m).コア数を取得(), 前のコア数 - 1, '減るのはソウルコア1個だけ');
  assert.equal(リザーブ保持者(m).ソウルコアあるか(), false, 'ソウルコアがリザーブから出て行く');
  assert.equal(
    new コア判定().ソウルコアあるか(トラッシュ保持者(m)),
    true,
    'ソウルコアはトラッシュに置かれる'
  );
});

test('《ソウルマジック》：該当色のシンボルが場に無ければ使えない', () => {
  const m = 試合を準備する();
  const マジック = フレイムハリケーンを作成('嵐');
  手札に加える(m, [マジック]);
  // 場は空＝赤のシンボルが無い
  リザーブにコアを置く(m, 3);
  リザーブ保持者(m).ソウルコアを設定(true);

  const 成功 = m.使用する(
    'p1',
    マジック,
    [{ 保持者: リザーブ保持者(m), 数: 1, ソウルコア数: 1 }],
    0,
    'フラッシュ',
    true
  );

  assert.equal(成功, false);
  assert.equal(リザーブ保持者(m).ソウルコアあるか(), true, 'ソウルコアは動かない');
  assert.equal(
    m.ゾーン管理.手札を取得(m.ゲーム, 'p1')!.カードを取得('嵐') !== undefined,
    true,
    'マジックは手札に残る'
  );
});

