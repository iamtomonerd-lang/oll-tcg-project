// フラッシュタイミング管理（ゲームエンジン層。バトル中のフラッシュ効果のやり取り。8-1-2／8-1-4）
// アタックされているプレイヤー（防御側）から始まり、各プレイヤーはフラッシュ効果を
// 1回使うかパスできる。使うかパスしたら相手に権利が移る。パスが2度続いたら終了する。
// ※フラッシュ効果の中身の解決は効果システム側（未実装）の担当。ここは権利の受け渡しのみ。
export class フラッシュタイミング管理 {
  private 権利者識別子: string;
  private 相手識別子: string;
  private 連続パス数 = 0;

  // 防御側（アタックされているプレイヤー）から開始する
  constructor(防御側識別子: string, 攻撃側識別子: string) {
    this.権利者識別子 = 防御側識別子;
    this.相手識別子 = 攻撃側識別子;
  }

  // 現在フラッシュ効果を使う権利を持つプレイヤー
  現在の権利者(): string {
    return this.権利者識別子;
  }

  // フラッシュ効果を使った（連続パスをリセットして相手へ権利を移す）
  効果を使用した(): void {
    this.連続パス数 = 0;
    this.権利を交代();
  }

  // パスした（連続パスを増やして相手へ権利を移す）
  パスした(): void {
    this.連続パス数 += 1;
    this.権利を交代();
  }

  // パスが2度続いたらフラッシュタイミングを終了する
  終了か(): boolean {
    return this.連続パス数 >= 2;
  }

  private 権利を交代(): void {
    const 一時 = this.権利者識別子;
    this.権利者識別子 = this.相手識別子;
    this.相手識別子 = 一時;
  }
}
