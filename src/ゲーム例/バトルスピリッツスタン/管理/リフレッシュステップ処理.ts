import { ゲームエンジン } from '../../../ゲームエンジン.js';
import { ゾーン管理 } from './ゾーン管理.js';
import { コア管理 } from './コア管理.js';
import { カードの表示形式管理 } from './カードの表示形式管理.js';

// リフレッシュステップ処理（ゲームエンジン層）
// リフレッシュステップのターン起因処理：
//  ① ターンプレイヤーのフィールドのカードをすべて回復させる（各カードを1段階回復）
//  ② トラッシュのコアすべてをリザーブに移動する
// ※『リフレッシュステップ』の誘発条件の効果の発揮、および解決待ち効果の解決は
//   効果システム側（未実装）の担当。回復による「回復したとき」効果も同様。
export class リフレッシュステップ処理 {
  private ゾーン管理: ゾーン管理;
  private コア管理: コア管理;
  private カードの表示形式管理: カードの表示形式管理;

  constructor() {
    this.ゾーン管理 = new ゾーン管理();
    this.コア管理 = new コア管理();
    this.カードの表示形式管理 = new カードの表示形式管理();
  }

  ターン起因処理(ゲーム: ゲームエンジン): boolean {
    const ターンプレイヤー = ゲーム.現在のプレイヤーを取得();
    if (!ターンプレイヤー) {
      return false;
    }

    const フィールド = this.ゾーン管理.フィールドを取得(ゲーム, ターンプレイヤー.識別子);
    const トラッシュ = this.ゾーン管理.トラッシュを取得(ゲーム, ターンプレイヤー.識別子);
    const リザーブ = this.ゾーン管理.リザーブを取得(ゲーム, ターンプレイヤー.識別子);
    if (!フィールド || !トラッシュ || !リザーブ) {
      return false;
    }

    // ① フィールドのカードをすべて回復させる（1段階：重疲労→疲労、疲労→回復）
    for (const カード of フィールド.カード一覧を取得()) {
      this.カードの表示形式管理.回復する(カード);
    }

    // ② トラッシュのコアをすべてリザーブへ移動する（ソウルコアも可）
    const トラッシュ保持者 = this.コア管理.ゾーンを保持者に(トラッシュ);
    const リザーブ保持者 = this.コア管理.ゾーンを保持者に(リザーブ);
    this.コア管理.全コアを移動(トラッシュ保持者, リザーブ保持者);

    return true;
  }
}
