import { コア保持者 } from '../判定/コア保持者.js';
import { コア管理 } from './コア管理.js';

// ソウルマジック管理（ゲームエンジン層 ＝ 遷移する者）
// 《ソウルマジック》のコスト支払い：ソウルコアのみでコストを支払う（12-2-1-2-1）。
// トラッシュは制限付き配置先ではないため、ソウルコアを問題なく移動できる。
export class ソウルマジック管理 {
  private コア管理: コア管理;

  constructor() {
    this.コア管理 = new コア管理();
  }

  ソウルコアでコストを支払う(元: コア保持者, トラッシュ: コア保持者): boolean {
    return this.コア管理.ソウルコアを移動(元, トラッシュ);
  }
}
