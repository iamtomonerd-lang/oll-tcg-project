import { ゾーン } from '../../../データ/ゾーン/ゾーン.js';
import { カード } from '../../../データ/カード/カード.js';
import { 継召判定 } from '../判定/継召判定.js';

// 継召管理（ゲームエンジン層 ＝ 遷移する者）
// 《継召》を発揮する：トラッシュのEXシンボルを持つカードをゲームから除外し、
// 除外した枚数分だけ軽減シンボルを満たす（12-2-1-3-1／12-2-1-3-2）。
// 除外自体は軽減の判定前に行う（12-2-1-3-2）。
export class 継召管理 {
  private 継召判定: 継召判定;

  constructor() {
    this.継召判定 = new 継召判定();
  }

  // トラッシュから除外エリアへ、除外するカード一覧を移動する。
  // 戻り値：実際に満たした軽減シンボルの数（＝除外できた枚数。0なら発揮できなかった）
  発揮する(トラッシュ: ゾーン, 除外エリア: ゾーン, 対象カード: カード, 除外するカード一覧: カード[]): number {
    if (!this.継召判定.除外は有効か(対象カード, 除外するカード一覧)) {
      return 0; // 12-2-1-3-2-1違反、またはEXシンボルを持たないカードが含まれる
    }

    let 実際に除外した数 = 0;
    for (const カード of 除外するカード一覧) {
      if (!トラッシュ.カードを取得(カード.識別子)) {
        continue; // トラッシュに無いカードは除外できない
      }
      const 取り出したカード = トラッシュ.カードを削除(カード.識別子);
      if (取り出したカード) {
        除外エリア.カードを追加(取り出したカード);
        実際に除外した数++;
      }
    }
    return 実際に除外した数;
  }
}
