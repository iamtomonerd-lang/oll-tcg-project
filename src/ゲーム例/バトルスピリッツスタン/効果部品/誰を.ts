// ③ 誰を（対象の絞り込み）
//
// 「相手のスピリット1体を指定する」の部分を1つの名前にした部品。
// 実装済みカードで最も使い回されている分類（相手のスピリットを選ぶ＝12枚）。
//
// 体数を書かなければ1体。まで:true なら「N体まで」（0体でもよい）、
// 任意:true なら「指定できる」（丸ごと飛ばせる）。
// 残りの項目（コスト以下・BP以下・系統など）はそのまま絞り込みになる。

import { カードフィルタ, 数値式, 処理ステップ } from '../../../効果解釈/効果定義.js';
import { 空の項目を落とす } from './内部.js';

export type 選び方 = Omit<カードフィルタ, '場' | 'ゾーン'> & {
  体数?: 数値式 | 'すべて';
  まで?: boolean;
  任意?: boolean;
};

function 選ぶ(基本: カードフィルタ, 設定: 選び方): 処理ステップ {
  const { 体数, まで, 任意, ...絞り込み } = 設定;
  return { 選択: 空の項目を落とす({ ...基本, ...絞り込み, 数: 体数 ?? 1, まで, 任意 }) };
}

// === 場のスピリット ===

// 「相手のスピリットN体を指定する」
//   相手のスピリットを選ぶ()                    → 1体
//   相手のスピリットを選ぶ({ コスト以下: 4 })   → コスト4以下の相手のスピリット1体
//   相手のスピリットを選ぶ({ BP以下: 3000 })    → BP3000以下の相手のスピリット1体
//   相手のスピリットを選ぶ({ 体数: 2, まで: true }) → 相手のスピリット1体〜2体
export function 相手のスピリットを選ぶ(設定: 選び方 = {}): 処理ステップ {
  return 選ぶ({ 場: '相手', 種別: 'スピリット' }, 設定);
}

// 「自分のスピリットN体を指定する」
//   自分のスピリットを選ぶ({ 系統: '血醒', アタック中: true })
//     → アタックしている系統：「血醒」を持つ自分のスピリット1体
export function 自分のスピリットを選ぶ(設定: 選び方 = {}): 処理ステップ {
  return 選ぶ({ 場: '自分', 種別: 'スピリット' }, 設定);
}

// 「相手のネクサスN個を指定する」
export function 相手のネクサスを選ぶ(設定: 選び方 = {}): 処理ステップ {
  return 選ぶ({ 場: '相手', 種別: 'ネクサス' }, 設定);
}

// 「《継召》を持つ自分のスピリットすべて」のように、キーワードで絞る書き方。
// 体数に 'すべて' を渡せば、条件に合うもの全部が対象になる。
//   自分のスピリットを選ぶ({ キーワード: '継召', 体数: 'すべて' })

// 「自分のスピリット/ネクサスNつを指定する」
// スピリットとネクサスのどちらでもよい、という書かれ方のカード用。
//   自分のスピリットかネクサスを選ぶ({ 系統: '風牙', 任意: true })
//     → 系統：「風牙」を持つ自分のスピリット/ネクサス1つを指定できる
export function 自分のスピリットかネクサスを選ぶ(設定: 選び方 = {}): 処理ステップ {
  return 選ぶ({ 場: '自分', 種別: ['スピリット', 'ネクサス'] }, 設定);
}

// === 場以外のゾーン ===

// 「自分のトラッシュの〜1枚を指定する」
//   自分のトラッシュから選ぶ({ 種別: 'スピリット', 系統: '風牙', コスト以下: 4 })
export function 自分のトラッシュから選ぶ(設定: 選び方 = {}): 処理ステップ {
  return 選ぶ({ 場: '自分', ゾーン: 'トラッシュ' }, 設定);
}

// 「自分の手札の〜1枚を指定する」
//   自分の手札から選ぶ({ 系統: '風牙' })
export function 自分の手札から選ぶ(設定: 選び方 = {}): 処理ステップ {
  return 選ぶ({ 場: '自分', ゾーン: '手札' }, 設定);
}

// 「めくったカードの中から〜を指定する」
// デッキの上をめくる() のあとに使う。
export function めくった中から選ぶ(設定: 選び方 = {}): 処理ステップ {
  return 選ぶ({ 元: 'スコープ' }, 設定);
}

// === めくる ===

// 「自分のデッキの上からN枚をオープンする」
// ゾーンは 'デッキ上'。接続側は 'デッキ' と同じくデッキエリアを指すが、
// 「上から」めくる操作だと読めるよう、語彙調査と同じ表記に揃えてある。
export function デッキの上をめくる(枚数: number, 場: '自分' | '相手' = '自分'): 処理ステップ {
  return { オープン: { 場, ゾーン: 'デッキ上', 数: 枚数 } };
}
