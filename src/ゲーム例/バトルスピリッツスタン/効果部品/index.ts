// 効果の部品ぜんぶ
//
// カードテキストは、いつも次の6つに割れる。
//
//   ［Lv2］《真界放》『アタック時』コスト4以下の相手のスピリット1体を指定する。
//    │      └②条件  └①いつ      └③誰を
//    └Lv                          それの{ソウルコア}以外のコア1個をリザーブに置く。
//                                  └④何をする
//
//   【起動：メイン】このネクサスを破壊する▶ …
//    └①いつ        └⑤代償
//
//   このバトル中、それをBP+2000する。
//   └⑥長さ
//
// この6つをそれぞれ部品にしてある。カードは部品を組み合わせて書く。
// どれか1分類が本体で他が付属品、ということはない。実データで最も使い回されているのは
// ③誰を の「相手のスピリットを選ぶ」（12枚）で、②条件 は枚数こそ少ないが
// 判定を間違えやすい場所であり、いずれも同格の資産として扱う。
//
// 対応表は docs/効果パーツ一覧.md。
//
// 正式なカードが1枚届いたときの手順：
//   1. カードテキストを①〜⑥に割る
//   2. 各部分に同じ部品があるか、この索引と一覧表から探す
//   3. 全部あれば組み合わせて書くだけ。無ければ部品を1つ足して一覧表に追記する
//   4. テストを流す。通れば既存のカードを壊していない

