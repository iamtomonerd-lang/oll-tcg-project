// === コアを動かす ===

// 「それの{ソウルコア}以外のコアN個をリザーブに置く」
// 「それのコアがN個になるようにリザーブに置く」
// 「（置くコアは相手が選ぶ）」
//
//   それのコアをリザーブに置く({ 個数: 1, ソウルコアは除く: true })
//   それのコアをリザーブに置く({ 残す: 1, 置くコアを選ぶのは: '相手' })
//   それのコアをリザーブに置く({ 個数: 2, 置くコアを選ぶのは: '相手' })
export function それのコアをリザーブに置く(
  設定: {
    個数?: number;
    // 「コアがN個になるように」。動かす数を残量から逆算する。
    残す?: number;
    // 「{ソウルコア}以外の」
    ソウルコアは除く?: boolean;
    // 「（置くコアは相手が選ぶ）」
    置くコアを選ぶのは?: 決定者;
    // コアの行き先のリザーブ。既定は相手（相手のスピリットから剥がすため）。
    リザーブの持ち主?: '自分' | '相手';
  } = {}
): 処理ステップ {
  return {
    コア移動: 空の項目を落とす({
      元: { 対象: '選択' as const },
      先: { ゾーン: 'リザーブ', 場: 設定.リザーブの持ち主 ?? '相手' },
      数: 設定.個数 ?? 0,
      残す: 設定.残す,
      除外: 設定.ソウルコアは除く ? ('ソウルコア' as const) : undefined,
      選ぶのは: 設定.置くコアを選ぶのは,
    }),
  };
}

