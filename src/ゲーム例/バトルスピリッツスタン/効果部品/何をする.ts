// 「自分のトラッシュの{ソウルコア}以外のコアN個をこのスピリットに置く」
// 「自分のトラッシュの{ソウルコア}をそれに置く」
//
//   トラッシュのコアを置く({ 個数: 2, まで: true, ソウルコアは除く: true })
//     → {ソウルコア}以外のコア2個まで を このカード に置く
//   トラッシュのコアを置く({ ソウルコアだけ: true, 置き先: '選択' })
//     → {ソウルコア} を 直前に選んだカード に置く
//   トラッシュのコアを置く({ ソウルコアは除く: true, 置き先: 'リザーブ' })
//     → {ソウルコア}以外のコア1個を 自分のリザーブ に置く
export function トラッシュのコアを置く(
  設定: {
    個数?: number;
    // 「N個まで」。トラッシュに足りなくても失敗にしない。
    まで?: boolean;
    // 「{ソウルコア}以外の」
    ソウルコアは除く?: boolean;
    // 「{ソウルコア}を」。動かすコアをソウルコアに限る。
    ソウルコアだけ?: boolean;
    // 置き先。カード（自身／直前に選んだもの）か、自分のリザーブ。
    // 既定は効果の発生元（「このスピリットに置く」）。
    置き先?: '自身' | '選択' | 'リザーブ';
    トラッシュの持ち主?: '自分' | '相手';
  } = {}
): 処理ステップ {
  const 置き先 = 設定.置き先 ?? '自身';
  return {
    コア移動: 空の項目を落とす({
      元: { ゾーン: 'トラッシュ', 場: 設定.トラッシュの持ち主 ?? '自分' },
      先:
        置き先 === 'リザーブ'
          ? { ゾーン: 'リザーブ', 場: '自分' as const }
          : { 対象: 置き先 },
      数: 設定.個数 ?? 1,
      まで: 設定.まで,
      除外: 設定.ソウルコアは除く ? ('ソウルコア' as const) : undefined,
      種類: 設定.ソウルコアだけ ? ('ソウルコア' as const) : undefined,
    }),
  };
}

