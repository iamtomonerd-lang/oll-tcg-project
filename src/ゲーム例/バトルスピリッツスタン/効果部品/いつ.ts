// ① いつ（きっかけ）
//
// 「どの場面で働く効果か」を1つの名前にした部品。
// カード側では ...召喚時 のように展開して使う。
//
// カードテキストの『召喚時』『アタック中』【起動：メイン】［フラッシュ］に対応する。

import { 効果定義 } from '../../../効果解釈/効果定義.js';

export type きっかけ = Pick<効果定義, 'トリガー' | '種別' | 'タイミング' | '状態' | 'ステップ'>;

// === 誘発（何かが起きたとき、ひとりでに働く） ===

// 『召喚時』
export const 召喚時: きっかけ = { トリガー: '召喚時' };
// 『配置時』（ネクサス）
export const 配置時: きっかけ = { トリガー: '配置時' };
// 『破壊時』
export const 破壊時: きっかけ = { トリガー: '破壊時' };
// 『アタック時』
export const アタック時: きっかけ = { トリガー: 'アタック時' };
// 『バトル終了時』
export const バトル終了時: きっかけ = { トリガー: 'バトル終了時' };
// 『自分のエンドステップ』
export const 自分のエンドステップ: きっかけ = { トリガー: '自分のエンドステップ' };
// 『自分が相手のスピリットを破壊した時』
export const 相手のスピリットを破壊した時: きっかけ = {
  トリガー: '自分が相手のスピリットを破壊した時',
};

// === 常在（条件を満たすあいだ、ずっと働く） ===

export const 常在: きっかけ = { 種別: '常在' };

// === 起動（プレイヤーが撃つ） ===

// 【起動：メイン】
export const 起動メイン: きっかけ = { 種別: '起動', タイミング: 'メイン' };
// 【起動：フラッシュ】
export const 起動フラッシュ: きっかけ = { 種別: '起動', タイミング: 'フラッシュ' };

// === 使用（マジックカード） ===

// ［メイン］
export const 使用メイン: きっかけ = { 種別: '使用', タイミング: 'メイン' };
// ［フラッシュ］
export const 使用フラッシュ: きっかけ = { 種別: '使用', タイミング: 'フラッシュ' };

// === 場面をさらに狭める ===

// 『アタック中』… 上のきっかけに重ねて使う。
// 例：アタック中だけ(起動フラッシュ) → 『アタック中』にだけ撃てる起動効果
//     アタック中だけ(バトル終了時)   → 自分がアタックしているバトルの終了時
export function アタック中だけ(き: きっかけ): きっかけ {
  return { ...き, 状態: 'アタック中' };
}

// 『アタック中』のあいだずっと働く常在効果。いちばんよく出る組み合わせ。
export const アタック中ずっと: きっかけ = アタック中だけ(常在);

// 『自分のアタックステップ』… 働く場面を自分のアタックステップに限る。
// 例：自分のアタックステップだけ(起動フラッシュ)
//       → 自分のアタックステップのあいだだけ撃てる【起動：フラッシュ】
//     自分のアタックステップだけ(相手のスピリットを破壊した時)
//       → 自分のアタックステップに起きた破壊にだけ反応する誘発効果
//
// 『アタック中』（アタック中だけ）は「このカードがアタックしているか」を見るのに対し、
// こちらは「今どのステップか」を見る。アタックしていなくても、
// 自分のアタックステップでありさえすれば働く。
//
// 置き場所が2つに分かれるのは、トリガー欄の使い方が種別で違うから。
//   起動・常在 … きっかけそのものが場面なので、トリガー欄に書く
//   誘発       … トリガー欄は「何が起きたか」で埋まっているので、ステップ欄に書く
// ここを取り違えると、相手のアタックステップに自分のブロッカーが相手を倒したときにも
// 働いてしまう。
export function 自分のアタックステップだけ(き: きっかけ): きっかけ {
  return き.トリガー === undefined
    ? { ...き, トリガー: '自分のアタックステップ' }
    : { ...き, ステップ: '自分のアタックステップ' };
}

// 『自分のアタックステップ』のあいだずっと働く常在効果。
// 例：浮遊岩域「継召を持つ自分のスピリットすべてをBP+2000する」
export const 自分のアタックステップずっと: きっかけ = 自分のアタックステップだけ(常在);
