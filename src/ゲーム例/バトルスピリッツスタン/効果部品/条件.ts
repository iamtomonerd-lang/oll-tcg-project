// ② 条件（〜なら）
//
// 効果が働くための「〜なら」を1つの名前にした部品。
//
// 使い回される枚数は1〜4枚と少ないが、ここは判定を間違えやすい場所であり、
// 一度正しく作れば二度と悩まない、という意味で①〜⑥のどれとも同格の資産。

import { カードフィルタ, 発動条件 } from '../../../効果解釈/効果定義.js';

// === カード自身の状態を問う ===

// 《真界放》している
export const 真界放している: 発動条件 = { 自身: { 真界放: true } };

// === 場にいるカードを問う ===

// 「疲労状態の〜が自分の場にいるなら」
// 絞り込みで属性・系統を足せる。
//   疲労している味方がいる({ 属性: '赤' })   → 疲労状態の自分の赤のスピリット
//   疲労している味方がいる({ 系統: '血醒' }) → 疲労状態の系統：「血醒」を持つ自分のスピリット
export function 疲労している味方がいる(絞り込み: カードフィルタ = {}): 発動条件 {
  return { 存在: { 場: '自分', 種別: 'スピリット', 状態: '疲労', ...絞り込み } };
}

// 「〜が自分の場にいるなら」（疲労を問わない場合）
export function 味方がいる(絞り込み: カードフィルタ = {}): 発動条件 {
  return { 存在: { 場: '自分', 種別: 'スピリット', ...絞り込み } };
}

// === 枚数を問う ===

// 「自分の手札がN枚以下なら」
export function 手札がN枚以下(枚数: number): 発動条件 {
  return { 数量: { 場: '自分', ゾーン: '手札', 以下: 枚数 } };
}

// === このターンに起きたことを問う ===

// 「このターンに自分のライフが減っていたなら」
export const このターンに自分のライフが減っていた: 発動条件 = { 履歴: '自分のライフが減った' };

// 「このターンに自分の効果で相手のスピリットが消滅していたなら」
export const このターンに自分の効果で相手を消滅させた: 発動条件 = {
  履歴: '自分の効果でスピリットを消滅させた',
};

// === 直前の処理の結果を問う ===

// 「消滅したなら」… 直前に選んだカードが消滅していたら
export const 選んだのが消滅したなら: 発動条件 = { 消滅した: '選択' };

// 「そうしたなら」… 直前の処理が実際に行われたなら
export const そうしたなら: 発動条件 = { 直前成功: true };

// === 回数制限 ===
//
// これは条件ではなく効果定義の項目なので、展開して使う。
//   { ...起動フラッシュ, ...ターン1回, 処理: [...] }
export const ターン1回 = { 制限: 'ターン1回' } as const;
