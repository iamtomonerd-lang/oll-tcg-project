// アタック宣言後の処理。
// バトルはすぐには解決せず、まず割り込みの窓（8-1-2）を開く。
// 窓が閉じてからブロック判断へ進む。
function 攻撃を宣言する(s: セッション, 攻撃者識別子: string, 攻撃側識別子: string): void {
  const 防御側識別子 = 相手識別子(攻撃側識別子);
  s.保留中のフラッシュ = {
    管理: new フラッシュタイミング管理(防御側識別子, 攻撃側識別子),
    段階: 'アタック後',
    攻撃者識別子,
    ブロッカー識別子: null,
    攻撃側識別子,
    防御側識別子,
  };
}

// 割り込みの窓が閉じたあとの進行。
// アタック後の窓が閉じたらブロック判断へ、ブロック後の窓が閉じたらバトルを解決する。
function フラッシュの窓を閉じる(s: セッション): void {
  const フラッシュ = s.保留中のフラッシュ;
  if (!フラッシュ) {
    return;
  }
  s.保留中のフラッシュ = null;

  if (フラッシュ.段階 === 'ブロック後') {
    バトルを即時解決する(s, フラッシュ.攻撃者識別子, フラッシュ.ブロッカー識別子);
    return;
  }

  // アタック後の窓が閉じた。ブロックできる相手がいれば判断を待つ。
  // 『〜からブロックされない』の制約を通すため、試合に聞いて候補を数える。
  const アタッカー = カードを探す(s.試合, フラッシュ.攻撃者識別子);
  const ブロック可能な候補あり =
    アタッカー !== null &&
    s.試合.ブロックできる候補を集める(フラッシュ.防御側識別子, アタッカー).length > 0;

  if (!ブロック可能な候補あり) {
    バトルを即時解決する(s, フラッシュ.攻撃者識別子, null);
    return;
  }

  s.保留中の攻撃 = {
    攻撃者識別子: フラッシュ.攻撃者識別子,
    攻撃側識別子: フラッシュ.攻撃側識別子,
    防御側識別子: フラッシュ.防御側識別子,
  };
}

// ブロック宣言のあと、もう一度割り込みの窓を開く（8-1-4）
function ブロック後のフラッシュを開く(
  s: セッション,
  攻撃者識別子: string,
  ブロッカー識別子: string | null,
  攻撃側識別子: string,
  防御側識別子: string
): void {
  s.保留中の攻撃 = null;
  s.保留中のフラッシュ = {
    管理: new フラッシュタイミング管理(防御側識別子, 攻撃側識別子),
    段階: 'ブロック後',
    攻撃者識別子,
    ブロッカー識別子,
    攻撃側識別子,
    防御側識別子,
  };
}

// フラッシュでパスする。2回続いたら窓を閉じる。
function フラッシュをパスする(s: セッション): void {
  const フラッシュ = s.保留中のフラッシュ;
  if (!フラッシュ) {
    return;
  }
  フラッシュ.管理.パスした();
  if (フラッシュ.管理.終了か()) {
    フラッシュの窓を閉じる(s);
  }
}

function 自動でブロック判断して解決する(s: セッション, 防御側AI: 練習用AI): void {
  if (!s.保留中の攻撃) {
    return;
  }
  const 保留 = s.保留中の攻撃;
  const アタッカー = カードを探す(s.試合, 保留.攻撃者識別子);
  if (!アタッカー) {
    s.保留中の攻撃 = null;
    return;
  }
  const ブロッカー候補 = 防御側AI.ブロッカーを選ぶ(s.試合, アタッカー);
  let 宣言したブロッカー識別子: string | null = null;
  if (ブロッカー候補) {
    const 成功 = s.試合.ブロック宣言する(ブロッカー候補, アタッカー);
    宣言したブロッカー識別子 = 成功 ? ブロッカー候補.識別子 : null;
  }
  ブロック後のフラッシュを開く(
    s,
    アタッカー.識別子,
    宣言したブロッカー識別子,
    保留.攻撃側識別子,
    保留.防御側識別子
  );
}

function バトルを即時解決する(s: セッション, 攻撃者識別子: string, ブロッカー識別子: string | null): void {
  const アタッカー = カードを探す(s.試合, 攻撃者識別子);
  s.保留中の攻撃 = null;
  if (!アタッカー) {
    return;
  }
  const ブロッカー = ブロッカー識別子 ? カードを探す(s.試合, ブロッカー識別子) : null;
  s.試合.バトルを解決する(アタッカー, ブロッカー);
  s.試合.バトル管理.バトルを終了(アタッカー, ブロッカー);
}

// 進行を人間の手番まで自動で進める（vsHumanモードではAIが登録されていないので何もしない）
function 人間の手番まで自動進行する(s: セッション): void {
  for (let 安全カウンタ = 0; 安全カウンタ < 200; 安全カウンタ++) {
    if (s.試合.試合終了か()) {
      return;
    }

    // 効果の対象選択が先。AIの効果ならAIに答えさせ、人間の効果なら制御を返す。
    if (s.試合.効果実行器.選択待ちか()) {
      if (!効果の選択待ちを解消する(s.試合, s.AIマップ)) {
        return; // 人間の判断待ち
      }
      continue;
    }

    // 割り込みの窓。権利を持つ側がAIならパスさせ、人間なら制御を返す。
    // （練習用AIはフラッシュ効果を使わない方針なので、常にパスする）
    if (s.保留中のフラッシュ) {
      const 権利者 = s.保留中のフラッシュ.管理.現在の権利者();
      if (!s.AIマップ.has(権利者)) {
        return; // 人間の判断待ち
      }
      フラッシュをパスする(s);
      continue;
    }

    if (s.保留中の攻撃) {
      const 防御側AI = s.AIマップ.get(s.保留中の攻撃.防御側識別子);
      if (!防御側AI) {
        return; // 人間の判断待ち
      }
      自動でブロック判断して解決する(s, 防御側AI);
      continue;
    }

    const ステップ = s.試合.次の行動可能なステップまで進める();
    if (!ステップ || s.試合.試合終了か()) {
      return;
    }
    if (ステップ !== 'アタックステップ') {
      s.攻撃ステップ初期化済み = false;
    }

    const ターンプレイヤー識別子 = s.試合.ゲーム.現在のプレイヤーを取得()?.識別子;
    const AI = ターンプレイヤー識別子 ? s.AIマップ.get(ターンプレイヤー識別子) : undefined;
    if (!AI || !ターンプレイヤー識別子) {
      return; // 人間の手番：制御を返す
    }

    if (ステップ === 'メインステップ') {
      AI.メイン1を行動する(s.試合);
      continue;
    }
    if (ステップ === '第2メインステップ') {
      AI.メイン2を行動する(s.試合);
      continue;
    }
    if (ステップ === 'アタックステップ') {
      if (!s.攻撃ステップ初期化済み) {
        AI.攻撃ステップを開始する(s.試合);
        s.攻撃ステップ初期化済み = true;
      }
      const アタッカー = AI.攻撃者を選ぶ(s.試合);
      if (!アタッカー) {
        s.試合.ステップを終了する();
        continue;
      }
      const 宣言成功 = s.試合.アタック宣言する(アタッカー);
      if (!宣言成功) {
        s.試合.ステップを終了する();
        continue;
      }
      攻撃を宣言する(s, アタッカー.識別子, ターンプレイヤー識別子);
      continue;
    }
    return;
  }
}

