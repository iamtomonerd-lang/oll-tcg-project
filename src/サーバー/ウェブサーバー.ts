// 効果の対象選択に答える
app.post('/api/action/select-effect-target', (req: Request, res: Response) => {
  const s = セッション必須(res);
  if (!s) return;
  const { as, targetCardIds, targetCardId } = req.body as {
    as: string;
    targetCardIds?: string[];
    targetCardId?: string;
  };

  const 待ち = s.試合.効果実行器.選択待ち情報を取得();
  if (!待ち) {
    return エラー応答(res, '選択待ちの効果はありません');
  }
  // 判断は必ず「聞かれている人」が答える。
  // 「（置くコアは相手が選ぶ）」のように効果の持ち主でない側が答える場面があるため、
  // ターンプレイヤーかどうかではなく、選択待ち情報の答える人と突き合わせる。
  if (待ち.所有者識別子 !== as) {
    return エラー応答(res, 'あなたが答える場面ではありません');
  }

  // 1体選択（targetCardId）と複数選択（targetCardIds）の両方を受け付ける。
  // 「指定できる」効果で何も選ばない場合は空配列を送る。
  const 選択 = targetCardIds ?? (targetCardId ? [targetCardId] : []);

  const 進行 = s.試合.効果実行器.選択に答える(選択);
  if (進行.状態 === 'アイドル') {
    人間の手番まで自動進行する(s);
  }

  res.json({ ok: true, state: 状態を作る(s, as) });
});

// 【起動】効果を発動する
app.post('/api/action/activate-effect', (req: Request, res: Response) => {
  const s = セッション必須(res);
  if (!s) return;
  const { as, effectId } = req.body as { as: string; effectId: string };

  if (s.試合.試合終了か()) return エラー応答(res, '試合は終了しています');
  if (s.保留中の攻撃) return エラー応答(res, 'ブロック判断待ちです');
  if (s.試合.効果実行器.選択待ちか()) return エラー応答(res, '効果の対象選択が先です');

  // 割り込みの窓の最中なら、権利を持つ側しか撃てない
  if (s.保留中のフラッシュ && s.保留中のフラッシュ.管理.現在の権利者() !== as) {
    return エラー応答(res, 'あなたが判断する場面ではありません');
  }

  const 進行 = s.試合.効果実行器.起動効果を発動する(as, effectId);
  if (進行.状態 === 'アイドル' && 進行.ログ.some(行 => 行.includes('発動できません'))) {
    return エラー応答(res, 'その効果は今発動できません');
  }

  // 撃ったので権利は相手へ移る（連続パスの数え直し）
  if (s.保留中のフラッシュ) {
    s.保留中のフラッシュ.管理.効果を使用した();
  }

  if (進行.状態 === 'アイドル') {
    人間の手番まで自動進行する(s);
  }
  res.json({ ok: true, state: 状態を作る(s, as) });
});

