app.post('/api/action/use', (req: Request, res: Response) => {
  const s = セッション必須(res);
  if (!s) return;
  const { as, cardId } = req.body as { as: string; cardId: string };

  // ［フラッシュ］のマジックは、割り込みの窓でも使える。
  // 権利を持っている間だけ許し、それ以外は通常のメインステップ確認に従う。
  const 割り込み中に使えるか =
    s.保留中のフラッシュ !== null && s.保留中のフラッシュ.管理.現在の権利者() === as;

  if (!割り込み中に使えるか) {
    const 検査 = プレイ前の共通確認(s, as);
    if (検査) return エラー応答(res, 検査);
  } else if (s.試合.効果実行器.選択待ちか()) {
    return エラー応答(res, '効果の対象選択が先です');
  }

  const 手札 = s.試合.ゾーン管理.手札を取得(s.試合.ゲーム, as);
  const リザーブ = s.試合.ゾーン管理.リザーブを取得(s.試合.ゲーム, as);
  if (!手札 || !リザーブ) return エラー応答(res, 'ゾーンが見つかりません');

  const カード = 手札.カードを取得(cardId);
  if (!カード) return エラー応答(res, '手札にありません');
  if (!カード種別ルール個体.マジックか(カード)) return エラー応答(res, 'マジックではありません');

  // 割り込み中に使えるのは［フラッシュ］のマジックだけ
  if (割り込み中に使えるか && !フラッシュで使えるマジックか(カード)) {
    return エラー応答(res, 'このマジックは割り込みでは使えません');
  }

  const リザーブ保持者 = s.試合.コア管理.ゾーンを保持者に(リザーブ);
  const コスト = 支払うコストを求める(s, as, カード);

  if (リザーブ保持者.コア数を取得() < コスト) {
    return エラー応答(res, 'コアが足りません');
  }

  // ［メイン］と［フラッシュ］の両方を持つマジックは、どちらで撃ったかで効果が変わる
  const 成功 = s.試合.使用する(
    as,
    カード,
    [{ 保持者: リザーブ保持者, 数: コスト }],
    0,
    割り込み中に使えるか ? 'フラッシュ' : 'メイン'
  );
  if (!成功) return エラー応答(res, '使用に失敗しました');

  // 割り込み中に使ったなら、権利は相手へ移る
  if (割り込み中に使えるか && s.保留中のフラッシュ) {
    s.保留中のフラッシュ.管理.効果を使用した();
  }

  if (!s.試合.効果実行器.選択待ちか()) {
    人間の手番まで自動進行する(s);
  }
  res.json({ ok: true, state: 状態を作る(s, as) });
});

