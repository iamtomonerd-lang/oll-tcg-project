function グンガタデッキを作成(接頭辞: string, 枚数 = 20): カード[] {
  const カード一覧: カード[] = [];
  // ロワミークを3枚追加（効果テスト用）
  for (let i = 0; i < 3; i++) {
    カード一覧.push(ロワミークを作成(`${接頭辞}-rowamique-${i + 1}`));
  }
  // 残りはグンガタで埋める
  for (let i = 0; i < 枚数 - 3; i++) {
    カード一覧.push(グンガタを作成(`${接頭辞}-gungata-${i + 1}`));
  }
  return カード一覧;
}

