function 手札カードを表示用に(
  試合インスタンス: 試合,
  カード: カード,
  フィールドのシンボル: string[],
  リザーブ保持者: コア保持者
) {
  const 基本コスト = コストルール個体.コストを取得(カード);
  const コスト = 軽減シンボルルール個体.軽減後のコストを計算(カード, 基本コスト, フィールドのシンボル);
  const 最低必要数 = 消滅判定個体.最小必要コア数を取得(カード);
  const 支払可能 = リザーブ保持者.コア数を取得() >= コスト + 最低必要数;
  return {
    識別子: カード.識別子,
    名前: カード.名称.表示名,
    カードナンバー: カードナンバールール個体.カードナンバーを取得(カード),
    種別: カード種別ルール個体.カード種別を取得(カード),
    基本コスト,
    コスト,
    最低必要数,
    支払可能,
    テキスト: (カード.名称 as any).カードテキスト ?? '',
  };
}

function フィールドカードを表示用に(試合インスタンス: 試合, カード: カード) {
  const 保持者 = 試合インスタンス.コア管理.カードを保持者に(カード);
  const Lv一覧 = Lvルール個体.Lvを取得(カード);
  const 現在Lv = 試合インスタンス.Lv管理.現在のLvを取得(カード);
  const 次のLv = Lv一覧.find(lv => lv.level === 現在Lv + 1) ?? null;
  return {
    識別子: カード.識別子,
    名前: カード.名称.表示名,
    カードナンバー: カードナンバールール個体.カードナンバーを取得(カード),
    Lv: 現在Lv,
    最大Lv: Lv一覧.length > 0 ? Lv一覧[Lv一覧.length - 1].level : 現在Lv,
    次のLvに必要な総コア数: 次のLv ? 次のLv.cost : null,
    BP: 試合インスタンス.BP管理.現在のBPを取得(カード),
    コア数: 保持者.コア数を取得(),
    ソウルコア: 保持者.ソウルコアあるか(),
    表示形式: 試合インスタンス.カードの表示形式管理.現在の表示形式を取得(カード),
  };
}

function プレイヤー状態を作る(s: セッション, プレイヤー識別子: string, 自分視点: boolean) {
  const 試合インスタンス = s.試合;
  const プレイヤー = 試合インスタンス.ゲーム.プレイヤーを取得(プレイヤー識別子);
  const ライフ = 試合インスタンス.ゾーン管理.ライフを取得(試合インスタンス.ゲーム, プレイヤー識別子)!;
  const リザーブ = 試合インスタンス.ゾーン管理.リザーブを取得(試合インスタンス.ゲーム, プレイヤー識別子)!;
  const 手札 = 試合インスタンス.ゾーン管理.手札を取得(試合インスタンス.ゲーム, プレイヤー識別子)!;
  const デッキ = 試合インスタンス.ゾーン管理.デッキエリアを取得(試合インスタンス.ゲーム, プレイヤー識別子)!;
  const トラッシュ = 試合インスタンス.ゾーン管理.トラッシュを取得(試合インスタンス.ゲーム, プレイヤー識別子)!;
  const フィールド = 試合インスタンス.ゾーン管理.フィールドを取得(試合インスタンス.ゲーム, プレイヤー識別子)!;

  const ライフ保持者 = 試合インスタンス.コア管理.ゾーンを保持者に(ライフ);
  const リザーブ保持者 = 試合インスタンス.コア管理.ゾーンを保持者に(リザーブ);

  const フィールドのシンボル = フィールド
    .カード一覧を取得()
    .flatMap(c => シンボルルール個体.シンボルを取得(c).map(x => x.色));

  return {
    識別子: プレイヤー識別子,
    名前: プレイヤー?.名前 ?? プレイヤー識別子,
    ライフ: コア判定個体.総コア数を取得(ライフ保持者),
    リザーブ: {
      通常: コア判定個体.通常コア数を取得(リザーブ保持者),
      ソウルコア: コア判定個体.ソウルコアあるか(リザーブ保持者),
    },
    デッキ枚数: デッキ.カード枚数を取得(),
    トラッシュ: トラッシュ.カード一覧を取得().map(c => ({
      識別子: c.識別子,
      名前: c.名称.表示名,
      カードナンバー: カードナンバールール個体.カードナンバーを取得(c),
    })),
    手札枚数: 手札.カード枚数を取得(),
    手札: 自分視点
      ? 手札.カード一覧を取得().map(c => 手札カードを表示用に(試合インスタンス, c, フィールドのシンボル, リザーブ保持者))
      : undefined,
    フィールド: フィールド.カード一覧を取得().map(c => フィールドカードを表示用に(試合インスタンス, c)),
  };
}

function 状態を作る(s: セッション, 視点: string) {
  const 相手 = 相手識別子(視点);
  const ターンプレイヤー識別子 = s.試合.ゲーム.現在のプレイヤーを取得()?.識別子 ?? null;
  const 実行者識別子 = s.保留中の攻撃 ? s.保留中の攻撃.防御側識別子 : ターンプレイヤー識別子;

  const 保留中のブロック =
    s.保留中の攻撃 && s.保留中の攻撃.防御側識別子 === 視点
      ? (() => {
          const アタッカー = カードを探す(s.試合, s.保留中の攻撃!.攻撃者識別子);
          return アタッカー ? { 攻撃者: フィールドカードを表示用に(s.試合, アタッカー) } : null;
        })()
      : null;

  return {
    モード: s.モード,
    試合終了か: s.試合.試合終了か(),
    勝敗結果: s.試合.勝敗結果を取得(),
    ステップ: s.試合.現在のステップ() ?? null,
    ターンプレイヤー識別子,
    実行者識別子,
    自分が実行者か: 実行者識別子 === 視点,
    保留中のブロック,
    自分: プレイヤー状態を作る(s, 視点, true),
    相手: プレイヤー状態を作る(s, 相手, true),
  };
}

