// 効果を確かめるためのデッキ。
// BPが低いカードだけで構成してあるので、ロワミークの「BP3000以下の相手」が
// 対象を見つけやすく、召喚時効果が実際に発動する場面に入りやすい。
// スピリットだけでなくネクサス・マジック・【起動】効果持ちも混ぜてあり、
// 3種類すべてのカードと、誘発／起動／使用のすべての効果の道を通せる。
// 【起動：フラッシュ】はグライファーと最奥：風牙岩、【起動：メイン】は紫21が担う。
function 効果デッキを作成(接頭辞: string, 枚数 = 24): カード[] {
  const 作り手 = [
    ロワミークを作成, // 召喚時に対象選択
    ムーシャッコを作成, // バトル終了時にドロー
    ゲン_ボーを作成, // 真界放の常在効果
    ハーリアを作成, // アタック時にデッキをめくって手札に加える
    キュペルを作成, // 召喚時／自分のエンドステップにトラッシュからコアを置く
    セルタリウスを作成, // 召喚時にトラッシュから手札に戻す（《継召》持ち）
    ブレイククローを作成, // マジック（メインとフラッシュの2つの撃ち方）
    オフェリングドローを作成, // マジック（デッキをめくって拾う／《継召》持ち）
    フレイムハリケーンを作成, // マジック（《ソウルマジック》／条件でBP射程が変わる）
    グライファーを作成, // アタック中の【起動：フラッシュ】と《真界放》の破壊
    飛傑レウファルスを作成, // 召喚時に条件つきで破壊／《真界放》の常在BP
    最奥_風牙岩を作成, // 赤のネクサス（『自分のアタックステップ』の【起動：フラッシュ】）
    浮遊岩域を作成, // 赤のネクサス（配置時／《継召》持ちへの常在BP）
    紫21を作成, // ネクサス（【起動：メイン】）
  ];
  const カード一覧: カード[] = [];
  for (let i = 0; i < 枚数; i++) {
    カード一覧.push(作り手[i % 作り手.length](`${接頭辞}-effect-${i + 1}`));
  }
  return カード一覧;
}

