// ［フラッシュ］タイミングを持つマジックか
function フラッシュで使えるマジックか(カード: カード): boolean {
  const 効果一覧 = (カード.名称 as any).効果 ?? [];
  return 効果一覧.some(
    (効果: any) => 効果.種別 === '使用' && 効果.タイミング === 'フラッシュ'
  );
}

// 召喚・配置・使用に共通する事前確認。問題があれば理由を返す。
function プレイ前の共通確認(s: セッション, as: string): string | null {
  if (s.試合.試合終了か()) return '試合は終了しています';
  if (s.保留中の攻撃) return 'ブロック判断待ちです';
  if (s.試合.効果実行器.選択待ちか()) return '効果の対象選択が先です';
  if (s.試合.ゲーム.現在のプレイヤーを取得()?.識別子 !== as) return 'あなたのターンではありません';
  if (!['メインステップ', '第2メインステップ'].includes(s.試合.現在のステップ() ?? '')) {
    return '今はメインステップではありません';
  }
  return null;
}

// 自分の場のシンボルによる軽減を反映した、実際に支払う額
function 支払うコストを求める(s: セッション, as: string, カード: カード): number {
  const フィールド = s.試合.ゾーン管理.フィールドを取得(s.試合.ゲーム, as);
  const フィールドのシンボル = (フィールド?.カード一覧を取得() ?? []).flatMap(c =>
    シンボルルール個体.シンボルを取得(c).map(x => x.色)
  );
  const 基本コスト = コストルール個体.コストを取得(カード);
  return 軽減シンボルルール個体.軽減後のコストを計算(カード, 基本コスト, フィールドのシンボル);
}



