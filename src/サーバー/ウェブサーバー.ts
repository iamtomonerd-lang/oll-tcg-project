function グンガタデッキを作成(接頭辞: string, 枚数 = 20): カード[] {
  return Array.from({ length: 枚数 }, (_, i) => グンガタを作成(`${接頭辞}-gungata-${i + 1}`));
}

function ゲン_ボーデッキを作成(接頭辞: string, 枚数 = 20): カード[] {
  return Array.from({ length: 枚数 }, (_, i) => ゲン_ボーを作成(`${接頭辞}-genbo-${i + 1}`));
}

function ムーシャッコデッキを作成(接頭辞: string, 枚数 = 20): カード[] {
  return Array.from({ length: 枚数 }, (_, i) => ムーシャッコを作成(`${接頭辞}-mushaako-${i + 1}`));
}

function デッキを作成(接頭辞: string, タイプ: デッキタイプ): カード[] {
  if (タイプ === 'genbo') {
    return ゲン_ボーデッキを作成(接頭辞);
  }
  if (タイプ === 'mushaako') {
    return ムーシャッコデッキを作成(接頭辞);
  }
  return グンガタデッキを作成(接頭辞);
}

// 先攻はp1固定、引き直し（マリガン）は行わない、というのが現状の割り切り。
function 新しい試合を作る(モード: モード, デッキタイプ: デッキタイプ = 'gungata'): セッション {
  const 試合インスタンス = new 試合();
  試合インスタンス.プレイヤーを準備する('p1', 'プレイヤー1');
  試合インスタンス.プレイヤーを準備する('p2', 'プレイヤー2');
  試合インスタンス.ボイドを準備する();
  試合インスタンス.デッキを設定する('p1', デッキを作成('p1', デッキタイプ));
  試合インスタンス.デッキを設定する('p2', デッキを作成('p2', デッキタイプ));
  試合インスタンス.準備を行う('p1');
  試合インスタンス.準備を行う('p2');
  試合インスタンス.先攻を決める('p1');
  試合インスタンス.試合を開始する();

  const AIマップ = new Map<string, 練習用AI>();
  if (モード === 'vsAI') {
    AIマップ.set('p2', new 練習用AI('p2', 'p1'));
  }

  return { モード, 試合: 試合インスタンス, AIマップ, 保留中の攻撃: null, 攻撃ステップ初期化済み: false };
}

function カードを探す(試合インスタンス: 試合, 識別子: string): カード | null {
  for (const プレイヤー of 試合インスタンス.ゲーム.全プレイヤーを取得()) {
    for (const ゾーン of 試合インスタンス.ゾーン管理.プレイヤーの全領域を取得(試合インスタンス.ゲーム, プレイヤー.識別子)) {
      const 見つかった = ゾーン.カードを取得(識別子);
      if (見つかった) {
        return 見つかった;
      }
    }
  }
  return null;
}

function 回復状態か(試合インスタンス: 試合, カード: カード): boolean {
  return 試合インスタンス.カードの表示形式管理.現在の表示形式を取得(カード) === '回復';
}

// アタック宣言後の処理：ブロックできる相手がいなければ即解決、いれば防御側の判断待ちにする
function 攻撃を宣言する(s: セッション, 攻撃者識別子: string, 攻撃側識別子: string): void {
  const 防御側識別子 = 相手識別子(攻撃側識別子);
  const 防御側フィールド = s.試合.ゾーン管理.フィールドを取得(s.試合.ゲーム, 防御側識別子);
  const ブロック可能な候補あり = (防御側フィールド?.カード一覧を取得() ?? []).some(c => 回復状態か(s.試合, c));

  if (!ブロック可能な候補あり) {
    バトルを即時解決する(s, 攻撃者識別子, null);
    return;
  }

  s.保留中の攻撃 = { 攻撃者識別子, 攻撃側識別子, 防御側識別子 };
}

function 自動でブロック判断して解決する(s: セッション, 防御側AI: 練習用AI): void {
  if (!s.保留中の攻撃) {
    return;
  }
  const アタッカー = カードを探す(s.試合, s.保留中の攻撃.攻撃者識別子);
  if (!アタッカー) {
    s.保留中の攻撃 = null;
    return;
  }
  const ブロッカー候補 = 防御側AI.ブロッカーを選ぶ(s.試合, アタッカー);
  let 宣言したブロッカー識別子: string | null = null;
  if (ブロッカー候補) {
    const 成功 = s.試合.バトル管理.ブロック宣言(s.試合.ゲーム, ブロッカー候補);
    宣言したブロッカー識別子 = 成功 ? ブロッカー候補.識別子 : null;
  }
  バトルを即時解決する(s, アタッカー.識別子, 宣言したブロッカー識別子);
}

function バトルを即時解決する(s: セッション, 攻撃者識別子: string, ブロッカー識別子: string | null): void {
  const アタッカー = カードを探す(s.試合, 攻撃者識別子);
  s.保留中の攻撃 = null;
  if (!アタッカー) {
    return;
  }
  const ブロッカー = ブロッカー識別子 ? カードを探す(s.試合, ブロッカー識別子) : null;
  s.試合.バトルを解決する(アタッカー, ブロッカー);
  s.試合.バトル管理.バトルを終了(アタッカー, ブロッカー);
}

// 進行を人間の手番まで自動で進める（vsHumanモードではAIが登録されていないので何もしない）
function 人間の手番まで自動進行する(s: セッション): void {
  for (let 安全カウンタ = 0; 安全カウンタ < 200; 安全カウンタ++) {
    if (s.試合.試合終了か()) {
      return;
    }

    if (s.保留中の攻撃) {
      const 防御側AI = s.AIマップ.get(s.保留中の攻撃.防御側識別子);
      if (!防御側AI) {
        return; // 人間の判断待ち
      }
      自動でブロック判断して解決する(s, 防御側AI);
      continue;
    }

    const ステップ = s.試合.次の行動可能なステップまで進める();
    if (!ステップ || s.試合.試合終了か()) {
      return;
    }
    if (ステップ !== 'アタックステップ') {
      s.攻撃ステップ初期化済み = false;
    }

    const ターンプレイヤー識別子 = s.試合.ゲーム.現在のプレイヤーを取得()?.識別子;
    const AI = ターンプレイヤー識別子 ? s.AIマップ.get(ターンプレイヤー識別子) : undefined;
    if (!AI || !ターンプレイヤー識別子) {
      return; // 人間の手番：制御を返す
    }

    if (ステップ === 'メインステップ') {
      AI.メイン1を行動する(s.試合);
      continue;
    }
    if (ステップ === '第2メインステップ') {
      AI.メイン2を行動する(s.試合);
      continue;
    }
    if (ステップ === 'アタックステップ') {
      if (!s.攻撃ステップ初期化済み) {
        AI.攻撃ステップを開始する(s.試合);
        s.攻撃ステップ初期化済み = true;
      }
      const アタッカー = AI.攻撃者を選ぶ(s.試合);
      if (!アタッカー) {
        s.試合.ステップを終了する();
        continue;
      }
      const 宣言成功 = s.試合.バトル管理.アタック宣言(s.試合.ゲーム, アタッカー);
      if (!宣言成功) {
        s.試合.ステップを終了する();
        continue;
      }
      攻撃を宣言する(s, アタッカー.識別子, ターンプレイヤー識別子);
      continue;
    }
    return;
  }
}

