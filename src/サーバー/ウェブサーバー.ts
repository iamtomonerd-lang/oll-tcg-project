app.post('/api/action/summon', (req: Request, res: Response) => {
  const s = セッション必須(res);
  if (!s) return;
  const { as, cardId } = req.body as { as: string; cardId: string };

  if (s.試合.試合終了か()) return エラー応答(res, '試合は終了しています');
  if (s.保留中の攻撃) return エラー応答(res, 'ブロック判断待ちです');
  if (s.試合.ゲーム.現在のプレイヤーを取得()?.識別子 !== as) return エラー応答(res, 'あなたのターンではありません');
  if (!['メインステップ', '第2メインステップ'].includes(s.試合.現在のステップ() ?? '')) {
    return エラー応答(res, '今はメインステップではありません');
  }

  const 手札 = s.試合.ゾーン管理.手札を取得(s.試合.ゲーム, as);
  const フィールド = s.試合.ゾーン管理.フィールドを取得(s.試合.ゲーム, as);
  const リザーブ = s.試合.ゾーン管理.リザーブを取得(s.試合.ゲーム, as);
  if (!手札 || !フィールド || !リザーブ) return エラー応答(res, 'ゾーンが見つかりません');

  const カード = 手札.カードを取得(cardId);
  if (!カード) return エラー応答(res, '手札にありません');
  if (!カード種別ルール個体.スピリットか(カード)) return エラー応答(res, 'スピリット以外はまだ対応していません');

  const リザーブ保持者 = s.試合.コア管理.ゾーンを保持者に(リザーブ);
  const フィールドのシンボル = フィールド.カード一覧を取得().flatMap(c => シンボルルール個体.シンボルを取得(c).map(x => x.色));
  const 基本コスト = コストルール個体.コストを取得(カード);
  const コスト = 軽減シンボルルール個体.軽減後のコストを計算(カード, 基本コスト, フィールドのシンボル);
  const 最低必要数 = 消滅判定個体.最小必要コア数を取得(カード);

  if (リザーブ保持者.コア数を取得() < コスト + 最低必要数) {
    return エラー応答(res, 'コアが足りません');
  }

  const 成功 = s.試合.召喚する(
    as,
    カード,
    [{ 保持者: リザーブ保持者, 数: コスト }],
    [{ 保持者: リザーブ保持者, 数: 最低必要数 }]
  );
  if (!成功) return エラー応答(res, '召喚に失敗しました');

  人間の手番まで自動進行する(s);
  res.json({ ok: true, state: 状態を作る(s, as) });
});

