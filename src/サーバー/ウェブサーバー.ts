// 効果が対象選択で止まっているなら、その効果の持ち主を返す
function 効果の選択を待っている相手(s: セッション): string | null {
  const 情報 = s.試合.効果実行器.選択待ち情報を取得();
  return 情報 ? 情報.所有者識別子 : null;
}

// 割り込みの窓が開いていて、この視点に権利があるなら、その情報を返す
function 保留中のフラッシュを表示用に(s: セッション, 視点: string) {
  const フラッシュ = s.保留中のフラッシュ;
  if (!フラッシュ || フラッシュ.管理.現在の権利者() !== 視点) {
    return null;
  }
  const アタッカー = カードを探す(s.試合, フラッシュ.攻撃者識別子);
  const ブロッカー = フラッシュ.ブロッカー識別子
    ? カードを探す(s.試合, フラッシュ.ブロッカー識別子)
    : null;
  return {
    段階: フラッシュ.段階,
    攻撃者名: アタッカー ? アタッカー.名称.表示名 : null,
    ブロッカー名: ブロッカー ? ブロッカー.名称.表示名 : null,
  };
}

// 効果が対象選択で止まっているとき、その情報を画面向けに整える。
