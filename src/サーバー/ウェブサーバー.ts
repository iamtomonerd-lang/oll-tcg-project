// 先攻はp1固定、引き直し（マリガン）は行わない、というのが現状の割り切り。
//
// 種を渡すと、デッキのシャッフルがその種で決まる。自動対戦テストが
// 「同じ種なら同じ試合」を前提にできるようにするための入口で、
// 実際の対戦では渡さない（毎回違う引きになる）。
function 新しい試合を作る(
  モード: モード,
  デッキタイプ: デッキタイプ = 'gungata',
  種?: number
): セッション {
  const 試合インスタンス = new 試合(種);
  試合インスタンス.プレイヤーを準備する('p1', 'プレイヤー1');
  試合インスタンス.プレイヤーを準備する('p2', 'プレイヤー2');
  試合インスタンス.ボイドを準備する();
  試合インスタンス.デッキを設定する('p1', デッキを作成('p1', デッキタイプ));
  試合インスタンス.デッキを設定する('p2', デッキを作成('p2', デッキタイプ));
  試合インスタンス.準備を行う('p1');
  試合インスタンス.準備を行う('p2');
  試合インスタンス.先攻を決める('p1');
  試合インスタンス.試合を開始する();

  const AIマップ = new Map<string, 練習用AI>();
  if (モード === 'vsAI') {
    AIマップ.set('p2', new 練習用AI('p2', 'p1'));
  }

  return {
    モード,
    試合: 試合インスタンス,
    AIマップ,
    保留中の攻撃: null,
    保留中のフラッシュ: null,
    攻撃ステップ初期化済み: false,
  };
}

function カードを探す(試合インスタンス: 試合, 識別子: string): カード | null {
  for (const プレイヤー of 試合インスタンス.ゲーム.全プレイヤーを取得()) {
    for (const ゾーン of 試合インスタンス.ゾーン管理.プレイヤーの全領域を取得(試合インスタンス.ゲーム, プレイヤー.識別子)) {
      const 見つかった = ゾーン.カードを取得(識別子);
      if (見つかった) {
        return 見つかった;
      }
    }
  }
  return null;
}

