import { 効果, 効果実行文脈, 効果結果 } from './効果.js';
import { カード } from '../データ/カード/カード.js';
import { ゾーン } from '../データ/ゾーン/ゾーン.js';

export class ゾーン移動効果 extends 効果 {
  constructor(識別子: string = 'ゾーン-移動', 名前: string = 'ゾーン移動') {
    super(識別子, 名前);
  }

  async 実行(文脈: 効果実行文脈): Promise<効果結果> {
    const { 発動源, 対象, 追加データ } = 文脈;

    if (!(発動源 instanceof カード)) {
      return { 成功: false, メッセージ: '発動源はカードである必要があります' };
    }

    if (!(対象 instanceof ゾーン)) {
      return { 成功: false, メッセージ: '対象はゾーンである必要があります' };
    }

    const 移動元ゾーン = 追加データ?.移動元ゾーン as ゾーン | undefined;

    if (移動元ゾーン) {
      const 削除結果 = 移動元ゾーン.カードを削除(発動源.識別子);
      if (!削除結果) {
        return { 成功: false, メッセージ: '移動元ゾーンからカードが見つかりません' };
      }
    }

    const 追加結果 = 対象.カードを追加(発動源);
    if (!追加結果) {
      if (移動元ゾーン) {
        移動元ゾーン.カードを追加(発動源);
      }
      return { 成功: false, メッセージ: '対象ゾーンにカードを追加できません' };
    }

    return {
      成功: true,
      メッセージ: `カード ${発動源.識別子} をゾーン ${対象.識別子} に移動しました`,
      データ: { カード: 発動源, 移動元: 移動元ゾーン, 移動先: 対象 },
    };
  }
}
