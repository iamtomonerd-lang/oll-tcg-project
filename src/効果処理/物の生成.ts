import { 効果, 効果実行文脈, 効果結果 } from './効果.js';
import { カード, 名称 } from '../データ/カード/カード.js';
import { ゲーム物, ゲーム物種別 } from '../データ/ゲーム物/ゲーム物.js';

export class 物の生成効果 extends 効果 {
  constructor(識別子: string = '生成', 名前: string = '物の生成') {
    super(識別子, 名前);
  }

  async 実行(文脈: 効果実行文脈): Promise<効果結果> {
    const { 追加データ } = 文脈;
    const 生成種別 = 追加データ?.種別 as 'カード' | 'ゲーム物' | undefined;

    if (生成種別 === 'カード') {
      const カード識別子 = 追加データ?.カード識別子 as string | undefined;
      const カード名称情報 = 追加データ?.カード名称 as 名称 | undefined;

      if (!カード識別子 || !カード名称情報) {
        return { 成功: false, メッセージ: 'カード生成に必要な情報が不足しています' };
      }

      const 新しいカード = new カード(カード識別子, カード名称情報);
      return {
        成功: true,
        メッセージ: `カード ${カード識別子} を生成しました`,
        データ: { 生成物: 新しいカード, 種別: 'カード' },
      };
    }

    if (生成種別 === 'ゲーム物') {
      const ゲーム物識別子 = 追加データ?.ゲーム物識別子 as string | undefined;
      const ゲーム物種別情報 = 追加データ?.ゲーム物種別 as ゲーム物種別 | undefined;

      if (!ゲーム物識別子 || !ゲーム物種別情報) {
        return { 成功: false, メッセージ: 'ゲーム物生成に必要な情報が不足しています' };
      }

      const 新しいゲーム物 = new ゲーム物(ゲーム物識別子, ゲーム物種別情報);
      return {
        成功: true,
        メッセージ: `ゲーム物 ${ゲーム物識別子} を生成しました`,
        データ: { 生成物: 新しいゲーム物, 種別: 'ゲーム物' },
      };
    }

    return { 成功: false, メッセージ: '不明な生成種別です' };
  }
}
